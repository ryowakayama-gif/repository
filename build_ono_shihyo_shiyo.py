def jiko(specs, miss):
    ng = []
    # 1 すべての指標に仕様がある
    if miss:
        ng.append(f"仕様がない指標が{len(miss)}件：{miss[:3]}")
    # 2 層が3つのいずれか（指標でないものは「―」）
    for g, s, n, _c, _t, sp in specs:
        if sp and sp[0] not in list(SOU) + ["―"]:
            ng.append(f"層が3つのいずれでもない：{n}")
    # 3 状態（Ｊ）は必ず毎年度×
    for g, s, n, _c, _t, sp in specs:
        if sp and sp[0] == "Ｊ" and sp[5] != "**×**":
            ng.append(f"状態（Ｊ）なのに毎年度が×でない：{n}")
    # 4 データ源が調査なら毎年度は×か△
    for g, s, n, _c, _t, sp in specs:
        if sp and sp[4] == "調査" and sp[5] == "○":
            ng.append(f"データ源が調査なのに毎年度が○：{n}")
    # 5 毎年度○なのにデータ源が調査でない
    for g, s, n, _c, _t, sp in specs:
        if sp and sp[5] == "○" and sp[4] == "調査":
            ng.append(f"毎年度○でデータ源が調査：{n}")
    # 6 データ源が GEN にある
    for g, s, n, _c, _t, sp in specs:
        if sp and sp[4] not in GEN and sp[4] != "―":
            ng.append(f"データ源が一覧にない：{n}（{sp[4]}）")
    # 7 割合の指標には母数がある
    for g, s, n, _c, _t, sp in specs:
        if sp and ("率" in n or "割合" in n or "認知度" in n) and sp[0] != "―":
            if sp[2] in ("―", ""):
                ng.append(f"割合の指標なのに母数がない：{n}")
    # 8 △には「決めること」が書かれている
    for g, s, n, _c, _t, sp in specs:
        if sp and sp[5] == "△" and len(sp[6]) < 20:
            ng.append(f"△なのに決めることが書かれていない：{n}")
    # 9 目標値が「―」のものは層が「―」
    for g, s, n, _c, t, sp in specs:
        if sp and t == "―" and sp[0] != "―":
            ng.append(f"目標値が「―」なのに層が付いている：{n}")
    return ng


