def read_shihyo():
    """素案の現物から成果指標を読み出す。"""
    def hiduke(p):
        import re
        m = re.search(r"_(\d{8})\.docx$", p.name)
        return (m.group(1) if m else "", p.name)

    cands = sorted(SOAN_DIR.glob("*第10期介護保険事業計画_素案_*.docx"),
                   key=hiduke)
    if not cands:
        raise SystemExit("計画素案が見つかりません。"
                         "先に build_ono_soan_elderly.py を実行してください。")
    path = cands[-1]
    d = Document(path)
    cur = mg = ""
    out = []
    for ch in d.element.body.iterchildren():
        if ch.tag == qn("w:p"):
            q = Paragraph(ch, d)
            if q.style.name == "Heading 2" and q.text.strip():
                mg = q.text.strip()
            if q.style.name == "Heading 3" and q.text.strip():
                cur = q.text.strip()
        elif ch.tag == qn("w:tbl"):
            t = Table(ch, d)
            if [c.text.strip() for c in t.rows[0].cells][:1] == ["成果指標（案）"]:
                for r in t.rows[1:]:
                    c = [x.text.strip() for x in r.cells]
                    out.append((mg, cur, c[0], c[1],
                                c[2] if len(c) > 2 else ""))
    return path.name, out


def spec_of(name):
    """指標名から仕様を引く。先頭一致で引き当てる。"""
    if name in SPEC:
        return SPEC[name]
    hit = [k for k in SPEC if name.startswith(k)]
    if hit:
        return SPEC[max(hit, key=len)]
    return None


