def jiko(r):
    ng = []
    kA = [x for x in K51 if x[4] == "**Ａ**"]
    kC = [x for x in K51 if x[4] == "**Ｃ**"]
    # 1 区分Aには反映先がある
    for x in kA:
        if not x[7].strip():
            ng.append("区分Ａに反映先がない：%s" % x[1])
    # 2 区分Cには照会番号がある
    ids = {y[0] for y in SHOKAI_MACHI} | {y[0] for y in SHOKAI_KEN}
    for x in kC:
        if not any(i in x[7] for i in ids):
            ng.append("区分Ｃに照会番号がない：%s" % x[1])
    # 3 施行日が空でない
    for x in K51:
        if not x[2].strip():
            ng.append("施行日が空：%s" % x[1])
    # 4 主体が3つのいずれかを含む
    for x in K51:
        if not any(k in x[3] for k in ("国", "都道府県", "市町村", "法人")):
            ng.append("主体が書かれていない：%s" % x[1])
    # 5 「原則令和9年4月1日」で丸めていない
    if any(x[2].strip() == "原則 令和9年4月1日" for x in K51):
        ng.append("施行日を原則で丸めている")
    # 6 都道府県の事項を区分Aに置いていない
    for x in K51:
        if x[3].startswith("**都道府県**") and x[4] == "**Ａ**":
            ng.append("都道府県の事項を市町村計画の区分Ａに置いている：%s" % x[1])
    # 7 医療的ケア児に条文番号・施行日を書いていない（原典未入手のため）
    for x in IRYO:
        if "第" in x[0] and "条" in x[0]:
            ng.append("原典のない条文番号を書いている：%s" % x[0])
    # 8 原典の一覧に未入手のものが明示されている
    if not any("未入手" in g[3] for g in GENTEN):
        ng.append("未入手の原典が明示されていない")
    # 9 照会番号に重複がない
    allid = [y[0] for y in SHOKAI_MACHI] + [y[0] for y in SHOKAI_KEN]
    if len(allid) != len(set(allid)):
        ng.append("照会番号が重複している")
    # 10 表の列幅の合計が本文幅
    return ng


