def _tally(data, col):
    out = {}
    for rec in data:
        out[rec[col]] = out.get(rec[col], 0) + 1
    return out


def verify():
    # 00シートに書いた件数が実データと合っていること
    t = _tally(SETSUMON, 4)
    assert t.get(C_OK) == 15 and t.get(C_COND) == 18 \
        and t.get(C_NG) == 4 and t.get(C_NONE) == 11, \
        f"04シートの判定の内訳が00シートの記載と合いません: {t}"
    t = _tally(SHISAKU, 8)
    assert t.get(C_OK) == 4 and t.get(C_COND) == 2 \
        and t.get(C_NG) == 1 and t.get(C_NONE) == 2, \
        f"01シートの判定の内訳が想定と異なります: {t}"
    t = _tally(SEIKA, 6)
    assert t.get(C_OK) == 2 and t.get(C_COND) == 3 \
        and t.get(C_NG) == 2 and t.get(C_NEW) == 1, \
        f"02シートの判定の内訳が想定と異なります: {t}"

    for name, data, col in (("SHISAKU", SHISAKU, 8), ("SEIKA", SEIKA, 6),
                            ("OTHERS", OTHERS, 4), ("SETSUMON", SETSUMON, 4)):
        got = {rec[col] for rec in data}
        unknown = got - set(CMP_FILL)
        assert not unknown, f"{name} に未定義の判定: {unknown}"
    ids = [s[0] for s in SHISAKU]
    assert len(ids) == len(set(ids)), "施策目標の番号が重複しています"
    assert len(SHISAKU) == 9, "第4次計画の目標値は本編に9か所（1件は再掲）"
    anq = [s for s in SHISAKU if s[5] == M_ANQ]
    assert len(anq) == 4, "アンケートで測る記載は4か所（K-9はK-5の再掲）"
    assert len({s[2].split("\n")[0] for s in anq}) == 3, "実質的なアンケート指標は3件"
    adm = [s for s in SHISAKU if s[5] == M_ADM]
    assert len(adm) == 5, "行政データで測る指標は5件"
    assert len(SEIKA) == 8, "第8期の成果目標は8区分"
    ids = [t[0] for t in TEISEI]
    assert len(ids) == len(set(ids)), "訂正の番号が重複しています"
    # 再掲の整合
    assert SHISAKU[8][2].endswith("（「生涯学習施策の充実」の目標値の再掲）"), \
        "K-9は再掲であることを明記する"


