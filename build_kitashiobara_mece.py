def anq_cross():
    """問27-1（現在利用）×問27-3（今後3年の利用希望）のクロスを数える。

    マニュアル P.26〜27（参考）手順Ⅱの手続をそのまま行う。
    複数回答のため、分母は両設問のいずれかに1つ以上選択した回答者とする。
    空欄は「選択しなかった」と「設問に答えなかった」の区別が付かないため、
    どちらの設問にも1つも選択がない回答者は分母から外す。
    """
    wb = load_workbook(ANQ_ADULT, data_only=True)
    ws = wb["データ"]
    rows = list(ws.iter_rows(values_only=True))
    labels = [("" if v is None else str(v)) for v in rows[2]]

    # 問27-1 と 問27-3 のブロック先頭列を見出し行から求める
    head = [("" if v is None else str(v)) for v in rows[0]]
    base = {}
    for i, h in enumerate(head):
        if h in ("問27-1", "問27-3") and h not in base:
            base[h] = i
    if len(base) != 2:
        raise LookupError(f"問27-1・問27-3の列が見つかりません: {sorted(base)}")
    A, B = base["問27-1"], base["問27-3"]
    n_opt = 19   # 18サービス＋「特にない」

    def sel(r, b, i):
        return r[b + i] not in (None, "", 0)

    def answered(r, b):
        return any(sel(r, b, i) for i in range(n_opt))

    data = rows[4:]
    both = [r for r in data if answered(r, A) and answered(r, B)]

    out = []
    inc = dec = 0
    for i in range(n_opt):
        name = labels[A + i]
        if "特にない" in name:
            continue
        now = sum(1 for r in both if sel(r, A, i))
        fut = sum(1 for r in both if sel(r, B, i))
        keep = sum(1 for r in both if sel(r, A, i) and sel(r, B, i))
        up = sum(1 for r in both if not sel(r, A, i) and sel(r, B, i))
        dn = sum(1 for r in both if sel(r, A, i) and not sel(r, B, i))
        inc += up
        dec += dn
        out.append((name, ANQ_MAP.get(name, "―"), now, fut, keep, up, dn))
    wb.close()
    return out, len(both), len(data), inc, dec


