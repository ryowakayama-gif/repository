# 対応状況の実地検出
#
# 指摘を直したあとに本チェックを回し直すと、直った指摘が「対応済み」に変わる。
# 「未対応」と書いた文字列を人が書き換える運用にすると実態とずれるため、
# 機械で確かめられるものは必ず現物を見て決める。
# ============================================================
def detect_state():
    """機械で確かめられる指摘の現在の状態を返す。"""
    st = {}

    # X-1 廃止区分「医療型児童発達支援」が共通定義に残っているか
    from kitashiobara_common import SERVICES_ADULT, SERVICES_CHILD
    st["X-1"] = ("未対応" if any(s[0] == "医療型児童発達支援" for s in SERVICES_CHILD)
                 else "対応済み")

    # E-10 短期入所（医療型）が個別積上げの対象に入っているか
    st["E-10"] = ("対応済み" if any("短期入所（医療型）" == s[0] for s in SERVICES_ADULT)
                  else "未対応")

    d = docx.Document(SUAN)

    # X-3 就労定着支援の単位が人／月なのに人日が残っているか
    st["X-3"] = "対応済み"
    for t in d.tables:
        for row in t.rows:
            c = [x.text.strip().replace("\n", "/") for x in row.cells]
            if c and c[0] == "就労定着支援" and len(c) > 3:
                if c[1] == "人／月" and "人日" in "".join(c[2:]):
                    st["X-3"] = "未対応"

    # 注記は網掛けの1セル表として入るため、段落と表のセルの両方を見る
    kijutsu = "\n".join(
        [p.text for p in d.paragraphs]
        + [c.text for t in d.tables for row in t.rows for c in row.cells])

    # X-5 請求件数と月平均利用者数が別の系列であることの注記が素案にあるか
    st["X-5"] = ("対応済み"
                 if ("請求件数を12で割った数" in kijutsu
                     and "一致しません" in kijutsu)
                 else "未対応")

    # X-2 どちらの系列が本計画の見込量かを素案が明示しているか
    st["X-2"] = ("対応済み"
                 if ("本計画の見込量とする" in kijutsu
                     and "第２次算定の方法" in kijutsu)
                 else "未対応")

    # E-11 地域生活支援事業の号番号
    src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "build_kitashiobara_chiiki.py"), encoding="utf-8").read()
    seikai = [("日常生活用具給付等事業", "第7号"), ("手話奉仕員養成研修事業", "第8号"),
              ("移動支援事業", "第9号"), ("地域活動支援センター機能強化事業", "第10号")]
    ok = all(f"法第77条第1項{num}" in src for _n, num in seikai)
    st["E-11"] = "対応済み" if ok else "未対応"

    # 残りは村・県の回答又は本文の判断を要するもの
    for k in ("E-1", "E-2", "E-3", "E-4", "E-5", "E-6", "E-7", "E-8", "E-9",
              "X-4", "X-8"):
        st.setdefault(k, "未対応")
    return st


