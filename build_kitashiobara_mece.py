def chiiki_live():
    """本村資料に現に書かれている号番号を読み、正しい号と突き合わせる。

    直したあとに本チェックを回すと「一致」に変わる。表に書いた文字列を
    人が書き換える運用にしないため、現物から読む。
    """
    src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "build_kitashiobara_chiiki.py"), encoding="utf-8").read()
    out = []
    for seikai, name, _kizai, _itchi, jokyo in E_CHIIKI:
        if seikai == "第3項":
            out.append((seikai, name, "法第77条第3項",
                        "一致" if f'"{name.split("（")[0]}", "法第77条第3項"' in src
                        or "法第77条第3項" in src else "ずれ", jokyo))
            continue
        # 事業名に付いている号を拾う。本村資料は日常生活用具を6区分に分けて行を立て、
        # 相談支援事業を「障がい者相談支援事業」と呼んでいるため、
        # 区分の括弧と「障がい者」「障害者」の冠は許す。
        pat = re.compile(
            r'"(?:障がい者|障害者)?' + re.escape(name)
            + r'(?:（[^"）]*）)?", "法第77条第1項(第\d+号)"')
        hits = sorted({m.group(1) for m in pat.finditer(src)})
        kizai = "／".join(f"法第77条第1項{h}" for h in hits) if hits else "記載なし"
        itchi = "一致" if hits == [seikai] else "ずれ"
        out.append((seikai, name, kizai, itchi, jokyo))
    return out


