def run_checks(cross, both_n, inc, dec):
    """書いた内容が材料と合っているかを確かめる。合わなければ終了コード1。"""
    ng = []

    # 1 別表第一 二〜五の市町村分（告示の事項数）
    if len(E_ADULT) != 23:
        ng.append(f"02シートの行数が23でない: {len(E_ADULT)}")
    if len(E_CHILD) != 8:
        ng.append(f"03シートの行数が8でない: {len(E_CHILD)}")

    # 2 02シートの判定の内訳が注記と合っているか
    tally = {}
    for rec in E_ADULT:
        tally[rec[4]] = tally.get(rec[4], 0) + 1
    if (tally.get("網羅"), tally.get("一部"), tally.get("位置づけ要整理")) != (17, 5, 1):
        ng.append(f"02シートの判定内訳が注記（網羅17・一部5・要整理1）と違う: {tally}")

    # 3 見込量算定ブックのサービス数と02・03シートの対応
    import runpy
    mod = runpy.run_path(os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "build_kitashiobara_mikomiryo.py"), run_name="_mece_check")
    n_adult = len(mod["ADULT_PLAN"])
    n_child = len(mod["CHILD_PLAN"])
    if n_adult != 22:
        ng.append(f"ADULT_PLANが22件でない: {n_adult}")
    if n_child != 5:
        ng.append(f"CHILD_PLANが5件でない: {n_child}")
    # 02シートのうち拠点等（活動指標）を除くとADULT_PLANと同数になる
    n_02_svc = sum(1 for rec in E_ADULT if rec[4] != "位置づけ要整理")
    if n_02_svc != n_adult:
        ng.append(f"02シートのサービス数({n_02_svc})とADULT_PLAN({n_adult})が合わない")

    # 4 地域生活支援事業の号番号は、正しい号が第1号から第10号まで欠けずに並ぶこと
    #   （本村資料のずれの数は実地で変わるため、ここでは正解側の網羅を確かめる）
    live = chiiki_live()
    zure = [r for r in live if r[3] == "ずれ"]
    hissu = [r[0] for r in E_CHIIKI if r[0] != "第3項"]
    want = [f"第{i}号" for i in range(1, 11)]
    if hissu != want:
        ng.append(f"必須事業の号が第1号〜第10号で並んでいない: {hissu}")

    # 5 アンケートのクロスが18サービスあり、増減の合計が行の合計と一致すること
    if len(cross) != 18:
        ng.append(f"08シートのクロスが18行でない: {len(cross)}")
    if sum(c[5] for c in cross) != inc or sum(c[6] for c in cross) != dec:
        ng.append("08シートの増加要素・減少要素の合計が行の合計と合わない")
    # 継続＋増加＝今後、継続＋減少＝現在 が各行で成り立つこと
    for name, _svc, now, fut, keep, up, dn in cross:
        if keep + up != fut or keep + dn != now:
            ng.append(f"08シートの整合が崩れている: {name} "
                      f"現在{now} 今後{fut} 継続{keep} 増{up} 減{dn}")

    # 6 指摘一覧に02・03・06・07シートの指摘番号が残らず載っていること
    # X-6〜X-8のうち「適正」と判定したものは指摘ではないため対象から外す。
    # 他のシートの本文から参照されていても、指摘一覧には載らないのが正しい。
    seitou = {rec[0] for rec in X_ROWS if rec[2] == OK and rec[0] not in
              {s[0] for s in SHITEKI}}
    ids = {s[0] for s in SHITEKI}
    ref = set()
    for recs in (E_ADULT, E_CHILD, E_CHIIKI, E_FUKA):
        for rec in recs:
            ref |= set(re.findall(r"[EX]-\d+", " ".join(str(x) for x in rec)))
    for rec in X_ROWS:
        if rec[2] != OK:
            ref.add(rec[0])
    missing = sorted(ref - ids - seitou)
    if missing:
        ng.append(f"指摘一覧に載っていない番号がある: {missing}")

    # 7 計画素案の見込量表が27行あること（02・03シートの前提）
    d = docx.Document(SUAN)
    rows_found = 0
    for t in d.tables:
        head = [c.text.strip().replace("\n", "") for c in t.rows[0].cells]
        if head[:2] == ["サービス種別", "単位"]:
            rows_found += len(t.rows) - 1
    if rows_found != 27:
        ng.append(f"計画素案の見込量表の行数が27でない: {rows_found}")

    # 8 対応状況が「対応済み」「未対応」のいずれかで、指摘の全件に付いていること
    state = detect_state()
    for s in SHITEKI:
        v = state.get(s[0])
        if v not in ("対応済み", "未対応"):
            ng.append(f"対応状況が決まっていない指摘がある: {s[0]}={v}")

    # 9 村・県の回答を待つ指摘が「対応済み」になっていないこと
    #   （こちらの判断だけで閉じられない指摘を、取り違えて閉じないための歯止め）
    machi = ["E-1", "E-2", "E-4", "E-5", "E-6", "X-8"]
    for k in machi:
        if state.get(k) == "対応済み":
            ng.append(f"{k}は村又は県の回答を待つ指摘であり、"
                      f"当方の判断だけで対応済みにはできない")

    if ng:
        print("自己点検 不合格:")
        for m in ng:
            print("  -", m)
        return False
    print(f"自己点検: 合格　"
          f"別表第一 二〜五 {len(E_ADULT)}事項／六 {len(E_CHILD)}事項／"
          f"地域生活支援事業 {len(E_CHIIKI)}事業（号番号のずれ{len(zure)}）／"
          f"算定方法 {len(E_HOUHOU)}／付加要件 {len(E_FUKA)}／"
          f"排他性 {len(X_ROWS)}／クロス {len(cross)}行／指摘 {len(SHITEKI)}件")
    return True


