def shogai_text():
    import docx
    if not os.path.exists(SHOGAI_SUAN):
        raise SystemExit(f"障がい計画の素案が見つかりません: {SHOGAI_SUAN}")
    d = docx.Document(SHOGAI_SUAN)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for row in t.rows:
            out += [c.text for c in row.cells]
    return "\n".join(out)


