def verify(counts, shogai, kaigo, genko):
    ng = []

    # 1 介護保険の素案に障がい福祉を指す語がないこと（結論の裏づけ）
    for kw in ("障害福祉", "障がい福祉", "適用除外", "共生型", "受給者証",
               "新高額障害福祉"):
        if counts[kw][1] != 0:
            ng.append(f"介護保険の素案に「{kw}」が{counts[kw][1]}件あります。"
                      "結論と05シートを書き直してください")

    # 2 障がい計画の素案に、書いたとした事項が実在すること
    for need in ("介護保険に相当するサービスがあるもの",
                 "介護保険に相当するサービスがないもの",
                 "新高額障害福祉サービス等給付費", "特定疾病", "共生型",
                 "障害支援区分２以上"):
        if need not in shogai:
            ng.append(f"障がい計画の素案に見つからない: {need}")

    # 3 障がい計画の素案に「適用除外」がないこと（K-1の前提）
    if "適用除外" in shogai:
        ng.append("障がい計画の素案に「適用除外」があります。K-1を見直してください")

    # 4 02シートの見込量が両計画の現物に実在すること
    for need in ("4人分", "7人分", "12人分", "9人分", "22人分"):
        if need not in shogai:
            ng.append(f"障がい計画の素案に見込量（{need}）が見つからない")
    for need in ("10.3", "40.1", "8.0", "11.9"):
        if need not in kaigo:
            ng.append(f"介護保険の素案に見込量（{need}）が見つからない")

    # 5 第2号被保険者の認定者2〜3人が介護保険の素案に実在すること
    if "第2号被保険者の認定者は各年度2人から3人" not in kaigo:
        ng.append("介護保険の素案に第2号被保険者の認定者2〜3人の記述が"
                  "見つからない。K-2を見直してください")

    # 6 現行計画の判定が実測と合っていること
    if genko.count("介護保険優先") == 0:
        ng.append("現行の障がい計画に「介護保険優先」が見つからない。"
                  "04シートを書き直してください")
    for kw in ("適用除外", "共生型", "受給者証", "特定疾病", "高額障害福祉"):
        if genko.count(kw) != 0:
            ng.append(f"現行の障がい計画に「{kw}」が{genko.count(kw)}件あります。"
                      "04シートを書き直してください")

    # 7 確認事項の番号が既存のM-1〜M-12と重ならないこと
    nums = [r for r in ("M-13", "M-14", "M-15", "M-16", "M-17")]
    if len(nums) != len(set(nums)):
        ng.append(f"確認事項の番号が重複している: {nums}")

    # 8 セルに Markdown の強調が残っていないこと
    for name, rows in (("JUKYUSHA", JUKYUSHA), ("TAIOU", TAIOU),
                       ("TENKEN", TENKEN)):
        for rec in rows:
            for cell in rec:
                if "**" in str(cell):
                    ng.append(f"{name} のセルに ** が残っている")

    # 9 点検の重さが3区分のいずれかであること
    for rec in TENKEN:
        if rec[5] not in ("重大", "重要", "中"):
            ng.append(f"点検の重さが不正: {rec[0]} / {rec[5]}")

    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("  -", x)
        return False
    print(f"自己点検: 合格　介護保険の素案に障がい福祉を指す語が0件であることを"
          f"実測／障がい計画の記載6点と見込量5点を現物で確認／"
          f"介護保険の見込量4点を現物で確認／"
          f"現行計画の判定6点を現物で確認／セルの Markdown 強調0件")
    return True


