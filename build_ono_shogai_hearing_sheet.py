def plan_questions():
    """実施計画書の質問票A・Bから、(番号, 大問, 小問) を読む。"""
    ps = [p.text.strip() for p in docx.Document(str(PLAN)).paragraphs if p.text.strip()]
    out, sheet, big = [], None, None
    for t in ps:
        m = re.match(r"^質問票([A-F])　", t)
        if m:
            sheet = m.group(1)
            continue
        if sheet not in ("A", "B"):
            continue
        m = re.match(r"^([1-9])　(.+)$", t)
        if m:
            big = (m.group(1), m.group(2))
            continue
        m = re.match(r"^（([1-9])）(.+)$", t)
        if m and big:
            out.append(("%s%s-%s" % (sheet, big[0], m.group(1)), big[1], m.group(2)))
    return out


def candidates():
    """対象先の候補。町内の全事業所と、町内にないサービスの田村地方の事業所（公表データ）。"""
    rows = []
    with open(HD.WAM, encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            a = r["事業所住所（市区町村）"]
            if a == HD.ONO:
                rows.append(("優先（町内）", r))
            elif a in HD.TAMURA:
                rows.append(("候補（田村地方）", r))
    return rows


