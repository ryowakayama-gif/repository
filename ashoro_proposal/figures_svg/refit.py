T = '<text class="{c}" x="{x}" y="{y}"{w} text-anchor="{a}" letter-spacing="0">{t}</text>'


def line(c, x, y, t, a="start", w=400):
    return T.format(c=c, x=x, y=y, t=t, a=a,
                    w=f' font-weight="{w}"' if w else "")


def _card09(x, cx, title, rows):
    """09の班カード1枚。幅168px・高さ110pxで組み直す。"""
    out = [f'<line class="s-brand2" x1="{cx}" y1="326" x2="{cx}" y2="346" stroke-width="1.6"/>',
           f'<rect class="f-surfalt s-border" x="{x}" y="346" width="168" height="110" rx="8" '
           f'stroke-width="1.2"/>',
           f'<rect class="f-brandpale" x="{x}" y="346" width="168" height="30" rx="8"/>',
           f'<rect class="f-brandpale" x="{x}" y="366" width="168" height="10" rx="8"/>',
           line("f-brand fs-13_5", cx, 366, title, a="middle", w=700)]
    top = 396 if len(rows) == 3 else 392
    step = 24 if len(rows) == 3 else 18
    for i, t in enumerate(rows):
        out.append(line("f-ink fs-11_5", cx, top + i * step, t, a="middle"))
    return "\n".join(out)


