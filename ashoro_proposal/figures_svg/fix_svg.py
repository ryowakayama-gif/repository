def rebuild_privacy(svg):
    start = svg.index('<rect class="f-brandpale" x="35" y="515"')
    end = svg.index("</svg>")
    top, colw = 515, 561
    parts = [f'<rect class="f-brandpale" x="35" y="{top}" width="1170" height="164" rx="10"/>',
             f'<text class="f-brand fs-16" x="59" y="{top + 32}" font-weight="700" '
             f'text-anchor="start">個人情報保護の措置</text>']
    for i, (label, body) in enumerate(PRIV_ITEMS):
        cx = 59 + (i % 2) * colw
        cy = top + 62 + (i // 2) * 54
        parts.append(f'<rect class="f-accent" x="{cx}" y="{cy - 8}" width="6" height="6" rx="1"/>')
        parts.append(f'<text class="f-brand fs-12_5" x="{cx + 16}" y="{cy}" font-weight="700" '
                     f'text-anchor="start">{label}</text>')
        parts.append(f'<text class="f-ink fs-12_5" x="{cx + 16}" y="{cy + 24}" '
                     f'text-anchor="start">{body}</text>')
    out = svg[:start] + "\n".join(parts) + "\n" + svg[end:]
    return (out.replace('viewBox="0 0 1240 630"', 'viewBox="0 0 1240 700"')
               .replace('<rect class="f-surface" width="1240" height="630"/>',
                        '<rect class="f-surface" width="1240" height="700"/>'))


def apply_typography(svg):
    svg = re.sub(r"font-family:var\(--fig-font,[^)]*\)",
                 f"font-family:var(--fig-font, {FONT_STACK})", svg)
    for token, px in FS_MAP.items():
        svg = re.sub(rf"\.fs-{token}\{{font-size:calc\([\d.]+px",
                     f".fs-{token}{{font-size:calc({px}px", svg)
    return svg


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    shutil.copy(SRC / "bzu-figures.css", OUT / "bzu-figures.css")

    errors = []
    for path in sorted(SRC.glob("*.svg")):
        svg = path.read_text(encoding="utf-8")
        for old, new in EDITS.get(path.name, []):
            if old not in svg:
                errors.append(f"{path.name}: 置換対象が見つかりません → {old[:40]}")
                continue
            svg = svg.replace(old, new)
        for old, new in SOURCE_EDITS.get(path.name, []):
            if old not in svg:
                errors.append(f"{path.name}: 原典突合の置換対象が見つかりません → {old[:40]}")
                continue
            svg = svg.replace(old, new)
        svg = apply_typography(svg)
        for old, new in refit.REFIT.get(path.name, []):
            if old not in svg:
                errors.append(f"{path.name}: 版面調整の対象が見つかりません → {old[:46]}")
                continue
            svg = svg.replace(old, new)
        for old, new in POST_EDITS.get(path.name, []):
            if old not in svg:
                errors.append(f"{path.name}: 座標調整の対象が見つかりません → {old}")
            svg = svg.replace(old, new)
        if path.name == "09_実施体制と品質管理.svg":
            svg = rebuild_privacy(svg)
        (OUT / path.name).write_text(svg, encoding="utf-8")

    import rebuild_01
    (OUT / "01_アンケート調査の全体フロー.svg").write_text(
        apply_typography(rebuild_01.build()), encoding="utf-8")

    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)
    print(f"修正済みSVGを {OUT} に出力（{len(list(OUT.glob('*.svg')))}点）")


if __name__ == "__main__":
    main()
