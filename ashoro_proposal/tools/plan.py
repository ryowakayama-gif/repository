_ids = {name: 900 + i for i, (_, name, _p) in enumerate(TOC)}


def bm(name):
    return _ids[name], f"_Toc_{name}"


def head(name, text):
    i, n = bm(name)
    return R.chapter_heading(text, i, n)


def sub(name, text):
    """新規の（ｎ）小見出し（ブックマーク付き）"""
    i, n = bm(name)
    return R.bookmark(R.subheading(text), i, n)


def resub(name, idx, old, new):
    """既存の小見出しを改題しつつブックマークを付ける"""
    i, n = bm(name)
    return R.bookmark(R.retext(R.BLOCKS[idx], old, new), i, n)


def keepsub(name, idx):
    i, n = bm(name)
    return R.bookmark(R.BLOCKS[idx], i, n)


