ZEN = "０１２３４５６７８９"


def cell_su(v):
    """表のセルの数。整数に近ければ整数、そうでなければ小数1桁。"""
    if isinstance(v, str):
        return v
    if abs(v - round(v)) < 0.05:
        return str(int(round(v)))
    return f"{v:.1f}"


def bun_su(v):
    """本文の数。1桁の整数は全角、2桁以上と小数は半角（正本の作法）。"""
    t = cell_su(v) if not isinstance(v, str) else v
    if re.fullmatch(r"\d", t):
        return ZEN[int(t)]
    return t


