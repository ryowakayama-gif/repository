CELL = re.compile(r"^(.+?)（(.+?)）(.*)$")


def _atai(src, i):
    """出所から値（表に書く字）を出す。i は 0=R6, 1=R7, 2=R8。"""
    if src is None:
        return None
    if src[0] == "資":
        return s23(src[1])["ji6" if i == 0 else "ji7"]
    if src[0] == "台":
        return cell_su(src[1]())
    if src[0] == "―":
        return "―"
    raise ValueError(src)


def _ato_cell(mae, v):
    if v is None:
        return mae
    m = CELL.match(mae)
    if not m:
        raise ValueError(f"表のセルの形が想定と違う: {mae}")
    return f"{v}（{m.group(2)}）{m.group(3)}"


def _hyou_atama(hyou):
    if hyou == "表５-29":
        return ("サービスの種類", "令和６年度", "令和７年度", "令和８年度")
    return ("サービス種別", "単位", "令和６年度", "令和７年度", "令和８年度")


