def _pdf_text():
    import pdfplumber
    with pdfplumber.open(SHIRYO23) as p:
        return "\n".join(pg.extract_text() or "" for pg in p.pages)


def _docx_cells(path):
    from docx import Document
    d = Document(path)
    out = []
    for t in d.tables:
        hdr = tuple(c.text.strip() for c in t.rows[0].cells)
        rows = [tuple(c.text for c in r.cells) for r in t.rows]
        out.append((hdr, rows))
    return out


def _docx_paras(path):
    from docx import Document
    return [p.text for p in Document(path).paragraphs]


def _norm(t):
    return re.sub(r"[\s　]+", "", t)


def _gyou(tables, rec):
    """表頭と行の頭（サービス種別・単位）で行を1つに絞る。"""
    hits = []
    for hdr, rows in tables:
        if hdr[:len(rec["atama"])] != rec["atama"]:
            continue
        for r in rows[1:]:
            head = (r[0], r[1]) if rec["tani"] else (r[0],)
            want = (rec["svc"], rec["tani"]) if rec["tani"] else (rec["svc"],)
            if head == want:
                hits.append(r)
    return hits


def kensa(pdf, tables_mae, paras_mae, tables_ato=None, paras_ato=None):
    """検査の本体。否定試験で同じ関数を壊した入力に当てる。"""
    ng = []
    pdf_n = _norm(pdf)
    # ① 資料２－３の行が原典に実在すること
    for k, line in S23.items():
        if _norm(line) not in pdf_n:
            ng.append(f"① 資料２－３に無い行: {k}")
    # ② 直す前のセルが他メンバー版の表にちょうど1行あること
    for rec in DK_HYOU:
        hits = _gyou(tables_mae, rec)
        if len(hits) != 1:
            ng.append(f"② 行が一意でない（{len(hits)}行）: {rec['no']}")
            continue
        n = 1 if rec["tani"] is None else 2
        if tuple(hits[0][n:n + 3]) != rec["mae"]:
            ng.append(f"② 直す前の値が違う: {rec['no']} "
                      f"{hits[0][n:n + 3]} ≠ {rec['mae']}")
    # ③ 直す前の評価の文が他メンバー版にちょうど1つあること
    for rec in DK_KAKIKAE:
        c = sum(1 for p in paras_mae if _norm(p) == _norm(rec["mae"]))
        if c != 1:
            ng.append(f"③ 直す前の文が一意でない（{c}件）: {rec['no']}")
    # ⑤ 正本（移植後）に直した後の値・文・注記が入っていること
    if tables_ato is not None:
        for rec in DK_HYOU:
            hits = _gyou(tables_ato, rec)
            n = 1 if rec["tani"] is None else 2
            if len(hits) != 1 or tuple(hits[0][n:n + 3]) != rec["ato"]:
                ng.append(f"⑤ 正本の値が直っていない: {rec['no']}")
        ato = _norm("\n".join(paras_ato))
        for rec in DK_KAKIKAE:
            if _norm(rec["ato"]) not in ato:
                ng.append(f"⑤ 正本の文が直っていない: {rec['no']}")
            if _norm(rec["mae"]) in ato:
                ng.append(f"⑤ 正本に直す前の文が残っている: {rec['no']}")
        cells = _norm("\n".join(c for _h, rows in tables_ato
                                for r in rows for c in r))
        for rec in DK_EDITS:
            if _norm(rec["nakami"][0][1]) not in cells:
                ng.append(f"⑤ 正本に注記が無い: {rec['no']}")
    return ng


def verify():
    ng = []
    pdf = _pdf_text()
    t_mae = _docx_cells(MEMBER)
    p_mae = _docx_paras(MEMBER)
    have = os.path.exists(HONPON)
    t_ato = _docx_cells(HONPON) if have else None
    p_ato = _docx_paras(HONPON) if have else None
    ng += kensa(pdf, t_mae, p_mae, t_ato, p_ato)

    # ④ 集計値の表に、利用者・事業所の名が入り込んでいないこと。
    #    列・種別・事業の名・備考の形を許したものだけに限る。
    with open(DAICHO, encoding="utf-8") as fh:
        rd = csv.reader(fh)
        hdr = next(rd)
        if hdr != ["kind", "jigyo", "nendo", "tsuki", "ninzu", "nissu",
                   "kingaku", "biko"]:
            ng.append(f"④ 集計値の列が想定と違う: {hdr}")
        for r in rd:
            if r[0] not in KIND_OK:
                ng.append(f"④ 種別が想定外: {r[0]}")
            if r[1] not in JIGYO_OK:
                ng.append(f"④ 事業の名が想定外: {r[1]}")
            if not BIKO_OK.match(r[7]):
                ng.append(f"④ 備考が想定外: {r[7]}")
            for v in r[2:7]:
                if v and not re.fullmatch(r"-?\d+(\.\d+)?", v):
                    ng.append(f"④ 数の欄に数でないもの: {v}")

    # ⑥ 資料２－３と台帳が大きく食い違わないこと（年度を通して読める
    #    令和７年度で、月平均の利用者数の差が1人以内）
    for j, key in (("居宅介護", "居宅介護/人"), ("生活介護", "生活介護/人"),
                   ("就労継続支援Ｂ型", "Ｂ型/人"),
                   ("共同生活援助", "共同生活援助"),
                   ("施設入所支援", "施設入所支援")):
        a = float(s23(key)["ji7"])
        b = heikin(ROWS, j, 7, "ninzu")
        if abs(a - b) > 1.0:
            ng.append(f"⑥ 資料２－３と台帳の差が大きい: {j} {a}／{b:.1f}")
    if _stoma(6) != int(s23("排泄管理")["ji6"]):
        ng.append("⑥ 排泄管理支援用具の令和６年度が資料２－３と合わない"
                  "（台帳の読み方を誤っている）")

    # ⑦ 地域活動支援センターの日数の切れ目が実在すること（2倍以上）
    a, b = _chikatsu_hi()
    if b < 2 * a:
        ng.append(f"⑦ 地域活動支援センターの日数の増え方が文と合わない: {a}→{b}")

    # ⑧ 本文の書き換えに表記の作法の違反が無いこと
    for rec in DK_KAKIKAE + [dict(no=r["no"], ato=r["nakami"][0][1])
                             for r in DK_EDITS]:
        t = rec["ato"]
        if re.search(r"令和[0-9]年", t) or "%" in t or "〜" in t:
            ng.append(f"⑧ 表記の作法: {rec['no']}")
        if re.search(r"(?<![0-9.])[0-9](?![0-9.])(人|件|日|か月|月)", t):
            ng.append(f"⑧ 1桁の数が半角: {rec['no']}")

    # ⑨ 照会の番号が他の生成器と重ならないこと（新しい番号であること）
    import glob
    for no, *_r in SHOUKAI:
        for f in glob.glob(os.path.join(os.path.dirname(
                os.path.abspath(__file__)), "build_kitashiobara_*.py")):
            if f.endswith("mura_daicho.py") or f.endswith("shoukai_bun.py") \
                    or f.endswith("kakunin_kubun.py"):
                continue
            if f'("{no}"' in open(f, encoding="utf-8").read():
                ng.append(f"⑨ 照会番号が既にある: {no}（{os.path.basename(f)}）")

    # 否定試験 62〜64（検査が壊れた入力を落とすこと）
    if not kensa(pdf.replace("30.25", "30.52"), t_mae, p_mae):
        ng.append("否定試験62: 資料２－３の値を変えても①が落ちない")
    bad_t = [(h, [tuple(c.replace("38（40）", "39（40）") for c in r)
                  for r in rows]) for h, rows in t_mae]
    if not kensa(pdf, bad_t, p_mae):
        ng.append("否定試験63: 直す前の値を変えても②が落ちない")
    if not kensa(pdf, t_mae, p_mae + [DK_KAKIKAE[0]["mae"]]):
        ng.append("否定試験64: 直す前の文が二つあっても③が落ちない")

    if ng:
        print("自己点検 不合格:")
        for e in ng:
            print("   -", e)
        raise SystemExit(1)
    return (f"資料２－３の{len(S23)}行が原典に実在／表{len(DK_HYOU)}行・"
            f"文{len(DK_KAKIKAE)}段落の直す前が他メンバー版に一意／"
            + ("正本に反映済み／" if have else "正本は未生成／")
            + "集計値に名が無い／資料２－３と台帳の差1人以内／否定試験3件")


