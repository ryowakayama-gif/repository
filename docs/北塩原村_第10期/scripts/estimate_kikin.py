# -*- coding: utf-8 -*-
"""介護給付費準備基金の取崩額を変えたときの第10期・第11期の保険料（WBS Ⅱ-64）

   国の推計ワークシート（将来推計総括表）を正本とする。
   当方が提供を受ける前に算定していた3案（A案6,756円・B案6,054円・C案【要算定】）は
   当方の算定ベースであり、国の算定ベースでは取崩なしが6,610.55円である。
   差は145円にとどまるが、第9期の条例基準額6,700円との向きが逆になる。

   【第11期の扱い】
   国の中長期シートは第11期を令和12年度の単年で立てている（KI_NENDO）。
   保険料は期を通じて同一に定めるため、残高を第11期に充てる効きは
   「3か年の分母で割った値」である。シートの取崩額の欄に残高をそのまま入れると
   単年の分母で割られ、3倍大きく出る。これはシートの作りによるもので、
   期の保険料の姿ではない。本スクリプトは3か年に均した値を本体とし、
   単年基準の値を「シートに機械的に入れた場合」として併記する。

   【第11期の分母の組み方と、その確かめ】
   様式は第11期の所得段階別加入割合補正後被保険者数を持たないため、
   令和12年度の第1号被保険者数×所得段階別加入割合補正係数×12か月×予定保険料収納率
   で組む。同じ組み方で第10期の分母を復元して、ワークシートの値と比べることで
   組み方の当否を確かめる（reconstruct() が返す差）。

     python3 scripts/estimate_kikin.py
"""
import os
import sys
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import parse_worksheet as W

# 検討する取崩額（円）。国の前提・第9期と同程度・取崩しなしの3点
ANS = (
    ("A案", 0, "基金を取り崩さない"),
    ("B案", 24_000_000, "第9期と同程度に取り崩す"),
    ("C案", 40_000_000, "国の推計ワークシートの前提どおり取り崩す"),
)
DAI9_JOREI = 6700      # 第9期の条例基準額（月額）

# ワークシートの読み取りは1回3〜4秒かかる。素案・委員会資料・点検がそれぞれ
# 呼ぶため、同じ算定を何度も走らせると組立てが目に見えて遅くなる。
# 結果を覚えておく（値は読み取り専用で用いる）。
_MEMO = {}


# 第9期の条例基準額の置き方
#   第9期計画の保険料収納必要額220,613千円÷収納率99.5%÷補正後被保険者数2,733人÷12
#   ＝6,760.6円（ワークシートが持つ第9期の基準額6,760.76円と一致する）に対し、
#   条例は6,700円である。四捨五入なら6,800円になるため、本村の第9期は
#   **百円未満を切り捨てている**。四捨五入を当てると案によって100円ずれるため、
#   第9期の実例に合わせて切捨てを本体とし、四捨五入の値を併記する。
DAI9_SANTEI = 6760.76   # 第9期の算定上の月額（ワークシート）


def jorei(en):
    """算定上の月額を条例上の基準額に直す（第9期の実例による百円未満切捨て）"""
    return int(en // 100) * 100


def jorei_shishagonyu(en):
    """同（百円未満四捨五入）。第9期の実例とは合わないが、一般的とされる扱い"""
    return int(round(en / 100.0)) * 100


def bunbo(nendo):
    """ある年度の分母（補正後被保険者数×12か月×予定保険料収納率。人・月）"""
    if ("bunbo", nendo) in _MEMO:
        return _MEMO[("bunbo", nendo)]
    h = W.ws("第1号被保険者数")[nendo]
    g = W.keisu_nendo()["所得段階別加入割合補正係数"][nendo]
    r = W.keisu()["予定保険料収納率"][0]
    _MEMO[("bunbo", nendo)] = h * g * 12 * r
    return _MEMO[("bunbo", nendo)]


def reconstruct():
    """第10期の分母を2とおりで出し、組み方の当否を確かめる

    返り値 (ワークシートによる分母, 当方の組み方による分母, 差の割合)
    """
    if "rec" in _MEMO:
        return _MEMO["rec"]
    ki = W.hokenryo_ki()
    ws_bunbo = (ki["準備基金取崩額"]["第10期"]
                / ki["準備基金取崩額の影響額"]["第10期"])
    my_bunbo = sum(bunbo(y) for y in ("令和9年度", "令和10年度", "令和11年度"))
    _MEMO["rec"] = (ws_bunbo, my_bunbo, (my_bunbo - ws_bunbo) / ws_bunbo)
    return _MEMO["rec"]


def run():
    if "run" in _MEMO:
        return _MEMO["run"]
    ki = W.hokenryo_ki()
    kk = W.kyufu_ki()
    zan = ki["準備基金の残高（前年度末の見込額）"]["第10期"]
    b10 = reconstruct()[0]                       # 第10期は様式の値で割る
    b11_tan = bunbo("令和12年度")                # 第11期を単年で見た分母
    b11_ki = b11_tan * 3                         # 期の3か年に均した分母
    syu10 = kk["保険料収納必要額（月額）"]["第10期"]   # 取崩なしの第10期
    syu11 = kk["保険料収納必要額（月額）"]["第11期"]   # 取崩なしの第11期（令和12年度）
    out = []
    for nm, x, setsu in ANS:
        nokori = zan - x
        g10 = syu10 - x / b10
        g11_ki = syu11 - nokori / b11_ki
        g11_tan = syu11 - nokori / b11_tan
        out.append({
            "案": nm, "考え方": setsu, "取崩額": x,
            "第10期": g10, "第10期条例": jorei(g10),
            "第10期条例_四捨五入": jorei_shishagonyu(g10),
            "第9期差": jorei(g10) - DAI9_JOREI,
            "残高": nokori,
            "第11期": g11_ki, "第11期条例": jorei(g11_ki),
            "第11期条例_四捨五入": jorei_shishagonyu(g11_ki),
            "第11期単年": g11_tan,
            "第10期比": (g11_ki - g10) / g10 * 100,
            # 残高が吸収できる推計の誤差（第10期の分母で月額に換算した緩衝力）
            "緩衝": nokori / b10,
        })
    _MEMO["run"] = (out, zan, b10, b11_tan, b11_ki, syu10, syu11)
    return _MEMO["run"]


def main():
    out, zan, b10, b11_tan, b11_ki, syu10, syu11 = run()
    ws_b, my_b, sa = reconstruct()
    print("■ 介護給付費準備基金の取崩額を変えたときの保険料\n")
    print("  準備基金の残高（令和8年度末の見込額）　%s円" % format(int(zan), ","))
    print("  第10期の分母（様式の取崩額÷影響額）　　%.1f 人・月" % ws_b)
    print("  同　当方の組み方による復元　　　　　　 %.1f 人・月（差 %+.2f%%）"
          % (my_b, sa * 100))
    print("  第11期（令和12年度）の分母　単年 %.1f ／ 3か年 %.1f 人・月"
          % (b11_tan, b11_ki))
    print("  取崩しなしの収納必要額　第10期 %.2f円 ／ 第11期 %.2f円\n" % (syu10, syu11))
    print("  %-4s %-26s %12s %10s %8s %8s %10s %8s"
          % ("案", "考え方", "取崩額", "第10期", "条例", "第9期差", "残高", "第11期"))
    print("  " + "─" * 104)
    for r in out:
        print("  %-4s %-26s %12s %9.2f円 %7s円 %+7d円 %10s %7s円"
              % (r["案"], r["考え方"], format(r["取崩額"], ","),
                 r["第10期"], format(r["第10期条例"], ","), r["第9期差"],
                 format(int(r["残高"]), ","), format(r["第11期条例"], ",")))
    print()
    for r in out:
        print("  %s　第11期は3か年に均すと %.2f円（第10期比 %+.1f%%）、"
              "シートに機械的に入れると %.2f円。"
              "残高が吸収できる推計の誤差は月額 %.0f円分"
              % (r["案"], r["第11期"], r["第10期比"], r["第11期単年"], r["緩衝"]))
    print("\n  ※ 国の推計ワークシートは第11期の取崩額を0としているため、"
          "同シートの第11期の出力は %.2f円である。\n"
          "     C案の第11期 %.2f円は、残高 %s円を第11期に充てた場合の値である。"
          % (syu11, out[2]["第11期"], format(int(out[2]["残高"]), ",")))
    print("  ※ 推計そのものの誤差は絶対値の平均で11.9%（月額約700円）あり"
          "（素案5-4(10)③）、基金はこれを吸収する役割を持つ。")
    print("\n  ※ 条例上の基準額は百円未満切捨てである。"
          "第9期は算定上%.2f円に対し条例6,700円であり、四捨五入（6,800円）では説明できない。" % DAI9_SANTEI)
    for r in out:
        if r["第10期条例"] != r["第10期条例_四捨五入"] or r["第11期条例"] != r["第11期条例_四捨五入"]:
            print("     %s を四捨五入で置くと 第10期 %s円・第11期 %s円（切捨てとは異なる）"
                  % (r["案"], format(r["第10期条例_四捨五入"], ","),
                     format(r["第11期条例_四捨五入"], ",")))
    print("\n  ※ 第11期は国の中長期シートが令和12年度の単年で立てている。"
          "保険料は期を通じて同一に定めるため、\n"
          "     残高を充てる効きは3か年の分母で割った値である。"
          "確実な値はワークシートを操作した再計算による。")


if __name__ == "__main__":
    main()
