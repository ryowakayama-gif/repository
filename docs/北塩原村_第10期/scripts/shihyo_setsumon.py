def setsumon_aru(chosa, ban):
    """その設問がコードブック（shukei_data）に実在するか。"""
    import shukei_data as D
    # N は ("ニーズ", 問, 枝番, …)、Z は ("在宅", 票, 問, …)
    if chosa == "ニーズ":
        return any(r[1] == ban[0] and r[2] == ban[1] for r in D.N)
    return any(r[1] == ban[0] and r[2] == ban[1] for r in D.Z)


def shihyo_anke():
    """素案のうち、アンケート・調査を出所とする指標を拾う。"""
    import soan_content as S
    out = []
    for ch in S.CH:
        for sec in ch["sections"]:
            for b in sec["blocks"]:
                if b["t"] not in ("table", "kpi"):
                    continue
                if "指標" not in str(b["head"][0]):
                    continue
                for r in b["rows"]:
                    if "アンケート" in str(r[-1]):
                        out.append((sec["no"], str(r[0])))
    return out


