def _kakutei_rows():
    """各資料の「確定した事項」の表を集めて、資料2-2の一覧にする。

       手で二重に書くと、資料を直したときに2-2が取り残される。
       ここで組むことで、確定した事項を足せば2-2も自動で増える。
    """
    out = []
    for c in CH:
        for sc in c["sections"]:
            for b in sc["blocks"]:
                if b.get("t") == "table" and b.get("head") == KT_HEAD:
                    for r in b["rows"]:
                        out.append([str(len(out) + 1), r[0],
                                    "%s-%s" % (c["no"], sc["no"].split("-")[-1])])
    return out


def _fill_2_2():
    """資料2-2 の空の表と本文の件数を埋める"""
    rows = _kakutei_rows()
    for c in CH:
        for sc in c["sections"]:
            if sc["no"] != "2-2":
                continue
            for b in sc["blocks"]:
                if b.get("t") == "table" and b.get("head", [None])[0] == "#":
                    b["rows"] = rows
                if b.get("t") == "p" and "骨子を作った時点" in str(b.get("v", "")):
                    b["v"] = KAKUTEI_BUN % (KOSHI_YOKAKUTEI, len(rows))


