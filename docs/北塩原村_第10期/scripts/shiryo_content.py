    MEI = {("推進交付金", "Ⅰ"): "持続可能な地域のあるべき姿をかたちにする",
           ("推進交付金", "Ⅱ"): "公正・公平な給付を行う体制を構築する",
           ("推進交付金", "Ⅲ"): "介護人材の確保その他のサービス提供基盤の整備",
           ("推進交付金", "Ⅳ"): "自立した日常生活（成果指標群）",
           ("支援交付金", "Ⅰ"): "介護予防／日常生活支援を推進する",
           ("支援交付金", "Ⅱ"): "認知症総合支援を推進する",
           ("支援交付金", "Ⅲ"): "在宅医療・在宅介護連携の体制を構築する",
           ("支援交付金", "Ⅳ"): "自立した日常生活（成果指標群）"}
    Y = ["令和6年度", "令和7年度", "令和8年度"]
    out, tot = _mokuhyo_suii()

    def zogen(d):
        return "＋%.0f" % d if d > 0 else ("▲%.0f" % -d if d < 0 else "±0")

    rows = []
    for kind in ("推進交付金", "支援交付金"):
        for k, t, v, _h in out:
            if k != kind:
                continue
            rows.append(["%s 目標%s　%s" % (kind[:2], t, MEI[(k, t)])]
                        + ["%.0f" % v[y] for y in Y] + [zogen(v[Y[2]] - v[Y[0]])])
        c = [tot[(kind, y)] for y in Y]
        rows.append(["%s 計（400点）" % kind[:2]] + ["%.0f" % x for x in c]
                    + [zogen(c[2] - c[0])])
    g = [sum(tot[(k, y)] for k in ("推進交付金", "支援交付金")) for y in Y]
    rows.append(["合計（800点）"] + ["%.0f" % x for x in g] + [zogen(g[2] - g[0])])
    return rows

