def _numbered():
    """並び順から章ごとの連番を振り、番号付きの表題にして返す。"""
    seq = {}
    out = []
    for e in _FIGS:
        key, fn, title, src = e[0], e[1], e[2], e[3]
        inline = bool(e[4]) if len(e) > 4 else False
        ch = key.split("|")[0]           # 「第2章」
        no = ch.replace("第", "").replace("章", "")   # 「2」
        seq[ch] = seq.get(ch, 0) + 1
        out.append((key, fn, "図%s-%d　%s" % (no, seq[ch], title), src, inline))
    return out


FIGS = _numbered()


def index_rows():
    """資料編の図表番号一覧に載せる行。(図番号, 図表名, 掲載箇所, 出典)"""
    rows = []
    for key, fn, cap, src, _inline in FIGS:
        num, title = cap.split("　", 1)
        ch, sec = key.split("|")
        rows.append([num, title, "%s %s" % (ch, sec), src])
    return rows


