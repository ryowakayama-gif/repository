def naiyou_hash(rev, path):
    """git show <rev>:<path> の sha256 先頭16桁。取り出せなければ None"""
    if not path:
        return None
    try:
        b = subprocess.run(["git", "show", f"{rev}:{path}"],
                           capture_output=True, timeout=60).stdout
    except Exception:
        return None
    if not b:
        return None
    return hashlib.sha256(b).hexdigest()[:16]


def shoumei():
    """記録した内容のハッシュを現物と照合する。ずれを返す"""
    zure = []
    for a in AITE:
        if not a["naiyou"]:
            continue
        ima = naiyou_hash(a["han"], a["path"])
        ok = (ima == a["naiyou"])
        zure.append((f"{a['han']}:{a['path']}", a["naiyou"], ima, ok))
    for m in MIRARETA:
        if not m["naiyou"]:
            continue
        ima = naiyou_hash(m["han"], m["path"])
        ok = (ima == m["naiyou"])
        zure.append((f"{m['han']}:{m['path']}", m["naiyou"], ima, ok))
    return zure


