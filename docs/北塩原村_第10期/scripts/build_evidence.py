def sheet(wb, title, heads, rows, widths, note=None, mark=None):
    ws = wb.create_sheet(title)
    r0 = 1
    if note:
        for ln in note:
            ws.cell(row=r0, column=1, value=ln).font = Font(name=F, size=9)
            r0 += 1
        r0 += 1
    for i, (h, w) in enumerate(zip(heads, widths), 1):
        c = ws.cell(row=r0, column=i, value=h)
        c.font = Font(name=F, size=9, bold=True, color="FFFFFF")
        c.fill = HEAD
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BD
        ws.column_dimensions[c.column_letter].width = w
    for n, row in enumerate(rows, 1):
        for i, v in enumerate(row, 1):
            c = ws.cell(row=r0 + n, column=i, value=v)
            c.font = Font(name=F, size=9)
            c.alignment = Alignment(vertical="top", wrap_text=True)
            c.border = BD
            if mark and mark(row):
                c.fill = MARK
    ws.freeze_panes = ws.cell(row=r0 + 1, column=2)
    return ws


def _docx_text(name):
    import docx
    d = docx.Document(P.out(name + ".docx"))
    return "\n".join("".join(x.text or "" for x in el.iter() if x.tag.endswith("}t"))
                     for el in d.element.body.iter() if el.tag.endswith("}p"))


