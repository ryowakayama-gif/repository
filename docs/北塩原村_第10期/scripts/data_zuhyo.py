def by_name():
    return {d["name"]: d for d in ZU}


_CACHE = {}

def read_book(path=None):
    """台帳のデータシートから数値を読み戻す。{name: [(系列名, 値), ...]}

    同じ台帳を何度も開かないよう、更新時刻を鍵にして覚えておく。
    台帳を直せば更新時刻が変わるため、直した内容は次の呼び出しに効く。
    """
    path = path or BOOK
    if not os.path.exists(path):
        return {}
    key = (path, os.path.getmtime(path), os.path.getsize(path))
    if key in _CACHE:
        return _CACHE[key]
    from openpyxl import load_workbook
    wb = load_workbook(path, read_only=True, data_only=True)
    got = {}
    names = set(by_name())
    for sn in wb.sheetnames:
        nm = sn[2:] if sn.startswith("D_") else sn
        if nm not in names:
            continue
        ws = wb[sn]
        rows = [list(r) for r in ws.iter_rows(min_row=HEAD_ROW, values_only=True)]
        if not rows:
            continue
        head = rows[0]
        ncol = sum(1 for v in head[1:] if v not in (None, ""))
        body = []
        for r in rows[1:]:
            if r[0] in (None, ""):
                break
            body.append(r)
        if not body or ncol == 0:
            continue
        got[nm] = [(head[1 + i], [r[1 + i] for r in body]) for i in range(ncol)]
    wb.close()
    _CACHE.clear()        # 覚えておくのは最後に読んだ1つだけにする
    _CACHE[key] = got
    return got


HEAD_ROW = 5          # データシートの見出し行。台帳の組立てと合わせる


def load(use_book=True, path=None):
    """作図に渡す図の定義を返す。台帳の数値があればそれを優先する。"""
    import copy
    zu = copy.deepcopy(ZU)
    if not use_book:
        return {d["name"]: d for d in zu}
    got = read_book(path)
    for d in zu:
        s = got.get(d["name"])
        if not s:
            continue
        base = d["series"]
        if len(s) != len(base) or any(len(v) != len(base[i][1]) for i, (_, v) in enumerate(s)):
            continue          # 行数・列数が変わっているときは読み戻さない
        # 系列名は本モジュールを正とし、数値のみを差し替える
        d["series"] = [(base[i][0], list(v)) for i, (_, v) in enumerate(s)]
    return {d["name"]: d for d in zu}


def vals(name, series_name, use_book=True):
    """図1本の1系列の値を返す。作図側はこれで引く。"""
    d = load(use_book)[name]
    for n, v in d["series"]:
        if n == series_name:
            return list(v)
    raise KeyError("%s に系列 %s がない" % (name, series_name))


def cats(name, use_book=True):
    return list(load(use_book)[name]["cats"])


