def tarinai():
    """まだ書いていないもの（要反映・確認待ち）"""
    return [x for x in H if x[5] in ("要反映", "確認待ち")]


def kubun():
    k = {}
    for x in H:
        k[x[5]] = k.get(x[5], 0) + 1
    return k


