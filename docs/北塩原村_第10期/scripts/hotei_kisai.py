def tarinai():
    """まだ書いていないもの（要反映・確認待ち）"""
    return [x for x in H if x[5] in ("要反映", "確認待ち")]


def kubun():
    k = {}
    for x in H:
        k[x[5]] = k.get(x[5], 0) + 1
    return k


def main():
    only = "--tarinai" in sys.argv
    if not only:
        print(f"■ 原典　{GENTEN['youkou']}")
        print(f"    {GENTEN['url']}")
        print(f"    手元 {GENTEN['tedoto']}（{GENTEN['hash']}）")
        print(f"    新旧対照条文 {GENTEN['shinkyu']}")
        print(f"      手元 {GENTEN['shinkyu_tedoto']}（{GENTEN['shinkyu_hash']}）"
              "　PDF 91〜95頁で号の並びを確認\n")
        print(f"■ 法が計画に定めることを求めている事項　{len(H)}件")
        print("    " + "／".join(f"{a} {b}件" for a, b in sorted(kubun().items())) + "\n")
        for jo, gi, naka, kai, sek, ats, saki, memo in H:
            mark = "★" if ats != "反映済み" else "  "
            print(f"{mark}{jo}　［{gi}］{'　' + kai if kai else ''}")
            print(f"      {naka[:84]}")
            print(f"      扱い {ats}　該当 {'・'.join(saki)}　施行 {sek}")
            print(f"      {memo[:88]}")
        print()
    w = tarinai()
    print(f"■ まだ書いていないもの　{len(w)}件\n")
    for jo, gi, naka, kai, sek, ats, saki, memo in w:
        print(f"  {jo}　［{gi}］{'　' + kai if kai else ''}　{ats}")
        print(f"      {naka}")
        print(f"      該当させる先 {'・'.join(saki)}　施行 {sek}")
        print(f"      {memo}")
        print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
