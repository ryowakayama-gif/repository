def kubun(dai):
    """その確認事項の区分。掲げていないものはＤ。"""
    return KUBUN.get(dai, ("Ｄ", ""))[0]


def riyu(dai):
    """当方が先行して行うこと。Ｄは空。"""
    return KUBUN.get(dai, ("Ｄ", ""))[1]


MACHI = ("未依頼", "一部回答", "再提起")


def tally():
    """区分ごとの件数。未解決のものだけを数える。"""
    n = {"Ｂ": 0, "Ｃ": 0, "Ｄ": 0}
    for k in _KK.K:
        if k[6] in MACHI:
            n[kubun(k[1])] += 1
    return n


def main():
    print("■ 確認事項の区分　確認事項 %d件（解決済 %d件）\n"
          % (len(_KK.K), len(_KK.SOLVED)))
    n = tally()
    for k, v in KIJUN.items():
        print("  %s　%-34s %3d件" % (k, v, n[k]))
    print("\n  村にご回答をお願いするのはＣ・Ｄの %d件である。" % (n["Ｃ"] + n["Ｄ"]))
    for tag in ("Ｂ", "Ｃ"):
        print("\n── %s　%s ──" % (tag, KIJUN[tag]))
        for k in _KK.K:
            if kubun(k[1]) == tag:
                print("  ・%s" % k[1][:56])
                print("      %s" % riyu(k[1]))
    return 0


