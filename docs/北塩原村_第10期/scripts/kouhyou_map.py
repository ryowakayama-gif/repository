    for (ch, _no), (ss, _m) in MAP.items():
        for s in ss:
            tsukau.append(s)
            uchi.setdefault(ch, []).append(s)
    for ch, _no, _nm, ss, _ne, _k in TSUIKA:
        for s in ss:
            tsukau.append(s)
            uchi.setdefault(ch, []).append(s)
    total = sum(h[s] for s in tsukau)
    # 章見出し7つ（第1〜6章・資料編）と、章の変わり目の改頁6つ
    total += 7 * (300 + 30 * 20)
    n = total / float(EL.BODY_H)
    # 章の変わり目の改頁で平均0.5頁の空きが出ると見込む
    return tsukau, uchi, total, int(n + 6 * 0.5 + 0.999)


