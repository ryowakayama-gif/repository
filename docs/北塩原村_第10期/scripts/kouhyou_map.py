def setsu_h(keikaku=True):
    """協議用素案の節ごとの高さ（twip）。公表用の見積りに使う。

       estimate_layout.soan_items と同じ積み上げを、節ごとに分けて返す。
       keikaku=True は編集注記（note）と5-12を落とした形（公表用はこの形）。
    """
    import estimate_layout as EL
    import estimate_pages as EP
    from figures_map import FIGS
    figs = {}
    for e in FIGS:
        figs.setdefault(e[0], []).append(e[1])
    out = {}
    for ch in SC.CH:
        for sec in ch["sections"]:
            h = 320 + 25 * 20 + 180          # 節見出し
            for fn in figs.get("%s|%s" % (ch["no"], sec["no"]), []):
                _, h_in = EP.fig_in(os.path.join(EP.FIGDIR, fn))
                h += 160 + h_in * 1440 + 60 + 240 + 40 + 220 + 200
            for b in sec["blocks"]:
                if keikaku and b["t"] == "note":
                    continue
                hb = EP.block_h(b)
                if b["t"] in ("table", "kpi"):
                    hb += 160
                h += hb
            out[sec["no"]] = h
    # 節の枝ごとの高さ（例 "5-5(1)" "5-5(2)"）。
    # 協議用5-5のように、公表用で1つの節を2つに分けるものがあるため、
    # 枝それぞれの高さを別に持つ。足すと節まるごとの高さになる（節見出しは1つ）。
    for ch in SC.CH:
        for sec in ch["sections"]:
            eda, ima = {}, None
            for b in sec["blocks"]:
                if b["t"] == "h3":
                    m = re.match(r"^\((\d)\)", str(b.get("v", "")))
                    if m:
                        ima = m.group(1)
                        eda.setdefault(ima, [])
                        continue
                if ima is not None:
                    eda[ima].append(b)
            if len(eda) < 2:
                continue
            for k, bs in eda.items():
                h = 320 + 25 * 20 + 180      # 節見出し（分けても1つ付く）
                for b in bs:
                    if keikaku and b["t"] == "note":
                        continue
                    hb = EP.block_h(b)
                    if b["t"] in ("table", "kpi"):
                        hb += 160
                    h += hb
                out["%s(%s)" % (sec["no"], k)] = h
    return out


