def yohanei():
    """まだ反映していない論点"""
    return [x for x in R if x[3] == "要反映"]


def kubun():
    k = {}
    for x in R:
        k[x[3]] = k.get(x[3], 0) + 1
    return k


def main():
    only = "--yohanei" in sys.argv
    if not only:
        print(f"■ 出所　{SHUTTEN['nm']}（{SHUTTEN['hi']}受領）")
        print(f"    もと {SHUTTEN['moto']}")
        print(f"    ※ {SHUTTEN['chui']}\n")
        print(f"■ 論点と本計画での扱い　{len(R)}件")
        k = kubun()
        print("    " + "／".join(f"{a} {b}件" for a, b in sorted(k.items())) + "\n")
        for i, r, d, a, s, m, y in R:
            mark = "★" if a == "要反映" else "  "
            print(f"{mark}{i}　{r}（{d}）")
            print(f"      扱い {a}　効く節 {'・'.join(s)}")
            print(f"      {m[:96]}")
            if y:
                print(f"      置かない理由 {y[:88]}")
        print()
    w = yohanei()
    print(f"■ まだ反映していないもの　{len(w)}件\n")
    for i, r, d, a, s, m, y in w:
        print(f"  {i}　{r}")
        print(f"      効く節 {'・'.join(s)}")
        print(f"      {m}")
        print()
    if not only:
        print(f"■ 実務対応　{len(P)}件\n")
        for i, nm, st, s, m in P:
            print(f"  {i}　{nm}　[{st}]　{'・'.join(s)}")
            print(f"      {m[:92]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
