FIELDS = ["資料","章","設問番号","設問文","令和7年8月版の対応項目","必須/オプション/村独自",
          "第9期(令和4年8月版)との異同","判定","対応要否・メモ"]
rows = list(csv.DictReader(open("突合ワークシート.csv", encoding="utf-8-sig")))
unmatched = []
for r in rows:
    if r["資料"].startswith("資料B"):
        sec = re.match(r"^(フェイス|問\s?\d+)", r["章"]).group(1).replace(" ", "")
        if sec == "フェイス": sec = "フェイス"
        key = (sec, r["設問番号"])
        if key in B:
            r["令和7年8月版の対応項目"], r["必須/オプション/村独自"] = B[key]
        else:
            unmatched.append((r["資料"][:5], r["章"], r["設問番号"], r["設問文"][:40]))
    else:
        sec = "Ｂ票" if r["章"].startswith("Ｂ票") else "Ａ票"
        key = (sec, r["設問番号"])
        if key in C:
            r["令和7年8月版の対応項目"], r["必須/オプション/村独自"] = C[key]
        elif r["章"].endswith("問９"):
            r["令和7年8月版の対応項目"] = "問9のサービス別利用状況の内訳（手法Ⅲの基本調査項目に該当の可能性）"
            r["必須/オプション/村独自"] = "要確認"
        else:
            unmatched.append((r["資料"][:5], r["章"], r["設問番号"], r["設問文"][:40]))
    # 判定
    std, kind = r["令和7年8月版の対応項目"], r["必須/オプション/村独自"]
    if kind == "必須":
        r["判定"] = "○ 標準様式の必須項目に一致"
    elif kind == "オプション":
        r["判定"] = "○ 標準様式のオプション項目に一致"
    elif kind.startswith("標準"):
        r["判定"] = "○ 標準様式に対応あり"
    elif kind == "要確認":
        r["判定"] = "△ 手法Ⅲの調査票本体で要確認"
    else:
        r["判定"] = "－ 村独自設問（自動集計ソフトの対象外）"
    if "★" in std:
        r["判定"] = "▲ " + r["判定"][2:] + "（注記あり）"

