# -*- coding: utf-8 -*-
"""北塩原村 第10期 保険料算定の構造と感応度

【算定の5式】（国の介護保険事業計画作成支援ツールの構造）
  ① 標準給付費見込額
       ＝ 総給付費 ＋ 特定入所者介護サービス費等 ＋ 高額介護サービス費等
         ＋ 高額医療合算介護サービス費等 ＋ 算定対象審査支払手数料
  ② 第1号被保険者負担分相当額 ＝（① ＋ 地域支援事業費）× α
  ③ 調整交付金相当額         ＝（① ＋ 総合事業費）× 5％
  ④ 保険料収納必要額         ＝ ② ＋ ③ － 調整交付金見込額
  ⑤ 保険料基準額（月額）
       ＝ ④ ÷ 予定保険料収納率 ÷ 所得段階別加入割合補正後被保険者数 ÷ 12
         － 介護給付費準備基金の取崩しによる軽減額

  α は第1号被保険者負担割合。全国の第1号・第2号被保険者数の比に応じ、
  3年の計画期間ごとに政令で定められる。第9期（令和6〜8年度）は23％。
  第10期に適用される政令は本稿の時点で確認できていない。

【調整交付金の見込交付割合】
  見込交付割合 ＝（α ＋ 0.05）－ α × F × G
    F＝後期高齢者加入割合補正係数、G＝所得段階別加入割合補正係数（いずれも全国値の係数による）

【限界率】
  給付費が1円増えたときに保険料収納必要額が増える額は
    α ＋ 0.05 － 見込交付割合 ＝ α × F × G
  である。これを限界率と呼ぶ。感応度はすべてこの率を経由する。
"""
import csv, os

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(BASE, 'data')

# ── 第9期計画の算定結果（第9期計画より。素案5-7に掲載）────────────
K9 = {
    '標準給付費見込額': 939_947_000,      # 3年計
    '地域支援事業費':   92_790_000,       # 3年計
    '調整交付金見込額': 40_600_000,
    '基金取崩額':       24_000_000,
    '保険料収納必要額': 220_613_000,
    '予定収納率':       0.995,
    '補正後被保険者数': 2_733,            # 3年計
    '保険料基準額':     6_700,
    '被保険者数見込':   2_849,            # 3年計（令和6年957・7年950・8年942）
}
ALPHA_K9 = 0.23

# ── 第10期の前提 ───────────────────────────────
# 第1号被保険者数はB案（令和8年度の実績水準に補正）による。doc28・doc29。
INS_10 = {'令和9年': 1_004, '令和10年': 995, '令和11年': 987}
# サービス諸費（介護サービス等諸費＋介護予防サービス等諸費）。doc30。
SVC_10 = {'令和9年': 263_470_000, '令和10年': 263_505_000, '令和11年': 262_488_000}
# 補助給付等（令和5年度決算。特定入所者＋高額介護＋高額医療合算＋審査支払手数料）
HOJO_R5 = 14_495_976 + 6_768_762 + 0 + 252_189
# 地域支援事業費（令和5年度決算）
CHIIKI_R5 = 39_885_993
# 総合事業費（令和5年度決算。介護予防・生活支援サービス事業費＋一般介護予防事業費）
SOGO_R5 = 14_637_340 + 1_825_335


def main():
    out = []
    p = out.append

    # ── 所得段階別加入割合補正係数 ──────────────────
    g_k9 = K9['補正後被保険者数'] / K9['被保険者数見込']
    p('■ 所得段階別加入割合補正係数（G）')
    p(f'  第9期計画から復元：{K9["補正後被保険者数"]:,}人 ÷ {K9["被保険者数見込"]:,}人 = {g_k9:.5f}')
    p('  第10期の標準段階数・標準乗率は政令の改正により定まるため、暫定的に第9期の値を用いる。')

    # ── 分母 ────────────────────────────
    ins3 = sum(INS_10.values())
    hosei3 = ins3 * g_k9
    denom = hosei3 * 12 * K9['予定収納率']
    p('')
    p('■ 分母（人・月）')
    p(f'  第1号被保険者数（3年計・B案）　　　　{ins3:,}人')
    p(f'  所得段階別加入割合補正後　　　　　　{hosei3:,.0f}人')
    p(f'  × 12か月 × 予定収納率{K9["予定収納率"]:.3f}　　{denom:,.0f}人・月')

    # ── 限界率 ───────────────────────────
    p('')
    p('■ 限界率（給付費1円の増が保険料収納必要額を増やす額）')
    lo, hi = None, None
    for lab, sogo3 in [('総合事業費を0とした場合', 0),
                       ('総合事業費＝令和5年度決算×3年', SOGO_R5 * 3)]:
        rate_kofu = K9['調整交付金見込額'] / (K9['標準給付費見込額'] + sogo3)
        marginal = ALPHA_K9 + 0.05 - rate_kofu
        p(f'  {lab}：見込交付割合 {rate_kofu*100:.2f}％ → 限界率 {marginal*100:.2f}％')
        lo = marginal if lo is None else min(lo, marginal)
        hi = marginal if hi is None else max(hi, marginal)
    marginal = (lo + hi) / 2
    p(f'  → 第9期から復元した限界率は {lo*100:.2f}〜{hi*100:.2f}％。以下は中位の {marginal*100:.2f}％を用いる。')

    # ── 標準給付費見込額（第10期） ──────────────────
    svc3 = sum(SVC_10.values())
    hyojun3 = svc3 + HOJO_R5 * 3
    chiiki3 = CHIIKI_R5 * 3
    p('')
    p('■ 標準給付費見込額（第10期・暫定）')
    p(f'  サービス諸費（3年計）　　　　　　　{svc3:,}円　（doc30）')
    p(f'  補助給付等　令和5年度決算{HOJO_R5:,}円 × 3年　{HOJO_R5*3:,}円')
    p(f'  標準給付費見込額（①）　　　　　　　{hyojun3:,}円')
    p(f'  地域支援事業費（3年計）　　　　　　{chiiki3:,}円　（令和5年度決算×3年）')

    # ── 第9期の再現（式の検算） ─────────────────
    p('')
    p('■ 第9期の再現（5式の検算）')
    fg_k9 = marginal / ALPHA_K9
    sogo_k9 = SOGO_R5 * 3          # 第9期計画に総合事業費の明示がないため令和5年度決算×3年で代用
    maru2 = (K9['標準給付費見込額'] + K9['地域支援事業費']) * ALPHA_K9
    maru3 = (K9['標準給付費見込額'] + sogo_k9) * 0.05
    kofu = (K9['標準給付費見込額'] + sogo_k9) * ((ALPHA_K9 + 0.05) - ALPHA_K9 * fg_k9)
    maru4 = maru2 + maru3 - kofu - K9['基金取崩額']
    p(f'  ② 第1号被保険者負担分相当額　（①{K9["標準給付費見込額"]:,}＋地域支援{K9["地域支援事業費"]:,}）×23％ ＝ {maru2:,.0f}円')
    p(f'  ③ 調整交付金相当額　　　　　（①＋総合事業費{sogo_k9:,}）×5％ ＝ {maru3:,.0f}円')
    p(f'  　 調整交付金見込額（式による）　　　　　　　　　　　　　　 ＝ {kofu:,.0f}円'
      f'（計画の記載値 {K9["調整交付金見込額"]:,}円）')
    p(f'  ④ 保険料収納必要額　②＋③－見込額－基金取崩{K9["基金取崩額"]:,} ＝ {maru4:,.0f}円')
    p(f'  　 第9期計画の記載値 {K9["保険料収納必要額"]:,}円との差 '
      f'{maru4 - K9["保険料収納必要額"]:+,.0f}円（{(maru4/K9["保険料収納必要額"]-1)*100:+.2f}％）')
    p('  総合事業費を令和5年度決算で代用しているため完全一致はしないが、0.3％以内で再現できる。')
    p('  第9期計画本文（②③の内訳と総合事業費）の受領後に完全一致まで詰める。')

    # ── 感応度 ───────────────────────────
    def yen(delta_kyufu):
        """給付費（①または地域支援事業費）の増分が月額に効く額"""
        return delta_kyufu * marginal / denom

    rows = []
    rows.append(('給付費の水準が1％上振れ', hyojun3 * 0.01, None))
    rows.append(('令和9年度の介護報酬改定が＋1％', hyojun3 * 0.01, '単価の改定は給付費にそのまま乗る'))
    rows.append(('地域支援事業費を算入しない場合の差', chiiki3, '②の算定基礎に含まれる'))
    rows.append(('通所介護の受給者が1人／月増', 74_026 * 12 * 3, '1人あたり給付月額74,026円（doc30）'))
    rows.append(('施設サービスの受給者が1人／月増', 301_000 * 12 * 3, '施設の1人あたり給付月額は約30万円'))
    rows.append(('グループホームの受給者が1人／月増', 216_000 * 12 * 3, '同 約22万円'))

    p('')
    p('■ 感応度（保険料基準額 月額への効き）')
    p(f'  {"項目":<34}{"給付費等の増減":>18}{"月額":>10}')
    for lab, d, note in rows:
        p(f'  {lab:<34}{d:>16,.0f}円{yen(d):>9.0f}円' + (f'　{note}' if note else ''))

    # 第1号被保険者負担割合
    p('')
    p('■ 第1号被保険者負担割合（α）の感応度')
    p('  αは政令で3年ごとに定められる。第1期17％から第9期23％まで1ポイントずつ上がってきた。')
    p('  αが上がると②が増える一方、見込交付割合も（α＋0.05）－α×F×G により上がるため、')
    p('  増え方は1ポイントあたり一定ではない。ここでは限界率＝α×F×G の形で計算する。')
    fg = marginal / ALPHA_K9
    p(f'  第9期から復元した F×G ＝ {fg:.5f}')
    base = None
    for a in (0.23, 0.24, 0.25):
        m = a * fg
        need = (hyojun3 + chiiki3) * a + (hyojun3 + SOGO_R5 * 3) * 0.05 \
            - (hyojun3 + SOGO_R5 * 3) * ((a + 0.05) - m)
        monthly = need / denom
        if base is None:
            base = monthly
        p(f'  α＝{a*100:.0f}％：限界率{m*100:.2f}％　保険料収納必要額{need:,.0f}円　月額{monthly:,.0f}円'
          + (f'（＋{monthly-base:,.0f}円）' if monthly != base else '（基準）'))

    # 基金取崩
    p('')
    p('■ 介護給付費準備基金の取崩しの効き')
    for m_yen in (10_000_000, 20_000_000, 24_000_000):
        p(f'  {m_yen:,}円を取り崩す：月額 ▲{m_yen/denom:,.0f}円')
    p('  第9期計画は24,000,000円の取崩しを見込んでいた（年額か3年計かは確認中。doc22 K-74）。')

    # ── 複数パターンの算定 ──────────────────────
    p('')
    p('■ 保険料基準額のパターン（α×基金取崩×給付費の水準）')
    PAT = []
    for a in (0.23, 0.24):
        for kikin, klab in ((0, '取崩なし'), (24_000_000, '第9期と同額24,000千円')):
            for mul, mlab in ((1.00, '推計どおり'),
                              (1.047, '令和5年度の伸び（+4.7%/年）が続く'),
                              (0.98, '供給制約により2%下振れ')):
                hy = hyojun3 * mul
                ch = chiiki3
                sg = SOGO_R5 * 3
                m = a * fg
                need = (hy + ch) * a + (hy + sg) * 0.05 \
                    - (hy + sg) * ((a + 0.05) - m) - kikin
                PAT.append((a, klab, mlab, need, need / denom))
    p(f'  {"α":<5}{"基金取崩":<22}{"給付費の水準":<30}{"月額":>9}')
    for a, klab, mlab, need, monthly in PAT:
        p(f'  {a*100:<4.0f}%{klab:<22}{mlab:<30}{monthly:>8,.0f}円')
    lo = min(x[4] for x in PAT); hi = max(x[4] for x in PAT)
    p(f'  → 12パターンで {lo:,.0f}円〜{hi:,.0f}円（幅 {hi-lo:,.0f}円）。第9期の条例基準額は6,700円。')

    # 出力
    path2 = os.path.join(DATA, '第10期_保険料パターン.csv')
    with open(path2, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f)
        w.writerow(['第1号被保険者負担割合', '基金取崩', '給付費の水準',
                    '保険料収納必要額(円)', '保険料基準額(月額・円)'])
        for a, klab, mlab, need, monthly in PAT:
            w.writerow([f'{a*100:.0f}%', klab, mlab, round(need), round(monthly)])

    # 出力
    path = os.path.join(DATA, '第10期_保険料感応度.csv')
    with open(path, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f)
        w.writerow(['項目', '給付費等の増減(円)', '月額への効き(円)', '備考'])
        for lab, d, note in rows:
            w.writerow([lab, round(d), round(yen(d), 1), note or ''])
        w.writerow([])
        w.writerow(['分母(人・月)', round(denom)])
        w.writerow(['限界率(%)', round(marginal * 100, 2)])
        w.writerow(['標準給付費見込額 3年計(円)', hyojun3])
    print('\n'.join(out))
    print(f'\n保存: {os.path.relpath(path, BASE)}')
    print(f'保存: {os.path.relpath(path2, BASE)}')


if __name__ == '__main__':
    main()
