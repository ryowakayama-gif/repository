def counts(p, r, b_assume):
    dec = same = up = 0
    for k, v, m, c, cu in RECS:
        if k == 'N':
            n, o = ST.bill(v, m, p), RC.bill(v, m)
        elif k == 'B':
            o = RC.bill(5, 2)
            n = ST.base_bill(p) if p[1] >= 5 else ST.bill(b_assume, 2, p)
        elif k == 'SPH':
            n, o = cu * p[0] / 1008.0, cu
        else:
            n, o = cu * r, cu
        if n < o - 0.5:
            dec += c
        elif n > o + 0.5:
            up += c
        else:
            same += c
    return dec, same, up


def w(fn, rows):
    with io.open(os.path.join(EV, fn), 'w', encoding='utf-8-sig', newline='') as f:
        csv.writer(f).writerows(rows)
    print('written:', fn)


