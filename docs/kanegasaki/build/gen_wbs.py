def sheet(ws, title, head, widths, rows, scol):
    ws['A1'] = title
    ws['A1'].font = Font(name=F, size=13, bold=True)
    ws['A2'] = '金ケ崎町　高齢者福祉計画・第10期介護保険事業計画・認知症施策推進計画　令和8年10月24日現在'
    ws['A2'].font = Font(name=F, size=9)
    for c, (h, w) in enumerate(zip(head, widths), 1):
        x = ws.cell(row=4, column=c, value=h)
        x.font = Font(name=F, size=9, bold=True, color='FFFFFF')
        x.fill = PatternFill('solid', fgColor=G)
        x.alignment = Alignment(horizontal='center', vertical='center', wrap_text=True)
        x.border = BD
        ws.column_dimensions[x.column_letter].width = w
    for r, row in enumerate(rows, 5):
        lines = 1
        for c, v in enumerate(row, 1):
            x = ws.cell(row=r, column=c, value=v)
            x.font = Font(name=F, size=9, bold=(c == scol))
            x.alignment = Alignment(wrap_text=True, vertical='top')
            x.border = BD
            lines = max(lines, int(len(str(v)) / max(widths[c - 1] / 1.9, 1)) + 1)
        ws.cell(row=r, column=scol).fill = PatternFill('solid', fgColor=FILL[row[scol - 1]])
        ws.row_dimensions[r].height = max(15, 13 * lines)
    ws.freeze_panes = 'A5'
    ws.print_title_rows = '4:4'
    ws.page_setup.orientation = 'landscape'
    ws.page_setup.paperSize = ws.PAPERSIZE_A4
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True


