def P(text='', **kw):
    a = [repr(text)]
    for k, v in kw.items():
        a.append('%s=%s' % (k, v))
    E('P(%s)' % ', '.join(a))


def H(lv, text):
    E('H%d(%s)' % (lv, repr(text)))


def T(rows, widths):
    E('TBL(%r, widths=%r)' % (rows, widths))


