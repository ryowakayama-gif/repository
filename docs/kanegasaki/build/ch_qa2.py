def QBLOCK(no, who, q, a, kon, rel):
    p = doc.add_paragraph(); pf = p.paragraph_format
    pf.space_before = Pt(10); pf.space_after = Pt(0); pf.keep_with_next = True
    pf.left_indent = Cm(0.15); pf.right_indent = Cm(0.15)
    _shd(p, 'EAF2ED'); _pbdr(p, G, ('top',), '12', '2')
    _f(p.add_run('Q%s　' % no), GFONT, 11.5, True, _rgb(G))
    _f(p.add_run('【%s】　' % who), FONT, 9.5, False, _rgb('595959'))
    _f(p.add_run(q), GFONT, 11.5, True)
    p = doc.add_paragraph(); pf = p.paragraph_format
    pf.space_before = Pt(4); pf.space_after = Pt(3); pf.keep_with_next = True
    pf.left_indent = Cm(0.6); pf.first_line_indent = Cm(-0.6)
    _f(p.add_run('A．'), GFONT, 11, True, _rgb('B85C22'))
    _runs(p, a, 10.5)
    for lab, t, last in (('【根拠データ】', kon, False), ('【関連資料】', rel, True)):
        p = doc.add_paragraph(); pf = p.paragraph_format
        pf.space_before = Pt(0); pf.space_after = Pt(6 if last else 0)
        pf.keep_with_next = not last
        pf.left_indent = Cm(0.15); pf.right_indent = Cm(0.15)
        _shd(p, 'F2F2F2')
        _f(p.add_run('　' + lab + ' '), FONT, 9, True, _rgb('595959'))
        _f(p.add_run(t), FONT, 9)


