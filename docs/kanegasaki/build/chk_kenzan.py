# -*- coding: utf-8 -*-
"""主要数値の検算（エビデンス用）。

  python3 -I chk_kenzan.py [出力.md]

計画素案（ch_soan.py）に書かれた入力値から、保険料の基準額・準備基金の3案・
認知症高齢者数・要介護1の重度化率・成果指標の件数・地域支援事業費の合計を
計算し直し、素案の記載と一致するかを表にする。入力値そのものの妥当性
（算定の原表との一致）を確かめるものではない。
"""
import re
import sys

S = open('ch_soan.py', encoding='utf-8').read()
rows = []


def chk(item, formula, calc, doc, ok=None):
    if ok is None:
        ok = (calc == doc)
    rows.append((item, formula, calc, doc, '○' if ok else '×'))


def has(s):
    return s in S


# ── 保険料
std, chiiki = 3_993_523_686, 199_236_838
sougou = 139_037_000  # 総合事業費3か年（千円表示139,037）
p1 = (std + chiiki) * 0.23
chk('第1号被保険者負担分相当額', '(3,993,523,686＋199,236,838)×23％', '{:,.2f}円'.format(p1),
    '964,334,920円', ok=int(p1) == 964_334_920 and has('964,334,920'))
need = 964_334_920 + 206_628_040 - 283_960_000
chk('保険料収納必要額', '964,334,920＋206,628,040－283,960,000', '{:,}円'.format(need),
    '887,002,960円', ok=need == 887_002_960 and has('887,002,960'))
den = 13_920.56 * 12 * 0.9977
for fund, doc in ((0, 5322), (72_000_000, 4890), (90_000_000, 4782)):
    v = (need - fund) / den
    chk('基準額（取崩%s円）' % '{:,}'.format(fund),
        '(887,002,960－%s)÷(13,920.56×12×0.9977)' % '{:,}'.format(fund),
        '{:,.2f}円'.format(v), '{:,}円'.format(doc),
        ok=round(v) == doc and has('{:,}円'.format(doc)))
chk('取崩1,000万円あたりの月額', '10,000,000÷分母', '{:.1f}円'.format(1e7 / den), '60.0円',
    ok=round(1e7 / den, 1) == 60.0)
bal = 271_741_782 - 21_581_000 + 460_000
chk('令和8年度末の基金残高見込', '271,741,782－21,581,000＋460,000', '{:,}円'.format(bal),
    '250,620,782円', ok=bal == 250_620_782 and has('250,620,782'))

# ── 認知症高齢者数（自立度Ⅱ以上＝認定者数×69.3％）
for y, n, doc in (('令和9年度', 796, 552), ('令和10年度', 803, 556), ('令和11年度', 807, 559)):
    v = n * 0.693
    chk('自立度Ⅱ以上 ' + y, '%d×69.3％' % n, '{:.1f}人'.format(v), '%d人' % doc,
        ok=round(v) == doc and has('**%d人**' % doc))
chk('令和11年度の値が1つに揃っている', '「569人」の出現', '%d件' % S.count('569人'), '0件',
    ok=S.count('569人') == 0)

# ── 要介護1の重度化率
for y, den1, k2, k3, oth, doc in (('令和2年度', 79, 10, 5, 4, '24.1'), ('令和4年度', 106, 36, 4, 4, '41.5'),
                                    ('令和6年度', 124, 44, 9, 3, '45.2'), ('令和7年度', 86, 40, 6, 3, '57.0')):
    v = (k2 + k3 + oth) / den1 * 100
    w = (k2 + k3) / den1 * 100
    chk('重度化率 ' + y, '(%d＋%d＋その他%d)÷%d' % (k2, k3, oth, den1),
        '{:.1f}％（要介護2・3のみ{:.1f}％）'.format(v, w), doc + '％',
        ok='{:.1f}'.format(v) == doc)

# ── 成果指標
i, j = S.index("H2('９-３"), S.index("H2('９-４")
seg = S[i:j]
kinds = {'成果': 0, '活動': 0, '体制': 0}
judge = {'目標': 0, '監視': 0, '置かない': 0}
for r in re.findall(r"\['\*\*(成果|活動|体制)\*\*'.*?\],", seg):
    kinds[r] += 1
for r in re.findall(r"\['\*\*(?:成果|活動|体制)\*\*'.*?\],", seg):
    last = re.findall(r"'([^']*)'", r)[-1]
    judge['監視' if '監視' in last else ('置かない' if '置かない' in last else '目標')] += 1
tot = sum(kinds.values())
chk('成果指標の件数', '成果＋活動＋体制', '%d（%d・%d・%d）' % (tot, kinds['成果'], kinds['活動'], kinds['体制']),
    '43（10・23・10）', ok=(tot, kinds['成果'], kinds['活動'], kinds['体制']) == (43, 10, 23, 10))
chk('目標値の区分', '目標＋監視＋置かない', '%d・%d・%d' % (judge['目標'], judge['監視'], judge['置かない']),
    '26・8・9', ok=(judge['目標'], judge['監視'], judge['置かない']) == (26, 8, 9))
chk('継続と新設', '8＋35', '%d' % (8 + 35), '43', ok=has('新設が35項目') and not has('新設が33項目'))
chk('「未把握8」の残存', '「把握できていない8」の出現', '%d件' % S.count('把握できていない8'), '0件',
    ok=S.count('把握できていない8') == 0)

# ── 地域支援事業費
for y, a, b, doc in (('令和9年度', 45_742, 20_089, 65_831), ('令和10年度', 46_329, 20_064, 66_393),
                     ('令和11年度', 46_967, 20_047, 67_013)):
    chk('地域支援事業費 ' + y, '%s＋%s（千円表示の和）' % ('{:,}'.format(a), '{:,}'.format(b)),
        '{:,}千円'.format(a + b), '{:,}千円'.format(doc), ok=abs(a + b - doc) <= 1)
chk('令和7年度決算の計', '35,741＋42,154＋73', '{:,}千円'.format(35_741 + 42_154 + 73), '77,968千円',
    ok=35_741 + 42_154 + 73 == 77_968)

# ── 調整済み認定率（基準人口が異なるため、合計と内訳は一致しないことを確かめる）
chk('調整済み重度＋軽度（全国基準）と合計（町基準）', '4.4＋8.8 と 15.9', '13.2％', '足し合わないと明記',
    ok=has('足し合わない'))
# ── 要介護1の更新時の移行の割合が幅で示されているか
chk('成果指標№1の現状値が幅で示されている', '「53.5〜57.0％」の出現', '%d件' % S.count('53.5〜57.0％'), '1件以上',
    ok=S.count('53.5〜57.0％') >= 1)
_kc = S.count('軽度から中度') - S.count('「軽度から中度」のような')
chk('「軽度から中度」の呼び方が残っていない', '「軽度から中度」の出現（用いないとする説明を除く）', '%d件' % _kc, '0件', ok=_kc == 0)

# ── 認知症の自立度（第4回レビュー）
chk('「Ⅱbのみ・Ⅱbだけ」の断定が残っていない', '「Ⅱbのみ」「Ⅱbだけ」「すべてⅡb」の出現',
    '%d件' % sum(S.count(x) for x in ('Ⅱbのみ', 'Ⅱbだけ', 'すべてⅡb')), '0件',
    ok=sum(S.count(x) for x in ('Ⅱbのみ', 'Ⅱbだけ', 'すべてⅡb')) == 0)
chk('Ⅲ以上の合計（令和2年4月末→令和6年10月末）', '231＋26＋94＋0 → 225＋39＋91＋5', '%d→%d人' % (231 + 26 + 94 + 0, 225 + 39 + 91 + 5),
    '351→360人', ok=(231 + 26 + 94, 225 + 39 + 91 + 5) == (351, 360) and has('351人から360人'))
B6 = open('ch_bp6.py', encoding='utf-8').read()
nb = len(re.findall(r"\['\*\*\d+\*\*', '[^']*', '[^']*', '[^']*', '', '', '', '', ''\]", B6))
chk('別表6 様式Ｂの行数', '実績の記入欄の行', '%d行' % nb, '43行', ok=nb == 43)

# ── 交付金
chk('交付金の合計得点（令和8年度）', '推進227＋努力支援207', '%d点' % (227 + 207), '434点', ok=227 + 207 == 434)
chk('令和7年度の交付額', '1,389,000＋2,758,000', '{:,}円'.format(1_389_000 + 2_758_000), '4,147,000円',
    ok=has('4,147,000'))

# ── 出力
out = ['# 主要数値の検算', '',
       '計画素案（協議用）の記載から入力値を取り、計算し直したもの。**入力値そのものの妥当性（算定の原表との一致）を確かめるものではない。**',
       '地域支援事業費は千円表示の和であり、円単位の計を丸めた表の値と1千円の差があり得る（○は差1千円以内）。', '',
       '| 項目 | 算式 | 再計算 | 素案の記載 | 判定 |', '|---|---|---|---|---|']
out += ['| %s | %s | %s | %s | %s |' % r for r in rows]
ng = sum(1 for r in rows if r[4] == '×')
out += ['', '**%d項目中、不一致 %d件**' % (len(rows), ng)]
txt = '\n'.join(out) + '\n'
if len(sys.argv) > 1:
    open(sys.argv[1], 'w', encoding='utf-8').write(txt)
print(txt)
sys.exit(1 if ng else 0)
