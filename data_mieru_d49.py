def d49_values():
    """地域差指数の値（令和5年・上川管内21保険者）を読む。

    値は `build_regional_gap_analysis.py` の `D49` にある。
    鍵が変数名であるため組ごとの `ast.literal_eval` ができないため、
    変数名を先に読み、辞書を手で組む。
    戻り値は (保険者の並び, 給付月額の鍵, 認定率, 受給率, 受給者単価, 指数)。
    **同じ読み取りを読む側ごとに書かない**（CLAUDE.md §4）。
    """
    import ast
    import io as _io
    import os as _os
    p = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)),
                      "build_regional_gap_analysis.py")
    src = _io.open(p, encoding="utf-8").read()
    env, d49 = {}, None
    for n in ast.parse(src).body:
        if not (isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "")):
            continue
        nm = n.targets[0].id
        if nm in ("INSURER", "G", "N", "J", "T"):
            env[nm] = ast.literal_eval(n.value)
        elif nm == "D49":
            d49 = {env[k.id]: ast.literal_eval(v)
                   for k, v in zip(n.value.keys, n.value.values)}
    ins = env["INSURER"]
    return (ins, env["G"], env["N"], env["J"], env["T"],
            {k: dict(zip(ins, v)) for k, v in d49.items()})


# 積と給付月額の指数が一致したとみる幅
ITCHI_HABA = 0.02


def bunkai_zure():
    """受給率×受給者単価が給付月額の指数と一致しない保険者を数える。

    戻り値は (保険者数, 一致する数, ずれる数, 最小の差, 最大の差)。
    """
    ins, g, _n, j, t, idx = d49_values()
    d = [idx[j][k] * idx[t][k] - idx[g][k] for k in ins]
    itchi = sum(1 for x in d if abs(x) <= ITCHI_HABA)
    return len(ins), itchi, len(ins) - itchi, min(d), max(d)


def shihyo_of(name):
    """指標名から (算式, 性・年齢調整の有無) を返す。"""
    for nm, shiki, adj in SHIHYO:
        if nm == name:
            return shiki, adj
    raise KeyError(name)


def chosei_ari():
    """性・年齢調整後である指標の名の一覧。"""
    return [nm for nm, _s, adj in SHIHYO if adj]


