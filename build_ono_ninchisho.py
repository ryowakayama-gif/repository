def taisei():
    """見える化 J16〜J18 を読み、福島県内59市町村のなかでの位置を求める。

    シートには59市町村に加えて「福島県」の行があるため、順位・中央値の算出から外す。
    """
    out = []
    for label, fn in TAISEI_FILES.items():
        ws = openpyxl.load_workbook(JIZEN / fn, data_only=True)["表形式（時系列）"]
        cols = [str(ws.cell(2, c).value).replace("\n", "") for c in (5, 6)]
        rows = [(ws.cell(r, 2).value, ws.cell(r, 5).value, ws.cell(r, 6).value)
                for r in range(3, 63)
                if ws.cell(r, 2).value and isinstance(ws.cell(r, 6).value, (int, float))]
        shi = [r for r in rows if r[0] != "福島県"]
        ono = next(r for r in shi if r[0] == "小野町")
        order = sorted(shi, key=lambda r: -r[2])
        rank = next(i for i, r in enumerate(order, 1) if r[0] == "小野町")
        vals = sorted(r[2] for r in shi)
        med = vals[len(vals) // 2]
        out.append({"指標": label, "基準": cols, "小野町": (ono[1], ono[2]),
                    "順位": rank, "団体数": len(shi), "中央値": med,
                    "ゼロ": sum(1 for r in shi if r[2] == 0),
                    "最大": vals[-1]})
    return out


def ninchisho_est():
    """認知症高齢者数の見込み。

    見える化の自立度は平成24年4月末と令和6年10月末の2時点しかなく、
    Ⅲa・Ⅲbが確認メモに落ちているため、把握できるのはⅡa・Ⅱb・Ⅳ・Mの4区分の
    合計にとどまる。したがってここで出せるのは自立度Ⅱ以上の**下限**である。
    """
    now = sum(v for _l, _h, v in JIRITSUDO)
    rate = now / NINTEI_R6_10
    est = {y: T.NINTEI_EST[y] * rate for y in PLAN_YEARS}
    est["令和8年3月末"] = NINTEI_R7_1GO * rate
    return now, rate, est


