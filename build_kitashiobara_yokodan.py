def _norm(s):
    return re.sub(r"\s+", "", str(s))


def _member_text():
    d = docx.Document(MEMBER)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            for c in r.cells:
                out += [p.text for p in c.paragraphs]
    return out


