def new_doc():
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = JP_MIN
    st.font.size = Pt(10.5)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), JP_MIN)
    return doc


def head(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        r.font.name = JP_GO
        r._element.rPr.rFonts.set(qn("w:eastAsia"), JP_GO)
    return p


def para(doc, *ts):
    for t in ts:
        doc.add_paragraph(t)


def note(doc, t):
    p = doc.add_paragraph(t)
    for r in p.runs:
        r.font.size = Pt(9)


def table(doc, header, rows, right_from=99):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for i, v in enumerate(header):
        c = t.rows[0].cells[i]
        c.text = str(v)
        for p in c.paragraphs:
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            for r in p.runs:
                r.font.bold = True
                r.font.size = Pt(8.5)
    for row in rows:
        cs = t.add_row().cells
        for i, v in enumerate(row):
            cs[i].text = "" if v is None else str(v)
            for p in cs[i].paragraphs:
                if i >= right_from:
                    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
                for r in p.runs:
                    r.font.size = Pt(8.5)


