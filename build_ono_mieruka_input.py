def ws_facts():
    """受領したワークシートから、入力状況の判定に用いる値を読む。"""
    wb = openpyxl.load_workbook(WS_FILE, data_only=True)
    s1, s2, s5 = wb["1_推計値サマリ"], wb["2_サービス別給付費"], wb["5_保険料推計"]
    f = {
        "第9期基準額": s5.cell(8, 6).value,
        "標準給付費3年計": s5.cell(68, 6).value,
        "第1号3年計": s5.cell(109, 6).value,
        "後期補正": [s5.cell(96, c).value for c in (7, 8, 9)],
        "認定者": {s1.cell(18, c).value: s1.cell(19, c).value
                 for c in range(4, 10)},
        "被保険者": {s1.cell(10, c).value: s1.cell(12, c).value
                  for c in range(4, 10)},
        "認定度別R7": [s1.cell(r, 5).value for r in range(20, 27)],
    }
    # 令和8年度が1か月分であることの根拠（人数・回数・日数の整数率）
    intg = {}
    for c, y in ((4, "令和6年度"), (5, "令和7年度"), (6, "令和8年度")):
        n = i = 0
        for r in range(12, s2.max_row + 1):
            if s2.cell(r, 3).value not in ("人数（人）", "回数（回）", "日数（日）"):
                continue
            v = s2.cell(r, c).value
            if isinstance(v, (int, float)) and v > 0:
                n += 1
                i += abs(v - round(v)) < 1e-9
        intg[y] = (n, i)
    f["整数率"] = intg
    return f


