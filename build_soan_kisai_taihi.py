def _docx_text(name):
    path = os.path.join(ODIR, name)
    if not os.path.exists(path):
        return ""
    d2 = Document(path)
    out = [p2.text for p2 in d2.paragraphs]
    for t2 in d2.tables:
        for r2 in t2.rows:
            out += [c2.text for c2 in r2.cells]
    return "\n".join(out)


