def in_draft(*words, sho=None, setsu=None):
    """語が素案（又は指定した章節）に現れるか。章節を限って判定する。"""
    if sho is None:
        hay = ALLTXT
    else:
        hay = "\n".join("\n".join(v["txt"]) for k, v in SECT.items()
                        if k[0] == sho and (setsu is None or k[1] == setsu))
    return all(w in hay for w in words)


def where(*words):
    """語が現れる章節を返す。"""
    out = []
    for k, v in SECT.items():
        t = "\n".join(v["txt"])
        if all(w in t for w in words):
            out.append("".join(x for x in k if x))
    return out


# ============================================================ 確認事項を読む
def _assign(path, *names):
    src = open(path, encoding="utf-8").read()
    out = {}
    for node in ast.parse(src).body:
        if (isinstance(node, ast.Assign)
                and getattr(node.targets[0], "id", None) in names):
            out[node.targets[0].id] = ast.literal_eval(node.value)
    return out


