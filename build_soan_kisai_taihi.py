def sheet(name, title, subtitle, widths, freeze="A5"):
    ws = wb.create_sheet(name)
    ws["A1"] = title
    ws["A1"].font = Font(name=FONT, size=14, bold=True, color="FFFFFF")
    ws["A1"].fill = PatternFill("solid", fgColor=NAVY)
    ws["A2"] = subtitle
    ws["A2"].font = Font(name=FONT, size=9)
    ws["A2"].fill = PatternFill("solid", fgColor=GRAY)
    ws["A2"].alignment = Alignment(wrap_text=True, vertical="top")
    n = max(len(widths), 6)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=n)
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=n)
    ws.row_dimensions[1].height = 26
    ws.row_dimensions[2].height = 80
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = freeze
    return ws


def header(ws, row, cols, height=30):
    for i, hh in enumerate(cols, start=1):
        c = ws.cell(row=row, column=i, value=hh)
        c.font = Font(name=FONT, size=9, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=HEAD)
        c.alignment = Alignment(wrap_text=True, horizontal="center",
                                vertical="center")
        c.border = BORDER
    ws.row_dimensions[row].height = height
    return row + 1


def body(ws, row, vals, fills=None, height=20, align=None, bold=False):
    for i, v in enumerate(vals, start=1):
        c = ws.cell(row=row, column=i, value=v)
        c.font = Font(name=FONT, size=9, bold=bold)
        c.border = BORDER
        ha = (align or {}).get(i, "left" if isinstance(v, str) else "right")
        c.alignment = Alignment(wrap_text=True, vertical="top", horizontal=ha)
        if fills and fills.get(i):
            c.fill = PatternFill("solid", fgColor=fills[i])
    ws.row_dimensions[row].height = height
    return row + 1


def lead(ws, row, text, span=10):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=FONT, size=10.5, bold=True, color=NAVY)
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span)
    ws.row_dimensions[row].height = 20
    return row + 1


def note(ws, row, text, span=10, height=None):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=FONT, size=8.5)
    c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span)
    ws.row_dimensions[row].height = height or (14 * (1 + text.count("\n")))
    return row + 1


# ============================================================ 素案を読む
PH = re.compile(r"［(要協議|要確認|要内訳)］")
SHO = re.compile(r"^(第\d+章|資料\d+|資料編)")
SETSU = re.compile(r"^(第\d+節|基本目標\d)")
LEADP = re.compile(r"^【(.+)】$")

_doc = Document(RP.DRAFT)

SECT = collections.OrderedDict()   # (章, 節) -> {"p":段落, "t":表, "f":図, "ph":未確定, "txt":本文}
LEADS = []                         # (章, 節, 見出し, 段落, 表)
SHIRYO6 = []                       # 資料6 の表の行
_sho, _setsu = "（表紙・目次）", ""
_cur_lead = None
_in_s6 = False


def _is_mokuji(t):
    """目次の行はタブでページ番号を連結しているため見出しとして数えない。"""
    return "\t" in t


def _key():
    return (_sho, _setsu)


for _ch in _doc.element.body.iterchildren():
    _tag = _ch.tag.split("}")[-1]
    if _tag == "p":
        _p = Paragraph(_ch, _doc)
        _t = _p.text.strip()
        if _is_mokuji(_t):
            continue
        if SHO.match(_t):
            _sho, _setsu, _cur_lead = _t.split()[0], "", None
            _in_s6 = _t.startswith("資料6")
        elif SETSU.match(_t):
            _setsu, _cur_lead = _t.split()[0], None
        _d = SECT.setdefault(_key(), {"p": 0, "t": 0, "f": 0, "ph": 0,
                                      "txt": [], "name": _t if SHO.match(_t)
                                      else ""})
        if not _t:
            continue
        _d["p"] += 1
        _d["txt"].append(_t)
        _d["ph"] += len(PH.findall(_t))
        _m = LEADP.match(_t)
        if _m:
            _cur_lead = [_sho, _setsu, _m.group(1), 0, 0]
            LEADS.append(_cur_lead)
        elif _cur_lead is not None:
            _cur_lead[3] += 1
    elif _tag == "tbl":
        _tb = Table(_ch, _doc)
        _d = SECT.setdefault(_key(), {"p": 0, "t": 0, "f": 0, "ph": 0,
                                      "txt": [], "name": ""})
        _d["t"] += 1
        for _r in _tb.rows:
            for _c in _r.cells:
                _d["ph"] += len(PH.findall(_c.text))
                _d["txt"].append(_c.text)
        if _cur_lead is not None:
            _cur_lead[4] += 1
        if _in_s6 and not SHIRYO6:
            SHIRYO6 = [[_c.text.strip() for _c in _r.cells]
                       for _r in _tb.rows][1:]

