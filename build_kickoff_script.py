TEXTW = 21.0 - 1.9 * 2


def P(text="", size=10.5, bold=False, align=None, space_after=4,
      color=None, indent=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.bold = bold
    r.font.name = FONT
    if color is not None:
        r.font.color.rgb = color
    r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    if align:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    return p


def BUL(text, size=10):
    p = doc.add_paragraph(style="List Bullet")
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.name = FONT
    r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    p.paragraph_format.space_after = Pt(2)
    return p


def _h(text, level, size, color=None):
    p = doc.add_paragraph(style="Heading %d" % level)
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.name = FONT
    r.font.color.rgb = color if color is not None else NAVY
    r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    p.paragraph_format.space_before = Pt(12 if level == 1 else 8)
    p.paragraph_format.space_after = Pt(4)
    p.paragraph_format.keep_with_next = True
    return p


def H1(t):
    return _h(t, 1, 14)


def H2(t):
    return _h(t, 2, 11.5)


def LABEL(t):
    p = P(t, size=10, bold=True, space_after=2, color=GRAY)
    p.paragraph_format.keep_with_next = True
    return p


def _shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)


def _cellmargin(t, left=0.14, right=0.14, top=0.08, bottom=0.08):
    mar = OxmlElement("w:tblCellMar")
    for tag, v in (("top", top), ("left", left),
                   ("bottom", bottom), ("right", right)):
        e = OxmlElement("w:" + tag)
        e.set(qn("w:w"), str(int(v * 567)))
        e.set(qn("w:type"), "dxa")
        mar.append(e)
    t._tbl.tblPr.append(mar)


def SCRIPT(lines):
    """読み上げる台本。1行1発話。網掛けの枠に入れる。"""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    _cellmargin(t, left=0.22, right=0.22, top=0.14, bottom=0.14)
    c = t.rows[0].cells[0]
    c.text = ""
    c.width = Cm(TEXTW)
    _shade(c, SCRIPTFILL)
    for i, ln in enumerate(lines):
        p = c.paragraphs[0] if i == 0 else c.add_paragraph()
        p.paragraph_format.space_after = Pt(3)
        p.paragraph_format.line_spacing = 1.15
        r = p.add_run(ln)
        r.font.size = Pt(10)
        r.font.name = FONT
        r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    t.rows[0]._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
    P("", size=6, space_after=2)
    return t


def TBL(head, rows, widths=None, size=9, center=None):
    center = center or set()
    t = doc.add_table(rows=1, cols=len(head))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    _cellmargin(t)
    for i, hh in enumerate(head):
        c = t.rows[0].cells[i]
        c.text = ""
        c.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        p = c.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(1)
        p.paragraph_format.space_after = Pt(1)
        r = p.add_run(hh)
        r.bold = True
        r.font.size = Pt(size)
        r.font.name = FONT
        r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
        _shade(c, HEADFILL)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            cells[i].vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            p = cells[i].paragraphs[0]
            if i in center:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            p.paragraph_format.space_before = Pt(1)
            p.paragraph_format.space_after = Pt(1)
            r = p.add_run("" if v is None else str(v))
            r.font.size = Pt(size)
            r.font.name = FONT
            r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    if widths:
        tot = sum(widths)
        if tot > TEXTW:
            widths = [w * TEXTW / tot for w in widths]
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    for row in t.rows:
        row._tr.get_or_add_trPr().append(OxmlElement("w:cantSplit"))
    t.rows[0]._tr.get_or_add_trPr().append(OxmlElement("w:tblHeader"))
    P("", size=6, space_after=2)
    return t


def NOTE(text, size=9):
    return P(text, size=size, space_after=8, color=GRAY)


