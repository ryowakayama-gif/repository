def torikoboshi(nendo="令和8年度", rate=45.0):
    """3町とも0点で、全国該当率が rate％以上の明細列を返す（該当率の降順）。"""
    out = [r for r in DETAIL[nendo]
           if all((v or 0) == 0 for v in r[7]) and r[6] >= rate]
    return sorted(out, key=lambda r: -r[6])


def item(nendo, daikomoku):
    """大項目名で明細列を絞り込む。"""
    return [r for r in DETAIL[nendo] if r[3] == daikomoku]


