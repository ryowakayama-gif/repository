def xlsx_build(soku):
    wb = Workbook()
    ws = wb.active
    ws.title = "論点漏れの点検"
    head = ["№", "論点", "根拠", "原典", "判定", "他素案の現状と対応", "優先",
            "他素案の出現", "当方素案の出現"]
    ws.append(head)
    hd = Font(bold=True, color="FFFFFF", name="游ゴシック", size=10)
    for c in ws[1]:
        c.font, c.fill = hd, PatternFill("solid", fgColor="1F3864")
    fill = {"漏れ": "F8CBAD", "誤り": "FF9999", "一部": "FFE699", "充足": "E2EFDA"}
    for x in RONTEN:
        a, b = soku[x[0]]
        ws.append([x[0], _p(x[1]), x[2], GENTEN[x[3]][1] if x[3] else "（原典照合なし）",
                   x[7], _p(x[8]), x[9], "" if a is None else a, "" if b is None else b])
        ws.cell(ws.max_row, 5).fill = PatternFill("solid", fgColor=fill[x[7]])
    for i, w in enumerate([6, 44, 28, 34, 7, 60, 6, 10, 10], 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(vertical="top", wrap_text=True)
    ws.freeze_panes = "A2"
    p = OUT / ("小野町_障がい計画_論点漏れの点検_%s.xlsx" % ASOF)
    wb.save(p)
    return p


# ------------------------------------------------------------------ 自己点検
def jiko(soku, doc_path=None):
    ng, sk = [], []
    ng += genten_ng()                                    # 1 原典に文言が実在する
    for x in RONTEN:                                     # 2 判定と出現の整合
        a = soku[x[0]][0]
        if a is None:
            continue
        if x[7] == "漏れ" and a != 0:
            ng.append("%s は漏れとしたが他素案に%d件ある" % (x[0], a))
        if x[7] in ("充足", "誤り", "一部") and a == 0 and x[5]:
            ng.append("%s は%sとしたが他素案に判定語がない" % (x[0], x[7]))
    if soku[RONTEN[0][0]][0] is None:
        sk.append("他素案が手元にないため、出現の整合は確かめていない")
    for x in RONTEN:                                     # 3 区分と優先
        if x[7] not in ("漏れ", "誤り", "一部", "充足"):
            ng.append("判定が不正：%s" % x[0])
        if x[7] == "充足" and x[9] != "―":
            ng.append("充足に優先がある：%s" % x[0])
        if x[7] != "充足" and x[9] not in ("高", "中", "低"):
            ng.append("優先がない：%s" % x[0])
        if x[3] is None and x[9] == "高":
            ng.append("原典照合のない観点を優先「高」にしている：%s" % x[0])
    if doc_path is not None:                             # 4 他団体の名称を出さない
        t = docx_txt(doc_path)
        for w in ("北塩原", "福島町", "北海道", "大雪", "東川", "会津"):
            if w in t:
                ng.append("他団体に結びつく語が出ている：%s" % w)
    # 5 対応表に№22〜31として入っている
    import build_ono_shogai_tsuika_taiou as T
    want = [x[0] for x in RONTEN if x[7] != "充足" and x[3] is not None]
    got = [re.search(r"R\d+", x[6]).group(0) for x in T.TAIOU
           if 22 <= x[0] and re.search(r"（論点漏れの点検 R\d+）", x[6])]
    if got != want:
        ng.append("対応表の№22以降が点検の R%s と合わない（%s）" % (
            "・".join(w[1:] for w in want), "・".join(got)))
    return ng, sk


