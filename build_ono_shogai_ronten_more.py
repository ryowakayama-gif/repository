# ------------------------------------------------------------------ 読み取り
def _norm(s):
    return unicodedata.normalize("NFKC", re.sub(r"\s+", "", s))


_TXT = {}


def genten_txt(key):
    if key not in _TXT:
        p = KOKU / GENTEN[key][0]
        r = subprocess.run(["pdftotext", "-layout", str(p), "-"],
                           capture_output=True, text=True)
        _TXT[key] = _norm(r.stdout) if r.returncode == 0 else None
    return _TXT[key]


def docx_txt(path):
    if not path.exists():
        return None
    import docx
    d = docx.Document(str(path))
    t = [p.text for p in d.paragraphs]
    for tb in d.tables:
        for rw in tb.rows:
            t += [c.text for c in rw.cells]
    return _norm("\n".join(t))


def sokutei():
    """他素案・当方素案での判定語の出現回数を数える。"""
    ta = docx_txt(TASO)
    to = docx_txt(TOUHOU)
    res = {}
    for x in RONTEN:
        no, ws_t, ws_o = x[0], x[5], x[6]
        res[no] = (
            None if ta is None else sum(ta.count(_norm(w)) for w in ws_t),
            None if to is None else sum(to.count(_norm(w)) for w in ws_o) if ws_o else None,
        )
    return res


def genten_ng():
    ng = []
    for x in RONTEN:
        key, words = x[3], x[4]
        if key is None:
            continue
        t = genten_txt(key)
        if t is None:
            ng.append("%s：原典が読めない（%s）" % (x[0], GENTEN[key][0]))
            continue
        for w in words:
            if _norm(w) not in t:
                ng.append("%s：原典（%s）に「%s」がない" % (x[0], key, w))
    return ng


