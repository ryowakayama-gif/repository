def _cellmargin(t, left=0.12, right=0.12, top=0.06, bottom=0.06):
    mar = OxmlElement("w:tblCellMar")
    for tag, v in (("top", top), ("left", left),
                   ("bottom", bottom), ("right", right)):
        e = OxmlElement("w:" + tag)
        e.set(qn("w:w"), str(int(v * 567)))
        e.set(qn("w:type"), "dxa")
        mar.append(e)
    t._tbl.tblPr.append(mar)


