def text_docx(p):
    d = docx.Document(str(p))
    return "\n".join([x.text for x in d.paragraphs] + [c.text for tb in d.tables for r in tb.rows for c in r.cells])


def kazoe_docx(p):
    """図（画像・グラフ）・表の数と、図表の題名・資料の付き方を数える。"""
    d = docx.Document(str(p))
    body = d.element.body
    W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
    zu = gu = hyo = dai = shiryo = 0
    prev = ""
    kids = list(body.iterchildren())
    for i, el in enumerate(kids):
        tag = el.tag.split("}")[1]
        if tag == "p":
            t = "".join(x.text or "" for x in el.iter(W + "t"))
            zu += len(el.findall(".//{http://schemas.openxmlformats.org/drawingml/2006/main}blip"))
            gu += len(el.findall(".//{http://schemas.openxmlformats.org/drawingml/2006/chart}chart"))
            prev = t
        elif tag == "tbl":
            hyo += 1
            if re.match(r"\s*(【表|■|◆|表\d)", prev):
                dai += 1
            # 表の直後の、空でない最初の段落（注記「※」を挟むことがあるため2段落まで見る）
            seen = 0
            for nxt in kids[i + 1:]:
                if not nxt.tag.endswith("}p"):
                    break
                nt = "".join(x.text or "" for x in nxt.iter(W + "t")).strip()
                if not nt:
                    continue
                if "資料：" in nt or nt.startswith(("資料", "出所")):
                    shiryo += 1
                    break
                seen += 1
                if seen >= 2:
                    break
    return {"画像": zu, "グラフ": gu, "表": hyo, "題名あり": dai, "資料あり": shiryo}


def kazoe_zenkai():
    """前回計画のPDFから、◆・■の図表の題名と、第2部の調査のグラフ（●の設問）を数える。"""
    t = subprocess.run(["pdftotext", "-layout", str(ZENKAI), "-"], capture_output=True, text=True).stdout
    pg = t.split("\f")
    dai = sum(len(re.findall(r"^\s*[◆■]", p, re.M)) for p in pg)
    chosa = sum(len(re.findall(r"^\s*●.+[。か]", p, re.M)) for p in pg[24:70])
    return {"頁": len([p for p in pg if p.strip()]), "題名（◆・■）": dai, "第2部の調査のグラフ": chosa}


