# ---------------------------------------------------------------- 自己点検
def jiko():
    ng = []
    import inspect
    import re
    src = inspect.getsource(doc_build) + "".join(
        str(x) for x in (KIHON, KIHON_JIKO, NAKADORI_KADAI, NAKADORI_TORIKUMI,
                         SAFETY, KANREN, CHUI, HANEI))
    # 1 他町村の固有名詞を書いていない
    for w in ("北塩原", "大雪", "金ヶ崎", "川崎町", "本村", "同村"):
        if w in src:
            ng.append("他町村を指す語がある：%s" % w)
    # 2 本町が属する圏域を取り違えていない（会津・浜通りを本町のものとして書かない）
    if "本町は会津" in src or "本町は浜通り" in src:
        ng.append("本町の生活圏域を取り違えている")
    if "本町は田村郡であり、**中通り**に属します" not in src and \
       "本町は田村郡であり、中通り" not in src.replace("**", ""):
        ng.append("本町が中通りに属することを書いていない")
    # 3 計画期間が本計画の前に満了することを書いている
    if "令和4年度から令和8年度" not in src and "令和4年度〜令和8年度" not in src:
        ng.append("県計画の計画期間を書いていない")
    # 見出しに書いていることもあるため、組の全体を見る。
    if not any("満了" in "".join(x) for x in CHUI):
        ng.append("計画期間の満了に触れていない")
    # 4 中通りの課題・取組に当たり先がそろっている
    for x in NAKADORI_KADAI + NAKADORI_TORIKUMI:
        if not x[1].strip():
            ng.append("中通りの項目に当たり先がない：%s" % x[0][:20])
    # 5 反映に時期がそろっている
    for x in HANEI:
        if not x[2].strip():
            ng.append("反映に時期がない：%s" % x[0])
    # 6 出典がある
    if src.count("r.src(") < 2:
        ng.append("出典が2つ未満")
    # 7 本文に件数を手で書いていない
    for m in re.findall(r"（\d+件）", inspect.getsource(doc_build)):
        ng.append("本文に件数を手で書いている：%s" % m)
    # 8 そのまま引けないことを必ず挙げている
    if not CHUI:
        ng.append("そのまま引けないことを挙げていない")
    return ng


