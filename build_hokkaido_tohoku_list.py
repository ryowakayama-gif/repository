def kubun(name):
    if name.endswith("県") or name == "北海道":
        return "道県"
    if name.endswith("市"):
        return "市"
    if name.endswith("町"):
        return "町"
    return "村"


def gimu_kubun(name):
    return "義務" if name in GIMU else "努力義務"


def default_rank(name, hantei):
    """スクリーニング前の仮置きランク（予算確認前のため、あくまで接触優先度）。"""
    if hantei.startswith("★"):
        return "最優先（R9満了）"
    if hantei.startswith("▲"):
        return "優先（候補・要確認）"
    if name in GIMU:
        return "優先（義務団体）"
    if kubun(name) == "市":
        return "中"
    return "低（要件次第）"


def next_action(name, hantei, joukyou):
    if hantei.startswith("★"):
        return "令和9年度当初予算への計上を狙い、令和8年度の予算要求期（夏〜秋）に接触する。改定必要度診断と概算見積を先に渡す"
    if hantei.startswith("▲"):
        return "まず計画PDFで終期を確定させる。令和9年度満了なら最優先へ格上げ"
    if joukyou in ("未確認", "一部確認"):
        return "計画PDFの表紙・第1章で計画期間を確認し、終期欄を埋める"
    if "一部改定" in hantei:
        return "改定業務が発注済みのため、範囲外の二次分析・レビューで入る余地を確認する"
