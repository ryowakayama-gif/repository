def verify(added):
    ng = []
    # ① 加筆の原文が受領ファイルに実在すること
    body = "\n".join(added.values())
    for rec in RONTEN:
        if rec[3] not in body:
            ng.append(f"受領ファイルに原文が見つからない: {rec[0]}（{rec[1]}）")
    # ② 加筆されたセルを論点として取りこぼしていないこと
    #    （見出しのセル2件は論点にしない）
    midashi = {"備考　（熊谷案）", "熊谷（考察）"}
    honbun = {k: v for k, v in added.items() if v and v not in midashi}
    if len(honbun) != len(RONTEN):
        ng.append(f"加筆{len(honbun)}セルに対し論点{len(RONTEN)}件。"
                  "取りこぼし又は重複があります: "
                  + "／".join(sorted(honbun)))
    # ③ 区分・優先度の語彙
    kubun = {"提案（方針）", "提案（村へ）", "提案（算定方針）",
             "合意（方法の確認が条件）", "合意（照会の方法まで）",
             "合意（除外の理由を村に伝える）", "指摘（是正）", "了承",
             "考察（確認が必要）"}
    for rec in RONTEN:
        assert rec[5] in kubun, f"区分が未定義: {rec[0]}（{rec[5]}）"
    for rec in URAZUKE:
        assert rec[1] in ("取れた", "取れていない"), f"裏づけが未定義: {rec[0]}"
    for rec in KAIKAI:
        assert rec[4] in ("最優先", "高", "中"), f"優先度が未定義: {rec[0]}"
    ids = [r[0] for r in RONTEN]
    assert len(ids) == len(set(ids)), "論点の番号が重複している"
    kids = [r[0] for r in KAIKAI]
    assert len(kids) == len(set(kids)), "照会事項の番号が重複している"
    # ④ 他団体の名を出さない
    for data in (RONTEN, URAZUKE, YOMITORI, KAIKAI):
        for rec in data:
            s = "".join(str(x) for x in rec)
            for bad in ("小野町", "金ヶ崎", "阿蘇"):
                if bad in s:
                    ng.append(f"他団体名が含まれている: {bad}")
    if ng:
        print("自己点検 不合格:")
        for e in ng:
            print("   -", e)
        raise SystemExit(1)
    print(f"  自己点検: 加筆{len(honbun)}セルと論点{len(RONTEN)}件が一対一／"
          "原文が受領ファイルに実在／区分・優先度の語彙すべて合")


