def _goukaku(t):
    """照会番号の記号を全角に揃える（比較のためだけに使う）。"""
    return t.replace("M-", "Ｍ-").replace("S-", "Ｓ-")


def load_added():
    """受領ファイルと当方の版の差分（加筆されたセル）を取り出す。"""
    a = load_workbook(MINE, data_only=True)
    b = load_workbook(SRC, data_only=True)
    added = {}
    for name in b.sheetnames:
        if name not in a.sheetnames:
            continue
        wa, wb_ = a[name], b[name]
        for r in range(1, max(wa.max_row, wb_.max_row) + 1):
            for c in range(1, max(wa.max_column, wb_.max_column) + 1):
                va = (wa.cell(row=r, column=c).value
                      if r <= wa.max_row and c <= wa.max_column else None)
                vb = (wb_.cell(row=r, column=c).value
                      if r <= wb_.max_row and c <= wb_.max_column else None)
                sa = "" if va is None else str(va).strip()
                sb = "" if vb is None else str(vb).strip()
                # 照会番号の記号の全角・半角の違いは加筆ではない。
                # 受領ファイルは固定であり半角のままである一方、
                # 当方は令和8年10月11日に全角へ揃えた。
                # 揃えずに比べると、直しただけのセルが
                # 「熊谷氏の加筆」として数えられてしまう。
                if _goukaku(sa) != _goukaku(sb):
                    coord = wb_.cell(row=r, column=c).coordinate
                    added[f"{name}!{coord}"] = sb
    return added


