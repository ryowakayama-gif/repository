#
# 判定は人が付けるが、**「本町の対応箇所」が実在することは機械で確かめる。**
# 素案の章立てを組み替えると、この欄だけが古い見出しを指したまま残る。
# 第9版で6章構成にしたとき、実際に「第4章 基本目標3③」のように
# 存在しない見出しを指す行が10件あった。

SOAN_DIR = ROOT / "小野町_引継ぎ_整理済" / "03_計画素案"


def soan_midashi():
    """素案の docx から章（15pt）と節（12.5pt）の見出しを読む。"""
    from docx import Document

    cands = sorted(SOAN_DIR.glob("*第10期介護保険事業計画_素案_*.docx"))
    if not cands:
        return None, {}
    path = cands[-1]
    out, cur = {}, None
    for q in Document(path).paragraphs:
        t = q.text.strip()
        if not t or not any(r.bold for r in q.runs):
            continue
        sz = max((r.font.size.pt for r in q.runs if r.font.size), default=0)
        if 15 <= sz < 16 and (re.match(r"^第\d+章　", t) or t == "資料編"
                              or t.startswith("参考")):
            cur = t.split("　")[0]            # 「第1章」「資料編」
            out.setdefault(cur, [])
        elif cur is not None and 12 <= sz < 15:
            out[cur].append(t)
    return path.name, out


def midashi_check():
    """「本町の対応箇所」が素案に実在するかを確かめる。"""
    name, mid = soan_midashi()
    if not mid:
        return name, ["素案の docx が見つかりません（先に素案を生成してください）"]
    bad = []
    for ch, se, ta, j, _memo in TAIHI:
        if ta.startswith("―"):
            continue
        # 「第6章8」「資料編9」の形を拾う（枝番・読点は無視する）
        hit = re.findall(r"(第\d+章|資料編)\s*(\d+)", ta)
        if not hit:
            # 節まで特定しない書き方（「第5章 各施策の…」）は章だけ見る
            sho = re.findall(r"(第\d+章|資料編)", ta)
            if not sho:
                bad.append(f"{ch}　{se}　対応箇所「{ta}」に章の記載がありません")
            for x in sho:
                if x not in mid:
                    bad.append(f"{ch}　{se}　対応箇所「{ta}」の{x}が素案にありません")
            continue
        for sho, setsu in hit:
            if sho not in mid:
                bad.append(f"{ch}　{se}　対応箇所「{ta}」の{sho}が素案にありません")
                continue
            if not any(s.startswith(f"{setsu}　") for s in mid[sho]):
                bad.append(f"{ch}　{se}　対応箇所「{ta}」の{sho}{setsu}が"
                           f"素案にありません（{sho}の節は "
                           + "／".join(s.split("　")[0] for s in mid[sho]) + "）")
    # 節番号が1から連番になっているか（第9版は第6章が6から始まっていた）
    for sho, ses in mid.items():
        nos = [int(m.group(1)) for s in ses
               if (m := re.match(r"^(\d+)　", s))]
        if sho.startswith("第") and nos and nos != list(range(1, len(nos) + 1)):
            bad.append(f"{sho}の節番号が1からの連番になっていません {nos}")
    return name, bad


