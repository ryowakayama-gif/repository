def taio(ch, se):
    """素案で対応した箇所。まだのものは空文字。"""
    return TAIO.get((ch, se), "")


def main():
    n_ok = sum(1 for *_x, j, _b in TAIHI if j == "○")
    n_sa = sum(1 for *_x, j, _b in TAIHI if j == "△")
    n_x = sum(1 for *_x, j, _b in TAIHI if j == "×")
    n_na = sum(1 for *_x, j, _b in TAIHI if j == "―")

    n_taio = sum(1 for ch, se, *_x in TAIHI if taio(ch, se))
    print(f"対比 {len(TAIHI)}件　○ {n_ok}／△ {n_sa}／× {n_x}／― {n_na}")
    print(f"うち素案（第9版）で対応した項目 {n_taio}件")
    print()
    print("■ 素案（第9版）で対応した項目")
    for ch, se, *_x in TAIHI:
        t = taio(ch, se)
        if t:
            print(f"  {ch}　{se}")
            print(f"      → {t}")
    print()
    print("■ 記載が無く、まだ対応していないもの（×）")
    for ch, se, _t, j, memo in TAIHI:
        if j == "×" and not taio(ch, se):
            print(f"  {ch}　{se}")
            if memo:
                print(f"      {memo.replace('**', '')}")
    print()
    print("■ 扱いが違い、まだ対応していないもの（△）")
    for ch, se, t, j, memo in TAIHI:
        if j == "△" and not taio(ch, se):
            print(f"  {ch}　{se}　→　{t}")
            if memo:
                print(f"      {memo.replace('**', '')}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
