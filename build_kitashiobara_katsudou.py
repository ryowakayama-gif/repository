def verify():
    names = [x[1] for x in INDICATORS]
    assert len(names) == len(set(names)), "活動指標名が重複しています"
    for x in INDICATORS:
        assert len(x) == 9, f"列数が9でない行があります: {x[1]}"
        assert x[3] in (M, P, MP), f"主体が想定外: {x[1]} -> {x[3]}"
        assert x[4] in (REQ, OPT), f"必須区分が想定外: {x[1]} -> {x[4]}"
        assert x[6] in ("設定", "検討", "設定しない", "―"), \
            f"設定欄が想定外: {x[1]} -> {x[6]}"
        # 都道府県のみの指標を本村で設定する矛盾がないこと
        if x[3] == P:
            assert x[6] == "―", f"都道府県指標に本村の設定が入っています: {x[1]}"
        # 必須は必ず本村で設定する
        if x[4] == REQ:
            assert x[6] == "設定", f"必須項目が設定になっていません: {x[1]}"
    n_req = sum(1 for x in INDICATORS if x[4] == REQ)
    n_v = sum(1 for x in INDICATORS if x[6] != "―")
    print(f"  自己検証: 全{len(INDICATORS)}項目／本村分{n_v}／必須{n_req}／"
          f"新規{sum(1 for x in INDICATORS if x[5] == '新規')} 整合")


