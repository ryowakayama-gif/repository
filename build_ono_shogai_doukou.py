def read_sheet():
    """見込量設定シートから、サービスと算定方法を読む。"""
    wb = load_workbook(SHEET, data_only=True)
    out = {}
    for nm, key in (("見込量算定(障害福祉)", "adult"),
                    ("見込量算定(障害児)", "child")):
        ws = wb[nm]
        rows = []
        for r in ws.iter_rows(values_only=True):
            v = list(r) + [None] * 10
            if v[0] and v[1] and str(v[0]).strip() not in ("分類",):
                rows.append({"区分": str(v[0]).strip(),
                             "サービス": str(v[1]).strip(),
                             "単位": "" if v[2] is None else str(v[2]).strip(),
                             "R5": v[3], "R6": v[4], "R7": v[5], "R8": v[6],
                             "方法": "" if v[7] is None else str(v[7]).strip()})
        out[key] = rows
    ws = wb["確認事項"]
    kaku = []
    for r in ws.iter_rows(values_only=True):
        v = list(r) + [None] * 6
        if v[0] and str(v[0]).strip() in ("最優先", "高", "中", "低"):
            kaku.append((str(v[0]).strip(), str(v[1]).strip()))
    wb.close()
    return out, kaku


