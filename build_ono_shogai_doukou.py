def run_checks(sheet, kaku, ono, iryo):
    ng = []

    # 1 設定シートの区分が国の別表第一と合うこと
    if len(sheet["adult"]) != 22:
        ng.append(f"障害福祉サービスが22区分でない: {len(sheet['adult'])}")
    if len(sheet["child"]) != 5:
        ng.append(f"障害児支援が5区分でない: {len(sheet['child'])}")
    names = [x["サービス"] for x in sheet["adult"]]
    for need in ("短期入所（福祉型）", "短期入所（医療型）", "就労選択支援"):
        if need not in names:
            ng.append(f"設定シートに{need}の行がない")

    # 2 本書2章が設定シートの算定方法を残らず拾っていること
    used = {x["方法"] for x in sheet["adult"] + sheet["child"] if x["方法"]}
    covered = set()
    for nm, _svc, _man, _sho in SANTEI:
        for part in nm.replace("／", "、").split("、"):
            covered.add(part.strip())
    miss = sorted(m for m in used if not any(c in m or m in c for c in covered))
    if miss:
        ng.append(f"2章が拾っていない算定方法がある: {miss}")

    # 3 確認事項との重複を避けていること（医療的ケア児等は重複を明示済み）
    if not kaku:
        ng.append("設定シートの確認事項を読めていない")
    kaku_txt = " ".join(x[1] for x in kaku)
    for kw in ("継続入所者", "保育所等", "別表第五", "全部過疎"):
        if kw in kaku_txt:
            ng.append(f"確認事項に既にある事項を指摘している: {kw}")

    # 4 骨子案の表記が新表記に揃っていること（D7の対応の確認）
    if iryo[1] != 0:
        ng.append(f"骨子案に旧表記が{iryo[1]}か所残っている。"
                  "build_ono_kosshi.py を直して作り直す")
    if iryo[0] < 1:
        ng.append("骨子案に「医療的ケア児等コーディネーター」が現れない")

    # 5 過疎の欄が一部過疎を含む区分であること（D4の前提）
    if not ono or ono["過疎"] is None:
        ng.append("小野町の過疎該当を読めていない")

    # 6 指摘の重さが3段階のいずれかであること
    for x in SHITEKI:
        if x[1] not in ("重大", "重要", "軽微"):
            ng.append(f"重さの区分が不正: {x[0]}={x[1]}")

    # 7 問31の15サービスがすべて設定シートのサービスに対応していること
    mon31, n31, _f = read_mon31()
    if len(mon31) != 15:
        ng.append(f"問31のサービスが15件でない: {len(mon31)}")
    svc = {x["サービス"] for x in sheet["adult"]}
    for _abbr, svcs, _c, _i in mon31:
        for sv in svcs:
            if sv not in svc:
                ng.append(f"問31の対応先が設定シートにない: {sv}")
    # 8 R8実績0かつ利用意向ありのサービスが存在すること（D8の前提）
    r8 = {x["サービス"]: x["R8"] for x in sheet["adult"]}
    zero = [a for a, svcs, _c, i in mon31
            if all((r8.get(sv) or 0) == 0 for sv in svcs) and i > 0]
    if not zero:
        ng.append("R8実績0かつ利用意向ありのサービスが無い。D8を取り下げる")
    if len(SHITEKI) < 10:
        ng.append(f"指摘が少なすぎる: {len(SHITEKI)}")

    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("  -", x)
        return False
    print(f"自己点検: 合格　"
          f"算定方法 {len(used)}種をすべて対照／"
          f"確認事項 {len(kaku)}件と重複なし／"
          f"国の動向 {len(DOUKOU)}件／ものとする要件 {len(MONOTOSURU)}件／"
          f"別表第五 {len(BEPPYO5)}項／医療的ケア {len(IRYO)}件／"
          f"手順の乖離 {len(TEJUN)}件")
    return True


