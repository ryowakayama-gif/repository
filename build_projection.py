def pop(c, y):
    """推計上の階級別人口＝実績人口×社人研推計の伸び率。"""
    return BP[c] * apop(c, y) / apop(c, BASE_Y)


def rate(c, y, sc):
    """シナリオ別の階級別認定率。"""
    d = int(y) - int(BASE_Y)
    if sc == 1:
        return BR[c]
    if sc == 2:
        return BR[c] + TR[c] * min(max(d, 0), TREND_END)
    # シナリオ3　令和11年度にかけて令和元年の水準へ戻り、以後固定
    k = min(max(d, 0), TREND_END) / TREND_END
    return BR[c] + (R1[c] - BR[c]) * k


def total(y, sc):
    return sum(pop(c, y) * rate(c, y, sc) / 100 for c in CL)


def pop_all(y):
    return sum(pop(c, y) for c in CL)


