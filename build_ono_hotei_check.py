def judge(text, words):
    """すべての語があれば○、一部なら△、どれもなければ×。"""
    hit = [w for w in words if w.replace("**", "") in text]
    if len(hit) == len(words):
        return "○", hit
    if hit:
        return "△", hit
    return "**✕**", hit


def run(path, spec):
    t = body(path)
    out = []
    for jo, koto, gimu, words, saki in spec:
        mark, hit = judge(t, words)
        nai = [w for w in words if w.replace("**", "") not in t]
        out.append((jo, koto, gimu, mark, saki,
                    "―" if mark == "○" else "見つからない語：" + "・".join(nai)))
    return out


