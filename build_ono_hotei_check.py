def jiko(kai, sho):
    ng = []
    # 1 現物が存在する
    for p in (SOAN, KOSSHI):
        if not p.exists():
            ng.append("現物がない：%s" % p.name)
    # 2 判定がすべて付いている
    for x in kai + sho:
        if x[3] not in ("○", "△", "**✕**"):
            ng.append("判定が付いていない：%s" % x[0])
    # 3 義務・努力の別が付いている
    for x in kai + sho:
        if x[2] not in ("義務", "努力", "―"):
            ng.append("義務の別が付いていない：%s" % x[0])
    # 4 判定に用いた語が空でない
    for jo, _k, _g, words, _s in KAIGO + SHOGAI_HOTEI:
        if not words:
            ng.append("判定に用いる語がない：%s" % jo)
    # 5 ○以外には見つからない語が書いてある
    for x in kai + sho:
        if x[3] != "○" and x[5] == "―":
            ng.append("○でないのに備考が―：%s" % x[0])
    # 6 老人福祉事業の量の目標を見ている
    if not any("老人福祉事業の量の目標" in x[1] for x in KAIGO):
        ng.append("老人福祉事業の量の目標を見ていない")
    # 7 改正で新設された号を見ている
    for need in ("第117条第2項第3号", "第117条第2項第4号", "第117条第5項【新設】"):
        if not any(x[0] == need for x in KAIGO):
            ng.append("改正の新設を見ていない：%s" % need)
    # 8 障がい側も改正の新設を見ている
    for need in ("総合支援法第88条第3項第3号", "総合支援法第88条第3項第4号",
                 "総合支援法第88条第3項第5号"):
        if not any(x[0] == need for x in SHOGAI_HOTEI):
            ng.append("障がいの新設を見ていない：%s" % need)
    return ng


def main():
    p, r, kai, sho = doc_build()
    ng = jiko(kai, sho)
    print("■ 法定記載事項チェック")
    print("   %s" % p.relative_to(ROOT.parent))
    print("   表%d・見出し%d" % (r.capno, len(r.headings)))
    for nm, rows in (("高齢者", kai), ("障がい", sho)):
        from collections import Counter
        c = Counter(x[3] for x in rows)
        print("   %s %d件　○%d／△%d／✕%d"
              % (nm, len(rows), c.get("○", 0), c.get("△", 0),
                 c.get("**✕**", 0)))
        for x in rows:
            if x[3] != "○":
                print("      %s %-34s %s" % (x[3].replace("**", ""),
                                             x[0], x[5][:46]))
    print("\n■ 自己点検 8項目")
    if ng:
        for x in ng:
            print("   NG  %s" % x)
        return 1
    print("   すべて適合")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
