def body(path):
    """docx の本文を1つの文字列にする（表の中も含む）。"""
    with zipfile.ZipFile(path) as z:
        raw = z.read("word/document.xml").decode("utf-8", "ignore")
    return re.sub(r"\s+", "", re.sub(r"<[^>]+>", "", raw))


