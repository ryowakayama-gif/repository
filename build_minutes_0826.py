def progress_text():
    """業務進捗の行の本文。

    議事録は会議の当日に報告した値を記すものであるため、
    現時点の値（data_progress.PROGRESS）ではなく、
    当日の記録（data_progress.KIROKU）を用いる。
    """
    import data_progress as G
    rec = G.KIROKU[KAIGI_HI]
    nm = {no: n for no, n, _v, _s, _d in G.PROGRESS}
    seq = [(no, nm[no], v) for no, v in rec.items()]
    zentai = round(sum(rec.values()) / len(rec) * 100)
    top = sorted(seq, key=lambda x: -x[2])[:3]
    low = [x for x in seq if x[2] <= 0.45]
    return (
        "仕様書４(1)〜(12)の区分ごとに業務進捗を報告し、"
        "%s時点の全体の進捗が%d％であることを確認。"
        "先行しているのは%sである。"
        "%sは、令和6〜8年度の実績（年報・月報・給付実績データ）の"
        "受領により進む。"
        "%sは今後の工程による。"
        "詳細は業務進捗報告書（令和8年8月分）による。"
        % (KAIGI_HI, zentai,
           "、".join("%s%s%d％" % (a, b, c * 100) for a, b, c in top),
           "(2)第9期計画の評価・検証%d％・(5)将来推計%d％"
           % (rec["(2)"] * 100, rec["(5)"] * 100),
           "、".join("%s%s%d％" % (a, b, c * 100) for a, b, c in low)))


def add_progress_row(content):
    """「2. 合意・確認された内容」の表の末尾に業務進捗の行を加える。"""
    anchor = "平準化に向け、今後検討。</text:span></text:p>" \
             "</table:table-cell></table:table-row>"
    if anchor not in content:
        raise AssertionError("業務進捗の行の挿入位置が見つからない")
    return content.replace(
        anchor, anchor + PROGRESS_ROW % progress_text(), 1)


def build_odt():
    """受領版の書式を保ったまま、本文と文書プロパティを校正する。"""
    with zipfile.ZipFile(SRC) as z:
        names = z.namelist()
        data = {n: z.read(n) for n in names}

    content = data["content.xml"].decode("utf-8")
    applied = []
    for row in FIX:
        old, new = row[6], row[7]
        if not old:
            continue
        if old not in content:
            raise AssertionError("置換対象が見つからない: %r" % old)
        n = content.count(old)
        content = content.replace(old, new)
        applied.append((row[0], n))
    content = add_progress_row(content)
    data["content.xml"] = content.encode("utf-8")

    if os.path.exists(OUT_ODT):
        os.remove(OUT_ODT)
    with zipfile.ZipFile(OUT_ODT, "w", zipfile.ZIP_DEFLATED) as z:
        # mimetype は無圧縮で先頭に置く
        z.writestr(zipfile.ZipInfo("mimetype"), data["mimetype"],
                   compress_type=zipfile.ZIP_STORED)
        for n in names:
            if n == "mimetype":
                continue
            z.writestr(n, data[n])

    docmeta.clean_odt(
        OUT_ODT,
        "大雪地区広域連合　第10期介護保険事業計画　"
        "第9期計画の評価・検証　中間報告　会議議事録（令和8年8月26日開催）",
        "第9期計画の評価・検証 中間報告の会議の議事録")
    return applied


