def _norm(t):
    return re.sub(r"[\s　]+", "", str(t))


def _honpon_rows():
    from docx import Document
    d = Document(HONPON)
    rows = []
    for t in d.tables:
        for r in t.rows:
            rows.append([_norm(c.text) for c in r.cells])
    return rows


def _review_text():
    from docx import Document
    d = Document(REVIEW)
    return _norm("\n".join(p.text for p in d.paragraphs))


def kensa(rows, review, kpi):
    ng = []
    # ① レビューの推奨項目がすべて定義票の欄になっていること
    m = re.search(r"KPIの名称／.*?を1指標ごとに記載する", review)
    if not m:
        ng.append("① レビューに推奨項目の文が無い")
    else:
        for _r, _k, go in RAN:
            if go and _norm(go) not in m.group(0):
                ng.append(f"① レビューに無い推奨項目を欄にしている: {go}")
        kou = [re.sub(r"（.*?）", "", x) for x in re.split(
            r"[／]", m.group(0).replace("を1指標ごとに記載する", "")) if x]
        mochi = "".join(_norm(go) for _r, _k, go in RAN if go)
        for x in kou:
            if not any(w in mochi for w in re.split(r"[・と]|または", x) if w):
                ng.append(f"① 推奨項目が欄に無い: {x}")
    # ② 正本の値を写したものは、正本の表の行に実在すること
    for k in kpi:
        for lab, val in k["hon"]:
            if not any(any(_norm(lab) == c for c in r) and
                       any(_norm(val) in c for c in r) for r in rows):
                ng.append(f"② 正本の表に無い値: {k['no']} {lab}＝{val}")
    # ③ 提案の指標に値を作っていないこと（基準値・目標値は村が決定）
    for k in kpi:
        if k["teian"]:
            mk = [v for v in k["mokuhyo"] if v not in (KETTEI, "―")]
            if mk:
                ng.append(f"③ 提案の指標に目標値を置いている: {k['no']}")
            if not k["na"].endswith("【提案】"):
                ng.append(f"③ 提案の指標に【提案】が無い: {k['no']}")
        elif not k["hon"] and k["bunya"] != "第４次計画":
            ng.append(f"③ 提案でない指標に正本の出所が無い: {k['no']}")
    # ④ 番号が連番で重ならず、公表区分・区分が定義どおりであること
    nos = [k["no"] for k in kpi]
    if nos != [f"Ｋ-{i:02d}" for i in range(1, len(kpi) + 1)]:
        ng.append("④ 番号が連番でない")
    for k in kpi:
        if k["kouhyou"] not in KOUHYOU:
            ng.append(f"④ 公表区分が未定義: {k['no']}")
        if k["kubun"] not in (SEIKA, KATSUDO, TAISEI):
            ng.append(f"④ 区分が未定義: {k['no']}")
    # ④b 参考の目標案は提案の指標にだけ置くこと
    for k in kpi:
        if k["sankou"] and not k["teian"]:
            ng.append(f"④b 提案でない指標に参考の目標案がある: {k['no']}")
    if set(DAI4JI_KUBUN) != {r[1] for r in SHIHYOU}:
        ng.append("④b 第４次計画の指標の区分が SHIHYOU と揃っていない")
    # ⑤ 国の8分野がすべて1指標以上あること
    for b in "①②③④⑤⑥⑦⑧":
        if not any(k["bunya"] == b for k in kpi):
            ng.append(f"⑤ 国の分野{b}の指標が無い")
    return ng


