def sheet(wb, name, header, rows, ws_widths, wrap_cols=(), st_col=None,
          notes=()):
    ws = wb.create_sheet(name)
    ws.append(header)
    for r in rows:
        ws.append(list(r))
    head_row(ws)
    widths(ws, ws_widths)
    body_style(ws, wrap_cols=wrap_cols, max_row=1 + len(rows))
    if st_col is not None:
        for i in range(len(rows)):
            c = ws.cell(2 + i, st_col + 1)
            f = ST_FILL.get(str(c.value))
            if f:
                c.fill = f
                c.alignment = Alignment(horizontal="center", vertical="center")
    for n in notes:
        ws.append([])
        ws.append([n])
        ws.cell(ws.max_row, 1).font = Font(size=8)
    ws.freeze_panes = "A2"
    return ws


