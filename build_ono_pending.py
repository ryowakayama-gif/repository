    # 2 優先順位が1からの通し番号か
    ranks = [d["rank"] for d in pend]
    if ranks != list(range(1, len(pend) + 1)):
        bad.append(f"優先順位の通し番号が崩れている {ranks[:5]}…")
    # 3 件数が打合せ資料と一致するか
    want = len(KETTEI) + len(SHIRYO) + len(KOKU)
    if len(pend) != want:
        bad.append(f"件数の不一致 {len(pend)} 対 {want}")
    # 4 波及先がWBSに存在するNoか（打ち間違いを捕まえる）
    for d in pend:
        for s in d["saki"]:
            if s not in wbs_nos:
                bad.append(f"波及先にないWBS No {s}（{d['kind']}{d['no']}）")
    for t in TSUZUKU:
        for s in t[5]:
            if s.startswith("障がい"):
                continue
            if s not in wbs_nos:
                bad.append(f"作業継続可能 {t[0]} の波及先にないWBS No {s}")
    # 5 1日の作業量が上限を超えていないか
    #   上限は「これから組む予定」に対する制約である。済んだ日は実績なので
    #   対象にしない（5b の土日の扱いと同じ）。予定より早く片づいた日を
    #   超過として止めると、前倒しできなくなる。
    per = defaultdict(float)
    for t in TSUZUKU:
        if t[7]:
            continue
        per[t[6]] += t[3]
    for day, h in sorted(per.items()):
        if h > DAY_H + 1e-9:
            bad.append(f"{day} の作業量 {h:.1f}時間が上限 {DAY_H:.1f}時間を超えている")
    # 5b 着手日が土日に乗っていないか（乗せても誰も作業しない）
    #    済んだ日は実績なので対象にしない。実際に動いた日は動いた日である。
    mada = {t[6] for t in TSUZUKU if not t[7]}
    for day in sorted(mada):
        if datetime.date.fromisoformat(day).weekday() >= 5:
            bad.append(f"着手日 {day} が土日（{youbi(day)}）")
    # 6 作業継続可能な項目に、町の回答を待つものが混ざっていないか
    machi = ("町データ待ち", "町の回答待ち", "受領待ち", "決算確定後")
    for t in TSUZUKU:
        if any(k in plain(t[2]) for k in machi):
            bad.append(f"作業継続可能 {t[0]} の理由に待ちが混ざっている")
    # 6b 着手日が基準日より前になっていないか（過去に着手予定は書けない）
    for t in TSUZUKU:
        if not t[7] and t[6] < ASOF_ISO:
            bad.append(f"作業継続可能 {t[0]} の着手日 {t[6]} が基準日より前"
                       "（済んでいないのに日付が過ぎている）")
        if t[7] and t[7] > ASOF_ISO:
            bad.append(f"作業継続可能 {t[0]} の完了日 {t[7]} が基準日より後")
    # 6b2 作業の並びが着手日の順になっているか
    # （1日の中の順番は、このリストの並びがそのまま着手順になる）
    days = [t[6] for t in TSUZUKU]
    if days != sorted(days):
        bad.append(f"作業継続可能の並びが着手日順でない {days}")
    # 6c 乖離が両計画について計算できているか
    for nm, wbs in (("高齢者", WBS_ELDERLY), ("障がい", WBS_DISABILITY)):
        k = kairi(wbs)
        if len(k["rows"]) != len(wbs):
            bad.append(f"{nm}の乖離の行数 {len(k['rows'])} が作業数 {len(wbs)} と違う")
        if any(not x[11] for x in k["rows"]):
            bad.append(f"{nm}に判定の付いていない作業がある")
    # 6d 次に着手するものに、その順にする理由が書いてあるか
    #     書いていないと、生成の途中で落ちる。先にここで止める。
    for t in TSUZUKU:
        if not t[7] and t[6] == NEXT_ISO and t[0] not in RIYU:
            bad.append(f"作業 {t[0]} に、その順にする理由（RIYU）がない")
    # 7 翌日の作業が1件以上あるか
    if not [t for t in TSUZUKU if t[6] == NEXT_ISO]:
        bad.append("翌日の作業が1件もない")
    # 8 Noの重複
    for nm, seq in (("作業継続可能", [t[0] for t in TSUZUKU]),):
        if len(set(seq)) != len(seq):
            bad.append(f"{nm}のNoに重複がある")
    if bad:
        for b in bad:
            print(f"  不適合: {b}")
        raise SystemExit(1)
    print(f"  自己点検 14項目 適合（ペンディング{len(pend)}件／"
          f"作業継続可能{len(TSUZUKU)}件／稼働{sum(per.values()):.1f}時間）")
    return per


