def _aite(label, no, tanto):
    """確認の相手。1回の打合せ・1通の照会で片付く単位で束ねるために使う。"""
    if label == "決定":
        return "町・関係機関" if "関係機関" in plain(tanto) else "町（政策判断）"
    if label == "依頼資料":
        # 調査結果報告書の中の食い違いは、町でも当方でも決着しない。
        return "調査を実施された事業者" if no == "19" else "町（資料・データ）"
    return plain(tanto)


def pending_rows():
    """止まっている項目を1本の待ち行列にして、影響度と緊急度から順位を付ける。

    出どころは3つある。前2つは打合せ資料から引き、国・県の決定待ちだけは
    町に向けた一覧がないため本資料で定義している。
    """
    rows = []
    for src, cls, label in ((KETTEI, EK, "決定"), (SHIRYO, ES, "依頼資料"),
                            (KOKU, None, "国・県")):
        for r in src:
            no = r[0]
            if cls is None:                       # KOKU は行に影響度を持つ
                eik, ugoku, saki, taisaku = r[4], r[5], r[6], r[7]
            else:
                if no not in cls:
                    raise SystemExit(
                        f"影響度が付いていない{label} {no}：{plain(r[1])}")
                eik, ugoku, saki, taisaku = cls[no]
            kpt, klab = kinkyu(r[2])
            # 波及点は、止まったままだと動かないWBSの作業の数（上限3点）。
            # 影響度と緊急度が同じなら、波及の広いものを先に片付ける。
            hakyu = min(len(saki), 3)
            if (label, no) not in TABA:
                raise SystemExit(f"束が付いていない{label} {no}：{plain(r[1])}")
            rows.append({
                "kind": label, "no": no, "name": r[1], "limit": r[2],
                "taba": TABA[(label, no)],
                "tanto": r[3], "aite": _aite(label, no, r[3]),
                "eik": eik, "eik_pt": EIKYO[eik][1],
                "kin": klab, "kin_pt": kpt,
                "ugoku": ugoku, "saki": saki, "hakyu": hakyu,
                "taisaku": taisaku,
                "score": EIKYO[eik][1] * 10 + kpt * 2 + hakyu,
            })
    rows.sort(key=lambda d: (-d["score"], d["kind"], int(d["no"])))
    for i, d in enumerate(rows, 1):
        d["rank"] = i
    return rows


