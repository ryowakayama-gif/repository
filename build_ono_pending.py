def plain(t):
    return re.sub(r"\*\*", "", str(t))


def kairi(wbs):
    """進捗の乖離。業務進捗管理表と同じ関数で計算するので、両者がずれない。"""
    kr = kairi_rows(wbs, ASOF_ISO)
    den = sum(r[10] for r in kr)
    return {
        "rows": kr,
        "ev": sum(r[7] * r[10] for r in kr) / den,
        "pv": sum(r[8] * r[10] for r in kr) / den,
        "cnt": Counter(r[11] for r in kr),
        "okure": sorted([r for r in kr
                         if r[11].startswith("期限超過") or r[11] == "遅れ"],
                        key=lambda x: (x[9], -x[10])),
    }


def youbi(day):
    return "月火水木金土日"[datetime.date.fromisoformat(day).weekday()]


def hizuke(day):
    """2026-10-02 → 10月2日（金）。"""
    d = datetime.date.fromisoformat(day)
    return f"{d.month}月{d.day}日（{youbi(day)}）"


