def build_xlsx(M):
    wb = openpyxl.Workbook()
    wb.remove(wb.active)

    ws = wb.create_sheet("00_コメント案")
    ws.append(["行", "節", "項目", "コメント案（そのまま貼れます）"])
    style_head(ws)
    for r, nm, sec, txt in COMMENT:
        ws.append([r, sec, nm, txt.replace("／", "\n")])
        ws.cell(ws.max_row, 4).fill = IN
    ws.append(["", "＜追記案＞", "ワーニングが残る件", WARN_NOTE])
    ws.cell(ws.max_row, 4).fill = IN
    body_style(ws, wrap=(3, 4))
    widths(ws, [6, 26, 34, 96])
    ws.freeze_panes = "A2"
    ws.append([])
    ws.append(["※ 出典：ワークシート「4_施策反映の解説」。行番号は同シートのもの。"])
    ws.append(["※ 【A案】伸びを0（ゼロ）に戻せた場合／"
               "【B案】やむを得ず他の伸びを選んだ場合／"
               "【C案】施策反映で数値を補正した場合。該当する1案を残す。"])

    ws = wb.create_sheet("01_伸びを戻す手だて")
    ws.append(["順", "手だて", "内容", "目安"])
    style_head(ws)
    for a, b, c, d in TEDATE:
        ws.append([a, b.replace("**", ""), c.replace("**", ""), d])
    body_style(ws, wrap=(2, 3))
    widths(ws, [4, 38, 80, 8])
    ws.freeze_panes = "A2"

    ws = wb.create_sheet("02_補正の目標値")
    ws.append(["サービス", "令和7年度の回（日）数", "令和7年度の利用者数",
               "1人1月あたり", "単位", "いまの推計値"])
    style_head(ws)
    for nm, (per, tani, kaisu, ninzu) in M.items():
        ws.append([nm, kaisu, ninzu, per, tani,
                   "要支援2が▲12.6回" if "訪問看護" in nm else "要介護1が20.5日"])
    for r in range(2, ws.max_row + 1):
        for c in (2, 3, 4):
            ws.cell(r, c).number_format = "#,##0.0"
        ws.cell(r, 4).fill = OK
    body_style(ws)
    widths(ws, [24, 20, 20, 14, 8, 22])
    ws.freeze_panes = "A2"
    ws.append([])
    ws.append(["※ 出典：ワークシート「2_サービス別給付費」の令和7年度。"
               "回（日）数・利用者数はいずれも1月あたり。"])
    ws.append(["※ 要介護（支援）度別の内訳は画面でご確認ください。"
               "画面の令和7年度の行の値を、令和9〜11年度にそのまま写します。"])

    p = OUT / f"小野町_見える化_コメント案_{ASOF}.xlsx"
    wb.save(p)
    return p


