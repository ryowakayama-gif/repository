def report_paras():
    d = docx.Document(str(REPORT))
    return [p.text for p in d.paragraphs if p.text.strip()]


def report_design():
    """報告書の表1-1（調査の概要）を読む。"""
    d = docx.Document(str(REPORT))
    for t in d.tables:
        rows = [[c.text.strip() for c in r.cells] for r in t.rows]
        if rows and rows[0][:3] == ["項目", "障がい者調査", "障がい児調査"] and any(r[0] == "配布数" for r in rows):
            return {r[0]: (r[1], r[2]) for r in rows[1:]}
    return {}


def cite_check(paras, items):
    """各結果の（語, 割合）が、報告書の同じ段落に並んで出てくるか。"""
    ng = []
    for nm, _txt, pairs in items:
        for w, pct in pairs:
            if not any(w in p and pct in p for p in paras):
                ng.append("調査の結果「%s」：報告書に「%s」と「%s」が並ぶ段落がない" % (nm, w, pct))
    return ng


def soan_marks():
    """素案（第3版）の未確定の印を数える。"""
    d = docx.Document(str(SOAN))
    texts = [p.text for p in d.paragraphs]
    for t in d.tables:
        texts += [c.text for r in t.rows for c in r.cells]
    cnt = {}
    for t in texts:
        for m in re.findall(r"【(町データ待ち|協議会で設定|決定後に記載|算定後に記載)】", t):
            cnt[m] = cnt.get(m, 0) + 1
    return cnt


