    zenbun = "\n".join(
        str(v) for g in (SHINKI, JIBUN_NAOSU, SEIKAHIN, SHOUKAI)
        for rec in g for v in rec)
    honbun = "\n".join(
        b[1] if isinstance(b[1], str) else ""
        for rec in TK_EDITS for b in rec["nakami"])
    honbun += "\n".join(r["ato"] for r in TK_KAKIKAE)
    if "か所" in honbun:
        ng.append("計画本文に「か所」を使っている（「カ所」とする）")
    for warui in ("小野町", "金ケ崎", "金ヶ崎", "阿蘇", "札幌"):
        if warui in zenbun + honbun:
            ng.append(f"他団体の案件の地名が入っている: {warui}")

