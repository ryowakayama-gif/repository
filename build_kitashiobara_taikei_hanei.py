def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for row in t.rows:
            for c in row.cells:
                out.append(c.text)
    return "\n".join(out)


def _norm(s):
    return re.sub(r"[\s　]+", "", str(s))


def _sho_setsu(path):
    """正本を章・節・項ごとに切り、本文を集める。

    表３-３に書いた「本計画での位置」が実際にその場所かを
    確かめるために使う。
    """
    from docx.table import Table
    from docx.text.paragraph import Paragraph
    d = docx.Document(path)
    out = {}
    sho = setsu = ko = ""

    def tsumu(t):
        for key in (sho, sho + setsu, sho + setsu + ko):
            if key:
                out[key] = out.get(key, "") + "\n" + t

    for ch in d.element.body.iterchildren():
        if ch.tag.endswith("}p"):
            p = Paragraph(ch, d)
            t = p.text.strip()
            if not t:
                continue
            st = p.style.name
            if st == "Heading 1" and re.match(r"^第[０-９]章", t):
                sho = t[:3]
                setsu = ko = ""
            elif st == "Heading 2":
                setsu = t.split("　")[0]
                ko = ""
            elif st in ("Heading 3", "小見出し") and t.startswith("（"):
                ko = t.split("　")[0] if "　" in t else t[:t.find("）") + 1]
            tsumu(t)
        elif ch.tag.endswith("}tbl"):
            tb = Table(ch, d)
            tsumu("\n".join(c.text for r in tb.rows for c in r.cells))
    return out


