def _level_ok(t):
    """見出しの階層が1段より多く飛んでいないこと。"""
    lv = [len(m.group(1)) for m in re.finditer(r"^(#+)\s", t, re.M)]
    return all(b - a <= 1 for a, b in zip(lv, lv[1:]))


def _table_ok(t):
    """表の列数が見出しの行と揃っていること。"""
    rows, head = [], None
    for ln in t.split("\n"):
        if ln.startswith("|") and ln.endswith("|"):
            n = ln.count("|") - 1
            if head is None:
                head = n
            elif set(ln.replace("|", "").replace(" ", "")) <= set("-:"):
                if n != head:
                    return False
            elif n != head:
                rows.append((head, n))
        else:
            head = None
    return not rows


