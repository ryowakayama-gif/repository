# 一式の名と群は、束ねる側の定めから読む（同じ一覧を2か所に持たない）。
def _literal(name, path="build_zips.py"):
    import ast
    with io.open(os.path.join(RP.ROOT, path), encoding="utf-8") as f:
        src = f.read()
    for node in ast.parse(src).body:
        if (isinstance(node, ast.Assign)
                and any(getattr(t, "id", None) == name
                        for t in node.targets)):
            return ast.literal_eval(node.value)
    raise KeyError(name)


