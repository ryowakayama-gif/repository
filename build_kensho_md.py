def sa(v, nd=1, c=False):
    """＋と▲で差を書く。"""
    f = ("{:+,.%df}" if c else "{:+.%df}") % nd
    s = f.format(v)
    return s.replace("-", "▲").replace("+", "＋")


def pct(v, nd=1):
    return ("{:.%df}％" % nd).format(v)


def yen(v):
    return "{:,.0f}円".format(v)


