def put_title(ws, title, subtitle, ncols):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncols)
    c = ws.cell(row=1, column=1, value=title)
    c.font = F_TITLE
    c.alignment = Alignment(vertical="center")
    ws.row_dimensions[1].height = 26
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=ncols)
    c2 = ws.cell(row=2, column=1, value=subtitle)
    c2.font = F_SMALL
    c2.alignment = Alignment(vertical="center", wrap_text=True)
    ws.row_dimensions[2].height = 16


def put_header(ws, row, headers, widths, fill=None):
    fill = fill or C["header"]
    for i, h in enumerate(headers, start=1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = F_HEAD
        c.fill = PatternFill("solid", fgColor=fill)
        c.alignment = AL_HEAD
        c.border = BORDER
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[row].height = 32
    ws.freeze_panes = ws.cell(row=row + 1, column=1)


def put_rows(ws, start_row, rows, center_cols=(), level_col=None, phase_col=None,
             band_col=None, band_colors=None):
    """rows: list[list] を書き込む。level_col/phase_col は 1-origin の列番号。"""
    r = start_row
    for idx, row in enumerate(rows):
        for i, v in enumerate(row, start=1):
            c = ws.cell(row=r, column=i, value=v)
            c.font = F_BODY
            c.border = BORDER
            c.alignment = AL_CTR if i in center_cols else AL_WRAP
            if idx % 2 == 1:
                c.fill = PatternFill("solid", fgColor=C["alt"])
        if level_col:
            lv = str(ws.cell(row=r, column=level_col).value or "")
            key = lv.strip().split("→")[-1].strip()
            if key in ("L1", "L2", "L3", "L4", "L5"):
                cc = ws.cell(row=r, column=level_col)
                cc.fill = PatternFill("solid", fgColor=C[key])
                cc.font = F_BOLD
        if phase_col:
            pv = str(ws.cell(row=r, column=phase_col).value or "")
            for k in ("Ⅰ", "Ⅱ", "Ⅲ", "Ⅳ", "Ⅴ"):
                if pv.startswith(k):
                    n = "P" + str("ⅠⅡⅢⅣⅤ".index(k) + 1)
                    ws.cell(row=r, column=phase_col).fill = PatternFill("solid", fgColor=C[n])
        if band_col and band_colors:
            bv = str(ws.cell(row=r, column=band_col).value or "")
            for k, col in band_colors.items():
                if k in bv:
                    cc = ws.cell(row=r, column=band_col)
                    cc.fill = PatternFill("solid", fgColor=col)
                    cc.font = Font(name="Meiryo UI", size=9, bold=True, color="FFFFFF")
                    break
        r += 1
    return r


def add_filter(ws, header_row, ncols, last_row):
    ws.auto_filter.ref = f"A{header_row}:{get_column_letter(ncols)}{last_row}"


def section(ws, row, text, ncols, color=None):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name="Meiryo UI", size=10, bold=True, color="FFFFFF")
    c.fill = PatternFill("solid", fgColor=color or C["subhead"])
    c.alignment = Alignment(vertical="center")
    ws.row_dimensions[row].height = 20
    return row + 1


