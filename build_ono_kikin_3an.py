def _sheet_year(title):
    t = title.translate(str.maketrans("０１２３４５６７８９", "0123456789"))
    for y in NEN:
        if t.startswith(y):
            return y
    return None


def kessan():
    """積立（歳出）と取崩（歳入の繰入金）を年度ごとに千円で返す。"""
    tsumi, tori, kuri = {}, {}, {}
    for f, col_nm, col_v, key, store in (
            ("決算状況（歳出）.xlsx", 5, 14, "介護給付費準備基金積立金", tsumi),
            ("決算状況（歳入）.xlsx", 4, 6, "介護給付費準備基金繰入金", tori),
            ("決算状況（歳入）.xlsx", 4, 6, "繰越金", kuri)):
        wb = openpyxl.load_workbook(KESSAN / f, read_only=True, data_only=True)
        for ws in wb.worksheets:
            y = _sheet_year(ws.title)
            if not y:
                continue
            for r in ws.iter_rows(min_row=2, values_only=True):
                if len(r) > col_v and r[col_nm] == key:
                    store[y] = float(r[col_v]) / 1000
    return tsumi, tori, kuri


def nenpo():
    d = {}
    for yr in (2021, 2022, 2023, 2024):
        wb = openpyxl.load_workbook(NENPO / ("年報データ_%d_小野町.xlsx" % yr), read_only=True, data_only=True)
        for r in wb["様式４"].iter_rows(values_only=True):
            s = [c for c in r if c is not None]
            if s and str(s[0]) == "介護給付費準備基金保有額":
                d["R%d" % (yr - 2018)] = float(s[1]) / 1000
    return d


def town_check():
    """町の公表資料の PDF の「介護給付費準備基金」の行に、TOWN_CHECK の数字が順に並んでいるか。"""
    import re
    import subprocess
    ng = []
    for f, nums in TOWN_CHECK:
        txt = subprocess.run(["pdftotext", "-layout", str(TOWN_DIR / f), "-"],
                             capture_output=True, text=True).stdout
        lines = [ln for ln in txt.splitlines() if "介護給付費" in ln]
        ok = any(re.search(r"\s+".join(re.escape(n) for n in nums) + r"(\s|$)",
                           re.sub(r"^.*?介護給付費\S*", "", ln)) for ln in lines)
        if not ok:
            ng.append("町の公表資料 %s に %s の並びがない" % (f, "・".join(nums)))
    return ng


def zandaka(tsumi, tori):
    """年度末残高。令和5年度末までは町の財務書類、以後は決算の積立・取崩、令和8年度は予算。"""
    flow = {y: tsumi.get(y, 0) - tori.get(y, 0) for y in NEN}
    z = dict(TOWN_ZAN)
    z["R6"] = z["R5"] + flow["R6"]
    z["R7"] = z["R6"] + flow["R7"]
    r8 = TOWN_R8["当初"] + TOWN_R8["9月補正"]
    z["R8"] = z["R7"] + r8                       # 繰入は存目（1千円）のため0とみる
    z8_tosho = z["R7"] + TOWN_R8["当初"]          # 9月補正の積立を除いたとき
    return flow, z, z8_tosho


