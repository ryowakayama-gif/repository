def set_text(p, text):
    """段落のテキストを差し替える（先頭の run に入れ、以降の run は空にする）。"""
    ts = list(p._p.iter(qn("w:t")))
    if not ts:
        return False
    ts[0].text = text
    ts[0].set(qn("xml:space"), "preserve")
    for t in ts[1:]:
        t.text = ""
    return True


def set_cell(cell, text):
    """表のセルのテキストを差し替える（2段落目以降は削除して書式は先頭段落のまま）。"""
    ps = cell.paragraphs
    for p in ps[1:]:
        p._p.getparent().remove(p._p)
    return set_text(ps[0], text)


def insert_after_el(el, tpl_p, texts):
    """el（段落または表）の直後に、tpl_p を書式のひな形として段落を挿入する。"""
    prev = el
    for text in texts:
        new = copy.deepcopy(tpl_p._p)
        ts = list(new.iter(qn("w:t")))
        if ts:
            ts[0].text = text
            ts[0].set(qn("xml:space"), "preserve")
            for t in ts[1:]:
                t.text = ""
        prev.addnext(new)
        prev = new


def set_widths(tbl, ratio):
    """列幅を ratio の比率に振り直す。総幅はひな形のまま保つ。"""
    grid = tbl.find(qn("w:tblGrid"))
    cols = grid.findall(qn("w:gridCol"))
    total = sum(int(c.get(qn("w:w"))) for c in cols)
    s = sum(ratio)
    new = [int(total * r / s) for r in ratio]
    new[-1] = total - sum(new[:-1])
    for c, w in zip(cols, new):
        c.set(qn("w:w"), str(w))
    for tr in tbl.findall(qn("w:tr")):
        for tc, w in zip(tr.findall(qn("w:tc")), new):
            tcPr = tc.find(qn("w:tcPr"))
            if tcPr is None:
                continue
            tcW = tcPr.find(qn("w:tcW"))
            if tcW is not None:
                tcW.set(qn("w:w"), str(w))
                tcW.set(qn("w:type"), "dxa")


