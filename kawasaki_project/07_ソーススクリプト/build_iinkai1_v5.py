def set_cell(cell, text, *, bold=None, color=None, size=None, align=None):
    """テンプレートのランの書式を保ったままセルの文字列を差し替える"""
    ps = cell.paragraphs
    for p in ps[1:]:
        p._p.getparent().remove(p._p)
    p = ps[0]
    runs = p.runs
    if not runs:
        r = p.add_run("")
        r.font.name = "BIZ UDPゴシック"
        r._element.rPr.rFonts.set(qn("w:eastAsia"), "BIZ UDPゴシック")
        runs = p.runs
    for r in runs[1:]:
        r._element.getparent().remove(r._element)
    run = runs[0]
    run.text = text
    if bold is not None:
        run.font.bold = bold
    if color is not None:
        run.font.color.rgb = RGBColor.from_string(color)
    if size is not None:
        run.font.size = Pt(size)
    if align is not None:
        p.alignment = align
    return cell


def clone_table(tpl, rows):
    """原本の表（要素）を複製し、行数を rows に合わせる（ゼブラ配色は交互に維持）"""
    new = copy.deepcopy(tpl)
    trs = new.findall(qn("w:tr"))
    head, odd, even = trs[0], trs[1], trs[2]
    for tr in trs[1:]:
        new.remove(tr)
    for i in range(rows):
        new.append(copy.deepcopy(odd if i % 2 == 0 else even))
    return new


def clone_par(doc, tpl_par, text):
    """原本の段落を複製して文字列を差し替える"""
    new = copy.deepcopy(tpl_par._p)
    from docx.text.paragraph import Paragraph
    p = Paragraph(new, tpl_par._parent)
    runs = p.runs
    for r in runs[1:]:
        r._element.getparent().remove(r._element)
    if runs:
        runs[0].text = text
    return p


def find_par(doc, needle, start=0):
    for i, p in enumerate(doc.paragraphs[start:], start):
        if needle in p.text:
            return i, p
    raise LookupError(needle)


def find_table(doc, needle):
    for i, t in enumerate(doc.tables):
        if needle in "\n".join(c.text for r in t.rows for c in r.cells):
            return i, t
    raise LookupError(needle)


def after(anchor, *elems):
    """anchor（段落 or 表要素）の直後に要素を順に挿入する"""
    cur = anchor._p if hasattr(anchor, "_p") else anchor
    for e in elems:
        el = e._p if hasattr(e, "_p") else e
        cur.addnext(el)
        cur = el
    return cur


def rep(doc, old, new):
    """本文・表を通した文字列置換（ラン跨ぎ対応）"""
    n = 0

    def fix(par):
        nonlocal n
        if old not in par.text:
            return
        runs = par.runs
        if not runs:
            return
        joined = "".join(r.text for r in runs)
        if old not in joined:
            return
        n += joined.count(old)
        runs[0].text = joined.replace(old, new)
        for r in runs[1:]:
            r.text = ""

    def walk(c):
        for p in c.paragraphs:
            fix(p)
        for t in c.tables:
            for row in t.rows:
                for cell in row.cells:
                    walk(cell)

    walk(doc)
    return n


