def main():
    doc = docx.Document(SRC)
    body = doc.element.body
    ps = [el for el in body.iterchildren() if el.tag == qn("w:p")]

    def text_of(el):
        return "".join(n.text or "" for n in el.iter(qn("w:t"))).strip()

    n = 0
    for el in body.iterchildren():
        if el.tag == qn("w:p"):
            t = text_of(el)
            new = t
            for a, b in SWAP:
                if a in new:
                    new = new.replace(a, b)
            if new != t:
                set_el(el, new)
                n += 1
        elif el.tag == qn("w:tbl"):
            tbl = docx.table.Table(el, doc)
            for row in tbl.rows:
                for c in row.cells:
                    s = c.text
                    new = s
                    for a, b in SWAP:
                        if a in new:
                            new = new.replace(a, b)
                    if new != s:
                        set_el(c.paragraphs[0]._p, new)
                        for p2 in c.paragraphs[1:]:
                            set_el(p2._p, "")
                        n += 1

    # 末尾に問答を追加する。最後の「QB-」段落とその答の体裁を写す。
    q_tpl = a_tpl = None
    last = None
    for el in body.iterchildren():
        if el.tag != qn("w:p"):
            continue
        t = text_of(el)
        if t.startswith("QB-"):
            q_tpl = copy.deepcopy(el)
        elif t.startswith("A．") and q_tpl is not None:
            a_tpl = copy.deepcopy(el)
            last = el
    if q_tpl is None or a_tpl is None or last is None:
        raise SystemExit("問答のテンプレートが見つからない")
    for q, ans in ADD:
        eq = copy.deepcopy(q_tpl)
        set_el(eq, q)
        last.addnext(eq)
        ea = copy.deepcopy(a_tpl)
        set_el(ea, ans)
        eq.addnext(ea)
        last = ea

    doc.save(DST)
    print("保存：", DST)
    d2 = docx.Document(DST)
    print(f"  段落 {len(d2.paragraphs)}　置換 {n}件　追加 {len(ADD)}問")
    qs = [p.text for p in d2.paragraphs if p.text.strip().startswith("QB-")]
    print(f"  問 {len(qs)}問（QB-{len(qs)}まで）")
    txt = "\n".join(p.text for p in d2.paragraphs) + "\n" + "\n".join(
        c.text for t in d2.tables for r in t.rows for c in r.cells)
    for bad in ("6,170", "5,518", "▲330", "▲982", "1,304", "2,807", "1,759",
                "14,809", "得点できます", "5点を得られます", "月額65円"):
        if bad in txt:
            print(f"  ⚠ 旧い記述が残っている：{bad} {txt.count(bad)}か所")


if __name__ == "__main__":
    main()
