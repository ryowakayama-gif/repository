def _font(run, name=MINCHO, size=10.5, bold=False, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)


def _shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear'); shd.set(qn('w:fill'), hexcolor)
    tcPr.append(shd)


def para(doc, text="", *, size=10.5, bold=False, color=None, name=MINCHO,
         align=None, space_before=0, space_after=4, indent=None):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    if indent:
        p.paragraph_format.left_indent = Cm(indent)
    if text:
        _font(p.add_run(text), name, size, bold, color)
    return p


def heading(doc, num, text):
    """章見出し（ネイビーの下線帯）"""
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(14)
    p.paragraph_format.space_after = Pt(6)
    _font(p.add_run(f"{num}．{text}"), GOTHIC, 13, True, NAVY)
    pPr = p._element.get_or_add_pPr()
    pbdr = OxmlElement('w:pBdr')
    bottom = OxmlElement('w:bottom')
    bottom.set(qn('w:val'), 'single'); bottom.set(qn('w:sz'), '12')
    bottom.set(qn('w:space'), '2'); bottom.set(qn('w:color'), NAVY)
    pbdr.append(bottom); pPr.append(pbdr)
    return p


def subhead(doc, text, color=BLUE):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(8)
    p.paragraph_format.space_after = Pt(3)
    _font(p.add_run("◆ " + text), GOTHIC, 11, True, color)
    return p


def bullets(doc, items, size=10, indent=0.5):
    for it in items:
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(indent)
        p.paragraph_format.space_after = Pt(2)
        _font(p.add_run("・" + it), MINCHO, size)


def table(doc, headers, rows, widths=None, head_fill=BLUE, size=9.5, align_right=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    align_right = align_right or []
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ""
        p = c.paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(1)
        _font(p.add_run(h), GOTHIC, size, True, "FFFFFF")
        _shade(c, head_fill)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            c = cells[i]; c.text = ""
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(1)
            if i in align_right:
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            elif i == 0 and len(headers) > 2:
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            else:
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            bold = str(v).startswith("★")
            _font(p.add_run(str(v).lstrip("★")), MINCHO, size, bold)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    return t


def note(doc, text, size=8.5):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(2)
    p.paragraph_format.space_after = Pt(6)
    _font(p.add_run(text), MINCHO, size, False, GRAY)


