def set_text(p, text):
    """段落のテキストを差し替える（先頭の run に入れ、以降の run は空にする）。"""
    ts = list(p._p.iter(qn("w:t")))
    if not ts:
        return False
    ts[0].text = text
    ts[0].set(qn("xml:space"), "preserve")
    for t in ts[1:]:
        t.text = ""
    return True


def set_runs(p, texts):
    """run ごとに文字列を割り当てる（番号＋本文の2 run 構成の段落用）。"""
    runs = p._p.findall(qn("w:r"))
    i = 0
    for r in runs:
        ts = r.findall(qn("w:t"))
        if not ts:
            continue
        ts[0].text = texts[i] if i < len(texts) else ""
        ts[0].set(qn("xml:space"), "preserve")
        for t in ts[1:]:
            t.text = ""
        i += 1
    return True


def insert_after(doc, anchor_idx, template_idx, texts):
    """template_idx の段落を書式のひな形として、anchor_idx の直後に段落を挿入する。"""
    ps = doc.paragraphs
    anchor = ps[anchor_idx]._p
    tpl = ps[template_idx]._p
    prev = anchor
    for text in texts:
        el = copy.deepcopy(tpl)
        ts = list(el.iter(qn("w:t")))
        if ts:
            ts[0].text = text
            ts[0].set(qn("xml:space"), "preserve")
            for t in ts[1:]:
                t.text = ""
        prev.addnext(el)
        prev = el


