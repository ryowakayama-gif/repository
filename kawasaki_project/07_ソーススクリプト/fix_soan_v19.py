    ps = doc.paragraphs
    n = 0
    for idx, text in REPLACE.items():
        if set_text(ps[idx], text):
            n += 1
    for idx, texts in REPLACE_RUNS.items():
        set_runs(ps[idx], texts)
        n += 1
    # 挿入は段落番号がずれるため、後ろから行う
    for anchor, tpl, texts in sorted(INSERT, key=lambda x: -x[0]):
        insert_after(doc, anchor, tpl, texts)

    doc.save(DST)
    d2 = docx.Document(DST)
