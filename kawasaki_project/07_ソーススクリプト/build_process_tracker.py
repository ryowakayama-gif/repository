# ---------------------------------------------------------------- 共通書式
def sheet(wb, name, title, lead, cols, widths, lead_h=52):
    ws = wb.create_sheet(name)
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    n = len(cols)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=n)
    c = ws.cell(row=1, column=1, value=title)
    c.font = Font(name=FONT, size=14, bold=True, color="FFFFFF")
    c.fill = PatternFill("solid", fgColor=C_TITLE)
    c.alignment = Alignment(vertical="center", horizontal="left", indent=1)
    ws.row_dimensions[1].height = 26

    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=n)
    c = ws.cell(row=2, column=1, value=lead)
    c.font = Font(name=FONT, size=9)
    c.fill = PatternFill("solid", fgColor=C_LEAD)
    c.alignment = Alignment(vertical="top", horizontal="left", wrap_text=True, indent=1)
    ws.row_dimensions[2].height = lead_h

    for i, h in enumerate(cols, 1):
        c = ws.cell(row=4, column=i, value=h)
        c.font = Font(name=FONT, size=9, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=C_HEAD)
        c.alignment = Alignment(vertical="center", horizontal="center", wrap_text=True)
        c.border = BORDER
    ws.row_dimensions[4].height = 32
    ws.freeze_panes = "A5"
    ws.sheet_view.showGridLines = False
    return ws


def put(ws, r, c, v, *, align="left", fill=None, bold=False, fmt=None, size=9):
    x = ws.cell(row=r, column=c, value=v)
    x.font = Font(name=FONT, size=size, bold=bold)
    x.alignment = Alignment(vertical="top", horizontal=align, wrap_text=True,
                            indent=1 if align == "left" else 0)
    x.border = BORDER
    if fill:
        x.fill = PatternFill("solid", fgColor=fill)
    if fmt:
        x.number_format = fmt
    return x


def status(ws, r, c, st):
    return put(ws, r, c, st, align="center", fill=ST_FILL[st])


def note(ws, r, ncol, text):
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=ncol)
    c = ws.cell(row=r, column=1, value=text)
    c.font = Font(name=FONT, size=8)
    c.alignment = Alignment(vertical="top", horizontal="left", wrap_text=True, indent=1)
    ws.row_dimensions[r].height = 26


def tally(ws, r, col_letter, first, last, label_col=1):
    put(ws, r, label_col, "区分", align="center", bold=True, fill=C_HEAD).font = \
        Font(name=FONT, size=9, bold=True, color="FFFFFF")
    put(ws, r, label_col + 1, "件数", align="center", bold=True, fill=C_HEAD).font = \
        Font(name=FONT, size=9, bold=True, color="FFFFFF")
    r += 1
    for st in [DONE, WIP, WAIT, TODO, NA]:
        put(ws, r, label_col, st, align="center", fill=ST_FILL[st])
        put(ws, r, label_col + 1,
            f'=COUNTIF({col_letter}{first}:{col_letter}{last},"{st}")', align="center")
        r += 1
    return r


