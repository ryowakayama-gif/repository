# ------------------------------------------------------------------ 生成
def main():
    doc = docx.Document(SRC)
    body = doc.element.body
    sectpr = body.find(qn("w:sectPr"))

    ps = doc.paragraphs
    tpl_p = {k: copy.deepcopy(ps[i]._p)
             for k, i in (("h1", P_H1), ("sub", P_SUB), ("num", P_NUM),
                          ("body", P_BODY), ("note", P_NOTE))}
    tpl_t = {k: copy.deepcopy(doc.tables[i]._tbl)
             for k, i in (("call", T_1COL), ("att", T_ATT),
                          ("t2", T_2COL), ("t3", T_3COL), ("t4", T_4COL))}
    # 表紙（先頭の空段落を含めて9段落）を保持する
    cover = [copy.deepcopy(ps[i]._p) for i in range(9)]

    for child in list(body):
        if child is not sectpr:
            body.remove(child)

    def add(el):
        if sectpr is not None:
            sectpr.addprevious(el)
        else:
            body.append(el)

    # 表紙
    COVER = {1: "川崎町　高齢者保健福祉計画・第１０期介護保険事業計画",
             2: "第二回　策定委員会資料",
             4: "計画骨子（案）とご選択いただきたい事項",
             6: "令和8年11月　日（　）",
             8: "川崎町　保健福祉課（介護保険事業計画・高齢者保健福祉計画策定委員会　事務局）"}
    for i, el in enumerate(cover):
        if i in COVER:
            set_para(el, COVER[i])
        add(el)

    n_p = n_t = 0
    for kind, payload in content():
        if kind in tpl_p:
            el = copy.deepcopy(tpl_p[kind])
            set_para(el, payload)
            add(el)
            n_p += 1
        elif kind in ("call", "att"):
            add(clone_callout(tpl_t[kind], [payload]))
            n_t += 1
        else:
            rows, widths = payload if isinstance(payload, tuple) else (payload, None)
            add(clone_table(tpl_t[kind], rows, widths))
            n_t += 1

    doc.save(DST)
    d2 = docx.Document(DST)
    print(f"保存：{DST}")
    print(f"  段落 {len(d2.paragraphs)} ／ 表 {len(d2.tables)}"
          f"（本文の段落{n_p}・表{n_t}）")


if __name__ == "__main__":
    main()
