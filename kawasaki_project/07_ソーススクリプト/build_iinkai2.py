def set_para(el, text):
    """段落要素のテキストを差し替える（先頭 run に入れ、以降は空にする）。"""
    ts = list(el.iter(qn("w:t")))
    if not ts:
        return
    ts[0].text = text
    ts[0].set(qn("xml:space"), "preserve")
    for t in ts[1:]:
        t.text = ""


def set_cell(tc, text):
    """セルのテキストを差し替える。改行は w:br で表す。

    2段落目以降と2つ目以降の run は削除し、先頭 run の書式を全体に適用する。
    """
    ps = tc.findall(qn("w:p"))
    for p in ps[1:]:
        tc.remove(p)
    p = ps[0]
    runs = p.findall(qn("w:r"))
    if not runs:
        return
    for r in runs[1:]:
        p.remove(r)
    r = runs[0]
    for child in list(r):
        if child.tag in (qn("w:t"), qn("w:br")):
            r.remove(child)
    lines = str(text).split("\n")
    for i, line in enumerate(lines):
        if i:
            r.append(r.makeelement(qn("w:br"), {}))
        t = r.makeelement(qn("w:t"), {qn("xml:space"): "preserve"})
        t.text = line
        r.append(t)


def set_widths(tbl, ratio):
    """列幅を ratio（合計は任意）の比率に振り直す。総幅はひな形のまま保つ。

    ひな形の4列表はいずれも 49:18:18:15 で、第1列だけが広い数値表向けの形である。
    文字量の多い表ではそのままでは収まらないため、列幅だけを調整する。
    書体・網掛け・罫線はひな形のままとする。
    """
    grid = tbl.find(qn("w:tblGrid"))
    cols = grid.findall(qn("w:gridCol"))
    total = sum(int(c.get(qn("w:w"))) for c in cols)
    s = sum(ratio)
    new = [int(total * r / s) for r in ratio]
    new[-1] = total - sum(new[:-1])
    for c, w in zip(cols, new):
        c.set(qn("w:w"), str(w))
    for tr in tbl.findall(qn("w:tr")):
        for tc, w in zip(tr.findall(qn("w:tc")), new):
            tcPr = tc.find(qn("w:tcPr"))
            if tcPr is None:
                continue
            tcW = tcPr.find(qn("w:tcW"))
            if tcW is not None:
                tcW.set(qn("w:w"), str(w))
                tcW.set(qn("w:type"), "dxa")


def clone_table(tpl, rows, widths=None):
    """表のひな形を複製し、行数を rows の数に合わせて中身を差し替える。

    ひな形の1行目を見出し、2行目を本文行のひな形として用いる。
    """
    tbl = copy.deepcopy(tpl)
    trs = tbl.findall(qn("w:tr"))
    head, body_tpl = trs[0], (trs[1] if len(trs) > 1 else trs[0])
    # 既存の本文行をすべて外す
    for tr in trs[1:]:
        tbl.remove(tr)
    # 見出し
    for tc, text in zip(head.findall(qn("w:tc")), rows[0]):
        set_cell(tc, text)
    # 本文
    prev = head
    for row in rows[1:]:
        tr = copy.deepcopy(body_tpl)
        for tc, text in zip(tr.findall(qn("w:tc")), row):
            set_cell(tc, text)
        prev.addnext(tr)
        prev = tr
    if widths:
        set_widths(tbl, widths)
    return tbl


def clone_callout(tpl, cells):
    tbl = copy.deepcopy(tpl)
    tr = tbl.findall(qn("w:tr"))[0]
    for tc, text in zip(tr.findall(qn("w:tc")), cells):
        set_cell(tc, text)
    return tbl


