def main():
    doc = docx.Document(SRC)
    ps = doc.paragraphs
    tbls = doc.tables

    tpl_p = {k: ps[i]._p for k, i in (
        ("break", P_BREAK), ("ch", P_CH), ("chtitle", P_CHTITLE), ("blank", P_BLANK),
        ("sec", P_SEC), ("sub", P_SUB), ("body", P_BODY), ("call", P_CALL),
        ("num", P_NUM), ("warn", P_WARN), ("note", P_NOTE))}
    tpl_t = {k: tbls[i]._tbl for k, i in (
        ("t2", T_2COL), ("t3", T_3COL), ("t5", T_5COL),
        ("tk", T_KPI), ("tj", T_JIGYO))}

    def build(items):
        out = []
        for kind, payload in items:
            if kind in tpl_p:
                el = copy.deepcopy(tpl_p[kind])
                set_el(el, payload)
                out.append(el)
            else:
                rows, widths = payload if isinstance(payload, tuple) else (payload, None)
                out.append(clone_table(tpl_t[kind], rows, widths))
        return out

    def insert_after(anchor_el, els):
        prev = anchor_el
        for el in els:
            prev.addnext(el)
            prev = el

    n_p = sum(1 for i, t in REPLACE.items() if set_text(ps[i], t))
    n_c = 0
    for (ti, r, c), text in TABLE.items():
        if set_cell(tbls[ti].rows[r].cells[c], text):
            n_c += 1

    # 図8-1 → 図9-1（図中の表題も改める）
    n_img = 0
    if os.path.exists(CHART):
        part = doc.part.related_parts[CHART_RID]
        with open(CHART, "rb") as f:
            part._blob = f.read()
        w, h = Image.open(CHART).size
        for el in ps[P_FIG]._p.iter():
            if el.tag in (qn("wp:extent"), qn("a:ext")):
                el.set("cy", str(int(int(el.get("cx")) * h / w)))
        n_img = 1

    # 新設（後ろから挿入して、前方の要素参照を崩さない）
    kpi = build(kpi_kanri())
    insert_after(ps[P_JOHOKOKAI]._p, kpi)
    ch8 = build(chapter_8())
    insert_after(ps[P_CH7_END]._p, ch8)
    kzk = build(kazoku_kaigo())
    insert_after(tbls[T_5_3_JIGYO]._tbl, kzk)

    # 版数の表記（取りこぼしを拾う）
    n_v = 0
    for p in doc.paragraphs:
        if "Ver.1.11" in p.text:
            set_text(p, p.text.replace("Ver.1.11", "Ver.1.12"))
            n_v += 1

    doc.save(DST)

    d2 = docx.Document(DST)
    print(f"保存：{DST}")
    print(f"  段落の置換 {n_p}箇所／表のセルの置換 {n_c}箇所／版数の表記 {n_v}箇所"
          f"／図の差替え {n_img}件")
    print(f"  5-3 に {len(kzk)}要素、第8章に {len(ch8)}要素、10-4 に {len(kpi)}要素を新設")
    print(f"  段落 {len(ps)} → {len(d2.paragraphs)}／表 {len(tbls)} → {len(d2.tables)}"
          f"／図 {len(d2.inline_shapes)}")

    body = "\n".join(p.text for p in d2.paragraphs)
    body += "\n".join(c.text for t in d2.tables for r in t.rows for c in r.cells)
    for word in ("Ver.1.11", "図8-1", "8-1で確定", "第 7 章", "第 8 章",
                 "第 9 章", "第 10 章"):
        print(f"  「{word}」の出現：{body.count(word)}件")


if __name__ == "__main__":
    main()
