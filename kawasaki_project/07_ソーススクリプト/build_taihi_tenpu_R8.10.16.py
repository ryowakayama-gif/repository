def tbls(path):
    d = docx.Document(path)
    out = []
    for el in d.element.body.iterchildren():
        if el.tag == qn("w:tbl"):
            tb = docx.table.Table(el, d)
            out.append([[c.text.replace("\n", "").strip() for c in r.cells]
                        for r in tb.rows])
    return out


def num(s):
    s = s.replace(",", "").replace("，", "").strip()
    m = re.fullmatch(r"-?\d+(?:\.\d+)?", s)
    return float(m.group(0)) if m else None


def tenpu_kyufu():
    """添付の令和7年度の給付額を サービス名→千円 で読む。"""
    out = {}
    for t in tbls(TENPU):
        if len(t) < 3:
            continue
        col = None
        for i, (a, b) in enumerate(zip(t[0], t[1])):
            if "令和7年度" in a and "給付額" in b:
                col = i
        if col is None:
            continue
        for r in t[3:]:
            if len(r) <= col:
                continue
            na = (r[1].strip() or r[0].strip())
            v = num(r[col])
            if na and v is not None:
                out.setdefault(na, v)
    return out


def zenbun(path):
    d = docx.Document(path)
    return "".join(n.text or "" for n in d.element.body.iter(qn("w:t")))


