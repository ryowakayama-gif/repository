THIN = Side(style="thin", color="BFBFBF")
BOX = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def title(ws, text, span):
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=span)
    c = ws.cell(1, 1, text)
    c.font = Font(name=FONT, size=13, bold=True, color="FFFFFF")
    c.fill = PatternFill("solid", fgColor=NAVY)
    c.alignment = Alignment(vertical="center")
    ws.row_dimensions[1].height = 26


def lead(ws, row, text, span):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span)
    c = ws.cell(row, 1, text)
    c.font = Font(name=FONT, size=10, color="404040")
    c.alignment = Alignment(vertical="center", wrap_text=True)


def section(ws, row, text, span):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span)
    c = ws.cell(row, 1, text)
    c.font = Font(name=FONT, size=11, bold=True, color=NAVY)
    c.fill = PatternFill("solid", fgColor=PALE)
    c.alignment = Alignment(vertical="center")
    for col in range(1, span + 1):
        ws.cell(row, col).border = BOX
    ws.row_dimensions[row].height = 20


def header(ws, row, labels):
    for i, t in enumerate(labels, start=1):
        c = ws.cell(row, i, t)
        c.font = Font(name=FONT, size=10, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=BLUE)
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BOX
    ws.row_dimensions[row].height = 34


def body(ws, row, values, inputs=(), wrap=True, height=None):
    """values の各セルを罫線つきで置く。inputs に含まれる列番号は記入欄（黄色）にする。"""
    for i, v in enumerate(values, start=1):
        c = ws.cell(row, i, v)
        c.border = BOX
        c.alignment = Alignment(vertical="top", wrap_text=wrap)
        if i in inputs:
            c.font = Font(name=FONT, size=10, color="0000FF")
            c.fill = PatternFill("solid", fgColor=INPUT)
        else:
            c.font = Font(name=FONT, size=10)
            if v is not None and str(v) != "":
                c.fill = PatternFill("solid", fgColor=GRAY)
    if height:
        ws.row_dimensions[row].height = height


def note(ws, row, text, span):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span)
    c = ws.cell(row, 1, text)
    c.font = Font(name=FONT, size=9, color="595959")
    c.alignment = Alignment(vertical="top", wrap_text=True)


def widths(ws, spec):
    for col, w in spec.items():
        ws.column_dimensions[col].width = w


