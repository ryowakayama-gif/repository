def mikomi_rows(names, pref=False):
    """見込量の表。給付費・回（日）数・利用者数の3行を1サービスにつき作る。"""
    out = [MIKOMI_HEAD[:]]
    for nm in names:
        key = nm + ("／予防" if pref else "")
        r = ROWS.get(key) or ROWS.get(nm)
        if r is None:
            continue
        has_q = r["R7量"] is not None and max(
            [r["R7量"]] + [r[y + "量"] for y in ALLY]) > 0
        first = True
        for item, fld, unit, fmt in (
                ("給付費", "給付費", "千円／年", f0),
                ("回（日）数", "量", r["unit"], f1),
                ("利用者数", "人数", "人／月", f1)):
            if item == "回（日）数" and not has_q:
                continue
            out.append([nm if first else "", item, unit,
                        fmt(r["R7" + fld])]
                       + [fmt(r[y + fld]) for y in ALLY])
            first = False
    return out


