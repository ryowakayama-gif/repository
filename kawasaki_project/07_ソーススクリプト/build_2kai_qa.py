def main():
    doc = docx.Document(SRC)
    body = doc.element.body
    ps = doc.paragraphs

    # ── 前付けの差替え
    set_text(ps[3 - 1], "第2回 策定委員会 想定問答集")
    set_text(ps[4 - 1],
             f"〜 委員からの想定質問と回答ポイント（全{len(QA)}問・"
             f"{len(CAT)}カテゴリ） 〜")
    set_text(ps[5 - 1], "令和8年11月")
    set_text(ps[10 - 1],
             "本資料は、第2回策定委員会において委員から想定される質問と"
             "回答ポイントをカテゴリ別に整理した事務局用参考資料です。"
             "第2回は「ご選択いただきたい事項（5件）」をお決めいただく回であり、"
             "選択の帰結が保険料に表れることから、"
             "保険料に関する問を最も厚く置いています。"
             "委員会本番では本資料を参照しながら、"
             "町担当課（保健福祉課）からの回答補強や事務局からの"
             "補足説明にお役立てください。")
    set_text(ps[12 - 1], f"▌ カテゴリ構成（全{len(QA)}問）")

    # ── カテゴリ表
    cnt = {c[0]: 0 for c in CAT}
    for q in QA:
        cnt[q[0]] += 1
    rows = [["カテゴリ", "テーマ", "問数", "想定質問者", "優先度"]]
    rows += [[k, t, str(cnt[k]), who, pri] for k, t, who, pri in CAT]
    tpl = doc.tables[0]._tbl
    new = clone_table(copy.deepcopy(tpl), rows)
    tpl.addprevious(new)
    tpl.getparent().remove(tpl)

    # ── 問のひな形を控える（P20 カテゴリ／P21 Q／P22 A／P23 根拠／P24 関連）
    TPL = {k: copy.deepcopy(ps[i - 1]._p)
           for k, i in (("cat", 20), ("q", 21), ("a", 22),
                        ("k", 23), ("r", 24))}

    # ── 旧い問の並び（P20〜P158）を取り除く
    anchor = ps[159 - 1]._p                        # 補遺の前の空段落
    for i in range(20, 159):
        el = ps[i - 1]._p
        if el.getparent() is not None:
            el.getparent().remove(el)

    # ── 新しい問を差し込む
    n = 0
    cur = None
    for kind, who, q, a, kon, rel in QA:
        if kind != cur:
            cur = kind
            nm = next(c[1] for c in CAT if c[0] == kind)
            el = copy.deepcopy(TPL["cat"])
            set_el(el, f"カテゴリ {kind}　{nm}（{cnt[kind]}問）")
            anchor.addprevious(el)
        n += 1
        for key, txt in (("q", f"QB-{n}　【{who}】　{q}"), ("a", a),
                         ("k", kon), ("r", rel)):
            el = copy.deepcopy(TPL[key])
            set_el(el, txt)
            anchor.addprevious(el)

    # ── 補遺の文言を第2回向けに改める
    ps = doc.paragraphs
    for p in ps:
        t = p.text
        if t.startswith("①　即答困難な質問は無理に回答せず"):
            set_text(p, "①　即答困難な質問は無理に回答せず、"
                        "「お持ち帰り検討」とし、第3回委員会で書面回答する旨を"
                        "委員に伝える。")
        elif t.startswith("②　賛否が分かれる事項"):
            set_text(p, "②　賛否が分かれる事項（選択1〜5）は、"
                        "複数意見を併記し、第3回委員会で再協議する。")
        elif t.startswith("①　重要な協議事項"):
            set_text(p, "①　ご選択いただきたい事項（5件）は時間を意識して進行する。"
                        "1件あたり8〜10分が目安。選択5は方向性のみ伺う。")
        elif t.startswith("本想定問答集の運用"):
            set_text(p, "本想定問答集の運用：委員会開始前に町担当・事務局で"
                        "15分程度の打合せをし、想定問答の流れを確認することを"
                        "推奨します。保険料（カテゴリE）は住民負担に直結するため、"
                        "回答の言い回しを事前にそろえておくことをお勧めします。")

    doc.save(DST)
    print("保存：", DST)
    print(f"全{len(QA)}問・{len(CAT)}カテゴリ")
    for k, t, _, _ in CAT:
        print(f"  {k} {t}　{cnt[k]}問")
    print(f"保険料 Ａ {PA:,.0f}円／Ｂ {PB:,.0f}円／Ｃ {PC:,.0f}円")


if __name__ == "__main__":
    main()
