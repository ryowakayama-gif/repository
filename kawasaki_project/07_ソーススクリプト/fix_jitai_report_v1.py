def tables_of(doc):
    return [Table(c, doc) for c in doc.element.body.iterchildren() if c.tag == qn("w:tbl")]


def node_text(el):
    return "".join(n.text or "" for n in el.iter(qn("w:t")))


def node_sub(el, pattern, repl, count=0):
    """置換文字列はリテラルとして扱う（\1 等の展開をしない）。"""
    ts = list(el.iter(qn("w:t")))
    if not ts:
        return False
    whole = "".join(t.text or "" for t in ts)
    new = re.sub(pattern, lambda m: repl, whole, count=count)
    if new == whole:
        return False
    ts[0].text = new
    ts[0].set(qn("xml:space"), "preserve")
    for t in ts[1:]:
        t.text = ""
    return True


def set_text(el, text):
    ts = list(el.iter(qn("w:t")))
    ts[0].text = text
    ts[0].set(qn("xml:space"), "preserve")
    for t in ts[1:]:
        t.text = ""


def find_par(doc, needle, nth=0):
    hits = [p for p in doc.paragraphs if needle in p.text]
    if not hits:
        raise KeyError(needle)
    return hits[nth]


def clone_par(tpl_par, text):
    p = copy.deepcopy(tpl_par._p)
    par = Paragraph(p, tpl_par._parent)
    for r in par.runs[1:]:
        r._element.getparent().remove(r._element)
    par.runs[0].text = text
    return p


def blank_par(tpl_par):
    p = copy.deepcopy(tpl_par._p)
    for r in Paragraph(p, tpl_par._parent).runs:
        r._element.getparent().remove(r._element)
    return p


def make_table(tpl_tbl, header, body, widths):
    """表5をテンプレートに、任意の列数・行数の表を作る（見出し行の書式・罫線を保持）。"""
    new = copy.deepcopy(tpl_tbl)
    trs = new.findall(qn("w:tr"))
    head_tr, body_tr = trs[0], trs[1]
    for tr in trs[1:]:
        new.remove(tr)

    def fit(tr, values):
        tcs = tr.findall(qn("w:tc"))
        while len(tcs) > len(values):
            tr.remove(tcs.pop())
        while len(tcs) < len(values):
            tc = copy.deepcopy(tcs[-1])
            tr.append(tc)
            tcs.append(tc)
        for tc, val, w in zip(tcs, values, widths):
            tcw = tc.find(qn("w:tcPr") + "/" + qn("w:tcW"))
            if tcw is not None:
                tcw.set(qn("w:w"), str(w))
                tcw.set(qn("w:type"), "dxa")
            set_text(tc, val)

    fit(head_tr, header)
    for vals in body:
        tr = copy.deepcopy(body_tr)
        fit(tr, vals)
        new.append(tr)

    g = new.find(qn("w:tblGrid"))
    for col in g.findall(qn("w:gridCol")):
        g.remove(col)
    for w in widths:
        col = OxmlElement("w:gridCol")
        col.set(qn("w:w"), str(w))
        g.append(col)
    return new


def insert_after(par, elements):
    """段落の直後に要素を順番に差し込む。"""
    anchor = par._p
    for el in elements:
        anchor.addnext(el)
        anchor = el


