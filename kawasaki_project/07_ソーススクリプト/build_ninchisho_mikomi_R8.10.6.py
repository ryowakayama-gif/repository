def yomu_kpi():
    """素案 10-4 のKPIの表を読む。指標の一覧を2か所に持たないため。"""
    d = docx.Document(SOAN)
    cur = ""
    for el in d.element.body.iterchildren():
        if el.tag == qn("w:p"):
            t = "".join(n.text or "" for n in el.iter(qn("w:t"))).strip()
            m = re.match(r"^(\d+-\d+)[　 ]", t)
            if m:
                cur = m.group(1)
        elif el.tag == qn("w:tbl") and cur == "10-4":
            tb = docx.table.Table(el, d)
            head = [c.text.replace("\n", "").strip() for c in tb.rows[0].cells]
            if head[:2] == ["指標", "区分"]:
                return [[c.text.replace("\n", " ").strip()
                         for c in r.cells] for r in tb.rows[1:]]
    raise SystemExit("素案 10-4 のKPIの表が見つからない")


