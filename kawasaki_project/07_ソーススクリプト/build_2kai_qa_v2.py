def main():
    doc = docx.Document(SRC)
    ps, ts = doc.paragraphs, doc.tables

    # ── 参照・数値・版の置換（全段落・全セル）
    n = 0
    for p in doc.paragraphs:
        t = p.text
        new = t
        for a, b in REF.items():
            new = new.replace(a, b)
        if new != t:
            set_text(p, new)
            n += 1
    for tb in doc.tables:
        for row in tb.rows:
            for cell in row.cells:
                t = cell.text
                new = t
                for a, b in REF.items():
                    new = new.replace(a, b)
                if new != t:
                    set_cell(cell, new)
                    n += 1
    print(f"  参照・数値・版の置換 {n}か所")

    for i, txt in P.items():
        set_text(doc.paragraphs[i - 1], txt)

    # ── カテゴリ構成の表にHを足し、問数を改める
    t1 = ts[0]
    set_cell(t1.rows[1].cells[2], "3")
    tpl_row = copy.deepcopy(t1.rows[-1]._tr)
    t1.rows[-1]._tr.addnext(tpl_row)
    new_row = t1.rows[-1]
    for c, v in zip(new_row.cells,
                    ["H", "交付金の評価", "5", "有識者・委員長",
                     "中（資料７に対応）"]):
        set_cell(c, v)

    # ══════════════════════════ カテゴリ H を「補遺」の前に挿入
    P_CAT = copy.deepcopy(doc.paragraphs[138 - 1]._p)   # カテゴリ見出し
    P_Q = copy.deepcopy(doc.paragraphs[139 - 1]._p)     # QB-xx
    P_A = copy.deepcopy(doc.paragraphs[140 - 1]._p)     # A．
    P_D = copy.deepcopy(doc.paragraphs[141 - 1]._p)     # 【根拠データ】
    P_R = copy.deepcopy(doc.paragraphs[142 - 1]._p)     # 【関連資料】

    anchor = next(p for p in doc.paragraphs
                  if p.text.strip().startswith("補遺：質問への対応原則"))._p

    def put(tpl, text):
        e = copy.deepcopy(tpl)
        set_el(e, text)
        anchor.addprevious(e)

    put(P_CAT, "カテゴリ H　交付金の評価（5問）")
    for q, a, d, r in QA:
        put(P_Q, q)
        put(P_A, a)
        put(P_D, d)
        put(P_R, r)

    doc.save(DST)
    print("保存：", DST)
    d2 = docx.Document(DST)
    print(f"  段落 {len(d2.paragraphs)}／表 {len(d2.tables)}")
    body = "\n".join([p.text for p in d2.paragraphs]
                     + [c.text for t in d2.tables for row in t.rows
                        for c in row.cells])
    print(f"  残存する「表N」参照 {len(re.findall(r'第2回資料 表[0-9]', body))}件")
    print(f"  残存する Ver.1.17 {body.count('Ver.1.17')}件")
    print(f"  問の数 {len(re.findall(r'QB-[0-9]+　', body))}件")


if __name__ == "__main__":
    main()
