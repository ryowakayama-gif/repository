def seiri(s):
    return str(s or "").replace("\n", "").strip()


def yomu_jigyo():
    """06_第10期反映方針 から事業の一覧を読む（⚠ 実物から数える）"""
    if not os.path.exists(JISSEKI):
        raise SystemExit("第9期実績一覧がない：" + JISSEKI)
    wb = openpyxl.load_workbook(JISSEKI)
    ws = wb["06_第10期反映方針"]
    out = []
    bunya = ""
    for r in ws.iter_rows(values_only=True):
        a, b, c = seiri(r[0]), seiri(r[1]), seiri(r[2]) if len(r) > 2 else ""
        if a.startswith("【") and a.endswith("】"):
            bunya = a.strip("【】")
            continue
        if not a or not b or a in ("事業区分",):
            continue
        if a.startswith("※") or b.startswith("※"):
            continue
        out.append((bunya, a, b, c))
    wb.close()
    return out


def kazoeru_kuran():
    """町記入用の未記入の件数を実物から数える（⚠ 推測しない）"""
    wb = openpyxl.load_workbook(JISSEKI)
    kei = {"記入済み": 0, "未記入": 0}
    for name in ("01_KPI一覧", "02_介護予防_健康", "03_在宅生活支援",
                 "04_認知症_包括", "05_介護サービス_人材"):
        if name not in wb.sheetnames:
            continue
        ws = wb[name]
        # 見出し行を探し、実績の列を特定する
        #   ⚠ **1行目の表題にも「実績」が入っている。**
        #   見出し行は1列目が「事業区分」又は「基本目標」であるもの。
        atama = None
        for i, r in enumerate(ws.iter_rows(values_only=True), 1):
            if seiri(r[0]) not in ("事業区分", "基本目標"):
                continue
            hit = [j for j, x in enumerate(r) if x and "実績" in seiri(x)]
            if hit:
                atama = (i, hit)
            break
        if atama is None:
            continue
        r0, cols = atama
        for r in ws.iter_rows(min_row=r0 + 1, values_only=True):
            if not seiri(r[1] if len(r) > 1 else ""):
                continue
            if seiri(r[0]).startswith("【") or seiri(r[0]).startswith("※"):
                continue
            for j in cols:
                if j >= len(r):
                    continue
                v = seiri(r[j])
                kei["記入済み" if v else "未記入"] += 1
    wb.close()
    return kei


def soan_setsu(doc):
    """素案に現にある節の番号を集める"""
    out = set()
    for p in doc.paragraphs:
        m = re.match(r"^(\d{1,2}-\d)　", p.text.strip())
        if m:
            out.add(m.group(1))
    return out


def soan_84(doc):
    """素案 8-4 の要件ア〜エを読む"""
    body = [p.text.strip() for p in doc.paragraphs]
    out = []
    for t in body:
        m = re.search(r"（要件([アイウエ])・(\d+)点）", t)
        if m:
            out.append((m.group(1), m.group(2), t))
    return out


