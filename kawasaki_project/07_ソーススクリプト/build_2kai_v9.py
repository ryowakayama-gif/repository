# ════════════════════════════════════════ docx の操作
def clean(s):
    """⚠ 強調記号（**）を落とす。

    本文に ** が残ると「守るべき制約の走査」で不適合になる。
    原稿を書くときに強調のつもりで付けたものを、ここで必ず落とす。
    """
    return s.replace("**", "")


def set_cell(cell, text):
    """セルの文字を書き換える（書体を残す）。改行で段落を分ける。"""
    ps = cell.paragraphs
    gyo = clean(text).split("\n")
    for i, p in enumerate(ps):
        s = gyo[i] if i < len(gyo) else ""
        if p.runs:
            p.runs[0].text = s
            for r in p.runs[1:]:
                r.text = ""
        elif s:
            p.add_run(s)
    if len(gyo) > len(ps):
        base = ps[-1]
        for g in gyo[len(ps):]:
            np = copy.deepcopy(base._p)
            base._p.addnext(np)
            import docx.text.paragraph as dp
            newp = dp.Paragraph(np, base._parent)
            if newp.runs:
                newp.runs[0].text = g
                for r in newp.runs[1:]:
                    r.text = ""
            else:
                newp.add_run(g)
            base = newp


def add_row(table):
    """最後の行をもとに1行足す（書体・罫線を保つ）。"""
    tr = copy.deepcopy(table.rows[-1]._tr)
    table._tbl.append(tr)
    row = table.rows[-1]
    for c in row.cells:
        set_cell(c, "")
    return row


def clone_table_after(src, after_el, gyo_su):
    """src の表を複製して after_el の直後に置き、行数を gyo_su にする。"""
    new = copy.deepcopy(src._tbl)
    after_el.addnext(new)
    import docx.table as dt
    t = dt.Table(new, src._parent)
    while len(t.rows) > gyo_su:
        new.remove(t.rows[-1]._tr)
    while len(t.rows) < gyo_su:
        new.append(copy.deepcopy(t.rows[-1]._tr))
    for row in t.rows:
        for c in row.cells:
            set_cell(c, "")
    return t


