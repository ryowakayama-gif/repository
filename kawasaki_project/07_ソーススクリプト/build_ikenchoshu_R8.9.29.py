"""認知症の人及び家族等からの意見聴取の記録様式（別添22）

認知症基本法第13条第3項において準用する第12条第3項は、市町村計画の案を
作成しようとするときに、あらかじめ認知症の人及び家族等の意見を聴くことを
求めている。同条第7項の準用により、毎年度の評価結果の取りまとめの前にも
同じ手続を要する。

介護保険保険者努力支援交付金 目標Ⅱ（ⅰ）1カ（5点・本町は令和8年度0点）は
「認知症の人及び家族等の意見を踏まえた市町村認知症施策推進計画の策定に
着手している」ことを評価し、その留意点で
「認知症の人と家族等が参画し、意見を反映させる仕組みを整備した上で
計画の策定に着手している場合に評価の対象とする」としている。
したがって、聴取を行う前に様式を定めることが要件そのものである。

様式の設計は、次の2つの国資料の考え方に沿っている。
  ・都道府県・市町村向け認知症施策推進計画策定の手引き（001476653）
    3.1（2）本人参画のあり方／3.3 基本計画におけるKPIの考え方
  ・認知症の本人の声を施策・事業運営に活かしていくためのヒント（001724276）
    STEP1 声の把握／STEP2 記録・蓄積・共有／STEP3 地域づくりのアクション

  00_この様式について
  様式1_実施計画　　　　　どの場で、いつ、誰から聴くか
  様式2_意見聴取記録票　　1回1枚。声が聴かれた場とプロセスを残す
  様式3_反映台帳　　　　　声を地域課題に翻訳し、施策への反映を追う
  様式4_フィードバック　　本人・家族・地域に還した記録
  様式5_評価時の意見聴取　毎年度の評価結果の取りまとめ前の聴取（法第12条第7項準用）
  06_要件チェック　　　　法・交付金・手引きの要件と様式の対応
"""
