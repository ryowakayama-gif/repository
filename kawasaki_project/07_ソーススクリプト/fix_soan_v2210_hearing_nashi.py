#   不適合にする。**
KYU = []


def midashi(t):
    try:
        return t.rows[0].cells[0].text.strip()
    except Exception:
        return ""


def ate(d, ban, mi, gyo, retsu):
    """表の番号で当て、見出しで取り違えを検出する。

    戻り　(セル, 理由)。セルが None のときは理由を返す。
    """
    if ban >= len(d.tables):
        return None, f"表{ban} がない（表は{len(d.tables)}個）"
    t = d.tables[ban]
    if midashi(t) != mi:
        return None, f"表{ban} の見出しが『{midashi(t)[:16]}』で『{mi}』でない"
    if gyo >= len(t.rows):
        return None, f"表{ban} に行{gyo} がない（{len(t.rows)}行）"
    r = t.rows[gyo]
    if retsu >= len(r.cells):
        return None, f"表{ban} 行{gyo} に列{retsu} がない"
    return r.cells[retsu], ""


def kaku(cell, s):
    """セルの文字を書き換える（最初の段落に寄せ、書体は残す）。"""
    ps = cell.paragraphs
    gyo = s.split("\n")
    for i, p in enumerate(ps):
        if i < len(gyo):
            if p.runs:
                p.runs[0].text = gyo[i]
                for r in p.runs[1:]:
                    r.text = ""
            else:
                p.add_run(gyo[i])
        else:
            for r in p.runs:
                r.text = ""
    # 段落が足りないとき
    if len(gyo) > len(ps):
        base = ps[-1]
        for g in gyo[len(ps):]:
            np = cell.add_paragraph()
            np.paragraph_format.alignment = base.paragraph_format.alignment
            run = np.add_run(g)
            if base.runs:
                run.font.name = base.runs[0].font.name
                run.font.size = base.runs[0].font.size


def dan_kaku(p, s):
    if p.runs:
        p.runs[0].text = s
        for r in p.runs[1:]:
            r.text = ""
    else:
        p.add_run(s)


