def unmerge_below(ws, at_row):
    """insert_rows は結合セルを動かさない。挿入位置より下の結合を先に解除して記録する。
    解除しないまま挿入すると、結合範囲に入る行へ値を書き込めず欠落する。"""
    kept = []
    for m in list(ws.merged_cells.ranges):
        if m.min_row >= at_row:
            kept.append((m.min_row, m.max_row, m.min_col, m.max_col))
            ws.unmerge_cells(str(m))
    return kept


def remerge(ws, kept, n):
    for r1, r2, c1, c2 in kept:
        ws.merge_cells(start_row=r1 + n, end_row=r2 + n, start_column=c1, end_column=c2)


def copy_row_style(ws, src_row, dst_row, ncol):
    for c in range(1, ncol + 1):
        s, d = ws.cell(src_row, c), ws.cell(dst_row, c)
        d._style = copy.copy(s._style)
    ws.row_dimensions[dst_row].height = ws.row_dimensions[src_row].height


