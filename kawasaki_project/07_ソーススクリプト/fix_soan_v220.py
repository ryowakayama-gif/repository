def main():
    doc = docx.Document(SRC)
    body = doc.element.body
    ps = [el for el in body.iterchildren() if el.tag == qn("w:p")]
    ts = [el for el in body.iterchildren() if el.tag == qn("w:tbl")]

    for i, txt in P.items():
        set_el(ps[i - 1], txt)

    TPL3 = copy.deepcopy(ts[2 - 1])
    TPL4 = copy.deepcopy(ts[47 - 1])
    TPL5 = copy.deepcopy(ts[5 - 1])
    P_SUB = copy.deepcopy(ps[303 - 1])
    P_BODY = copy.deepcopy(ps[301 - 1])

    def text_of(el):
        return "".join(n.text or "" for n in el.iter(qn("w:t"))).strip()

    def find_p(pred, skip=0):
        hit = 0
        for el in body.iterchildren():
            if el.tag != qn("w:p"):
                continue
            if pred(text_of(el)):
                if hit == skip:
                    return el
                hit += 1
        raise KeyError("段落が見つからない")

    def find_tbl(head):
        for el in body.iterchildren():
            if el.tag != qn("w:tbl"):
                continue
            tbl = docx.table.Table(el, doc)
            if [c.text.strip() for c in tbl.rows[0].cells][:len(head)] == head:
                return el
        raise KeyError("表が見つからない")

    def sub(anchor, text):
        e = copy.deepcopy(P_SUB)
        set_el(e, text)
        anchor.addprevious(e)

    def bodyp(anchor, text):
        e = copy.deepcopy(P_BODY)
        set_el(e, text)
        anchor.addprevious(e)

    def table(anchor, tpl, rows, widths):
        anchor.addprevious(clone_table(tpl, rows, widths=widths))

    # ══════════ ① 6-1の冒頭に「本町が目指す姿と『新しい認知症観』」
    a = find_p(lambda t: t == "▌ 認知症基本法の概要")
    sub(a, MEZASU_H)
    for t in MEZASU:
        bodyp(a, t)

    # ══════════ ② 対応方針①の書き改め
    e = find_p(lambda t: t.startswith("①　本人及び家族等の意見の反映"))
    set_el(e, HOSHIN1)

    # ══════════ ③④⑤ 6-2の直前に置く
    a = find_p(lambda t: t.startswith("6-2　認知症施策の体系"))
    sub(a, SANKAKU_H)
    bodyp(a, SANKAKU_P)
    table(a, TPL3, T_SANKAKU, (16, 46, 38))
    bodyp(a, SANKAKU_NOTE)
    sub(a, OUDAN_H)
    for t in OUDAN:
        bodyp(a, t)
    sub(a, RENDO_H)
    bodyp(a, RENDO_P)
    table(a, TPL3, T_RENDO, (26, 48, 26))

    # ══════════ ⑥ 6-2の表のあと（6-3の直前）に注記
    a = find_p(lambda t: t.startswith("6-3　重点施策とKPI"))
    bodyp(a, TAIOUSHINAI)

    # ══════════ ⑦ 6-3「第9期からの見直し」を重点施策の前に
    a = find_p(lambda t: t == "▌ 重点施策（5本柱）")
    sub(a, MINAOSHI_H)
    bodyp(a, MINAOSHI)

    # ══════════ ⑧ KPIの表を5列に差し替える
    old = find_tbl(["層", "指標", "現状値", "目標値（R11）"])
    new = clone_table(TPL5, T_KPI, widths=(11, 13, 36, 24, 16))
    old.addprevious(new)
    old.getparent().remove(old)

    # ══════════ ⑨ KPIの考え方（表のあと・⚠意見聴取の注記の前）
    a = find_p(lambda t: t.startswith(
        "⚠ 認知症の人及びその家族等からの意見聴取は、認知症基本法第13条第3項"))
    for t in KPI_NOTE:
        bodyp(a, t)

    # ══════════ ⑩ 6-4に事業の追加候補（第7章の直前）
    a = find_p(lambda t: t == "第 7 章")
    sub(a, KOUHO_H)
    bodyp(a, KOUHO_P)
    table(a, TPL4, T_KOUHO, (6, 30, 44, 20))

    doc.save(DST)
    print("保存：", DST)
    d2 = docx.Document(DST)
    print(f"  段落 {len(d2.paragraphs)}／表 {len(d2.tables)}")
    for name, head, n in (("本人参画の進め方", ["段階", "誰が、何をするか"], 5),
                          ("他の計画との連動", ["計画・分野", "連動のさせ方"], 9),
                          ("KPI", ["層", "対応する国の重点目標"], 15),
                          ("追加候補", ["区分", "追加候補の事業又は内容"], 16)):
        for t in d2.tables:
            h = [c.text.strip() for c in t.rows[0].cells]
            if h[:len(head)] == head:
                mark = "○" if len(t.rows) == n else "×"
                print(f"  {mark} {name}：{len(t.rows)}行 × {len(t.columns)}列"
                      f"（想定{n}行）")
                break
        else:
            print(f"  × {name}：見つからない")
    for kw in ("新しい認知症観", "目指す姿", "部署横断", "重点目標", "ケアパス",
               "ピアサポート", "認知症サポート医", "認知症希望大使"):
        n1 = sum(p.text.count(kw) for p in d2.paragraphs)
        n2 = sum(c.text.count(kw) for t in d2.tables
                 for r in t.rows for c in r.cells)
        print(f"  {kw}：{n1 + n2}回")


if __name__ == "__main__":
    main()
