def cat_of(s):
    m = re.match(r"^カテゴリ ([A-H])　", s)
    return "カテゴリ " + m.group(1) if m else None


def txt(el):
    return "".join(n.text or "" for n in el.iter(qn("w:t"))).strip()


def main():
    futeki = []

    def judge(ok, mi, setsu=""):
        print(("   ○ " if ok else "   × ") + mi + (("　" + setsu)
                                                   if setsu else ""))
        if not ok:
            futeki.append(mi)

    print("第2回策定委員会 想定問答集 v4 → v5（令和8年10月21日）")
