def main():
    doc = docx.Document(SRC)
    body = doc.element.body
    ps = [el for el in body.iterchildren() if el.tag == qn("w:p")]
    ts = [el for el in body.iterchildren() if el.tag == qn("w:tbl")]
    P_BODY = copy.deepcopy(ps[65 - 1])
    TPL4 = None
    TPL3 = None
    for el in ts:
        t = docx.table.Table(el, doc)
        if len(t.columns) == 4 and TPL4 is None:
            TPL4 = copy.deepcopy(el)
        if len(t.columns) == 3 and TPL3 is None:
            TPL3 = copy.deepcopy(el)
    for el in ts:
        t = docx.table.Table(el, doc)
        if len(t.columns) == 4 and len(t.rows) >= 4:
            TPL4 = copy.deepcopy(el)
            break

    def text_of(el):
        return "".join(n.text or "" for n in el.iter(qn("w:t"))).strip()

    def find_p(pred):
        for el in body.iterchildren():
            if el.tag == qn("w:p") and pred(text_of(el)):
                return el
        raise KeyError("段落が見つからない")

    # ── ① 段落・表のセルの数値の置換（訂正事項の表を作る前に行う）
    def apply(text):
        new = text
        for a, b in SWAP:
            if a in new:
                new = new.replace(a, b)
        return new

    n_swap = 0
    for el in body.iterchildren():
        if el.tag != qn("w:p"):
            continue
        t = text_of(el)
        new = apply(t)
        if new != t:
            set_el(el, new)
            n_swap += 1

    n_cell = 0
    for el in body.iterchildren():
        if el.tag != qn("w:tbl"):
            continue
        t = docx.table.Table(el, doc)
        for row in t.rows:
            for c in row.cells:
                s0 = c.text
                new = apply(s0)
                if new != s0:
                    set_el(c.paragraphs[0]._p, new)
                    for p2 in c.paragraphs[1:]:
                        set_el(p2._p, "")
                    n_cell += 1

    # ── ② 交付金の断定を削除
    set_el(find_p(lambda t: t.startswith("令和８年度の失点272点のうち")), P70)
    n_ka = 0
    for el in body.iterchildren():
        if el.tag != qn("w:tbl"):
            continue
        t = docx.table.Table(el, doc)
        for row in t.rows:
            c = row.cells
            if len(c) >= 4 and "認知症の人と家族等が参画し意見を反映させる仕組み" \
                    in c[3].text:
                set_el(c[3].paragraphs[0]._p, KOFU_KA)
                for p2 in c[3].paragraphs[1:]:
                    set_el(p2._p, "")
                n_ka += 1

    # ── ③ 追加候補と財源（「７．交付金の評価」の見出しの前に置く）
    a = find_p(lambda t: t.startswith("７．交付金の評価と取り戻せる27点"))

    def bodyp(anchor, text):
        e = copy.deepcopy(P_BODY)
        set_el(e, text)
        anchor.addprevious(e)

    bodyp(a, KOUHO_H)
    bodyp(a, KOUHO_P)
    a.addprevious(clone_table(TPL4, T_KOUHO, widths=(22, 8, 46, 24)))
    bodyp(a, "◆ 認知症施策の追加による保険料への影響（財源別）")
    a.addprevious(clone_table(TPL4, T_ZAIGEN, widths=(26, 30, 22, 22)))
    bodyp(a, ZAIGEN_NOTE)

    # ── ⑤ 訂正事項（既存の訂正事項の表を差し替える）
    old = None
    for el in body.iterchildren():
        if el.tag != qn("w:tbl"):
            continue
        t = docx.table.Table(el, doc)
        h = [c.text.strip() for c in t.rows[0].cells]
        if h[:2] == ["No", "訂正の内容"] or \
                (h and "訂正" in h[0]) or h[:2] == ["No", "内容"]:
            old = el
    if old is not None:
        old.addprevious(clone_table(TPL4, TEISEI, widths=(5, 40, 27, 28)))
        old.getparent().remove(old)
        print("  訂正事項の表を差し替えました")
    else:
        a2 = find_p(lambda t: t.startswith(
            "◆ 第１回でいただいた主なご意見と本資料での扱い"))
        bodyp(a2, "◆ 当社資料の訂正（保険料試算の再検算による６件）")
        bodyp(a2, TEISEI_P)
        a2.addprevious(clone_table(TPL4, TEISEI, widths=(5, 40, 27, 28)))
        print("  訂正事項の表を「２．」の節に新設しました")

    doc.save(DST)
    print("保存：", DST)
    print(f"  段落の置換 {n_swap}件／セルの置換 {n_cell}件／"
          f"交付金カの書き改め {n_ka}件")
    d2 = docx.Document(DST)
    print(f"  段落 {len(d2.paragraphs)}／表 {len(d2.tables)}")
    body2 = "\n".join(p.text for p in d2.paragraphs) + "\n" + "\n".join(
        c.text for t in d2.tables for r in t.rows for c in r.cells)
    for bad in ("6,170", "5,518", "▲330", "▲982", "1,304円", "▲5.1", "▲15.1",
                "＋273円", "148,789千円", "得点できます",
                "そのまま要件となります"):
        if bad in body2:
            print(f"  ⚠ 旧い記述が残っている：{bad} {body2.count(bad)}か所")
    for good in (f"{PB:,}円", f"{PC:,}円", f"{KIKIN_TSUKI:,}円",
                 "評価の対象となる可能性", "按分"):
        print(f"  {good}：{body2.count(good)}か所")


if __name__ == "__main__":
    main()
