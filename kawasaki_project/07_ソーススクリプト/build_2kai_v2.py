def d_kyufu(d_year):
    """総給付費が各年度 d_year 円増えたときの月額の増分。"""
    tot = 0.0
    for y in YEARS:
        f = FIN[y]
        sc = (f["総給付費"] + d_year) / f["総給付費"]
        hyo = ((f["総給付費"] + d_year)
               + (f["特定入所者"] + f["高額介護"] + f["高額医療合算"]) * sc
               + f["審査手数料"])
        tot += ((hyo + f["地域支援事業費"]) * 0.23 + hyo * 0.05
                + f["総合事業費"] * 0.05 - (hyo + f["総合事業費"]) * M.KOFU[y])
    return prem(tot) - PA


def kaitei(r):
    """介護報酬改定率rを乗じた場合の保険料収納必要額。"""
    tot = 0.0
    for y in YEARS:
        f = FIN[y]
        hyo = ((f["総給付費"] + f["特定入所者"] + f["高額介護"]
                + f["高額医療合算"]) * (1 + r) + f["審査手数料"])
        tot += ((hyo + f["地域支援事業費"]) * 0.23 + hyo * 0.05
                + f["総合事業費"] * 0.05 - (hyo + f["総合事業費"]) * M.KOFU[y])
    return tot


