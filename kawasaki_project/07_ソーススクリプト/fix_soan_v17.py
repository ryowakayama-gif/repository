TPL_3COL = 17   # 4-3「計画の重点ポイント」表。同じ第4章の3列表を書式のひな形にする


def add_taiou(doc, anchor_par):
    """3列の対応表を、第4章の既存3列表を複製して作る（見出し行の書式・罫線を引き継ぐ）。"""
    tpl = tables_of(doc)[TPL_3COL]._tbl
    new = copy.deepcopy(tpl)
    trs = new.findall(qn("w:tr"))
    head, bodyr = trs[0], trs[1]
    for tr in trs[1:]:
        new.remove(tr)
    for i, row in enumerate(TAIOU):
        tr = head if i == 0 else copy.deepcopy(bodyr)
        tcs = tr.findall(qn("w:tc"))
        for tc, val in zip(tcs, row):
            ps = tc.findall(qn("w:p"))
            lines = val.split("\n")
            set_text(ps[0], lines[0])
            for extra in ps[1:]:
                tc.remove(extra)
            for ln in lines[1:]:
                np = copy.deepcopy(ps[0])
                set_text(np, ln)
                tc.append(np)
        if i:
            new.append(tr)
    anchor_par._p.addnext(new)
    spacer = copy.deepcopy(anchor_par._p)
    for r in Paragraph(spacer, anchor_par._parent).runs:
        r._element.getparent().remove(r._element)
    anchor_par._p.addnext(spacer)


