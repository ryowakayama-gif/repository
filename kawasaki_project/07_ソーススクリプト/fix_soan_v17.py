def tables_of(doc):
    return [Table(c, doc) for c in doc.element.body.iterchildren() if c.tag == qn("w:tbl")]


def node_text(el):
    return "".join(n.text or "" for n in el.iter(qn("w:t")))


def sub(el, old, new, regex=False):
    ts = list(el.iter(qn("w:t")))
    if not ts:
        return False
    whole = "".join(t.text or "" for t in ts)
    pat = old if regex else re.escape(old)
    out = re.sub(pat, lambda m: new, whole)
    if out == whole:
        return False
    ts[0].text = out
    ts[0].set(qn("xml:space"), "preserve")
    for t in ts[1:]:
        t.text = ""
    return True


def set_text(el, text):
    ts = list(el.iter(qn("w:t")))
    ts[0].text = text
    ts[0].set(qn("xml:space"), "preserve")
    for t in ts[1:]:
        t.text = ""


def find(doc, needle, nth=0):
    hits = [p for p in doc.paragraphs if needle in p.text]
    if not hits:
        raise KeyError(needle)
    return hits[nth]


def clone_par(tpl, text):
    p = copy.deepcopy(tpl._p)
    par = Paragraph(p, tpl._parent)
    for r in par.runs[1:]:
        r._element.getparent().remove(r._element)
    par.runs[0].text = text
    return p


def cell_sub(tbl, old, new):
    n = 0
    for tc in tbl.iter(qn("w:tc")):
        for p in tc.findall(qn("w:p")):
            if sub(p, old, new):
                n += 1
    return n


