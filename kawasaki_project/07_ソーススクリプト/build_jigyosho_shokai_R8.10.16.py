# ══════════════════════════ 電子（Excel）の記入様式
#   ⚠ 照会票（docx）と**同じ並び**から起こす。片方だけ直ることがない。
def build_excel_youshi():
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter
    KINYU = PatternFill("solid", fgColor="FFF2CC")   # ご記入欄（うすい黄）
    wb = openpyxl.Workbook()
    bg = bangou()
    first = True
    for code, name, kubun, taisho in YOSHIKI:
        ws = wb.active if first else wb.create_sheet()
        first = False
        ws.title = f"{code}_{name}"[:31]
        ws.cell(1, 1).value = f"川崎町 介護サービス事業所 現況照会票" \
                              f"　{code}　{name}（{kubun}）"
        ws.cell(1, 1).font = Font(name="游ゴシック", size=13, bold=True,
                                  color="FFFFFF")
        ws.cell(1, 1).fill = GY.TITLE
        ws.row_dimensions[1].height = 24
        ws.cell(2, 1).value = (f"ご記入いただく事業所：{taisho}\n"
                               "⚠ 一番右の、うすい黄色のセルがご記入欄です"
                               "（その左の列は選択肢・ご記入の形のご参考です）。"
                               "分からない欄は空欄のままで結構です。"
                               "記録をお取りでない場合は「記録なし」、"
                               "該当がない場合は「0」とご記入ください。")
        ws.cell(2, 1).font = Font(name="游ゴシック", size=9)
        ws.cell(2, 1).fill = GY.LEAD
        ws.cell(2, 1).alignment = Alignment(wrap_text=True, vertical="top")
        ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=4)
        ws.row_dimensions[2].height = 48
        for c, (h, w) in enumerate(zip(["問", "お伺いすること",
                                        "選択肢・ご記入の形（ご参考）",
                                        "ご記入欄"],
                                       [8, 46, 42, 30]), start=1):
            cell = ws.cell(4, c)
            cell.value = h
            cell.font = Font(name="游ゴシック", size=9, bold=True,
                             color="FFFFFF")
            cell.fill = GY.HEAD
            cell.alignment = Alignment(horizontal="center",
                                       vertical="center", wrap_text=True)
            ws.column_dimensions[get_column_letter(c)].width = w
        ws.freeze_panes = "A5"
        r = 5
        # 冒頭の3欄
        for k, v in (("事業所の名称", ""), ("ご記入者のお名前", ""),
                     ("ご記入の年月日", "令和　年　月　日")):
            ws.cell(r, 2).value = k
            ws.cell(r, 3).value = v or None
            ws.cell(r, 4).fill = KINYU
            for c in (1, 2, 3, 4):
                ws.cell(r, c).font = Font(name="游ゴシック", size=9)
                ws.cell(r, c).alignment = Alignment(wrap_text=True,
                                                    vertical="top")
            r += 1
        r += 1
        for yo, sid, toi, kata, _w, _s, _src in SETSUMON:
            if yo != code:
                continue
            ws.cell(r, 1).value = f"問{bg[sid][1]}"
            ws.cell(r, 2).value = toi
            for c in (1, 2, 3, 4):
                ws.cell(r, c).font = Font(name="游ゴシック", size=9,
                                          bold=True)
                ws.cell(r, c).fill = GY.HI
                ws.cell(r, c).alignment = Alignment(wrap_text=True,
                                                    vertical="top")
            r += 1
            if kata == "kv":
                naka = [(k, v) for k, v in RAN[sid]]
            elif kata == "sel":
                naka = [("当てはまるものに○", x) for x in RAN[sid]]
            elif kata == "free":
                naka = [("ご自由にご記入ください", "")]
            elif kata == "month":
                naka = [(x[0], "／".join(tsukiwari()[0][1:]))
                        for x in tsukiwari()[1:]]
            elif kata == "table":
                naka = [("／".join(kyushi_hyo()[0]), "") for _ in range(4)]
            for k, v in naka:
                ws.cell(r, 2).value = k
                ws.cell(r, 3).value = v or None
                ws.cell(r, 4).fill = KINYU
                for c in (1, 2, 3, 4):
                    ws.cell(r, c).font = Font(name="游ゴシック", size=9)
                    ws.cell(r, c).alignment = Alignment(wrap_text=True,
                                                        vertical="top")
                r += 1
            r += 1
        ws.cell(r, 2).value = "そのほかお伝えになりたいこと"
        ws.cell(r, 2).font = Font(name="游ゴシック", size=9, bold=True)
        ws.cell(r, 4).fill = KINYU
    wb.save(OUT_E)
    return len(wb.worksheets)

