def bangou():
    """様式ごとに問番号を振る。{id: (様式, 問番号)} を返す。"""
    out, cnt = {}, {}
    for yo, sid, *_ in SETSUMON:
        cnt[yo] = cnt.get(yo, 0) + 1
        out[sid] = (yo, cnt[yo])
    return out


def toi_label(sid):
    yo, n = bangou()[sid]
    return f"{yo} 問{n}"


