def kotei():
    """発送から第2回策定委員会までの逆算。"""
    out = []
    for k in KOUHO:
        haifu = k - dt.timedelta(days=T_HAIFU)
        hanei = haifu - dt.timedelta(days=T_HANEI)
        kigen = hanei - dt.timedelta(days=T_SHUKEI)
        n = (kigen - HASSO).days
        han = "○ 間に合う" if n >= 10 else ("△ ぎりぎり" if n >= 7
                                            else "× 間に合わない")
        out.append((k, haifu, hanei, kigen, n, han))
    return out


def kaito_kikan():
    """ご回答にいただける日数の幅（間に合う候補日のみ）。"""
    n = [r[4] for r in kotei() if not r[5].startswith("×")]
    return (min(n), max(n)) if n else (0, 0)


