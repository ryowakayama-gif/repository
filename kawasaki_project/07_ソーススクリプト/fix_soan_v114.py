def mikomi_rows(names, pref=False):
    out = [HEAD]
    for nm in names:
        r = y(nm, pref)
        disp = DISP.get(nm, nm)
        out.append([disp, "給付費", "千円／年", f0(r["R7給付費"])]
                   + [f0(r[t + "給付費"]) for t in YEARS])
        has_q = (r["R7量"] is not None
                 and max([r["R7量"]] + [r[t + "量"] for t in YEARS]) > 0)
        if has_q:                                   # 月包括報酬で回数の概念がない
            u = "回／月" if r["unit"] == "回" else "日／月"
            out.append(["", "回（日）数", u, f1(r["R7量"])]
                       + [f1(r[t + "量"]) for t in YEARS])
        out.append(["", "利用者数", "人／月", f1(r["R7人数"])]
                   + [f1(r[t + "人数"]) for t in YEARS])
    return out


def kubun_total(kb, ku):
    sel = [r for r in M.ROWS if r["kubun"] == kb and r["区分"] == ku]
    return ([sum(r["R7給付費"] for r in sel)]
            + [sum(r[t + "給付費"] for r in sel) for t in YEARS])


