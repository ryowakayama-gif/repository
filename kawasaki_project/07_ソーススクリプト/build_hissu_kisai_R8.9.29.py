def sheet(wb, name, head, widths):
    ws = wb.create_sheet(name)
    for c, (h, w) in enumerate(zip(head, widths), start=1):
        cell = ws.cell(1, c, h)
        cell.font = Font(bold=True)
        cell.fill = HEAD
        cell.border = BOX
        cell.alignment = WRAP
        ws.column_dimensions[get_column_letter(c)].width = w
    ws.freeze_panes = "A2"
    ws.page_setup.orientation = "landscape"
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.page_setup.fitToWidth = 1
    return ws


def put(ws, rows, judge_col=None, start=2):
    for i, r in enumerate(rows, start=start):
        for j, v in enumerate(r, start=1):
            cell = ws.cell(i, j, v)
            cell.border = BOX
            cell.alignment = WRAP
        if judge_col is not None:
            f = FILL.get(str(r[judge_col - 1]).strip())
            if f:
                for j in range(1, len(r) + 1):
                    ws.cell(i, j).fill = f
    return start + len(rows)


def notes(ws, n, ncol, texts, h=34):
    for t in texts:
        ws.cell(n, 1, t).alignment = WRAP
        ws.cell(n, 1).fill = PART
        ws.merge_cells(start_row=n, start_column=1, end_row=n, end_column=ncol)
        ws.row_dimensions[n].height = h
        n += 1
    return n


