def make_alignment_sheet(name, title, subtitle, items, theme_color=None):
    """整合性確認シート作成
    items: [(項目名, 国の方向性, 県の方向性, 町の対応, ステータス, 備考), ...]
    """
    theme_color = theme_color or NAVY
    ws = wb.create_sheet(name)
    
    ms(ws, "A1:G1", title, f_title, F(theme_color), cc)
    ws.row_dimensions[1].height = 26
    ms(ws, "A2:G2", subtitle, f_sub, F(BLUE), cl)
    ws.row_dimensions[2].height = 20
    
    # ヘッダ行
    headers = [
        ("No", 6),
        ("項目・テーマ", 16),
        ("【国】基本指針の方向性", 22),
        ("【宮城県】計画の方向性", 22),
        ("【川崎町】本計画の対応", 22),
        ("整合性", 8),
        ("備考・根拠", 22),
    ]
    for i, (h, w) in enumerate(headers, 1):
        c = ws.cell(row=3, column=i, value=h)
        c.font = f_head
        if i == 3:
            c.fill = F(NAT_FILL); c.font = Font(name="游ゴシック", size=10, bold=True, color=NAVY)
        elif i == 4:
            c.fill = F(PREF_FILL); c.font = Font(name="游ゴシック", size=10, bold=True, color=NAVY)
        elif i == 5:
            c.fill = F(TOWN_FILL); c.font = Font(name="游ゴシック", size=10, bold=True, color=NAVY)
        else:
            c.fill = F(theme_color)
        c.alignment = cc; c.border = border
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[3].height = 36
    
    # データ行
    r = 4
    for item in items:
        if isinstance(item, str):
            # セクション見出し行
            ms(ws, f"A{r}:G{r}", item, f_section, F(LBLUE), cl)
            ws.row_dimensions[r].height = 22
            r += 1
            continue
        no, name_, nat, pref, town, status, note = item
        c = ws.cell(row=r, column=1, value=no)
        c.font = Font(name="游ゴシック", size=10, bold=True, color=NAVY); c.alignment = cc; c.border = border
        c.fill = F(LBLUE)
        c = ws.cell(row=r, column=2, value=name_)
        c.font = Font(name="游ゴシック", size=10, bold=True); c.alignment = cl; c.border = border
        c.fill = F(LGRAY)
        c = ws.cell(row=r, column=3, value=nat)
        c.font = f_body; c.alignment = cl; c.fill = F(NAT_FILL); c.border = border
        c = ws.cell(row=r, column=4, value=pref)
        c.font = f_body; c.alignment = cl; c.fill = F(PREF_FILL); c.border = border
        c = ws.cell(row=r, column=5, value=town)
        c.font = f_body; c.alignment = cl; c.fill = F(TOWN_FILL); c.border = border
        match_cell(ws, r, 6, status)
        c = ws.cell(row=r, column=7, value=note)
        c.font = f_note; c.alignment = cl; c.border = border
        ws.row_dimensions[r].height = 60
        r += 1
    
    setup_page(ws)
    return ws

