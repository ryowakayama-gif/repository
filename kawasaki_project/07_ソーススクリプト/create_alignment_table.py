def match_cell(ws, row, col, status):
    """整合状況セル：整合/部分整合/要確認/未対応"""
    c = ws.cell(row=row, column=col)
    c.border = border
    c.alignment = cc
    if status == "整合":
        c.value = "○ 整合"
        c.font = f_match
        c.fill = F(LGREEN)
    elif status == "部分整合":
        c.value = "△ 部分整合"
        c.font = f_partial
        c.fill = F("FFEB9C")
    elif status == "要確認":
        c.value = "? 要確認"
        c.font = f_partial
        c.fill = F(LORANGE)
    elif status == "未対応":
        c.value = "× 未対応"
        c.font = f_gap
        c.fill = F(LRED)
    elif status == "町独自":
        c.value = "★ 町独自"
        c.font = Font(name="游ゴシック", size=10, bold=True, color=PURPLE)
        c.fill = F(LPURPLE)
    else:
        c.value = status
        c.font = f_body

