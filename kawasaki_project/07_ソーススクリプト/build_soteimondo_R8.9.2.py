def set_runs(el, texts):
    """段落要素の run に順に文字列を割り当てる（run 数を超える分は最後の run に連結）。"""
    runs = el.findall(qn("w:r"))
    for i, r in enumerate(runs):
        ts = r.findall(qn("w:t"))
        if not ts:
            continue
        if i < len(texts):
            v = texts[i] if i < len(runs) - 1 else "".join(texts[i:])
        else:
            v = ""
        ts[0].text = v
        ts[0].set(qn("xml:space"), "preserve")
        for t in ts[1:]:
            t.text = ""


