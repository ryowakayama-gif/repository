def tables_of(doc):
    return [Table(c, doc) for c in doc.element.body.iterchildren() if c.tag == qn("w:tbl")]


def node_text(el):
    return "".join(n.text or "" for n in el.iter(qn("w:t")))


def sub(el, old, new):
    ts = list(el.iter(qn("w:t")))
    if not ts:
        return False
    whole = "".join(t.text or "" for t in ts)
    out = re.sub(re.escape(old), lambda m: new, whole)
    if out == whole:
        return False
    ts[0].text = out
    ts[0].set(qn("xml:space"), "preserve")
    for t in ts[1:]:
        t.text = ""
    return True


def set_text(el, text):
    ts = list(el.iter(qn("w:t")))
    ts[0].text = text
    ts[0].set(qn("xml:space"), "preserve")
    for t in ts[1:]:
        t.text = ""


def find(doc, needle):
    for p in doc.paragraphs:
        if needle in p.text:
            return p
    raise KeyError(needle)


def clone_par(tpl, text):
    p = copy.deepcopy(tpl._p)
    par = Paragraph(p, tpl._parent)
    for r in par.runs[1:]:
        r._element.getparent().remove(r._element)
    par.runs[0].text = text
    return p


def make_table(tpl_tbl, rows):
    new = copy.deepcopy(tpl_tbl)
    trs = new.findall(qn("w:tr"))
    head, bodyr = trs[0], trs[1]
    for tr in trs[1:]:
        new.remove(tr)
    for i, row in enumerate(rows):
        tr = head if i == 0 else copy.deepcopy(bodyr)
        for tc, val in zip(tr.findall(qn("w:tc")), row):
            ps = tc.findall(qn("w:p"))
            set_text(ps[0], val)
            for extra in ps[1:]:
                tc.remove(extra)
        if i:
            new.append(tr)
    return new


def insert_after(anchor_el, elements):
    cur = anchor_el
    for el in elements:
        cur.addnext(el)
        cur = el
    return cur


def fill_kpi(doc, ti, mapping):
    """KPI表の現状値欄を実測値で埋める。"""
    t = tables_of(doc)[ti]._tbl
    n = 0
    for tr in t.findall(qn("w:tr")):
        tcs = tr.findall(qn("w:tc"))
        label = node_text(tcs[0])
        for key, val in mapping.items():
            if key in label:
                set_text(tcs[1].findall(qn("w:p"))[0], val)
                n += 1
    return n


