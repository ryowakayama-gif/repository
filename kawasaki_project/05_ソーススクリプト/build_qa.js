function qaBlock(qNo, qPerson, question, answer, evidence, refs) {
  const blocks = [];

  // 質問ヘッダ（青系）
  blocks.push(new Paragraph({
    spacing: { before: 280, after: 0 },
    shading: { type: ShadingType.SOLID, fill: C.lblue },
    border: {
      top: { style: BorderStyle.SINGLE, size: 18, color: C.navy },
      bottom: { style: BorderStyle.SINGLE, size: 4, color: C.navy },
    },
    children: [
      text(`Q${qNo}　`, { size: 22, bold: true, color: C.navy }),
      text(`【${qPerson}】　`, { size: 18, italics: true, color: C.gray }),
      text(question, { size: 22, bold: true }),
    ],
  }));

  // 回答ブロック（白）
  blocks.push(new Paragraph({
    spacing: { before: 0, after: 0 },
    children: [
      text("A．", { size: 22, bold: true, color: C.red }),
      text(answer, { size: 20 }),
    ],
  }));

  // 根拠データ
  if (evidence) {
    blocks.push(new Paragraph({
      spacing: { before: 120, after: 60 },
      shading: { type: ShadingType.SOLID, fill: "F2F2F2" },
      border: { top: { style: BorderStyle.SINGLE, size: 4, color: C.gray } },
      children: [
        text("　【根拠データ】 ", { size: 18, bold: true, color: C.gray }),
        text(evidence, { size: 18 }),
      ],
    }));
  }

  // 関連資料
  if (refs) {
    blocks.push(new Paragraph({
      spacing: { before: 0, after: 200 },
      shading: { type: ShadingType.SOLID, fill: "F2F2F2" },
      border: { bottom: { style: BorderStyle.SINGLE, size: 4, color: C.gray } },
      children: [
        text("　【関連資料】 ", { size: 18, bold: true, color: C.gray }),
        text(refs, { size: 18, color: C.navy }),
      ],
    }));
  }

  return blocks;
}

