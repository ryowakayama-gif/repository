def pdf_text(p):
    return subprocess.run(["pdftotext", "-layout", str(p), "-"], capture_output=True, text=True).stdout


def wam():
    """サービス種別ごとに、小野町・田村地方・圏域の事業所数と小野町の定員を数える。"""
    ono, tam, ken, cap = collections.Counter(), collections.Counter(), collections.Counter(), collections.defaultdict(int)
    with open(WAM, encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            k = r["サービス種別"]
            ken[k] += 1
            a = r["事業所住所（市区町村）"]
            if a in TAMURA:
                tam[k] += 1
            if a == ONO:
                ono[k] += 1
                if r["定員"].strip().isdigit():
                    cap[k] += int(r["定員"])
    return ono, tam, ken, cap


