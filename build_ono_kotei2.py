def jp(d):
    """2027-02-26 → 令和9年2月26日（金）。"""
    g = d.year - 2018
    return f"令和{g}年{d.month}月{d.day}日（{'月火水木金土日'[d.weekday()]}）"


def _biz(d):
    """土日に落ちた期限は、手前の金曜に寄せる（遅らせる方向には寄せない）。"""
    while d.weekday() >= 5:
        d -= datetime.timedelta(days=1)
    return d


def gyakusan(nouki, chain):
    """納期から逆算して、各工程を「この日までに終える」日を出す。

    chain は納期に近いほうから並べた (工程, 所要日数) の列。
    返すのは納期から遠いほう（＝着手側）から並べ直したもの。
    """
    d = datetime.date.fromisoformat(nouki)
    out = []
    for name, days in chain:
        out.append((name, _biz(d), days))
        d -= datetime.timedelta(days=days)
    return list(reversed(out))


