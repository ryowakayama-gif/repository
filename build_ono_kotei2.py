def kairi(wbs):
    kr = kairi_rows(wbs, ASOF_ISO)
    den = sum(r[10] for r in kr)
    return {
        "rows": kr,
        "ev": sum(r[7] * r[10] for r in kr) / den,
        "pv": sum(r[8] * r[10] for r in kr) / den,
        "cnt": Counter(r[11] for r in kr),
        "okure": sorted([r for r in kr
                         if r[11].startswith("期限超過") or r[11] == "遅れ"],
                        key=lambda x: (x[9], -x[10])),
    }


def first_star(g):
    """★印のうち最も手前のもの（＝いちばん早く来る期限）。"""
    return [x for x in g if x[0].startswith("★")][0]


def selfcheck(cases, gD, gH, KE, KD):
    bad = []
    allg = [(f"高齢者{c}", g) for c, g, _n, _p in cases] + \
           [("障がい", gD), ("ヒアリング", gH)]
    # 1 逆算の日付が、着手側から納期側へ向かって進んでいるか
    for nm, g in allg:
        ds = [d for _n, d, _k in g]
        if ds != sorted(ds):
            bad.append(f"{nm}の逆算の日付が前後している {ds[:4]}")
    # 2 納期を越えていないか
    for nm, g in allg:
        nouki = NOUKI_D if nm.startswith(("障がい", "ヒア")) else NOUKI_E
        if g[-1][1] > datetime.date.fromisoformat(nouki):
            bad.append(f"{nm}の最終工程 {g[-1][1]} が納期 {nouki} を越えている")
    # 3 ★印の節目があり、それが基準日より後か（過ぎていたらもう間に合わない）
    for nm, g in allg:
        st = [x for x in g if x[0].startswith("★")]
        if not st:
            bad.append(f"{nm}に★印の節目がない")
        elif st[0][1] <= ASOF_D:
            bad.append(f"{nm}の最も早い期限 {st[0][1]} が基準日を過ぎている"
                       "（本文の結論を書き直すこと）")
    # 4 乖離の件数が業務進捗管理表と一致するか（同じ関数で計算している）
    for nm, k, wbs in (("高齢者", KE, WBS_ELDERLY), ("障がい", KD, WBS_DISABILITY)):
        if len(k["rows"]) != len(wbs):
            bad.append(f"{nm}の乖離の行数が作業数と違う")
    # 5 協議会を減らすほど、また印刷を縮めるほど第1回の期限が後ろになるか
    #   （逆になっていたら鎖の組み方が間違っている）
    lim = {(n, p): first_star(g)[1] for _c, g, n, p in cases}
    for p in (25, 18):
        if lim[(3, p)] <= lim[(4, p)]:
            bad.append(f"印刷{p}日で、協議会を3回にしても第1回の期限が後ろにならない")
    for n in (4, 3):
        if lim[(n, 18)] <= lim[(n, 25)]:
            bad.append(f"協議会{n}回で、印刷を縮めても第1回の期限が後ろにならない")
    if bad:
        for b in bad:
            print(f"  不適合: {b}")
        raise SystemExit(1)
    print("  自己点検 5項目 適合")


