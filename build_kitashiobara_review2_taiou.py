def load_soan():
    doc = Document(SOAN)
    parts = []
    for ch in doc.element.body.iterchildren():
        tag = ch.tag.split("}")[-1]
        if tag == "p":
            parts.append(Paragraph(ch, doc).text)
        elif tag == "tbl":
            for row in Table(ch, doc).rows:
                seen = set()
                for c in row.cells:
                    if id(c._tc) in seen:
                        continue
                    seen.add(id(c._tc))
                    parts.append(c.text)
    return "\n".join(parts), len(doc.paragraphs), len(doc.tables)


def load_pdf(path, columns=1):
    """PDFの本文を照合用の1つの文字列にまとめる。

    新旧対照表（改正案｜現行の2段組）は、そのまま extract_text すると
    左右の段が1行ずつ交互に混ざり、条文の途中で別の段の文が割り込む。
    改正案の側だけを読むため、columns=2 のときは頁を左右に切って
    左（改正案）→右（現行）の順に連結する。
    """
    import pdfplumber
    import re
    parts = []
    with pdfplumber.open(path) as pdf:
        for pg in pdf.pages:
            if columns == 2:
                w, h = pg.width, pg.height
                parts.append(pg.crop((0, 0, w / 2, h)).extract_text() or "")
                parts.append(pg.crop((w / 2, 0, w, h)).extract_text() or "")
            else:
                parts.append(pg.extract_text() or "")
    return re.sub(r"[\s　]+", "", "\n".join(parts))


