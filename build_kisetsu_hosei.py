def detrend(nm):
    """対数値から線形トレンドを除いた残差を返す。"""
    y = np.log(np.array([SER[nm]["値"][m] for m in MS], dtype=float))
    X = np.column_stack([np.ones_like(TT), TT])
    b, *_ = np.linalg.lstsq(X, y, rcond=None)
    return y - X @ b, b[1]


def fuyu_natsu(nm, sel=None):
    """冬季と夏季の対比（トレンド除去後）。比とt値と自由度を返す。"""
    r, _ = detrend(nm)
    if sel is not None:
        r = np.where(sel, r, np.nan)
    w = r[np.isin(MONTHS, WIN) & ~np.isnan(r)]
    s = r[np.isin(MONTHS, SUM) & ~np.isnan(r)]
    d = w.mean() - s.mean()
    sp2 = ((w.var(ddof=1) * (len(w) - 1) + s.var(ddof=1) * (len(s) - 1))
           / (len(w) + len(s) - 2))
    se = (sp2 * (1 / len(w) + 1 / len(s))) ** 0.5
    df = len(w) + len(s) - 2
    return exp(d), d / se, df


