def verify():
    judges = {rec[5] for rec in SERVICE_GAP} | {rec[4] for rec in CHIIKI_GAP}
    unknown = judges - set(GAP_FILL)
    assert not unknown, f"未定義の判定区分: {unknown}"
    for rec in SERVICE_GAP:
        assert len(rec[3]) == 3, f"{rec[1]} の年度数が3ではありません"
    for rec in CHIIKI_GAP:
        assert len(rec[2]) == 3, f"{rec[0]} の年度数が3ではありません"
    # 前回アンケートの合計行の整合
    # 「（重複所有者）3人」は内数の注記であり合計に加算しない（114+30+12+8＝164）
    send = sum(r[1] for r in PREV_SURVEY_ROWS[:4] if r[1])
    recv = sum(r[2] for r in PREV_SURVEY_ROWS[:6] if r[2])
    total_send, total_recv, total_rate = PREV_SURVEY_ROWS[-1][1:]
    assert send == total_send, f"発送数の合計 {send} ≠ {total_send}"
    assert recv == total_recv, f"回収数の合計 {recv} ≠ {total_recv}"
    assert abs(recv / send - total_rate) < 0.001, "回収率が合計と一致しません"
    measurable = sum(1 for r in POLICY_TARGETS if r[6] == "測定可能")
    print(f"  自己検証: サービス{len(SERVICE_GAP)}区分・地域生活支援事業{len(CHIIKI_GAP)}事業・"
          f"成果目標{len(OUTCOME_TARGETS)}区分・施策指標{len(POLICY_TARGETS)}件"
          f"（測定可能{measurable}／測定不能{len(POLICY_TARGETS) - measurable}）／"
          f"前回調査 発送{total_send}・回収{total_recv}・{total_rate:.1%} 整合")


