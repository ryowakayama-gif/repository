def load_soan_text():
    """他メンバー素案の本文と表を1つの文字列にまとめる（照合用）。"""
    from docx import Document
    from docx.table import Table
    from docx.text.paragraph import Paragraph

    doc = Document(SOAN)
    out = []
    ntbl = 0
    for child in doc.element.body.iterchildren():
        tag = child.tag.split("}")[-1]
        if tag == "p":
            t = Paragraph(child, doc).text.strip()
            if t:
                out.append(t)
        elif tag == "tbl":
            ntbl += 1
            tb = Table(child, doc)
            for row in tb.rows:
                seen = set()
                cells = []
                for c in row.cells:
                    if id(c._tc) in seen:
                        continue
                    seen.add(id(c._tc))
                    cells.append(c.text.strip().replace("\n", " "))
                out.append(" | ".join(cells))
    return "\n".join(out), len(doc.paragraphs), ntbl


def load_kokuji_text():
    """告示本文のPDFを1つの文字列にまとめる（原典照合用）。"""
    import pdfplumber
    parts = []
    with pdfplumber.open(KOKUJI) as pdf:
        for pg in pdf.pages:
            parts.append(pg.extract_text() or "")
    return _norm("\n".join(parts))


def _norm(s):
    """改行・空白を落として照合しやすくする（PDFは行途中で折り返す）。"""
    return re.sub(r"[\s　]+", "", s)


def count_tinted(path):
    """ワークシートの着色セル（＝仮置き値）を数える。"""
    wb = load_workbook(path, data_only=True)
    res = {}
    for name in wb.sheetnames:
        ws = wb[name]
        tint = 0
        for row in ws.iter_rows():
            for c in row:
                if not isinstance(c.value, (int, float)):
                    continue
                f = c.fill
                rgb = None
                if f is not None and f.fill_type == "solid" and f.fgColor is not None:
                    rgb = f.fgColor.rgb if isinstance(f.fgColor.rgb, str) else None
                if rgb == TINT:
                    tint += 1
        if tint:
            res[name] = tint
    return res, wb.sheetnames


