def verify(soan_text, kokuji_text, tinted):
    """引用が原典に実在することを確かめる。"""
    soan_n = _norm(soan_text)
    errors = []

    # ① 国の基本指針の数値が告示本文に実在すること
    for item, orig, _soan, _note in KOKUJI_QUOTE:
        if _norm(orig) not in kokuji_text:
            errors.append(f"告示本文に見つからない引用: {item}『{orig}』")

    # ② 素案に「ある」と書いた数値・語が素案に実在すること
    aru = [
        "2,316", "43.1", "127人", "療育手帳が16人", "38人", "181人",
        "22.1", "23.0", "有効回答数",
        "６％以上", "５％以上", "319.3", "10.3", "17.4", "25.7",
        "1.31", "1.47", "82,000", "100万人",
        "のぞまないセルフプラン", "インクルージョン推進のための協議の場",
        "会津北部地域生活支援拠点", "地域生活支援センターいなわしろ",
        "心のサポーター", "就労選択支援",
    ]
    for w in aru:
        if _norm(w) not in soan_n:
            errors.append(f"素案に見つからない（あるとした記述）: {w}")

    # ③ 素案に「ない」と書いた語が本当にないこと
    nai = [
        "基盤整備量", "圏域単位", "計画的な基盤整備", "その他実施に必要な事項",
        "公共職業安定所", "障害者職業センター", "就業・生活支援センター",
        "経営基盤", "処遇改善", "主任相談支援専門員",
        "基準年度", "支給決定", "実利用", "確保可能", "不足量",
        "継続入所者", "保育所等における", "国保連", "受給者証",
        "障害支援区分", "適用除外", "共生型", "特定疾病",
        "福島県障がい者計画", "会津障がい保健福祉圏域", "県の成果目標",
        "過疎", "別表第五", "別表第一", "別表第二",
        "給付費", "財源", "国庫負担", "内数",
        "こども家庭センター", "地域福祉計画", "こども計画",
        "令和8年7月10日", "令和8年8月19日",
    ]
    for w in nai:
        if _norm(w) in soan_n:
            errors.append(f"素案にある（ないとした語）: {w}")

    # ④ 「介護保険」は1件だけであること（結論Ｈの根拠）
    n_kaigo = soan_text.count("介護保険")
    if n_kaigo != 1:
        errors.append(f"「介護保険」の出現が1件でない: {n_kaigo}件。結論Ｈを書き直す")

    # ⑤ 仮置き値の裏づけ（主要シートに着色セルがあること）
    need_tint = [
        "人口状況", "身体障がい者手帳保持者", "障がい支援区分認定者数",
        "自立支援医療受給者数", "サービス見込量（訪問系） (2)",
        "サービス見込量（日中活動系） (2)", "サービス見込量（居住系・相談系） (2)",
        "サービス見込量（障がい児） (2)",
    ]
    for name in need_tint:
        if tinted.get(name, 0) == 0:
            errors.append(f"着色セル（仮置き値）が見つからない: {name}")

    # ⑥ 突合表の素案の値が素案に実在すること（代表例）
    for svc, unit, _a, _b, _c, r6, r7, r8, _d in TOTSUGO:
        if unit == "人／月":
            for v in (r6, r7, r8):
                if f"{v}（" not in soan_text and f"{v}人分" not in soan_text:
                    errors.append(f"素案に見つからない見込量: {svc} {v}")
                    break

    # ⑦ 重さの語彙が決めたものだけであること
    for rec in KETSURON:
        assert rec[3] in ("最優先", "高", "中", "低"), f"重さが未定義: {rec[0]}"
    for rec in BEPPYO2:
        assert rec[4] in ("充足", "一部", "不足"), f"判定が未定義: {rec[0]}"
    for rec in TASSEI:
        assert rec[4] in ("一致", "不一致"), f"判定が未定義: {rec[0]}"

    # ⑧ 本件の成果品に他町村の名を出さない（他団体の案件の資料は用いない）
    for sheet_data in (KETSURON, BEPPYO2, SEIKA, KARIOKI, TOTSUGO, TASSEI,
                       TOUHOU, KAKUNIN):
        for rec in sheet_data:
            s = "".join(str(x) for x in rec)
            for bad in ("小野町", "金ヶ崎", "阿蘇"):
                if bad in s:
                    errors.append(f"他団体名が含まれている: {bad}")

    if errors:
        print("自己点検 不合格:")
        for e in errors:
            print("   -", e)
        raise SystemExit(1)
    print(f"  自己点検: 告示引用{len(KOKUJI_QUOTE)}件・素案にある記述{len(aru)}件・"
          f"素案にない語{len(nai)}件・着色シート{len(need_tint)}件すべて合")


