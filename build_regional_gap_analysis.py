OUTLIER = {("下川町", "H25")}


def sv(k, y):
    """当該年度の 保険料月額 − 必要保険料月額。算定できない場合はNone。"""
    if (k, y) in OUTLIER:
        return None
    p, n = PREM[k][YI[y]], NEED[k][YI[y]]
    return None if (p is None or n is None) else p - n


def per_sv(k, ys):
    vs = [sv(k, y) for y in ys]
    return sum(vs) if all(v is not None for v in vs) else None


