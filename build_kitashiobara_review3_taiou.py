def load_honpon():
    if not os.path.exists(HONPON):
        return None
    d = docx.Document(HONPON)
    parts = [p.text for p in d.paragraphs]
    for t in d.tables:
        for row in t.rows:
            for c in row.cells:
                parts.append(c.text)
    return "\n".join(parts)


