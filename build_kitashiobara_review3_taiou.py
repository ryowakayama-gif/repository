def _kaiki(xs, ys):
    """最小二乗法の傾きと切片。外部ライブラリに依らない。"""
    n = len(xs)
    mx = sum(xs) / n
    my = sum(ys) / n
    bunshi = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    bunbo = sum((x - mx) ** 2 for x in xs)
    katamuki = bunshi / bunbo
    return katamuki, my - katamuki * mx


def shisan():
    """4通りの試算。
    戻り値 {仮説: {手帳: [令和9, 令和10, 令和11]}}（合計を含む）
    """
    out = {}

    # 仮説Ⅰ 平成31年〜令和5年の回帰を延長する（トレンド延長法）
    a = {}
    for k, ys in JISSEKI.items():
        b, c = _kaiki(NEN5, ys)
        a[k] = [round(c + b * y) for y in SAKI]
    out["Ⅰ"] = a

    # 仮説Ⅰ-b 所持率法・基準年 令和5年
    b_ = {}
    for k, ys in JISSEKI.items():
        r = ys[-1] / JINKO5[-1]
        b_[k] = [round(r * JINKO[y]) for y in SAKI]
    out["Ⅰ-b"] = b_

    # 仮説Ⅱ 所持率法・基準年 令和8年（仮置きの値を用いる）
    c_ = {}
    for k, v8 in KARIOKI_R8.items():
        r = v8 / JINKO[2026]
        c_[k] = [round(r * JINKO[y]) for y in SAKI]
    out["Ⅱ"] = c_

    # 仮説Ⅱ-b 令和5年から令和8年までの増加のペースが続く
    d = {}
    for k, ys in JISSEKI.items():
        b = (KARIOKI_R8[k] - ys[-1]) / 3
        d[k] = [round(KARIOKI_R8[k] + b * (y - 2026)) for y in SAKI]
    out["Ⅱ-b"] = d

    for v in out.values():
        v["合計"] = [sum(v[k][i] for k in JISSEKI) for i in range(3)]
    return out


