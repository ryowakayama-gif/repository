def compute():
    """第10期の標準給付費・保険料と感応度を求める。"""
    act, _sub, gen = T.extract()
    proj = T.project(act, gen, "1号", "1号", 0.0)
    t = T.totals(proj)
    r = T.kasan_ratios(gen)
    ken3 = sum(sum(row["見込"][i][0] for k in ("介護", "予防") for row in proj[k])
               for i in range(1, len(T.EST_YEARS)))
    kyu3 = sum(t[1:])
    std = kyu3 * (1 + r["特定入所"] + r["高額"] + r["高額合算"]) + ken3 * T.TESURYO / 1000

    # 調整交付金見込交付割合を第9期の公表値から逆算する
    wari = ((STD9 + CHI9) * ALPHA + (STD9 + SOGO9) * 0.05 - NEED9) / (STD9 + SOGO9)

    # 所得段階別加入割合補正係数と補正後被保険者数
    pop3 = sum(T.POP_EST[y]["1号"] for y in T.PLAN_YEARS)
    act_tot = sum(n for _n, _r, n in T.SHOTOKU_R7)
    tiers = [(nm, rt, round(n / act_tot * pop3)) for nm, rt, n in T.SHOTOKU_R7]
    pop3 = sum(n for _n, _r, n in tiers)
    hosei = sum(rt * n for _n, rt, n in tiers)

    def getsu(kikin=0, alpha=ALPHA, w=None, chi=CHI9, sogo=SOGO9, s=None):
        s = std if s is None else s
        w = wari if w is None else w
        need = (s + chi) * alpha + (s + sogo) * 0.05 - (s + sogo) * w - kikin
        return need / RATE * 1000 / hosei / 12

    base = getsu()
    d = {
        "総給付費": kyu3, "標準給付費": std, "件数": ken3,
        "地域支援": CHI9, "総合事業": SOGO9,
        "見込交付割合": wari, "補正係数": hosei / pop3,
        "被保険者数": pop3, "補正後": hosei, "tiers": tiers,
        "基準": base,
        "基金12": getsu(12000), "基金35": getsu(35000),
        "交付5.0": getsu(w=0.05), "交付7.0": getsu(w=0.07),
        "負担24": getsu(alpha=0.24),
        "限界率": ALPHA + 0.05 - wari,
    }
    d["給付費1％"] = base - getsu(s=std * 0.99)
    d["地域支援1％"] = base - getsu(chi=CHI9 * 0.99, sogo=SOGO9 * 0.99)
    d["交付割合1pt"] = base - getsu(w=wari + 0.01)
    d["基金1千万"] = base - getsu(10000)
    d["負担1pt"] = getsu(alpha=ALPHA + 0.01) - base
    return d


