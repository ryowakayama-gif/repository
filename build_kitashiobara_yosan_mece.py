def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            for c in r.cells:
                out.append(c.text)
    return "\n".join(out)


def _norm(s):
    return re.sub(r"\s+", "", str(s))


def load_yosan():
    import pypdf
    out = {}
    for name, path in (("R8", R8), ("R7", R7)):
        if not os.path.exists(path):
            raise SystemExit(
                f"予算資料が見つかりません: {path}\n"
                "source/国資料/ に格納してください。")
        r = pypdf.PdfReader(path)
        out[name] = _norm("\n".join((p.extract_text() or "")
                                    for p in r.pages))
        out[name + "_頁"] = len(r.pages)
    return out


