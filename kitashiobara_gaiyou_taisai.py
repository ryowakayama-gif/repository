def measure():
    """前回計画の概要版のＰＤＦを測る。"""
    import pdfplumber
    from collections import Counter
    out = dict(fonts=set(), honbun=[], iro=set())
    with pdfplumber.open(ZENKAI_PDF) as pdf:
        out["pages"] = len(pdf.pages)
        out["width"] = round(float(pdf.pages[0].width))
        out["height"] = round(float(pdf.pages[0].height))
        for pg in pdf.pages:
            cs = pg.chars
            for ch in cs:
                out["fonts"].add(re.sub(r"^[A-Z]{6}\+", "", ch["fontname"]))
                c = ch.get("non_stroking_color")
                if isinstance(c, (tuple, list)) and len(c) == 3:
                    out["iro"].add(tuple(round(x, 4) for x in c))
            c = Counter(round(ch["size"], 1) for ch in cs)
            out["honbun"].append(c.most_common(1)[0][0])
    from pypdf import PdfReader
    out["producer"] = (PdfReader(ZENKAI_PDF).metadata or {}).get(
        "/Producer", "")
    return out


def verify():
    ng = []
    if not os.path.exists(ZENKAI_PDF):
        raise SystemExit(f"前回計画の概要版が見つかりません: {ZENKAI_PDF}")
    m = measure()

    # ① 頁数・寸法・作成ソフト
    for key in ("pages", "width", "height"):
        if m[key] != ZENKAI[key]:
            ng.append(f"前回の{key}が実測と違う: "
                      f"実測{m[key]}／記録{ZENKAI[key]}")
    if ZENKAI["producer"] not in str(m["producer"]):
        ng.append(f"前回の作成ソフトが実測と違う: {m['producer']}")

    # ② 書体。ＵＤデジタル教科書体が使われていること。
    ud = {f for f in m["fonts"] if "UDDigiKyokasho" in f}
    if not ud:
        ng.append("前回の概要版にＵＤデジタル教科書体が見当たらない")
    if not ZENKAI["fonts"] <= m["fonts"]:
        ng.append(f"記録した書体が実測に無い: "
                  f"{sorted(ZENKAI['fonts'] - m['fonts'])}")

    # ③ 本文の大きさ（頁ごとに最も多いもの）
    if m["honbun"] != ZENKAI["honbun"]:
        ng.append(f"前回の本文の大きさが実測と違う: "
                  f"実測{m['honbun']}／記録{ZENKAI['honbun']}")
    #    当方の本文が前回の範囲に収まっていること
    if not min(ZENKAI["honbun"]) <= BODY_PT <= max(ZENKAI["honbun"]):
        ng.append(f"当方の本文（{BODY_PT}ポイント）が"
                  f"前回の範囲（{min(ZENKAI['honbun'])}〜"
                  f"{max(ZENKAI['honbun'])}ポイント）の外にある")

    # ④ 色。記録した見出しの色と帯の色が実測にあること。
    if ZENKAI["midashi_iro"] not in m["iro"]:
        ng.append(f"前回の見出しの色が実測に無い: "
                  f"{ZENKAI['midashi_iro']}")
    #    当方の基調色が前回の見出しの色から作られていること
    if DARK != _rgb16(ZENKAI["midashi_iro"]):
        ng.append(f"当方の基調色が前回の実測から作られていない: {DARK}")
    if OBI != _rgb16(ZENKAI["obi_iro"]):
        ng.append(f"当方の帯の色が前回の実測から作られていない: {OBI}")

    # ⑤ 書体名がＵＤデジタル教科書体であること（当方の側）
