def jiko(soan):
    ng = []
    ids = [r[0] for r in items()]
    if set(ids) != set(J):
        ng.append("判定のない項目 %s／余分な判定 %s" % (sorted(set(ids) - set(J)),
                                              sorted(set(J) - set(ids))))
    for k, (st, kekka, shiji, ura) in J.items():
        if st not in ST:
            ng.append("%s の判定が不正" % k)
        for w in ura:
            if w.startswith("file:"):
                if not (HERE / w[5:]).exists():
                    ng.append("%s：成果品 %s がない" % (k, w[5:]))
            elif _n(w) not in soan:
                ng.append("%s：素案に「%s」がない" % (k, w))
        if st == "完" and not ura:
            ng.append("%s：完了としたが裏づけがない" % k)
    return ng


