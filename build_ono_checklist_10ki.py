def _n(s):
    return unicodedata.normalize("NFKC", re.sub(r"\s+", "", s))


def soan_text():
    import docx
    d = docx.Document(str(SOAN))
    t = [p.text for p in d.paragraphs]
    for tb in d.tables:
        for r in tb.rows:
            t += [c.text for c in r.cells]
    return _n("\n".join(t))


