def head(ws, headers, widths, freeze="A2", autofilter=None):
    for i, h in enumerate(headers, 1):
        c = ws.cell(row=1, column=i, value=h)
        c.font = Font(size=9, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=HEAD_FILL)
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[chr(64 + i) if i <= 26 else "A"].width = w
    ws.freeze_panes = freeze
    if autofilter:
        ws.auto_filter.ref = autofilter


def put(ws, row, values, wrap_cols=()):
    for i, v in enumerate(values, 1):
        c = ws.cell(row=row, column=i, value=v)
        if i in wrap_cols:
            c.alignment = Alignment(wrap_text=True, vertical="top")
        else:
            c.alignment = Alignment(vertical="top")
    return row + 1


def paint_state(ws, row, col):
    c = ws.cell(row=row, column=col)
    fill = STATE_FILL.get(str(c.value))
    if fill:
        c.fill = PatternFill("solid", fgColor=fill)


