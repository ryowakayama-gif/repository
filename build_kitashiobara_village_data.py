def verify():
    """データの内部整合を検証する。"""
    total = sum(n for _k, n, _s, _y, _b in KUBUN_ROWS)
    assert total == 15, f"区分別人数の合計が15人と一致しない: {total}"

    # 修正指示の版が「者」「児」のみであること
    versions = {v for v, *_ in SHUSEI}
    assert versions == {"者", "児"}, f"想定外の版: {versions}"

    # 障がい者版17頁・障がい児版19頁を超える頁番号がないこと
    for v, p, toi, *_ in SHUSEI:
        limit = 17 if v == "者" else 19
        assert 1 <= p <= limit, f"{v}版の頁番号が範囲外: {toi} p.{p}"

    # 問44の選択肢が12項目であること（村の朱書きのとおり）
    assert len(TOI44) == 12, f"問44の選択肢数が12でない: {len(TOI44)}"

    # 成果目標は8区分
    assert len(SEIKA_HANEI) == 8, f"成果目標が8区分でない: {len(SEIKA_HANEI)}"

    # 反映先のサービス名が SERVICES_ADULT / 既知のサービスに存在すること
    known = set(load_service_mikomi())
    for name, *_ in MIKOMI_HANEI:
        if name in ("重度訪問介護", "行動援護", "障害児通所支援（児童発達支援・放課後等デイ）",
                    "障害児入所支援", "医療的ケア児等関連の活動指標"):
            continue
        assert name in known, f"SERVICES_ADULT にないサービス名: {name}"


