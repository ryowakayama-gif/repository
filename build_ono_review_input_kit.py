def unit_gaps():
    """アプリの単位定義と見える化ワークシートの行がずれているものを返す。"""
    ws, _t, _k, _h = W.read()
    name2 = {}
    for kind, mp in (("介護", W.MAP_KAIGO), ("予防", W.MAP_YOBO)):
        for mname, (_cat, myname) in mp.items():
            name2[myname] = (kind, mname)
    out = []
    for name, u in APP_UNIT.items():
        if name not in name2:
            continue
        kind, mname = name2[name]
        d = ws[kind].get(mname, {})
        have = "回" if "回" in d else ("日" if "日" in d else "人数のみ")
        if not (u == have or (u == "人" and have == "人数のみ")):
            out.append((name, u, have))
    return out


