def verify():
    ng = []
    a = zenbu()

    # ① 割付が照会の単一出所と1対1であること
    nos = [x[0] for x in KUBUN]
    if len(nos) != len(set(nos)):
        import collections
        dup = [k for k, v in collections.Counter(nos).items() if v > 1]
        ng.append(f"区分の割付に重複がある: {dup}")
    naka = set(nos)
    moto = set(a)
    if naka - moto:
        ng.append(f"実在しない番号に区分を付けている: {sorted(naka - moto)}")
    if moto - naka:
        ng.append(f"区分を付けていない照会がある: {sorted(moto - naka)}")

    # ② 件数の検算（合計・欠番・重複）
    ku = _kazu()
    gokei = sum(len(v) for v in ku.values())
    if gokei != len(KUBUN):
        ng.append(f"区分ごとの件数の合計が合わない: {gokei} ≠ {len(KUBUN)}")
    for pre in ("Ｍ", "Ｓ"):
        ban = sorted(int(x.split("-")[1]) for x in nos
                     if x.startswith(pre))
        if len(ban) != len(set(ban)):
            ng.append(f"{pre}の番号に重複がある")
        #   Ｓ-13からＳ-18 は欠番である（他団体の案件ではない）。
        #   Ｍ は現行の採番（40以上）が連番であること。
        #   39以下は第1回から第3回までのレビューの過程で振った旧番号で
        #   あり、解決・統合したものは番号を再利用していないため欠番が
        #   ある。旧番号のうち正本の注記が引いているものを令和8年10月22日に
        #   台帳へ戻した。正本の現物との整合は
        #   build_kitashiobara_zenki_redteam.py の検査④で確かめる。
        if pre == "Ｍ":
            genkou = [n for n in ban if n >= 40]
            nuke = [n for n in range(genkou[0], genkou[-1] + 1)
                    if n not in genkou]
            if nuke:
                ng.append(f"Ｍの番号に欠番がある: {nuke}")

    # ③ 区分が4つのいずれかであること
    for no, kubun, riyu, togo in KUBUN:
        if kubun not in (A, B, C, D):
            ng.append(f"区分が未定義: {no} {kubun}")
        if not riyu.strip():
            ng.append(f"判断の理由が空: {no}")

    # ④ 統合のきまり
    #    統合先を書けるのはＡだけ。統合先は実在し、Ａでないかつ
    #    さらに統合されていないこと（統合の連鎖を作らない）。
    togo_saki = {}
    for no, kubun, _riyu, togo in KUBUN:
        if togo and kubun != A:
            ng.append(f"Ａ以外に統合先を書いている: {no}（{kubun}）")
        if togo:
            togo_saki[no] = togo
    for no, saki in togo_saki.items():
        if saki not in a:
            ng.append(f"統合先が実在しない: {no} → {saki}")
            continue
        rec = [x for x in KUBUN if x[0] == saki]
        if not rec:
            ng.append(f"統合先に区分が付いていない: {saki}")
        elif rec[0][1] == A:
            ng.append(f"統合先がＡである（統合の連鎖）: {no} → {saki}")
    #    統合先の理由に、統合したことが書かれていること
    for no, saki in togo_saki.items():
        rec = [x for x in KUBUN if x[0] == saki]
        if rec and no not in rec[0][2] and "含める" not in rec[0][2] \
                and "受け皿" not in rec[0][2] and "まとめ" not in rec[0][2]:
            ng.append(f"統合先の理由に統合したことが書かれていない: "
                      f"{saki}（{no} をまとめた）")

    # ④b 便・節・電話に入っている番号がすべて区分されていること
    m = _shoukai()
    waritsuke = {no for b in m.BIN for no in b["nos"]}
    waritsuke |= {no for s in m.MEMBER_SETSU for no in s["nos"]}
    waritsuke |= set(m.DENWA)
    nuke2 = sorted(waritsuke - set(nos))
    if nuke2:
        ng.append(f"便・節・電話に入っているのに区分していない: {nuke2}")

    # ⑤ Ａ・Ｂは相手に尋ねないため、Ｃ・Ｄだけが照会に残ること
    nokoru = [x[0] for x in ku[C] + ku[D]]
    if len(nokoru) != len(ku[C]) + len(ku[D]):
        ng.append("Ｃ・Ｄの件数が合わない")
    #    Ｍ-18・Ｍ-19（村資料の側で管理している最優先の2件）は
    #    照会の単一出所に入っていないため、ここには現れない。
    if "Ｍ-18" in naka or "Ｍ-19" in naka:
        ng.append("村資料の側で管理している番号に区分を付けている")

    # ⑥ 他団体の案件の資料・固有の事実を用いていないこと。
    #    方法だけを採り、団体名は書かない。
    #    成果品に載る文（区分の割付・裏づけ・区分の意味）と、
    #    このブックの解説（モジュールの説明文）を見る。
    #    検査そのものが持つ団体名の一覧は対象にしない。
    zen = "\n".join(
        str(v) for recs in (KUBUN, URADUKE_NASHI, KUBUN_IMI)
        for rec in recs for v in rec)
    zen += "\n" + (__doc__ or "")
    for hoka in ("小野町", "金ヶ崎", "金ケ崎", "kanegasaki", "阿蘇",
                 "札幌", "kawasaki", "川崎町"):
        if hoka in zen:
            ng.append(f"他団体の名が入っている: {hoka}")

    # ⑦ 裏づけが取れていないものが、照会として実在する番号を引くこと
    for koto, _doko, sho in URADUKE_NASHI:
        for no in sho.split("・"):
            no = no.strip()
            if no.startswith(("Ｍ-", "Ｓ-")) and no not in a:
                ng.append(f"裏づけの照会番号が実在しない: {koto} → {no}")

    # ⑧ Ｂに置いたものが、当方の手元の資料で確かめられる旨を
    #    書いていること（転嫁しないという原則の裏づけ）
    for no, kubun, riyu, _t in KUBUN:
        if kubun != B:
            continue
        if not any(w in riyu for w in ("受領", "原典", "手元", "当方")):
            ng.append(f"Ｂの理由に当方で確かめられる根拠がない: {no}")

    if ng:
        for x in ng:
            print(f"  × {x}")
        raise SystemExit("確認事項の区分の自己点検で止めました")

    bin_nos, setsu_nos, denwa = _mae_no_seiri()
    mae = len(set(bin_nos) | set(setsu_nos) | set(denwa))
    ato = len(ku[C]) + len(ku[D])
    togo = [x for x in KUBUN if x[3]]
    return (f"確認事項{len(KUBUN)}件／"
            f"Ａ{len(ku[A])}・Ｂ{len(ku[B])}・Ｃ{len(ku[C])}・"
            f"Ｄ{len(ku[D])}（合計 検算済み）／"
            f"相手に尋ねる件数 {mae}件から{ato}件へ（{ato - mae:+d}）／"
            f"まとめたもの{len(togo)}件／"
            f"裏づけが取れていないもの{len(URADUKE_NASHI)}件")


