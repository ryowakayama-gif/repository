def _shoukai():
    m = importlib.import_module("build_kitashiobara_shoukai_bun")
    return m


def zenbu():
    """生きている確認事項の全体集合。

    照会の単一出所（atsumeru）に、第2回レビューの確認事項（K_R2）のうち
    いま他メンバー・県あてとして生きている番号を加える。
    K_R2 は宛先の形が違うため atsumeru の対象外に置かれており、
    atsumeru だけを見るとＳ-11 を取りこぼす
    （令和8年10月15日にこの取りこぼしを見つけた）。
    """
    m = _shoukai()
    out = dict(m.atsumeru())
    ikiteru = set(m.HOKA) | set(m.KEN_KEIYU)
    for r in m.K_R2:
        no = r[0].replace("M-", "Ｍ-").replace("S-", "Ｓ-")
        if no in ikiteru and no not in out:
            out[no] = dict(no=no, atesaki=r[1], kenmei=r[2], naiyo=r[3],
                           tsukaimichi="", kigen="令和８年10月31日（金）")
    return out


def _mae_no_seiri():
    """前の整理（便と節への割付）から、相手に尋ねていた件数を出す。

    便89件＋節22件＋電話1件＝112件。これが区分する前に
    相手にお尋ねしていた件数である。
    """
    m = _shoukai()
    bin_nos = [no for b in m.BIN for no in b["nos"]]
    setsu_nos = [no for s in m.MEMBER_SETSU for no in s["nos"]]
    denwa = list(m.DENWA)
    return bin_nos, setsu_nos, denwa


