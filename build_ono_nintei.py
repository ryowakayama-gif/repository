def tot(d, i):
    return sum(d[g][i] for g in GR)


def sheet(wb, name, header, rows, widths, wrap_cols=(), group_col=None, flag_col=None):
    ws = wb.create_sheet(name)
    ws.append(header)
    for c in ws[1]:
        c.font = Font(bold=True, size=9, color="FFFFFF")
        c.fill = HDR
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        c.border = BORDER
    for r in rows:
        ws.append(list(r))
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row):
        for i, c in enumerate(row):
            c.font = Font(size=9)
            c.border = BORDER
            c.alignment = Alignment(wrap_text=(i in wrap_cols), vertical="top")
        if group_col is not None and len(row) > group_col and row[group_col].value:
            row[group_col].fill = GRP
            row[group_col].font = Font(size=9, bold=True)
        if flag_col is not None and len(row) > flag_col:
            v = str(row[flag_col].value or "")
            if "★" in v or "異常" in v:
                for c in row:
                    c.fill = BAD
            elif "要確認" in v:
                row[flag_col].fill = WARN
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "B2"
    return ws


def series_sheet(wb, name, d, per=PER, note=None):
    hdr = ["要介護度"] + [f"{p}年\n3月末" for p in per]
    rows = [[g] + [d[g][i] for i in range(len(per))] for g in GR]
    rows.append(["合計"] + [tot(d, i) for i in range(len(per))])
    rows.append([])
    rows.append(["対前年増減"] + ["―"] + [tot(d, i) - tot(d, i - 1) for i in range(1, len(per))])
    rows.append(["増減率"] + ["―"] +
                [f"{(tot(d,i)-tot(d,i-1))/tot(d,i-1)*100:+.1f}%" for i in range(1, len(per))])
    ws = sheet(wb, name, hdr, rows, [14] + [9] * len(per))
    for c in ws[ws.max_row - 3]:
        c.font = Font(size=9, bold=True)
    if note:
        ws.append([])
        ws.append([note])
        ws[f"A{ws.max_row}"].font = Font(size=9, italic=True)
    return ws


