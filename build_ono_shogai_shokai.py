def selfcheck(rows, src_sheets):
    ok, ng = [], []

    def chk(no, name, kitai, kekka):
        (ok if kitai == kekka else ng).append((no, name, str(kitai),
                                               str(kekka)))

    machi = [r for r in rows if r[1] == "町"]
    gyo = [r for r in rows if r[1] == "事業所"]
    nos = {r[0] for r in rows}
    moto = set(range(1, 16))            # 受領確認票の15論点
    tsuika = {16, 17}                   # 当方が足した2件

    chk("1", "元の15論点がすべて振り分けられている", moto, nos & moto)
    chk("2", "振り分け先のない論点", set(), moto - nos)
    chk("3", "元にない論点番号を作っていない", tsuika, nos - moto)
    # 両方に置いた論点は、聞く内容が違うこと
    ryoho = {r[0] for r in machi} & {r[0] for r in gyo}
    dup = []
    for n in ryoho:
        a = next(r[3] for r in machi if r[0] == n)
        b = next(r[3] for r in gyo if r[0] == n)
        if a == b:
            dup.append(n)
    chk("4", "両方に置いた論点で聞く内容が同じもの", [], dup)
    chk("5", "両方に置いた論点の数", 7, len(ryoho))
    chk("6", "町向けの件数", 13, len(machi))
    chk("7", "事業所向けの件数", 11, len(gyo))
    # 宛先が答えられないことを聞いていないか（語での点検）
    GYO_ONLY = ("定員", "稼働率", "離職", "採用", "休廃止", "処遇改善")
    MACHI_ONLY = ("支給決定台帳", "虐待の相談件数", "名簿の登録者数")
    bad = [f"町{r[0]}「{w}」" for r in machi for w in GYO_ONLY if w in r[3]]
    bad += [f"事業所{r[0]}「{w}」" for r in gyo for w in MACHI_ONLY
            if w in r[3]]
    chk("8", "宛先が答えられない語が混ざっていないか", [], bad)
    # 受領確認票の入力シートを引き継いでいるか
    chk("9", "受領確認票のシートが読めた", True,
        "02_行政実績" in src_sheets and "04_供給制約" in src_sheets)
    # 優先度がすべて付いているか
    chk("10", "優先度が空のもの", [],
        [r[0] for r in rows if r[6] not in ("最優先", "高", "中")])
    return ok, ng, machi, gyo


