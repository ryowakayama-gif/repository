# ---------------------------------------------------------------- 書式

def head_row(ws, row=1, widths=None):
    if widths:
        for i, w in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(i)].width = w
    for c in ws[row]:
        if c.value is None:
            continue
        c.font = Font(bold=True, size=9, color="FFFFFF")
        c.fill = HEAD
        c.border = BORDER
        c.alignment = Alignment(wrap_text=True, vertical="center",
                                horizontal="center")


def body(ws, min_row=2, wrap=(), fill_cols=()):
    for row in ws.iter_rows(min_row=min_row):
        for i, c in enumerate(row):
            if c.value is not None:
                c.border = BORDER
            c.font = Font(size=9)
            c.alignment = Alignment(wrap_text=(i in wrap), vertical="top")
            if i in fill_cols:
                c.fill = YEL
                c.border = BORDER


def title(ws, lines, row=1):
    for i, (t, sz, b) in enumerate(lines, row):
        c = ws.cell(row=i, column=1, value=t)
        c.font = Font(bold=b, size=sz,
                      color="1F3864" if b and sz >= 12 else "000000")
    return row + len(lines)


def shushi(wb, name, atesaki, n, lines):
    ws = wb.create_sheet(name)
    for i, w in enumerate([3, 26, 62, 26], 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    r = 1
    for t, sz, b in lines:
        c = ws.cell(row=r, column=2 if sz < 14 else 1, value=plain(t))
        c.font = Font(bold=b, size=sz,
                      color="1F3864" if sz >= 14 else "000000")
        c.alignment = Alignment(wrap_text=True, vertical="top")
        r += 1
    return ws


