def members(hno):
    """保険者番号から構成市町村の一覧を返す。"""
    for h, _n, _p, m in RENGO:
        if h == hno:
            return m
    return []


def avg(hno, idx=8):
    """構成市町村の得点の単純平均。idx=8は推進・支援合計。"""
    m = members(hno)
    return sum(x[idx] for x in m) / len(m) if m else None


