def _num(s):
    try:
        return float(str(s).replace("人", "").replace("%", ""))
    except ValueError:
        return None


def totsugo(mura, gaisan):
    """村の令和7年度実績と当方の第1次概算を突き合わせる。"""
    rows = []
    for name, units in mura.items():
        if name in MURA_ONLY:
            continue
        key = ALIAS.get(name, name)
        rec = gaisan.get(key)
        if rec is None:
            continue
        users = units.get("実利用者数（人／月）")
        if users is None:
            continue
        act = _num(users["r7_act"])
        mine = rec["users"]
        r8 = _num(users["r8_plan"])
        if act is None:
            state, sa, seishitsu = NEW, "―", "村資料に令和7年度の実績がない"
        elif abs(act - mine) < 0.05:
            state, sa, seishitsu = ITCHI, "0", "―"
        else:
            state = SA
            sa = f"{mine - act:+.1f}人"
            if r8 is not None and abs(r8 - mine) < 0.05:
                seishitsu = ("当方の値は村の令和8年度見込と一致する。"
                             "実績との差は系列の違い（村は月平均、"
                             "当方は年間請求件数を基礎にした人数）。"
                             "計画値を実績に寄せるか見込量に寄せるかを決める")
            elif act > mine:
                seishitsu = ("当方が過小。村の公表実績を反映していない。"
                             "村の値に置き換える")
            elif act == 0:
                seishitsu = ("村の実績0に対し当方が成果目標により計上した分。"
                             "村の令和8年度見込とも一致しないため、"
                             "成果目標との整合を村に確認する")
            else:
                seishitsu = ("当方が実績・村の令和8年度見込のいずれとも"
                             "一致しない。成果目標による補正分であり、"
                             "根拠を村に確認する")
        qty = units.get("サービス量（時間／月）") or units.get(
            "サービス量（人日／月）")
        rows.append({
            "name": name, "users_r6": users["r6_act"],
            "users_r7": users["r7_act"], "users_r8plan": users["r8_plan"],
            "qty_r7": (qty["r7_act"] if qty else "―"),
            "qty_r8plan": (qty["r8_plan"] if qty else "―"),
            "mine": mine, "sa": sa, "state": state,
            "seishitsu": seishitsu,
        })
    return rows


