def verify(mura, gaisan, rows, mokuhyo):
    ng = []

    # 1 村資料の読み出しが足りていること
    if len(mura) < 40:
        ng.append(f"村の見込量と実績が{len(mura)}件しか読めていない")
    if len(mokuhyo) < 10:
        ng.append(f"村の成果目標が{len(mokuhyo)}件しか読めていない")

    # 2 村資料から読んだ値が、原典の既知の値と一致すること
    known = [
        ("居宅介護", "実利用者数（人／月）", "r7_act", "2.6"),
        ("居宅介護", "サービス量（時間／月）", "r7_act", "30.25"),
        ("生活介護", "実利用者数（人／月）", "r7_act", "5.6"),
        ("生活介護", "サービス量（人日／月）", "r7_act", "111"),
        ("就労継続支援B型", "実利用者数（人／月）", "r7_act", "11.8"),
        ("共同生活援助", "実利用者数（人／月）", "r7_act", "8.75"),
        ("施設入所支援", "実利用者数（人／月）", "r7_act", "3.6"),
        ("計画相談支援", "実利用者数（人／月）", "r7_act", "25"),
        ("放課後等デイサービス", "実利用者数（人／月）", "r7_act", "2.25"),
        ("障がい児相談支援", "実利用者数（人／月）", "r7_act", "4"),
    ]
    for name, unit, key, want in known:
        got = mura.get(name, {}).get(unit, {}).get(key)
        if got != want:
            ng.append(f"村資料の読み出しが合わない: {name}／{unit}／{key}"
                      f" 読み={got} 原典={want}")

    # 3 突合の判定が3区分のいずれかで、差があるものが実在すること
    for x in rows:
        if x["state"] not in (ITCHI, SA, NEW):
            ng.append(f"突合の判定が不正: {x['name']}／{x['state']}")
    if not any(x["state"] == SA for x in rows):
        ng.append("差があるサービスが0件。突合が働いていない")

    # 4 レビューの判定が3区分のいずれかであること
    for rec in TAIOU:
        if rec[2] not in (TORU, ICHIBU, TORANAI):
            ng.append(f"レビューの判定が不正: {rec[0]}／{rec[2]}")

    # 5 修正箇所の実施欄が「本回で実施」又は「次回」で始まること
    for rec in SHUUSEI:
        if not rec[3].startswith(("本回で実施", "次回")):
            ng.append(f"修正箇所の実施欄が不正: {rec[0]}／{rec[3]}")

    # 6 セルに Markdown の強調が残っていないこと
    for name, table in (("TAIOU", TAIOU), ("SHUUSEI", SHUUSEI)):
        for rec in table:
            for cell in rec:
                if "**" in str(cell):
                    ng.append(f"{name} のセルに ** が残っている")

    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("  -", x)
        return False
    print(f"自己点検: 合格　村資料から{len(mura)}サービスを読み出し、"
          f"既知の10点を原典と照合／突合{len(rows)}件の判定が3区分に収まる／"
          f"レビュー{len(TAIOU)}件の判定が3区分／"
          f"修正箇所{len(SHUUSEI)}件の実施欄が正常／セルの Markdown 強調0件")
    return True


