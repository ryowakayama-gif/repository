def read_mura_mikomi():
    """村の「見込量と実績」から、サービス別の見込量・実績を読む。

    pdfplumber で表の罫線から読む。pypdf のテキスト抽出では
    行と列が崩れるため、数値の取り違えが起こる。
    """
    import pdfplumber
    if not os.path.exists(MIKOMI_PDF):
        raise SystemExit(f"村資料が見つかりません: {MIKOMI_PDF}")
    keys = ["r6_plan", "r6_act", "r6_rate",
            "r7_plan", "r7_act", "r7_rate", "r8_plan"]
    out = {}
    with pdfplumber.open(MIKOMI_PDF) as pdf:
        for page in pdf.pages:
            for tbl in page.extract_tables():
                name = None
                for row in tbl:
                    c = ["" if x is None else x.replace("\n", "").strip()
                         for x in row]
                    # 単位の列を探す。列の位置は表によって違う。
                    ui = next((i for i, v in enumerate(c)
                               if "／月" in v or "／年" in v or "カ所" in v),
                              None)
                    if ui is None:
                        continue
                    # 単位より左の、数字でない語がサービス名。
                    # サービス量の行は名前が空なので直前の名前を引き継ぐ。
                    label = next((v for v in c[:ui]
                                  if v and not v.isdigit()), "")
                    if label:
                        name = label
                    if name is None:
                        continue
                    vals = (c[ui + 1:] + [""] * len(keys))[:len(keys)]
                    out.setdefault(name, {})[c[ui]] = dict(zip(keys, vals))
    if len(out) < 40:
        raise SystemExit(f"村の見込量と実績を読めていません: {len(out)}件")
    return out


def read_mura_mokuhyo():
    """村の「提供体制の確保に係る目標」から、成果目標の進捗を読む。"""
    import pdfplumber
    if not os.path.exists(MOKUHYO_PDF):
        raise SystemExit(f"村資料が見つかりません: {MOKUHYO_PDF}")
    out = []
    with pdfplumber.open(MOKUHYO_PDF) as pdf:
        kubun = ""
        for page in pdf.pages:
            for tbl in page.extract_tables():
                for row in tbl:
                    c = ["" if x is None else x.replace("\n", "").strip()
                         for x in row]
                    joined = "".join(c)
                    m = re.search(r"\((\d)\)", joined)
                    if m and "目標設定" in joined:
                        kubun = f"（{m.group(1)}）" + re.sub(
                            r".*\(\d\)", "", joined).replace(
                            "に関する目標設定", "").strip()
                        continue
                    if "項目" in c or not kubun:
                        continue
                    label = next((v for v in c
                                  if v and v not in ("目標", "・進捗",
                                                     "目標・進捗", "目",
                                                     "標・進捗")), "")
                    vals = [v for v in c if v and v != label][-5:]
                    if label and len(vals) >= 4 and "数" in label + "設置" \
                            or (label and len(vals) >= 4):
                        out.append((kubun, label, vals))
    if len(out) < 10:
        raise SystemExit(f"村の成果目標を読めていません: {len(out)}件")
    return out


