def selfcheck(N):
    bad = []
    for y, n in N.items():
        if sum(n) != SYS_POP[y]:
            bad.append(f"{y} 合計{sum(n)}≠{SYS_POP[y]}")
    tot = sum(v[3] for v in CHIIKI) + sum(v[1] for v in CHIIKI_MACHI)
    if tot != CHIIKI_NEN:
        bad.append(f"地域支援事業費の合計 {tot:,}≠{CHIIKI_NEN:,}")
    return bad


