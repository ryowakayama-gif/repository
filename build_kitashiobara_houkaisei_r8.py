def load_pdf(path):
    from pypdf import PdfReader
    r = PdfReader(path)
    return "\n".join((pg.extract_text() or "") for pg in r.pages)


def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for row in t.rows:
            for c in row.cells:
                out.append(c.text)
    return "\n".join(out)


