def find_para(doc, prefix, style=None):
    """本文中から、指定の文字列で始まる段落の XML 要素を返す。"""
    for child in doc.element.body.iterchildren():
        if child.tag != qn("w:p"):
            continue
        p = Paragraph(child, doc)
        if p.text.strip().startswith(prefix) and (style is None or p.style.name == style):
            return child
    raise LookupError(f"段落が見つかりません: {prefix!r}")


def find_table(doc, prefix):
    """本文中から、先頭セルが指定の文字列で始まる表の XML 要素を返す。"""
    for child in doc.element.body.iterchildren():
        if child.tag != qn("w:tbl"):
            continue
        if Table(child, doc).cell(0, 0).text.strip().startswith(prefix):
            return child
    raise LookupError(f"表が見つかりません: {prefix!r}")


def set_box_lines(doc, tbl_element, lines):
    """1x1 の注記ボックス（≪国の基本指針≫欄など）の中身を行単位で差し替える。

    原本は 1 行 = 1 段落で組まれているため、先頭段落を書式の雛形として複製する。
    """
    cell = Table(tbl_element, doc).cell(0, 0)
    paras = cell.paragraphs
    template = copy.deepcopy(paras[0]._p)
    for extra in paras[1:]:
        extra._p.getparent().remove(extra._p)

    def write(p_el, text):
        p = Paragraph(p_el, doc)
        for run in list(p.runs):
            run._r.getparent().remove(run._r)
        run = p.add_run(text)
        _set_font(run, size=9.5)

    write(paras[0]._p, lines[0])
    cur = paras[0]._p
    for line in lines[1:]:
        new = copy.deepcopy(template)
        write(new, line)
        cur.addnext(new)
        cur = new


def find_block_after(doc, anchor, tag):
    """anchor 以降で最初に現れる指定タグの要素を返す。"""
    seen = False
    for child in doc.element.body.iterchildren():
        if child is anchor:
            seen = True
            continue
        if seen and child.tag == qn(f"w:{tag}"):
            return child
    raise LookupError(f"{tag} が見つかりません")


def insert_after(anchor, elements):
    """anchor の直後に elements を順番どおり挿入する。"""
    cur = anchor
    for e in elements:
        cur.addnext(e)
        cur = e
    return cur


def insert_before(anchor, elements):
    for e in elements:
        anchor.addprevious(e)
    return anchor


def replace_note_text(doc, tbl_element, text):
    """既存の【要更新・要確認】ボックスの本文を差し替える。"""
    t = Table(tbl_element, doc)
    para = t.cell(0, 0).paragraphs[0]
    for run in list(para.runs):
        run._r.getparent().remove(run._r)
    run = para.add_run(text)
    _set_font(run, size=9.5)


def renumber_heading(doc, old_text, new_text, style="Heading 2"):
    """見出しの本文を書式を保ったまま差し替える。"""
    el = find_para(doc, old_text, style=style)
    p = Paragraph(el, doc)
    runs = list(p.runs)
    if not runs:
        run = p.add_run(new_text)
        _set_font(run, size=12, bold=True)
        return
    runs[0].text = new_text
    for run in runs[1:]:
        run._r.getparent().remove(run._r)


def replace_para_text(doc, element, paragraphs):
    """段落の本文を差し替える。1段落を複数段落に分ける場合はリストで渡す。"""
    p = Paragraph(element, doc)
    for run in list(p.runs):
        run._r.getparent().remove(run._r)
    run = p.add_run(paragraphs[0])
    _set_font(run)
    p.paragraph_format.first_line_indent = Pt(10.5)
    extra = [make_para(doc, t) for t in paragraphs[1:]]
    insert_after(element, extra)
    return extra[-1] if extra else element


