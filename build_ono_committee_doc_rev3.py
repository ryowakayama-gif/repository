# ---------------------------------------------------------------- 書式保持ユーティリティ

def set_para(p, text):
    """段落のテキストを、先頭ランの書式を保ったまま差し替える。"""
    runs = p.runs
    if not runs:
        p.add_run(text)
        return
    runs[0].text = text
    for r in runs[1:]:
        r._element.getparent().remove(r._element)


def set_cell(cell, text):
    """セルのテキストを差し替える。2段落目以降は削除する。"""
    paras = cell.paragraphs
    set_para(paras[0], text)
    for p in paras[1:]:
        p._element.getparent().remove(p._element)


def insert_para_after(anchor, text):
    """anchor 段落の直後に、同じ書式の段落を挿入して返す。"""
    new = copy.deepcopy(anchor._element)
    anchor._element.addnext(new)
    from docx.text.paragraph import Paragraph

    p = Paragraph(new, anchor._parent)
    set_para(p, text)
    return p


def clone_row(table, src_index):
    """table の src_index 行を複製して末尾に追加し、追加した行を返す。"""
    src = table.rows[src_index]._tr
    new = copy.deepcopy(src)
    src.getparent().append(new)
    return table.rows[-1]


def set_row(row, values):
    for cell, v in zip(row.cells, values):
        set_cell(cell, v)


def find_para(doc, needle):
    for p in doc.paragraphs:
        if needle in p.text:
            return p
    raise LookupError(f"段落が見つかりません: {needle}")


