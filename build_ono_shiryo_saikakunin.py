# ---------------------------------------------------------------- 自己点検
def jiko():
    ng = []
    # 1 番号に重複がない
    nos = [x[0] for x in MACHI] + [x[0] for x in HANDAN] + [x[0] for x in MACHIKI]
    if len(nos) != len(set(nos)):
        ng.append("番号が重複している")
    # 2 取り下げるものには必ず「どこにあるか」がある
    for x in TORISAGE:
        if not x[2].strip():
            ng.append("取り下げに所在がない：%s" % x[0])
        if not x[3].strip():
            ng.append("取り下げに受領時期がない：%s" % x[0])
    # 3 町にしかないものには必ず期限と影響度がある
    for x in MACHI:
        if not x[3].strip() or not x[4].strip():
            ng.append("町の件に期限または影響度がない：%s" % x[0])
    # 4 影響度Ｓは期限が11月6日までか10月28日まで
    for x in MACHI:
        if "Ｓ" in x[4] and "まで" not in x[3]:
            ng.append("Ｓなのに期限が日付でない：%s" % x[0])
    # 5 県・国待ちの宛先が県か国
    for x in MACHIKI:
        if x[1] not in ("県", "国"):
            ng.append("県・国待ちの宛先が県でも国でもない：%s" % x[0])
    # 6 「何が動くか」が空でない
    for x in MACHI + MACHIKI:
        if not x[2].strip():
            ng.append("何が動くかが空：%s" % x[0])
    for x in HANDAN:
        if not x[2].strip():
            ng.append("何が動くかが空：%s" % x[0])
    # 7 受領の照合は3件
    if len(UKETORI) != 3:
        ng.append("ご提供いただいた点数が3でない：%d" % len(UKETORI))
    # 8 本文に件数を手で書いていない
    import inspect
    import re
    src = inspect.getsource(doc_build)
    for m in re.findall(r"（\d+件）|は\d+件です", src):
        if "%d" not in m:
            ng.append("本文に件数を手で書いている：%s" % m)
    return ng


