def kensa(rows, mikomi):
    ng = []
    for r in rows:
        if (_norm(r["svc"]), _norm(r["tani"])) not in mikomi:
            ng.append(f"① 正本の見込量の表に行が無い: {r['svc']} {r['tani']}")
        if r["v"] is None or r["v"] < 0:
            ng.append(f"② 参考値が求められない: {r['svc']} {r['tani']}")
    #   起点は台帳又は資料２－３の現物から出していること（作った値でない）
    for svc, tani, kansu, setsumei, _s in SPEC:
        if not ("台帳" in setsumei or "資料２－３" in setsumei
                or "１人当たり" in setsumei or setsumei.startswith("同上")):
            ng.append(f"③ 起点の出所が書かれていない: {svc} {tani}")
    return ng


def verify():
    rows = keisan()
    mikomi = honpon_mikomi()
    ng = kensa(rows, mikomi)
    #   ④ 検算：共同生活援助の起点が台帳の直近の月の人数と合うこと
    gh = next(r for r in rows if r["svc"] == "共同生活援助")
    last = [int(x["ninzu"]) for x in tsuki_rows(ROWS, "共同生活援助", 8)[-3:]]
    if abs(gh["v"] - sum(last) / 3) > 1e-9:
        ng.append("④ 共同生活援助の起点が台帳と合わない")
    #   ⑤ 計画の表に置く場合の丸め
    for v, w in ((0.0, 0), (0.3, 1), (0.8, 1), (2.4, 2), (2.5, 3), (11.7, 12)):
        if hyou_ni(v) != w:
            ng.append(f"⑤ 丸めの規則が違う: {v}→{hyou_ni(v)}")
    #   ⑥ 判定の検算（共同生活援助は正本が下回り、施設入所支援は概ね整合）
    for svc, tani, want in (("共同生活援助", "人／月", "正本が下回る"),
                            ("施設入所支援", "人／月", "概ね整合"),
                            ("計画相談支援", "人／月", KAZOEKATA)):
        x = next(r for r in rows if r["svc"] == svc and r["tani"] == tani)
        got = hantei(x["v"], mikomi[(_norm(svc), _norm(tani))], tani, svc)
        if got != want:
            ng.append(f"⑥ 判定が想定と違う: {svc} {got}")
    #   否定試験70：正本に無い行を足すと①が落ちること
    bad = rows + [dict(svc="存在しないサービス", tani="人／月", v=1.0,
                       setsumei="台帳", shoukai="")]
    if not kensa(bad, mikomi):
        ng.append("否定試験70: 正本に無い行を足しても①が落ちない")
    if ng:
        print("自己点検 不合格:")
        for e in ng:
            print("   -", e)
        raise SystemExit(1)
    return (f"{len(rows)}行の参考値を台帳・資料２－３から算出／"
            "正本の見込量を正本の表から読んで照合／丸めの規則の検算／否定試験1件")


