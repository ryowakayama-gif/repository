def hitori(jigyo, nendo=8, n=None):
    """１人当たりの月の利用日数（利用日数÷利用者の延べ月数）。

    n を与えると直近 n か月に限る。令和８年10月24日の第３回のレビューで、
    人数の起点（直近３か月）と１人当たりの利用量の対象期間を揃えるよう
    指摘を受けたため、起点が直近３か月のサービスは同じ３か月で出す。
    """
    t = tsuki_rows(ROWS, jigyo, nendo)
    if n:
        t = t[-n:]
    t = [r for r in t if int(r["ninzu"]) > 0]
    hito = sum(int(r["ninzu"]) for r in t)
    return sum(float(r["nissu"]) for r in t) / hito if hito else None


