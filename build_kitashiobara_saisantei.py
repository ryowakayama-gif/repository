def _norm(t):
    return re.sub(r"[\s　]+", "", str(t))


def honpon_mikomi(path=HONPON):
    from docx import Document
    d = Document(path)
    out = {}
    for t in d.tables:
        hdr = [c.text.strip() for c in t.rows[0].cells]
        if hdr[:3] != ["サービス種別", "単位", "令和９年度"]:
            continue
        rows = [[_norm(c.text) for c in r.cells] for r in t.rows[1:]]
        #   第４章２（２）の精神障がいの方の内数の表を除く
        if rows and rows[0][0] == "地域移行支援":
            continue
        for r in rows:
            vals = [float(re.match(r"[0-9.]+", x).group(0)) for x in r[2:5]]
            out[(r[0], r[1])] = vals
    return out


KAZOEKATA = "数え方が違う"


def hantei(sankou, seihon, tani, svc):
    """令和９〜11年度のうち最も離れた年度で判定する。
    人数は0.5人以上、量（人日・時間）は１割以上の差を「離れている」とする。
    相談支援は正本が年度の実人数で書いているため、月平均と比べない。"""
    if svc in JITSU:
        return KAZOEKATA
    sa = max(seihon, key=lambda v: abs(v - sankou)) - sankou
    if tani == "人／月":
        hanare = abs(sa) >= 0.5
    else:
        hanare = abs(sa) >= 0.1 * max(sankou, 1)
    if not hanare:
        return "概ね整合"
    return "正本が上回る" if sa > 0 else "正本が下回る"


