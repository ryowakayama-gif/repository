def keisan():
    out = []
    hito_v = {}
    for svc, tani, kansu, setsumei, shoukai in SPEC:
        if isinstance(kansu, tuple):
            v = hito_v[svc] * kansu[1]
        else:
            v = kansu()
            hito_v[svc] = v
        out.append(dict(svc=svc, tani=tani, v=v, setsumei=setsumei,
                        shoukai=shoukai))
    return out


def hyou_ni(v):
    """計画の表に置く場合の整数。０を超え１未満は１、他は四捨五入。"""
    if v <= 0:
        return 0
    if v < 1:
        return 1
    return int(math.floor(v + 0.5))


