def run_checks(kosshi, ken, st, cnt):
    ng = []

    # 1 県計画から引いた記載が原典に実在すること
    for q in ("郡山市、須賀川市、田村市、鏡石町、天栄村、石川町、玉川村、"
              "平田村、浅川町、古殿町、三春町、小野町",
              "田村地方（田村市、三春町及び小野町）は令和3年度に整備されました",
              "計画相談を担う相談支援専門員の不足が課題",
              "郡山市、須賀川市、田村市及び石川町を除く町村においては、"
              "社会基盤が少ない状況",
              "県中地域障害者就業・生活支援センター",
              "本計画の期間は、「福島県総合計画」及び"
              "「福島県保健医療福祉復興ビジョン」との整合を図るため、"
              "目標年度を合わせ、令和4年度から令和12年度までの9年間とします"):
        if norm(q) not in norm(ken):
            ng.append(f"県計画の原典に見つからない引用: {q[:40]}")

    # 2 2章で指摘した骨子案の記載が、骨子案の現物に実在すること
    for need in ("県障がい者計画は令和9年度で満了",
                 "医療型児童発達支援",
                 "第8期福島県障がい福祉計画・第4期福島県障がい児福祉計画"):
        if norm(need) not in norm(kosshi):
            ng.append(f"骨子案の現物に見つからない指摘: {need}。"
                      "指摘を取り下げてください")

    # 3 判定が3区分のいずれかで、件数の合計が項目数に合うこと
    if sum(cnt.values()) != len(KOUMOKU):
        ng.append(f"判定の件数が合わない: {cnt}／{len(KOUMOKU)}項目")
    for ban, _k, _ko, _kon, _w, _o in KOUMOKU:
        if st[ban][0] not in (OK, SASHI, NG):
            ng.append(f"判定が不正: {ban}")

    # 4 廃止区分は骨子案に載っていれば未着手であること（逆転していないか）
    a3 = st["A-3"]
    if a3[1] and a3[0] != NG:
        ng.append("A-3は骨子案に廃止区分が載っているのに未着手になっていない")
    if not a3[1] and a3[0] != OK:
        ng.append("A-3は骨子案に廃止区分がないのに反映済みになっていない")

    # 5 未着手の項目に理由が書かれていること
    for ban, _k, _ko, _kon, _w, _o in KOUMOKU:
        if st[ban][0] == NG and _naze(ban) == "―":
            ng.append(f"未着手なのに理由がない: {ban}")

    # 6 他団体名が成果品に現れないこと（本ブランチの規律）
    out_text = doc_text(OUT / f"小野町_障がい計画_指針との不整合の点検と"
                              f"県計画の反映_{ASOF}.docx")
    found = set(re.findall(r"[一-龥ァ-ヶー]{1,5}[市町村県]", out_text))
    ok_words = {
        "小野町", "福島県", "町村", "道府県", "本町", "当町", "同町", "都市",
        # 「第7期県計画」「第5次県計画」の語末
        "期県", "次県",
        # 県計画の県中圏域の構成市町村と広域の枠。県計画の原典から引いている
        "郡山市", "須賀川市", "田村市", "鏡石町", "天栄村", "石川町",
        "玉川村", "平田村", "浅川町", "古殿町", "三春町", "田村",
    }
    ng += [f"他団体名が成果品に現れている: {t}" for t in sorted(found)
           if not any(t.endswith(x) for x in ok_words)]

    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("  -", x)
        return False
    print(f"自己点検: 合格　県計画からの引用6件を原典と照合／"
          f"骨子案への指摘3件を現物で確認／"
          f"判定{len(KOUMOKU)}件が3区分に収まる／"
          f"未着手{cnt[NG]}件に理由あり／"
          f"成果品に現れる自治体名は小野町・福島県と"
          f"県中圏域の構成市町村のみ（{len(found)}語を照合）")
    return True


