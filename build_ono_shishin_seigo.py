def doc_text(path):
    if not path.exists():
        raise SystemExit(f"見つかりません: {path}")
    d = docx.Document(str(path))
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for row in t.rows:
            out += [c.text for c in row.cells]
    return "\n".join(out)


def ken_text():
    """県計画2点の本文テキストを1つにまとめる（引用の照合に用いる）。"""
    parts = []
    for p in (KEN_FUKUSHI, KEN_SHOGAISHA):
        if not p.exists():
            raise SystemExit(f"県計画が見つかりません: {p}")
        parts.append(p.read_text(encoding="utf-8"))
    return "\n".join(parts)


def norm(s):
    z = "０１２３４５６７８９"
    for i, c in enumerate(z):
        s = s.replace(c, str(i))
    s = s.replace("：", ":").replace("，", ",")
    return re.sub(r"[\s　,]", "", s)


def detect(kosshi, hoka):
    """項目ごとの反映状況を、骨子案と他の成果品の現物から判定する。"""
    out = {}
    for ban, _ku, _koto, _kon, kws, _oki in KOUMOKU:
        in_kosshi = sum(kosshi.count(k) for k in kws)
        in_hoka = sum(h.count(k) for k in kws for h in hoka)
        if ban == "A-3":
            # 廃止区分は「載っていないこと」が正しい。骨子案に載っていれば未対応。
            out[ban] = (NG if in_kosshi else OK, in_kosshi, in_hoka)
            continue
        if in_kosshi:
            out[ban] = (OK, in_kosshi, in_hoka)
        elif in_hoka:
            out[ban] = (SASHI, in_kosshi, in_hoka)
        else:
            out[ban] = (NG, in_kosshi, in_hoka)
    return out


