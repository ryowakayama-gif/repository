def verify(counts, kosshi_heads, suan_heads):
    """レビューの前提が崩れていないことを確かめる。"""
    judges = {r[5] for r in BEPPYO2} | {r[4] for r in SEIKA} | {r[4] for r in SANSHA}
    unknown = judges - set(JUDGE_FILL)
    assert not unknown, f"未定義の判定: {unknown}"

    duties = {r[2] for r in BEPPYO2} | {r[3] for r in GAPS}
    unknown = duties - set(DUTY_FILL) - {"―"}
    assert not unknown, f"未定義の位置づけ: {unknown}"

    ids = [g[0] for g in GAPS]
    assert len(ids) == len(set(ids)), "不足項目の番号が重複しています"
    ids = [k[0] for k in KAKUNIN]
    assert len(ids) == len(set(ids)), "確認事項の番号が重複しています"

    # 骨子案に無かったことは動かない事実として確かめる
    for kw in ("医療的ケア者", "経営基盤", "公共職業安定所", "計画的な基盤整備", "意思決定支援",
               "障害者就業・生活支援センター", "障害者職業センター",
               "医療的ケア児等支援センター", "医療的ケア児等支援地域協議会"):
        assert counts[kw][0] == 0, f"{kw} は骨子案では0のはずです: {counts[kw]}"

    # 令和8年9月24日に反映した語が、計画素案に現れていること
    for kw in ("医療的ケア者", "経営基盤", "公共職業安定所",
               "障害者就業・生活支援センター", "障害者職業センター", "意思決定支援",
               "医療的ケア児等支援センター", "医療的ケア児等支援地域協議会"):
        assert counts[kw][1] > 0, f"{kw} が計画素案に反映されていません: {counts[kw]}"

    # 未対応のものは計画素案でも0のままであること
    for kw in ("計画的な基盤整備", "難病", "放課後児童", "地域福祉計画",
               "賃貸住宅供給促進計画"):
        assert counts[kw][1] == 0, f"{kw} は未対応のはずです: {counts[kw]}"

    # 骨子案より計画素案のほうが見出しが多いこと
    assert len(suan_heads) > len(kosshi_heads), "計画素案の見出しが骨子案より少なくなっています"

    # 別表第二の項が改正後の8項（枝番を含め17行）であること
    kou = {r[0][0] for r in BEPPYO2}
    assert kou == set("一二三四五六七八"), f"別表第二の項が揃っていません: {kou}"


