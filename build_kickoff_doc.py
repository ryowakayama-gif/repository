def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear")
    sh.set(qn("w:fill"), hexcolor)
    tcPr.append(sh)


def cell_text(cell, text, size=9, bold=False, color=None):
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(1)
    p.paragraph_format.space_before = Pt(1)
    for i, line in enumerate(str(text).split("\n")):
        if i:
            p = cell.add_paragraph()
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.space_before = Pt(0)
        r = p.add_run(line)
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.name = FONT
        if color is not None:
            r.font.color.rgb = color
        r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)


def TBL(head, rows, widths=None, size=9):
    t = doc.add_table(rows=0, cols=len(head))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    hr = t.add_row().cells
    for i, h in enumerate(head):
        cell_text(hr[i], h, size=size, bold=True, color=WHITE)
        shade(hr[i], HEADFILL)
    for row in rows:
        c = t.add_row().cells
        for i, v in enumerate(row):
            cell_text(c[i], v, size=size)
    if widths:
        for r in t.rows:
            for i, w in enumerate(widths):
                r.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return t


def BOX(title, lines):
    """青枠の注記。アジェンダとまとめの2箇所のみで用いる。"""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    c = t.rows[0].cells[0]
    c.text = ""
    p = c.paragraphs[0]
    p.paragraph_format.space_after = Pt(2)
    r = p.add_run(title)
    r.font.size = Pt(10.5)
    r.font.bold = True
    r.font.color.rgb = NAVY
    r.font.name = FONT
    r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    for line in lines:
        p = c.add_paragraph()
        p.paragraph_format.space_after = Pt(1)
        p.paragraph_format.space_before = Pt(0)
        r = p.add_run("・" + line)
        r.font.size = Pt(9.5)
        r.font.name = FONT
        r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    shade(c, BLUEBOX)
    c.width = Cm(17.2)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return t


def BUL(text, size=10.5):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.left_indent = Cm(0.5)
    r = p.add_run("・" + text)
    r.font.size = Pt(size)
    r.font.name = FONT
    r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    return p


