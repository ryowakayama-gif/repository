def kaikyu(key, hiritsu):
    """対計画比の分布のうち、値が属する階級と最頻の階級を返す。"""
    bins = M.CHART[key]["ブロック"]["対計画比の分布"]
    ken = bins["行"][0][2]
    zoku = ("―", None)
    for h, v in zip(bins["見出し"], ken):
        num_s = h.replace("未満", "").replace("以下", "")
        try:
            edge = float(num_s)
        except ValueError:
            continue
        if hiritsu < edge or h.endswith("以下"):
            zoku = (h, v)
            break
    ari = [(h, v) for h, v in zip(bins["見出し"], ken) if v is not None]
    sai = max(ari, key=lambda x: x[1]) if ari else ("―", None)
    return zoku, sai


