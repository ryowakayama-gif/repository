def measure():
    """02シートに書く実測値を作る。"""
    import itertools
    from collections import defaultdict
    adult, child, byd, pool = load_att()
    src = load_src()
    m = {}

    # 1 手元の集計との突合
    att = {(str(v[0]).strip(), str(v[2]).strip()): v[3] for v in adult}
    common = set(att) & set(src)
    m["kensu_match"] = (f"共通 {len(common)}件",
                        f"件数相違 {sum(1 for k in common if att[k] != src[k])}件")

    # 2 割合＝件数÷n
    bad = sum(1 for v in adult
              if None not in (v[3], v[4], v[5]) and v[5]
              and abs(v[4] - v[3] / v[5]) > 0.0006)
    m["pct_calc"] = (f"{len(adult)}行", f"不一致 {bad}件")

    # 3 単一回答の合計＝n
    tot = defaultdict(lambda: [0, None, None])
    for v in adult:
        if v[3] is None:
            continue
        q = str(v[0]).strip()
        tot[q][0] += v[3]
        tot[q][1] = v[5]
        tot[q][2] = v[6]
    ng = sum(1 for q, (s, n, f) in tot.items()
             if f and "単一回答" == str(f) and n and s != n)
    m["single_sum"] = (f"単一回答の設問 "
                       f"{sum(1 for q, (s, n, f) in tot.items() if f and '単一回答' == str(f))}問",
                       f"不一致 {ng}件")

    # 4 n の一貫性
    ns = sorted({v[5] for v in adult if v[5] is not None})
    m["n_uniform"] = (f"設問 {len(tot)}問", f"n は {ns}（有効回答{VALID_ADULT}件）")

    # 5 本文・表の割合の出所
    body = body_of(load_body_xml())
    texts = [ptext(p).strip() for p in body.iter(f"{W}p")]
    texts += [ptext(tc).strip() for tc in body.iter(f"{W}tc")]
    byq = defaultdict(list)
    for v in adult + child:
        if v[4] is not None:
            byq[str(v[0]).strip()].append(round(v[4] * 100, 1))
    sums = set()
    for vals in byq.values():
        for k in (2, 3, 4):
            for c in itertools.combinations(vals, k):
                s = round(sum(c), 1)
                sums |= {s, round(s - 0.1, 1), round(s + 0.1, 1)}
    allow = pool | sums
    n_pct = miss = 0
    missing = []
    for t in texts:
        for mm in re.finditer(r"(\d{1,3}\.\d)％", t):
            n_pct += 1
            if float(mm.group(1)) not in allow:
                miss += 1
                missing.append(float(mm.group(1)))
    m["pct_source"] = (f"{n_pct}件",
                       f"ブック内の値で説明できないもの {miss}件"
                       + (f"（{sorted(set(missing))}％。本文で分母を明示して算出）"
                          if miss else ""))

    # 6 クロス集計の割合
    ncross = cbad = 0
    for t in body.iter(f"{W}tbl"):
        rows = t.findall(f"{W}tr")
        hdr = [ptext(c).strip().replace("\n", " ") for c in rows[0].findall(f"{W}tc")]
        if not (len(hdr) > 2 and hdr[0] == "区分"
                and any("n=" in h or "n＝" in h for h in hdr)):
            continue
        ncross += 1
        nn = [int(mm.group(1)) for h in hdr[1:]
              for mm in [re.search(r"n[=＝](\d+)", h)] if mm]
        for tr in rows[1:]:
            cs = [ptext(c).strip() for c in tr.findall(f"{W}tc")]
            for j, c in enumerate(cs[1:]):
                mm = re.search(r"([\d.]+)%\((\d+)\)", c.replace("％", "%"))
                if mm and j < len(nn) and nn[j]:
                    if abs(float(mm.group(1)) - int(mm.group(2)) / nn[j] * 100) > 0.06:
                        cbad += 1
    m["cross_pct"] = (f"クロス表 {ncross}件", f"割合の不一致 {cbad}件")

    # 7 障がい児の単一回答
    ctot = defaultdict(lambda: [0, None])
    for v in child:
        if v[3] is None:
            continue
        ctot[str(v[0]).strip()][0] += v[3]
        ctot[str(v[0]).strip()][1] = v[6]
    cng = sum(1 for q, (s, f) in ctot.items()
              if f and "単一回答" == str(f) and s != VALID_CHILD)
    m["child_sum"] = (f"設問 {len(ctot)}問", f"不一致 {cng}件"
                      + "（問25は「単一回答（項目別）」として別扱い）")

    # 8 表5の差
    diff_ng, diff_blank = [], []
    for t in body.iter(f"{W}tbl"):
        rows = t.findall(f"{W}tr")
        hdr = [ptext(c).strip().replace("\n", " ") for c in rows[0].findall(f"{W}tc")]
        if not (hdr and hdr[-1].startswith("差")):
            continue
        for tr in rows[1:]:
            cs = [ptext(c).strip() for c in tr.findall(f"{W}tc")]
            if len(cs) < 5:
                continue

            def pc(s):
                mm = re.search(r"([\d.]+)%\((\d+)\)", s.replace("％", "%"))
                return (float(mm.group(1)), int(mm.group(2))) if mm else (None, None)

            (p1, k1), (p3, k3) = pc(cs[1]), pc(cs[3])
            if p1 is None or p3 is None:
                continue
            # 差の欄に数値がないもの。件数差が0なら「－」で正しく、
            # 0でないのに空欄のもの（「特にない」「無回答」）はR-17で別に挙げる
            if not re.search(r"\d", cs[4]):
                if k3 != k1:
                    diff_blank.append(cs[0])
                continue
            if round(p3 - p1, 1) != round((k3 - k1) / VALID_ADULT * 100, 1):
                diff_ng.append(cs[0])
    m["diff_col"] = ("表5の18サービス",
                     f"丸めた割合の差と件数差からの値がずれる行 {len(diff_ng)}件"
                     + (f"（{'・'.join(diff_ng)}）" if diff_ng else "")
                     + f"／差の欄が空の行 {len(diff_blank)}件"
                     + (f"（{'・'.join(diff_blank)}）" if diff_blank else ""))
    return m, len(adult), len(child), len(byd)


