def run_checks(m):
    ng = []

    # 1 復元した本文が読めること（レビューの前提）
    xml = load_body_xml()
    if b"<w:body" not in xml:
        ng.append("復元した本文に w:body がない")
    if len(xml) < 1_000_000:
        ng.append(f"復元した本文が小さすぎる: {len(xml):,}バイト")

    # 2 数値整合の実測が「不一致なし」であること（崩れたら指摘を足す）
    for key, want in (("kensu_match", "件数相違 0件"),
                      ("pct_calc", "不一致 0件"),
                      ("single_sum", "不一致 0件"),
                      ("cross_pct", "割合の不一致 0件")):
        if want not in m[key][1]:
            ng.append(f"02シート {key} が「{want}」でない: {m[key][1]}")

    # 3 本文の割合で説明できないものが1件（61.9％）であること
    if "できないもの 1件" not in m["pct_source"][1]:
        ng.append(f"本文の割合で説明できないものが1件でない: {m['pct_source'][1]}")

    # 4 表5の差のずれが3行であること
    if "ずれる行 3件" not in m["diff_col"][1]:
        ng.append(f"表5の差のずれが3行でない: {m['diff_col'][1]}")

    # 5 成果目標8区分がすべて並び、未対応が2件であること
    kubun = [x[0] for x in SEIKA_TAIOU]
    if kubun != ["一", "二", "三", "四", "五", "六", "七", "八"]:
        ng.append(f"成果目標の区分が一〜八で並んでいない: {kubun}")
    mitaiou = [x[0] for x in SEIKA_TAIOU if x[4] != "対応"]
    if mitaiou != ["七", "八"]:
        ng.append(f"未対応の区分が七・八でない: {mitaiou}")

    # 6 引継ぎが10件で、未解消が引継ぎ7であること
    if len(HIKITSUGI) != 10:
        ng.append(f"引継ぎが10件でない: {len(HIKITSUGI)}")
    mikaishou = [x[0] for x in HIKITSUGI if x[3] == "未解消"]
    if mikaishou != [7]:
        ng.append(f"未解消の引継ぎが7でない: {mikaishou}")

    # 7 指摘一覧に観点が7つすべて現れること
    kanten = {x[2] for x in SHITEKI}
    want = {"国の指針", "前回計画課題", "経年比較", "今期施策",
            "見込量算定", "数値整合", "クロス分析", "表記・公表"}
    miss = sorted(want - kanten)
    if miss:
        ng.append(f"指摘一覧に現れない観点がある: {miss}")

    # 8 当方の修正（Ｓ-1）が計画素案に反映されていること
    import docx
    d = docx.Document(f"{OUT_DIR}/北塩原村_計画素案.docx")
    txt = "\n".join([p.text for p in d.paragraphs]
                    + [c.text for t in d.tables for row in t.rows for c in row.cells])
    for need in ("65.8％", "68.4％", "23.7％", "172件", "22.1％", "57.9％"):
        if need not in txt:
            ng.append(f"計画素案にＳ-1の修正が入っていない: {need} が見つからない")

    # 9 当方の修正（Ｓ-2）がMECEチェックに反映されていること
    import runpy
    mod = runpy.run_path(os.path.join(
        os.path.dirname(os.path.abspath(__file__)),
        "build_kitashiobara_mece.py"), run_name="_review_check")
    cross, both_n, total_n, inc, dec = mod["anq_cross"]()
    if total_n != VALID_ADULT:
        ng.append(f"MECEチェックの回答者数が{total_n}で有効回答{VALID_ADULT}件と違う")
    shisetsu = [c for c in cross if c[1] == "施設入所支援"]
    if not shisetsu or shisetsu[0][2] != 5 or shisetsu[0][3] != 9:
        ng.append(f"MECEチェックの施設入所支援が現在5・今後9でない: "
                  f"{shisetsu[0][2:4] if shisetsu else 'なし'}")

    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("  -", x)
        return False
    print(f"自己点検: 合格　"
          f"復元本文 {len(xml):,}バイト／数値整合 {len(SEIGO_DEF)}項目／"
          f"経年比較 {len(KEINEN)}項目／成果目標 {len(SEIKA_TAIOU)}区分（未対応2）／"
          f"新規事項 {len(SHINKI)}／引継ぎ {len(HIKITSUGI)}（未解消1）／"
          f"施策 {len(SESAKU)}／見込量 {len(MIKOMI_SETSUZOKU)}／"
          f"クロス {len(CROSS_CHECK)}／指摘 {len(SHITEKI)}／当方の修正 {len(JISHA)}")
    return True


