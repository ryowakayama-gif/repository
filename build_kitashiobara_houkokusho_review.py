def load_body_xml():
    """復元済みの本文（word/document.xml）を読む。

    受領版の docx は ZIP の末尾を欠いているため、受領時に
    ローカルファイルヘッダを辿って 108 エントリを取り出し、
    本文だけを source/アンケート結果/分析報告書_本文_復元.xml として保存した。
    再送を受けたときは salvage_docx() で取り出し直せる。
    """
    if not os.path.exists(SRC_XML):
        raise SystemExit(
            "\n".join([
                f"復元した本文が見つかりません: {SRC_XML}",
                "受領版の docx（ZIP末尾欠落）から取り出したものです。",
                f"  大きさ {UKETORI_DOCX['大きさ']:,}バイト",
                f"  SHA-256 {UKETORI_DOCX['SHA-256']}",
                "再送を受けた場合は salvage_docx(受領版のパス) で",
                "word/document.xml を取り出し、上記の場所に保存してください。",
            ]))
    return open(SRC_XML, "rb").read()


def salvage_docx(path):
    """ZIP構造の末尾を欠いた docx から、ローカルヘッダを辿って本文を取り出す。

    受領時にこの手順で 108 エントリを復元した。再送を受けたときに使う。
    """
    d = open(path, "rb").read()
    entries, pos, truncated = {}, 0, None
    while True:
        i = d.find(b"PK\x03\x04", pos)
        if i < 0 or len(d) - i < 30:
            break
        (_v, _f, method, _t, _dt, _crc, csz, usz,
         nlen, elen) = struct.unpack("<HHHHHIIIHH", d[i + 4:i + 30])
        name_end = i + 30 + nlen
        if name_end > len(d):
            break
        name = d[i + 30:name_end].decode("utf-8", errors="replace")
        body = name_end + elen
        end = body + csz
        if end > len(d):
            truncated = name
            break
        raw = d[body:end]
        try:
            out = zlib.decompress(raw, -15) if method == 8 else raw
            if usz and len(out) != usz:
                raise ValueError("長さ不一致")
            entries[name] = out
        except Exception:
            pass
        pos = end
    has_eocd = d.rfind(b"PK\x05\x06") >= 0
    return entries, truncated, has_eocd, len(d)


def body_of(xml_bytes):
    root = etree.fromstring(xml_bytes)
    return root.find(f"{W}body")


def ptext(el):
    """ルビの読み（w:rt配下）を除いたテキスト。"""
    return "".join(
        t.text or "" for t in el.iter(f"{W}t")
        if not any(a.tag == f"{W}rt" for a in t.iterancestors()))


