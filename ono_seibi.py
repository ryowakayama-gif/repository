"""施設整備ケース（仕様書4(2)「新たに介護施設を整備する場合」）。素案・見込量推計結果報告書で共通に使う。

1人当たり給付費（月）は年報 様式2 の令和7年度（介護給付）の給付費÷件数。自然体推計と同じく令和7年度の単価で置く。
入所する方は在宅で介護サービスを利用していた方とし、在宅の1人当たり給付費
（居宅サービス計÷居宅介護支援の件数）を差し引く。町外の施設からの移行、特定入所者介護サービス費の増は見込まない。
"""

import build_ono_tanka as T

Y7 = "令和7年度"
ZAITAKU = ["訪問介護", "訪問入浴介護", "訪問看護", "訪問リハビリテーション", "居宅療養管理指導", "通所介護",
           "通所リハビリテーション", "短期入所生活介護", "短期入所療養介護（介護老人保健施設）",
           "短期入所療養介護（病院等）", "短期入所療養介護（介護医療院）", "福祉用具貸与", "特定福祉用具販売",
           "住宅改修", "定期巡回・随時対応型訪問介護看護", "夜間対応型訪問介護", "地域密着型通所介護",
           "認知症対応型通所介護", "小規模多機能型居宅介護", "看護小規模多機能型居宅介護", "居宅介護支援・介護予防支援"]
# (名称, サービス, 定員, 開設, 月数)。令和10年4月開設・2年間（24か月）
CASES = [("地域密着型介護老人福祉施設を1ユニット（定員10人）整備", "地域密着型介護老人福祉施設入所者生活介護", 10, "令和10年4月", 24),
         ("認知症対応型共同生活介護を1ユニット（定員9人）整備", "認知症対応型共同生活介護", 9, "令和10年4月", 24)]

_ACT = T.extract()[0]
ZAITAKU_TANKA = (sum(_ACT[Y7]["給付費"].get(s, (0, 0))[1] for s in ZAITAKU)
                 / _ACT[Y7]["件数"]["居宅介護支援・介護予防支援"][1])


def cases(std3, chiiki3, sogo3, pop3):
    """[(名称, サービス, 定員, 開設, 月数, 1人当たり給付費, 標準給付費の増（千円）, 保険料の算定結果)]"""
    out = []
    for nm, svc, tei, kai, mon in CASES:
        tk = T.unit_price(_ACT, svc, "介護", Y7)
        zou = tei * mon * (tk - ZAITAKU_TANKA) / 1000
        out.append((nm, svc, tei, kai, mon, tk, zou, T.premium(std3 + zou, chiiki3, sogo3, pop3)))
    return out
