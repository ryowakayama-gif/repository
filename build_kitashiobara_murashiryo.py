def load_docx(path):
    doc = docx.Document(path)
    parts = []
    for ch in doc.element.body.iterchildren():
        tag = ch.tag.split("}")[-1]
        if tag == "p":
            parts.append(Paragraph(ch, doc).text)
        elif tag == "tbl":
            for row in Table(ch, doc).rows:
                seen = set()
                for c in row.cells:
                    if id(c._tc) in seen:
                        continue
                    seen.add(id(c._tc))
                    parts.append(c.text)
    return "\n".join(parts)


