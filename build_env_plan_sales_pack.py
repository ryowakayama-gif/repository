AL_WRAP = Alignment(vertical="top", wrap_text=True)
AL_CTR = Alignment(vertical="center", horizontal="center", wrap_text=True)


def write_sheet(wb, title, subtitle, headers, widths, rows, notes=None, first=False):
    """1シート分を共通書式で書き出す。"""
    ws = wb.active if first else wb.create_sheet()
    ws.title = title

    ncol = len(headers)
    # タイトル行
    ws.cell(row=1, column=1, value=subtitle).font = F_TITLE
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncol)
    for c in range(1, ncol + 1):
        ws.cell(row=1, column=c).fill = PatternFill("solid", fgColor=C_TITLE)
    ws.row_dimensions[1].height = 26

    # ヘッダ行
    for c, h in enumerate(headers, start=1):
        cell = ws.cell(row=2, column=c, value=h)
        cell.font = F_HEAD
        cell.fill = PatternFill("solid", fgColor=C_SUBHEAD)
        cell.alignment = AL_CTR
        cell.border = BORDER
    ws.row_dimensions[2].height = 32

    # データ行
    r = 3
    for row in rows:
        # 見出し帯（1要素だけのリストは区切り帯として扱う）
        if len(row) == 1:
            cell = ws.cell(row=r, column=1, value=row[0])
            cell.font = F_BOLD
            cell.fill = PatternFill("solid", fgColor=C_BAND)
            ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=ncol)
            for c in range(1, ncol + 1):
                ws.cell(row=r, column=c).fill = PatternFill("solid", fgColor=C_BAND)
                ws.cell(row=r, column=c).border = BORDER
            r += 1
            continue

        fill = PatternFill("solid", fgColor=C_ALT) if (r % 2 == 1) else None
        for c, v in enumerate(row, start=1):
            cell = ws.cell(row=r, column=c, value=v)
            cell.font = F_BODY
            cell.alignment = AL_WRAP
            cell.border = BORDER
            if fill:
                cell.fill = fill
        r += 1

    # 注記
    if notes:
        r += 1
        for n in notes:
            cell = ws.cell(row=r, column=1, value=n)
            cell.font = F_NOTE
            cell.alignment = AL_WRAP
            ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=ncol)
            for c in range(1, ncol + 1):
                ws.cell(row=r, column=c).fill = PatternFill("solid", fgColor=C_NOTE)
            r += 1

    for c, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(c)].width = w

    ws.freeze_panes = "A3"
    if len(rows) > 1:
        ws.auto_filter.ref = f"A2:{get_column_letter(ncol)}{max(3, r - 1)}"
    ws.sheet_view.zoomScale = 90
    return ws


