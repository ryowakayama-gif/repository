    return "%d件（重大%d・中%d・軽微%d）" % (
        _cnt(cat=cat),
        len([f for f in FIND if f[1] == cat and f[2] == "重大"]),
        len([f for f in FIND if f[1] == cat and f[2] == "中"]),
        len([f for f in FIND if f[1] == cat and f[2] == "軽微"]))


