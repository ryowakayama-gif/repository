def P(text="", size=10.5, bold=False, align=None, space_after=4, color=None):
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(0)
    if align is not None:
        p.alignment = align
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.bold = bold
    r.font.name = FONT
    if color is not None:
        r.font.color.rgb = color
    r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    return p


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear")
    sh.set(qn("w:fill"), hexcolor)
    tcPr.append(sh)


def set_text(cell, text, size=9.5, bold=False, color=None):
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(1)
    p.paragraph_format.space_before = Pt(1)
    for i, line in enumerate(str(text).split("\n")):
        if i:
            p = cell.add_paragraph()
            p.paragraph_format.space_after = Pt(1)
            p.paragraph_format.space_before = Pt(0)
        r = p.add_run(line)
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.name = FONT
        if color is not None:
            r.font.color.rgb = color
        r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)


def item(no, cat, title, content, choices, impact, src, blank_lines=3):
    """1項目1枠のヒアリング欄。"""
    t = doc.add_table(rows=0, cols=2)
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER

    row = t.add_row().cells
    set_text(row[0], "%s\n%s" % (no, cat), size=10, bold=True,
             color=RGBColor(0xFF, 0xFF, 0xFF))
    shade(row[0], "1F3864")
    set_text(row[1], title, size=11, bold=True)
    shade(row[1], "DEEBF7")

    row = t.add_row().cells
    set_text(row[0], "確認・決定\nしていただく内容", size=9, bold=True)
    shade(row[0], "F2F2F2")
    set_text(row[1], content)

    if choices:
        row = t.add_row().cells
        set_text(row[0], "選択肢", size=9, bold=True)
        shade(row[0], "F2F2F2")
        set_text(row[1], "\n".join("□　" + c for c in choices))

    row = t.add_row().cells
    set_text(row[0], "決定内容\n（ご記入欄）", size=9, bold=True)
    shade(row[0], "FFF2CC")
    set_text(row[1], "\n" * blank_lines)

    row = t.add_row().cells
    set_text(row[0], "決まらない場合", size=9, bold=True)
    shade(row[0], "F2F2F2")
    set_text(row[1], impact, size=9)

    row = t.add_row().cells
    set_text(row[0], "出所", size=9, bold=True)
    shade(row[0], "F2F2F2")
    set_text(row[1], src, size=8.5)

    for r in t.rows:
        r.cells[0].width = Cm(3.4)
        r.cells[1].width = Cm(13.8)
    doc.add_paragraph().paragraph_format.space_after = Pt(8)
    return t


