def LEAD(text, size=10):
    """表・図の前に置く小見出し（【 】付き）。"""
    return P(text, size=size, bold=True, space_after=3)


def UNIT(text, size=8.5):
    """表の直前に置く「単位：〜」の右寄せ1行（前回計画の体裁）。"""
    return P(text, size=size, align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=1)


def SRC(text, size=8.5):
    """表の直後に置く「資料：〜」の右寄せ1行（前回計画の体裁）。"""
    return P("資料：" + text, size=size, align=WD_ALIGN_PARAGRAPH.RIGHT, space_after=8)


def TBL(head, rows, widths=None, size=8.5, headsize=None):
    t = doc.add_table(rows=1, cols=len(head))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, hh in enumerate(head):
        c = t.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(hh)
        r.bold = True
        r.font.size = Pt(headsize or size)
        r.font.name = FONT
        r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run("" if v is None else str(v))
            r.font.size = Pt(size)
            r.font.name = FONT
            r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    if widths:
        for i, w in enumerate(widths):
            for row in t.rows:
                row.cells[i].width = Cm(w)
    return t


def NOTE(text, size=8.5):
    return P(text, size=size, space_after=8)


