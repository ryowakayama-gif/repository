def set_font(run, name=MINCHO, size=10.5, bold=False, color=None):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)


def shade(cell, hexcolor):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), hexcolor)
    tcPr.append(shd)


def para(doc, text="", size=10.5, bold=False, name=MINCHO, align=None,
         space_before=0, space_after=4, indent=None, color=None):
    p = doc.add_paragraph()
    if align is not None:
        p.alignment = align
    pf = p.paragraph_format
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    pf.line_spacing = 1.15
    if indent is not None:
        pf.left_indent = Cm(indent)
    if text:
        set_font(p.add_run(text), name=name, size=size, bold=bold, color=color)
    return p


def heading(doc, text, level):
    """level 1=章, 2=節, 3=項"""
    spec = {1: (16, 18, 10, GOTHIC, "1F3864"),
            2: (13, 14, 6, GOTHIC, "1F3864"),
            3: (11.5, 10, 4, GOTHIC, "2E75B6")}[level]
    size, before, after, name, color = spec
    h = doc.add_heading("", level=level)
    h.paragraph_format.space_before = Pt(before)
    h.paragraph_format.space_after = Pt(after)
    set_font(h.add_run(text), name=name, size=size, bold=True, color=color)
    if level == 1:
        pPr = h._p.get_or_add_pPr()
        pbdr = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "12")
        bottom.set(qn("w:color"), "1F3864")
        bottom.set(qn("w:space"), "4")
        pbdr.append(bottom)
        pPr.append(pbdr)
    return h


def bullets(doc, items, indent=0.6):
    for it in items:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.left_indent = Cm(indent + 0.5)
        pf.first_line_indent = Cm(-0.5)
        pf.space_after = Pt(2)
        pf.line_spacing = 1.15
        set_font(p.add_run("・" + it), size=10.5)


def callout(doc, text, kind="pending"):
    """差し替え・記載待ちの注記ボックス"""
    fill, col = {"pending": ("FCE4E4", "C00000"),
                 "tbd": ("FFF2E0", "C55A11"),
                 "calc": ("E8F0FA", "1F4E79")}[kind]
    t = doc.add_table(rows=1, cols=1)
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = t.cell(0, 0)
    shade(cell, fill)
    cell.width = Cm(16.4)
    p = cell.paragraphs[0]
    p.paragraph_format.space_before = Pt(3)
    p.paragraph_format.space_after = Pt(3)
    set_font(p.add_run(text), name=GOTHIC, size=9.5, bold=True, color=col)
    para(doc, "", space_after=4)
    return t


def table(doc, headers, rows, widths=None, note=None, align_right_from=1,
          highlight_rows=(), first_col_width=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    if widths is None:
        w0 = first_col_width or 4.4
        rest = (16.4 - w0) / max(1, len(headers) - 1)
        widths = [w0] + [rest] * (len(headers) - 1)
    hdr = t.rows[0]
    for i, h in enumerate(headers):
        cell = hdr.cells[i]
        cell.width = Cm(widths[i])
        shade(cell, "1F3864")
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_before = Pt(1)
        p.paragraph_format.space_after = Pt(1)
        set_font(p.add_run(str(h)), name=GOTHIC, size=9, bold=True, color="FFFFFF")
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].width = Cm(widths[i])
            if ri in highlight_rows:
                shade(cells[i], "DDEBF7")
            p = cells[i].paragraphs[0]
            p.paragraph_format.space_before = Pt(1)
            p.paragraph_format.space_after = Pt(1)
            if i >= align_right_from:
                p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            txt = "－" if v is None else (f"{v:,}" if isinstance(v, int) else
                                         (f"{v:,.1f}" if isinstance(v, float) else str(v)))
            set_font(p.add_run(txt), name=GOTHIC, size=9,
                     bold=(ri in highlight_rows))
    if note:
        para(doc, note, size=8.5, name=GOTHIC, color="595959", space_after=8)
    else:
        para(doc, "", space_after=6)
    return t


def add_field(paragraph, instr, placeholder="", name=MINCHO, size=10.5):
    """Word のフィールド（PAGE / TOC 等）を begin-instr-separate-result-end の形で挿入"""
    def run_with(*children):
        r = paragraph.add_run()
        set_font(r, name=name, size=size)
        for c in children:
            r._r.append(c)
        return r

    begin = OxmlElement("w:fldChar")
    begin.set(qn("w:fldCharType"), "begin")
    instr_el = OxmlElement("w:instrText")
    instr_el.set(qn("xml:space"), "preserve")
    instr_el.text = instr
    sep = OxmlElement("w:fldChar")
    sep.set(qn("w:fldCharType"), "separate")
    end = OxmlElement("w:fldChar")
    end.set(qn("w:fldCharType"), "end")

    run_with(begin)
    run_with(instr_el)
    run_with(sep)
    if placeholder:
        r = paragraph.add_run(placeholder)
        set_font(r, name=name, size=size)
    run_with(end)


def toc(doc):
    """目次（Word で開いた際に F9 で更新）"""
    heading(doc, "目　次", 1)
    p = doc.add_paragraph()
    p.paragraph_format.space_after = Pt(6)
    add_field(p, ' TOC \\o "1-2" \\h \\z \\u ',
              placeholder="※Word で開き、この行を選択して F9 を押すと目次が生成されます。",
              name=GOTHIC, size=9.5)
    page_break(doc)


def page_break(doc):
    p = doc.add_paragraph()
    p.add_run().add_break(WD_BREAK.PAGE)


