def count_markers(path):
    """生成した docx 内のマーカー数を数える"""
    import zipfile
    xml = zipfile.ZipFile(path).read("word/document.xml").decode("utf-8")
    text = re.sub(r"<[^>]+>", "", xml)
    return {"pending": text.count(PENDING), "tbd": text.count(TBD), "calc": text.count(CALC)}


