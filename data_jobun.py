def jobun_of(houmei, jo=None):
    """法令名（及び条）で絞って返す。"""
    return [x for x in JOBUN
            if x[0] == houmei and (jo is None or x[1] == jo)]


def check_of(no):
    """確認事項の番号を含む条文を返す。"""
    return [x for x in JOBUN if no in (x[6] or "")]


def jo_list(houmei):
    """法令ごとの条の一覧（現れた順）。"""
    out = []
    for x in JOBUN:
        if x[0] == houmei and x[1] not in out:
            out.append(x[1])
    return out


def counts():
    """法令ごとの件数。"""
    d = {}
    for x in JOBUN:
        d[x[0]] = d.get(x[0], 0) + 1
    return d


