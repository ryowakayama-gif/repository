def draft_text():
    """計画素案（docx）の本文と表のテキスト。固定値で書かない。"""
    if not os.path.exists(RP.DRAFT):
        return ""
    from docx import Document
    d = Document(RP.DRAFT)
    out = [q.text for q in d.paragraphs]
    for t in d.tables:
        for row in t.rows:
            out.extend(c.text for c in row.cells)
    return "\n".join(out)


