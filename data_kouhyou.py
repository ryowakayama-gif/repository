def rows():
    """列名を鍵とする辞書の並びを返す。"""
    return [dict(zip(COLS, r)) for r in JIGYOSHO]


def of_service(name):
    """サービス名（公表システムの区分名）で絞る。"""
    return [r for r in rows() if r["サービス"] == name]


def of_machi(machi):
    return [r for r in rows() if r["町"] == machi]


def teiin(name):
    """サービスごとの（事業所数, 定員の合計, 利用者数の合計）。"""
    xs = [r for r in of_service(name) if r["定員"]]
    return (len(xs), sum(r["定員"] for r in xs),
            sum(r["利用者数"] or 0 for r in xs))


def unit_sum(name="グループホーム"):
    """共同生活住居（ユニット）数の合計。"""
    return sum(r["ユニット"] or 0 for r in of_service(name))


def jigyosho_no():
    """事業所番号の集合（同一番号で複数のサービスを行うものを1つに数える）。"""
    return sorted({r["番号"] for r in rows()})


def kyoryoku_nashi():
    """施設・居住系のうち協力医療機関の記載がないもの。"""
    return [r for r in rows()
            if r["サービス"] in SHISETSU and not r["協力医療機関"]]


def yachin():
    """家賃（月額）が公表されているもの。"""
    return [r for r in rows() if r["家賃"]]


def aki():
    """空き人数（受け入れ可能人数）が公表されているもの。"""
    return [r for r in rows() if r["空き人数"] is not None]


