def _p(t):
    """xlsx には強調マーカーを持ち込まない。"""
    return t.replace("**", "")


HEAD = ["No", "期限", "期限の目安", "影響度", "影響度の意味", "宛先",
        "資料・確認事項", "何が動くか", "出ないときの扱い", "既往"]
W = [5, 6, 22, 7, 26, 18, 52, 52, 46, 20]


def xlsx_build():
    wb = Workbook()
    ws = wb.active
    ws.title = "必要資料の優先順位"
    hd = Font(bold=True, color="FFFFFF", name="游ゴシック", size=10)
    fill = PatternFill("solid", fgColor="1F3864")
    ws.append(HEAD)
    for c in ws[1]:
        c.font, c.fill = hd, fill
        c.alignment = Alignment(horizontal="center", vertical="center")
    eik_fill = {"Ｓ": PatternFill("solid", fgColor="F8CBAD"),
                "Ａ": PatternFill("solid", fgColor="FFE699"),
                "Ｂ": PatternFill("solid", fgColor="D9E1F2"),
                "Ｃ": PatternFill("solid", fgColor="E2EFDA")}
    for no, k, eik, atesaki, shiryo, ugoku, daitai, kiou in IRAI:
        ws.append([no, k, KIGEN[k][0], eik, EIKYO[eik], atesaki,
                   _p(shiryo), _p(ugoku), _p(daitai), _p(kiou)])
        ws.cell(ws.max_row, 4).fill = eik_fill[eik]
    for i, w in enumerate(W, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(vertical="top", wrap_text=True)
        ws.row_dimensions[row[0].row].height = 68
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = "A1:%s%d" % (get_column_letter(len(HEAD)), ws.max_row)

    p = OUT / ("小野町_必要資料の優先順位_%s.xlsx" % ASOF)
    wb.save(p)
    return p


# ---------------------------------------------------------------- 自己点検
def jiko():
    ng = []
    # 1 番号に重複がない
    nos = [x[0] for x in IRAI]
    if len(nos) != len(set(nos)):
        ng.append("番号が重複している")
    # 2 期限が1〜5のいずれか
    for x in IRAI:
        if x[1] not in KIGEN:
            ng.append("期限が区分外：%s" % x[0])
    # 3 影響度がＳＡＢＣのいずれか
    for x in IRAI:
        if x[2] not in EIKYO:
            ng.append("影響度が区分外：%s" % x[0])
    # 4 Ｓは期限1か2に置く（保険料は後から動かせない）
    for x in IRAI:
        if x[2] == "Ｓ" and x[1] not in ("1", "2"):
            ng.append("Ｓなのに期限が1・2でない：%s" % x[0])
    # 5 国（期限5）には町・県を宛先にしない
    for x in IRAI:
        if x[1] == "5" and not x[3].startswith("国"):
            ng.append("期限5なのに宛先が国でない：%s" % x[0])
        if x[1] != "5" and x[3].startswith("国"):
            ng.append("宛先が国なのに期限5でない：%s" % x[0])
    # 6 「何が動くか」と「出ないときの扱い」が空でない
    for x in IRAI:
        if not x[5].strip():
            ng.append("何が動くかが空：%s" % x[0])
        if not x[6].strip():
            ng.append("出ないときの扱いが空：%s" % x[0])
    # 7 既往が空でない（新規なら「新規」と書く）
    for x in IRAI:
        if not x[7].strip():
            ng.append("既往が空：%s" % x[0])
    # 8 期限1には必ず件がある（空の区分を作らない）
    for k in KIGEN:
        if not _kigen_items(k):
            ng.append("期限%sに1件もない" % k)
    # 9 xlsxの列数と見出しが合う
    if len(HEAD) != len(W):
        ng.append("xlsxの見出しと列幅の数が合わない")
    # 10 本文の件数を手で書いていない
    #    前は「Ｓは3件です」と手で書いており、1件足したときに食い違った。
    import inspect
    src = inspect.getsource(doc_build)
    for n in ("%d件" % len(IRAI),):
        pass
    for bad in ("は3件です", "は4件です", "は5件です"):
        if bad in src:
            ng.append("本文に件数を手で書いている：%s" % bad)
    return ng


