def val(d, k, y):
    return d[k][ix[y]]


r = lead(ws, 4, "【1　社人研推計の公表値（5年刻み）と補間値】", 7)
r = header(ws, r, ["年", "区分", "総人口", "65歳以上", "65〜74歳",
                   "75歳以上", "備考"])
for y, lbl, kind in [("2020", "令和2年", "公表値（国勢調査）"),
                     ("2025", "令和7年", "公表値"),
                     ("2026", "令和8年", "線形補間値"),
                     ("2027", "令和9年", "線形補間値"),
                     ("2028", "令和10年", "線形補間値"),
                     ("2029", "令和11年", "線形補間値"),
                     ("2030", "令和12年", "公表値")]:
    r = body(ws, r, [lbl, kind,
                     int(val(P.A2, "総人口", y)),
                     int(val(P.A2, "高齢者数", y)),
                     int(val(P.A3, "前期高齢者数", y)),
                     int(val(P.A3, "後期高齢者数", y)),
                     ("第10期の最終年度" if y == "2029" else
                      ("国勢調査の実績" if y == "2020" else ""))],
             {2: (OK_G if kind.startswith("公表値") else IN_Y)}, height=20,
             align={3: "right", 4: "right", 5: "right", 6: "right"})

note(ws, r,
     "注）令和11年の26,195人は社人研の公表値ではなく、"
     "令和7年27,102人と令和12年25,969人を線形補間した値である。"
     "27,102＋(25,969−27,102)×4÷5＝26,195.6 で、"
     "見える化A2の値26,195と一致する。"
     "65歳以上9,313人・75歳以上5,890人も同じく補間値である。"
     "社人研が公表しているのは5年刻みの値のみで、"
     "令和11年の公表値は存在しない。"
     "時点は各年10月1日現在（国勢調査及び社人研推計の基準日）である。", 7)
r += 2

r = lead(ws, r, "【2　住民基本台帳との突合（枠）】", 7)
r = header(ws, r, ["区分", "住基\n令和8年1月1日", "見える化\n令和8年10月1日",
                   "差", "乖離率", "", "見方"])
JUKI = {"総人口": 27498, "65歳以上": 9176, "75歳以上": 5492}
MIE = {"総人口": int(val(P.A2, "総人口", "2026")),
       "65歳以上": int(val(P.A2, "高齢者数", "2026")),
       "75歳以上": int(val(P.A3, "後期高齢者数", "2026"))}
for k in ["総人口", "65歳以上", "75歳以上"]:
    a, b = JUKI[k], MIE[k]
    d = a - b
    r = body(ws, r, [k, a, b, d, "%+.1f%%" % (d / b * 100), "",
                     ("住基が622人多い。乖離は若年層にある" if k == "総人口"
                      else ("住基が144人少ない。総人口とは向きが逆である"
                            if k == "65歳以上"
                            else "住基が256人少ない。乖離率は最も大きい"))],
             {4: (OK_G if d > 0 else NG_O)}, height=26,
             align={2: "right", 3: "right", 4: "right", 5: "right"})

note(ws, r + 1,
     "注1）住民基本台帳の値は別途整理によるもので、当方は原表を保有していない。"
     "計画本文に用いる前に原表との照合を要する。"
     "注2）時点が9か月異なる（住基は令和8年1月1日、"
     "見える化は令和8年10月1日）。同一時点に揃えた比較を要する。"
     "注3）総人口では住基が622人多いのに、"
     "65歳以上では144人、75歳以上では256人少ない。"
     "総人口の乖離は若年層にあり、"
     "社人研推計の高齢者数はむしろ実績を上回っている。"
     "総人口を上方に補正しても給付費は増えない。"
     "むしろ75歳以上を下方に補正する方向であり、"
     "この場合は給付費が減る。"
     "注4）介護保険の第1号被保険者の資格は住民基本台帳による。"
     "保険料の算定は住基と接続させ、"
     "社人研推計は年齢構成の伸び率としてのみ用いる設計が考えられる。"
     "注5）保険料基準額は「給付費の第1号被保険者負担分÷"
     "所得段階別加入割合補正後被保険者数÷収納率」で算定するため、"
     "第1号被保険者数の過大は分子・分母の双方を動かして相殺される。"
     "影響が出るのは保険料ではなく給付費の絶対額であり、"
     "準備基金の取崩し規模と国庫・道費・支払基金交付金の"
     "負担額に現れる。"
     "注6）住基の65歳以上・75歳以上の令和2年から令和8年までの推移を"
     "いただければ、同一時点に揃えた突合と、"
     "社人研の伸び率との比較を行う。", 7)

