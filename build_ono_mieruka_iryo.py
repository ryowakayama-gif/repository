def shihyo_master():
    """指標リスト（目的別）から、リスト表示名の一覧を読む。"""
    wb = openpyxl.load_workbook(LIST, read_only=True)
    ws = wb["指標リスト"]
    out = {}
    for r in ws.iter_rows(min_row=4, values_only=True):
        if r and r[2] and r[5]:
            out.setdefault(str(r[5]).strip(), (r[2], r[3], r[4]))
    return out


def selfcheck(master):
    """依頼する指標が、本当に見える化システムにあるかを確かめる。

    無い指標を依頼しても出てこない。名前の写し違いをここで捕まえる。
    """
    bad = []
    for ba, name, _tsukai in IRAI:
        if name.strip() not in master:
            bad.append(f"指標リストに無い名前　[{ba}] {name}")
    for ba in {b for b, _n, _t in IRAI}:
        if ba not in SHIME:
            bad.append(f"場面 {ba} の使い道が定義されていない")
    names = [n for _b, n, _t in IRAI]
    if len(set(names)) != len(names):
        dup = {n for n in names if names.count(n) > 1}
        bad.append(f"同じ指標を重ねて依頼している {dup}")
    if bad:
        for b in bad:
            print(f"  不適合: {b}")
        raise SystemExit(1)
    print(f"  自己点検 3項目 適合（依頼 {len(IRAI)}指標、"
          f"すべて指標リストに実在）")


