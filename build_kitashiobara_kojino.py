def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            for c in r.cells:
                out.append(c.text)
    return "\n".join(out)


def _norm(s):
    return re.sub(r"\s+", "", str(s))


def load_genten():
    """施行通知（PDF）と施行令（本文）を読む。"""
    import pypdf
    out = {}
    if not os.path.exists(TSUUCHI):
        raise SystemExit(f"施行通知が見つかりません: {TSUUCHI}")
    r = pypdf.PdfReader(TSUUCHI)
    out["通知"] = _norm("\n".join((p.extract_text() or "")
                                 for p in r.pages))
    out["通知_頁"] = len(r.pages)
    if not os.path.exists(SEIREI):
        raise SystemExit(f"施行令が見つかりません: {SEIREI}")
    out["施行令"] = _norm(open(SEIREI, encoding="utf-8").read())
    return out


def verify(ge):
    ng = []
    for p in (HONPON, MOTO):
        if not os.path.exists(p):
            ng.append(f"原典が無い: {os.path.basename(p)}")
    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("   -", x)
        raise SystemExit(1)

    hon = _norm(load_docx(HONPON))
    moto = _norm(load_docx(MOTO))

    # ① 本書が引いた記述が、それぞれの原典にあること
    for shiryo, basho, midashi, _youten, terasu, _atsukai in GENTEN:
        if shiryo not in ge:
            ng.append(f"原典が読めていない: {shiryo}")
        elif _norm(terasu) not in ge[shiryo]:
            ng.append(f"{shiryo}{basho}に見つからない（{midashi}）: "
                      f"{terasu[:26]}")

    # ② 施行日が通知と施行令の両方で確かめられていること。
    #    予算資料を根拠にしてはならない（これが前回の論点だった）。
    if _norm("令和８年４月１日から施行されたところです") not in ge["通知"]:
        ng.append("施行通知に法の施行日が無い")
    if _norm("この政令は、令和八年四月一日から施行する") not in ge["施行令"]:
        ng.append("施行令に政令の施行日が無い")

    # ③ 施行令の除外規定が4つそろっていること。
    #    ここを落とすと窓口の切り分けが崩れる。
    for g in ("先天性疾病による認知機能の障害",
              "周産期における胎児又は新生児が受けた脳の損傷による"
              "認知機能の障害",
              "介護保険法(平成九年法律第百二十三号)第五条の二第一項に"
              "規定する認知症",
              "発達障害者支援法(平成十六年法律第百六十七号)第二条第一項に"
              "規定する発達障害"):
        if _norm(g) not in ge["施行令"]:
            ng.append(f"施行令に除外規定が無い: {g[:24]}")
    nozoku = [t for t in TEIGI if "除かれる" in t[1]]
    if len(nozoku) != 4:
        ng.append(f"除かれるものが4件でない（{len(nozoku)}）")

    # ④ 「各自治体」とされた事項を村の側に、
    #    「都道府県等」とされた事項を県の側に置いていること
    mura = {y[0] for y in YAKUWARI if y[2].startswith("村")}
    ken = {y[0] for y in YAKUWARI if y[2].startswith("県")}
    for jou in ("法第17条", "法第29条", "法第5条", "法第10条第2項"):
        if jou not in mura:
            ng.append(f"各自治体の事項を村の側に置いていない: {jou}")
    for jou in ("法第19条", "法第25条", "法第24条"):
        if jou not in ken:
            ng.append(f"都道府県等の事項を県の側に置いていない: {jou}")
    if mura & ken:
        ng.append(f"同じ条が村と県の両方にある: {sorted(mura & ken)}")

    # ⑤ 追記の挿入位置が正本にちょうど1つあること
    for rec in KN_EDITS:
        n = hon.count(_norm(rec["ichi"]))
        if n != 1:
            ng.append(f"{rec['no']}の挿入位置が正本に{n}件: "
                      f"{rec['ichi'][:30]}")
        if rec["kata"] not in ("本文", "注記後", "表の後"):
            ng.append(f"{rec['no']}の挿入位置の型が未定義: {rec['kata']}")

    # ⑥ 追記した文が他メンバー版に無く、正本にちょうど1つ入ったこと
    for rec in KN_EDITS:
        for blk in rec["nakami"]:
            if blk[0] not in ("p", "note"):
                continue
            if _norm(blk[1]) in moto:
                ng.append(f"{rec['no']}の文が既に他メンバー版にある")
            if hon.count(_norm(blk[1])) != 1:
                ng.append(f"{rec['no']}の文が正本に"
                          f"{hon.count(_norm(blk[1]))}件: {blk[1][:26]}")

    # ⑦ 他メンバー版の「成立を踏まえた」を書き換えていないこと。
    #    国の基本指針を写したもので、成立は事実である。
    if _norm("高次脳機能障害者支援法の成立を踏まえた相談支援体制の充実") \
            not in hon:
        ng.append("他メンバー版の「成立を踏まえた」が正本から消えている。"
                  "基本指針の原典が無いため書き換えてはならない")

    # ⑧ 施行日を予算資料ではなく法令・通知の側から書いていること
    for rec in KN_EDITS:
        k = rec["konkyo"]
        if "令和８年４月１日" in _norm("".join(
                str(b[1]) for b in rec["nakami"] if b[0] == "p")):
            if "予算" in k:
                ng.append(f"{rec['no']}が施行日の根拠に予算資料を挙げている")
            if "施行" not in k:
                ng.append(f"{rec['no']}の根拠に施行通知又は施行令が無い")

    # ⑨ 照会の番号と、本文の注記に未定義の番号が無いこと
    nos = [s[0] for s in SHOUKAI]
    if nos != ["Ｍ-107"]:
        ng.append(f"照会の番号が想定と違う: {nos}")
    for rec in KN_EDITS:
        for blk in rec["nakami"]:
            if blk[0] != "note":
                continue
            for m in re.findall(r"Ｍ-\d+", blk[1]):
                if m not in nos and m not in ("Ｍ-99", "Ｍ-22"):
                    ng.append(f"{rec['no']}の注記が未起票の番号を"
                              f"参照している: {m}")

    # ⑩ 表記の作法
    for rec in KN_EDITS:
        for blk in rec["nakami"]:
            txt = blk[1] if blk[0] in ("p", "note") else ""
            if "~" in txt:
                ng.append(f"{rec['no']}に半角チルダがある")
            if "か所" in txt and "カ所" in txt:
                ng.append(f"{rec['no']}で「か所」と「カ所」が混在している")
            for warui in ("小野町", "金ケ崎", "金ヶ崎", "阿蘇", "札幌"):
                if warui in txt:
                    ng.append(f"他団体の案件の地名が入っている: {warui}")

    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("   -", x)
        return False
    print(f"  自己点検: 原典の記述{len(GENTEN)}点を"
          f"施行通知（{ge['通知_頁']}頁）と施行令の現物と照合／"
          f"施行日を通知と施行令の両方で確認（予算資料を根拠にしない）／"
          f"施行令の除外規定4件／"
          f"各自治体の事項{len(mura)}条を村・"
          f"都道府県等の事項{len(ken)}条を県に区分／"
          f"追記{len(KN_EDITS)}件の挿入位置と本文が正本に実在／"
          f"他メンバー版の記述を書き換えていない／表記の作法")
    return True


