# -*- coding: utf-8 -*-
"""業務内容別の進捗（仕様書４（1）〜（12））.

業務工程管理表と業務進捗報告書とで進捗率が食い違わないよう、
値をここに一元化する。両方のスクリプトがこの表を読む。

  番号, 業務内容, 進捗（0〜1／対象外はNone）, 状態, 前月からの動き（ポイント）

進捗は、当該業務の作業項目のうち完了したものの割合を受託者が見積もったもの。
「全体」は、進捗を数値で表せる業務（(11)(12)を除く10業務）の単純平均とする。
"""

KIJUNBI = "令和8年8月26日"

PROGRESS = [
    ("(1)", "制度改正等の整理", 0.85, "実施中", "＋10pt"),
    ("(2)", "第9期計画の評価・検証", 0.65, "実施中", "＋35pt"),
    ("(3)", "実施済み調査結果の集計・分析", 0.95, "実施中", "＋75pt"),
    ("(4)", "現状分析及び地域課題の整理", 0.85, "実施中", "＋45pt"),
    ("(5)", "将来推計", 0.78, "実施中", "＋58pt"),
    ("(6)", "計画書の作成", 0.70, "実施中", "＋40pt"),
    ("(7)", "計画策定支援", 0.65, "実施中", "＋25pt"),
    ("(8)", "各種会議への技術的支援", 0.15, "実施中", "＋15pt"),
    ("(9)", "パブリックコメント支援", 0.00, "未着手", "―"),
    ("(10)", "成果品の作成", 0.45, "実施中", "＋35pt"),
    ("(11)", "成果品の帰属", None, "対象外", "―"),
    ("(12)", "その他", None, "随時", "―"),
]


def rate(no):
    """業務番号から進捗（0〜1）を返す。対象外は None。"""
    for n, _nm, v, _st, _d in PROGRESS:
        if n == no:
            return v
    raise KeyError(no)


def overall():
    """全体進捗（進捗を数値で表せる業務の単純平均）。"""
    v = [p for _n, _nm, p, _st, _d in PROGRESS if p is not None]
    return sum(v) / len(v)


def overall_pct():
    """全体進捗の百分率（四捨五入）。"""
    return round(overall() * 100)


if __name__ == "__main__":
    for n, nm, v, st, d in PROGRESS:
        print("%-5s %-22s %s  %s  %s"
              % (n, nm, "―  " if v is None else "%3.0f％" % (v * 100), st, d))
    print("全体（%d業務の単純平均）　%.3f → %d％"
          % (len([1 for _a, _b, p, _c, _d in PROGRESS if p is not None]),
             overall(), overall_pct()))
