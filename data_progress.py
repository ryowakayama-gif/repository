def rate(no):
    """業務番号から進捗（0〜1）を返す。対象外は None。"""
    for n, _nm, v, _st, _d in PROGRESS:
        if n == no:
            return v
    raise KeyError(no)


def overall():
    """全体進捗（進捗を数値で表せる業務の単純平均）。"""
    v = [p for _n, _nm, p, _st, _d in PROGRESS if p is not None]
    return sum(v) / len(v)


def overall_pct():
    """全体進捗の百分率（四捨五入）。"""
    return round(overall() * 100)


if __name__ == "__main__":
    for n, nm, v, st, d in PROGRESS:
        print("%-5s %-22s %s  %s  %s"
              % (n, nm, "―  " if v is None else "%3.0f％" % (v * 100), st, d))
    print("全体（%d業務の単純平均）　%.3f → %d％"
          % (len([1 for _a, _b, p, _c, _d in PROGRESS if p is not None]),
             overall(), overall_pct()))
