def area(c):
    """区域内・区域外・死亡・把握なしに分ける。"""
    o = sum(v for k, v in c.items() if "区域外" in k)
    d = sum(v for k, v in c.items() if k == "死亡")
    u = sum(v for k, v in c.items() if "把握" in k)
    return sum(c.values()) - o - d - u, o, d, u


