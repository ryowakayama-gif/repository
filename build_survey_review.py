def xtab(ws, r, title, d, rows=None, cols=None, span=10, pct=False):
    """クロス表を書き出す。行合計・列合計を付ける。"""
    rk = rows or sorted(d)
    ck = cols or sorted({c for v in d.values() for c in v})
    r = lead(ws, r, title, span)
    r = header(ws, r, [""] + ck + ["計"] + [""] * max(0, span - len(ck) - 2))
    tot = collections.Counter()
    for k in rk:
        v = d.get(k, {})
        n = sum(v.values())
        cells = []
        for c in ck:
            x = v.get(c, 0)
            tot[c] += x
            cells.append("%d（%.0f％）" % (x, x / n * 100) if pct and n else x)
        r = body(ws, r, [k] + cells + [n]
                 + [""] * max(0, span - len(ck) - 2), height=20, align=RIGHT)
    r = body(ws, r, ["計"] + [tot[c] for c in ck] + [sum(tot.values())]
             + [""] * max(0, span - len(ck) - 2), {1: GRAY}, height=20,
             align=RIGHT, bold=True)
    return r + 1


