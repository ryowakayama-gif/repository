# ---------------------------------------------------------------- 自己点検
def jiko():
    ng = []
    # 1 他町村の固有名詞を本文に書いていない
    import inspect
    src = inspect.getsource(doc_build) + "".join(
        str(x) for x in (SUMAI, IRYO, SONOTA, JOBAN, SHOKAI, HANEI, GENJO))
    for word in ("北塩原", "大雪", "金ケ崎", "金ヶ崎", "川崎町"):
        if word in src:
            ng.append("他町村の固有名詞が本文にある：%s" % word)
    # 2 他町村の数値を書いていない（村内・同村・本村という語で判定）
    for word in ("本村", "同村", "村内"):
        if word in src:
            ng.append("他町村を指す語が本文にある：%s" % word)
    # 3 照会に重複がない
    nos = [x[0] for x in SHOKAI]
    if len(nos) != len(set(nos)):
        ng.append("照会番号が重複している")
    # 4 住まいの各件に根拠と扱いと直し方がそろっている
    for x in SUMAI + IRYO:
        if not (x[1].strip() and x[2].strip() and x[3].strip()):
            ng.append("住まい・医療の件に欠けがある：%s" % x[0])
    # 5 条番号の落とし穴には確かめた根拠がある
    for x in JOBAN:
        if not x[1].strip():
            ng.append("条番号の件に根拠がない：%s" % x[0])
    # 6 確かめていない条番号には「要確認」を付けている
    for x in SUMAI:
        if "第4条の2" in x[1] and "要確認" not in x[1]:
            ng.append("未確認の条番号に要確認がない：%s" % x[0])
    # 7 本文に件数を手で書いていない
    import re
    for m in re.findall(r"（\d+件）", inspect.getsource(doc_build)):
        ng.append("本文に件数を手で書いている：%s" % m)
    # 8 出典が1つ以上ある
    if "r.src(" not in inspect.getsource(doc_build):
        ng.append("出典がない")
    return ng


