def sheet_bunsho(wb):
    ws = add_sheet(
        wb, "06_正本に入れる文章", "実際に入れる文章（Ｙ-1〜Ｙ-8）",
        "ここに書いたものがそのまま正本に入る。"
        "表は行数、注記は【村へ確認】の有無を示す。",
        [8, 10, 34, 46, 14, 34])
    style_header_row(ws, 5, ["番号", "型", "入れる先", "中身", "分量", "根拠"])
    r = 6
    for i, rec in enumerate(HP3_EDITS):
        naka = []
        for blk in rec["nakami"]:
            if blk[0] == "h2":
                naka.append(f"［節］{blk[1]}")
            elif blk[0] == "p":
                naka.append(blk[1][:60] + "…")
            elif blk[0] == "tbl":
                naka.append(f"［表］{blk[1][0][0]}／{blk[1][0][-1]}"
                            f"（{len(blk[1])}行）")
            elif blk[0] == "note":
                naka.append(f"［注記］{blk[1][:40]}…")
        n_p = sum(1 for b in rec["nakami"] if b[0] == "p")
        n_t = sum(1 for b in rec["nakami"] if b[0] == "tbl")
        n_n = sum(1 for b in rec["nakami"] if b[0] == "note")
        r = write_row(ws, r, [
            rec["no"], rec["kata"], rec["saki"], "\n".join(naka),
            f"段落{n_p}・表{n_t}・注記{n_n}", rec["konkyo"],
        ], alt=(i % 2 == 1))
    return ws


