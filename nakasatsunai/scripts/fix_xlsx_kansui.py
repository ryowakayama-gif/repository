# -*- coding: utf-8 -*-
"""簡易水道側の整合：「簡水現況予測」の指標の算式と名称を水道事業のものへ。

 E-9  給水原価の算式が、費用から収益項目（営業収益その他・基準内繰入金）を控除しており、
      給水原価97.75円/㎥・料金回収率115.4%と実績（167.56円・67.31%）から大きく外れていた。
      総務省定義（経常費用−長期前受金戻入）に是正する。
 E-10 115行の有収水量が外部ブック（[13]「P参考 R12繰入０円180％」）を参照しており、
      3,016,564㎥（正しくは741,320㎥）となっていた。内部参照へ是正する。
 E-11 指標名が下水道の用語（汚水処理費・使用料収入・経費回収率・汚水処理原価）のまま。
      水道事業の用語（給水費・料金収入・料金回収率・給水原価）へ。
 E-12 1行目「3事業合算」（本村は単独事業）と、収益的支出の「(3)流域下水道負担金」
      （簡易水道に該当なし・番号も(3)が重複）を是正する。
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import xlsxlib
from xlsxlib import Workbook, colseq

SRC = sys.argv[1]
DST = sys.argv[2]
w = Workbook(SRC)
K = '簡水現況予測'
G = '下水道現況予測'
PLAN = colseq('P', 'Y')          # 令和7〜16年度

print('■ 1. 事業名（1行目）— 本村は単独事業のため「3事業合算」は誤り')
SHEETS1 = [(K, '簡易水道事業')] + [(s, '下水道事業') for s in w.SHEET
                                  if s.startswith('下水道現況予測')]
for sheet, name in SHEETS1:
    x = w.get(sheet)
    x = w.set_str(x, 'A1', name, f'{sheet} 「3事業合算」→「{name}」（本村は単独事業）')
    w.put(sheet, x)
    print(f'   {sheet}!A1 → {name}')

print('\n■ 2. E-11 指標名を水道事業の用語へ（「簡水現況予測」のみ）')
x = w.get(K)
LAB = [('J16', '給水費（A）'), ('J17', '料金収入（B）'), ('J18', '料金回収率（B÷A）'),
       ('J20', '給水原価（A÷C）'), ('C113', '給水費（千円）'), ('C114', '料金回収率'),
       ('C116', '給水原価（円）')]
for ref, text in LAB:
    x = w.set_str(x, ref, text, f'{K} 指標名を水道事業の用語へ')
    print(f'   {ref} → {text}')

print('\n■ 3. E-12 簡易水道に該当しない費目を削除')
for ref in ('D48', 'F48'):
    x = w.clear(x, ref, f'{K} 「(3)流域下水道負担金」は簡易水道に該当しない（(3)の重複も解消）')
print('   D48・F48 をクリア（減価償却費の (3) と番号が重複していた）')

print('\n■ 4. E-9 給水原価の算式を総務省定義へ')
#  現行 =P53-P35-P103-P30 は、費用から営業収益その他(P30)と基準内繰入金(P103)という
#  「収益」を差し引いている。給水費＝経常費用−受託工事費−材料及び不用品売却原価
#  −長期前受金戻入 であり、本事業は受託工事費・材料売却原価の計上がないため
#  経常費用(P53)−長期前受金戻入(P35) となる。
old = w.cached(x, 'P16')
x = w.set_cell(x, 'P16', '<f>P53-P35</f><v>0</v>',
               f'{K} 給水費＝経常費用−長期前受金戻入（収益項目の控除をやめる）')
x = w.set_cell(x, 'Q16', '<f t="shared" ref="Q16:Y16" si="2">Q53-Q35</f><v>0</v>',
               f'{K} 同上（共有数式の親。R〜Y列へ展開される）')
print(f'   P16 =P53-P35-P103-P30 → =P53-P35（令和7年度 {old:,.0f}千円 → 再計算）')

print('\n■ 4b. E-13 料金回収率の分母（62〜64行）を是正')
#  63行「給水原価」＝料金収入÷有収水量 は、実際には「供給単価」。
#  64行「供給原価」＝(経常費用−営業収益その他÷2−調整額) は、収益の控除に加えて
#  年度ごとの調整額（令和8年度△1,000千円〜令和16年度△8,000千円）が数式に直接
#  書き込まれており、これが料金回収率を右肩上がりに見せる原因になっていた。
x = w.set_str(x, 'B63', '供給単価（円／㎥）', f'{K} 63行は料金収入÷有収水量＝供給単価')
x = w.set_str(x, 'B64', '給水原価（円／㎥）', f'{K} 64行が料金回収率の分母＝給水原価')
SRCC = colseq('F', 'O')          # 「予測」シートの令和7〜16年度
for i, c in enumerate(PLAN):
    x = w.set_cell(x, f'{c}64',
                   f'<f>ROUND(({c}53-{c}35)*1000/予測!{SRCC[i]}36,2)</f><v>0</v>',
                   f'{K} 給水原価＝（経常費用−長期前受金戻入）÷有収水量'
                   f'（収益の控除と年度別の調整額をやめる）')
print('   B63 → 供給単価（円／㎥）／B64 → 給水原価（円／㎥）')
print('   P64〜Y64 =ROUND((P53-P30/2−調整額)*1000/予測!F36,2) → =ROUND((P53-P35)*1000/予測!F36,2)')
print('   （調整額は 令和8年度△1,000〜令和16年度△8,000千円が数式に直接書かれていた）')

print('\n■ 5. E-10 有収水量の参照先を外部ブックから内部へ')
for c in PLAN:
    x = w.set_cell(x, f'{c}115', f'<f>{c}19</f><v>0</v>',
                   f"{K} 115行 有収水量 ='[13]P参考 R12繰入０円180％'! → 同シート19行")
print(f"   P115〜Y115 ='[13]P参考　R12繰入０円180％'!D17〜M17 → =P19〜Y19")
w.put(K, x)

print('\n■ 6. 再計算')
total, fixed_err, bk = w.recalc(verbose=True)
print(f'   計 {total} セルのキャッシュを更新'
      + (f'／エラー値が解消 {len(fixed_err)}件' if fixed_err else ''))

print('\n■ 7. 検算（令和7〜16年度）')
Y = [f'令和{n}' for n in range(7, 17)]
rows = [('給水費（千円）', 16, '{:>9,.0f}'), ('料金収入（千円）', 17, '{:>9,.0f}'),
        ('料金回収率', 18, '{:>9.1%}'), ('有収水量（㎥）', 19, '{:>9,.0f}'),
        ('給水原価（円/㎥）', 20, '{:>9.2f}'), ('経常収支比率', 21, '{:>9.1%}'),
        ('　62行 料金回収率', 62, '{:>9.1%}'), ('　63行 供給単価', 63, '{:>9.2f}'),
        ('　64行 給水原価', 64, '{:>9.2f}')]
print('                    ' + ' '.join(f'{y:>9s}' for y in Y))
for lab, r, f in rows:
    vals = [bk.eval(K, f'{c}{r}') for c in PLAN]
    print(f'  {lab:18s} ' + ' '.join(f.format(v) for v in vals))
r18 = [bk.eval(K, f'{c}18') for c in PLAN]
print(f'\n  本文記載の令和5年度実績：給水原価 167.56円／㎥・料金回収率 67.31%'
      f'・経常収支比率 110.17%')
print(f'  → 料金回収率は {r18[0]:.1%} → {r18[-1]:.1%} と低下し、'
      f'令和5年度基準（67.31%）を{"上回る" if r18[-1] > 0.6731 else "下回る"}')

w.save(DST)
print(f'\n=== 編集 {len(w.log)} セル／共有文字列 +{w._added} 件 → {DST} ===')
