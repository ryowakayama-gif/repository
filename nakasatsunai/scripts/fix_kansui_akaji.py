# -*- coding: utf-8 -*-
"""簡易水道事業経営戦略 本文：赤字（仮置き）表記と項目番号の不整合を是正する。

村のご判断により、簡易水道側は「赤字部分」と「大きな不整合」に限って修正する。

 E-5  仮置きの「サンプル」表記2箇所（p.―「【参考】サンプル」、「4．施設の状況　サンプル」）
      ※「サンプル」は赤（EE0000）で着色された仮置き表記
 E-5  節番号の重複「（５）民間活力の活用等」「（５）資産活用の状況」→（５）（６）（７）へ繰り下げ
 E-5  項番の飛び「❺その他今後の取組についての検討事項」→❸へ
 E-16 原価計算の記述で百分率の単位が脱落（８４.７６ → ８４.７６％）
"""
import sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from docxlib import Doc, log

SRC, DST = sys.argv[1], sys.argv[2]
K = Doc(SRC)

# ── 赤字（仮置き）表記の削除 ─────────────────────────────────────
K.edit(1099, '【参考】サンプル', '【参考】',
       'p.― 原価計算表の見出しに残っていた仮置きの「サンプル」（赤字）を削除')
K.edit(1140, '4．施設の状況　サンプル', '4．施設の状況',
       'p.― 章見出しに残っていた仮置きの「サンプル」（赤字）を削除')

# ── 節番号の重複・飛びの是正 ────────────────────────────────────
#  （４）これまでの主な経営健全化の取組 が追加された際に、以降の番号が
#  繰り下がらず（５）が重複していた。
K.edit(970, '（５）資産活用の状況', '（６）資産活用の状況',
       'p.― （５）が「民間活力の活用等」と重複していたため繰り下げ')
K.edit(981, '（６）簡易水道事業の経営比較分析表による現状分析',
       '（７）簡易水道事業の経営比較分析表による現状分析',
       'p.― 上記の繰り下げに伴う連動')
K.edit(1440, '❺その他今後の取組についての検討事項', '❸その他今後の取組についての検討事項',
       'p.― ❶❷に続く項番が❺になっていた（下水道は❶〜❺で連続）')

# ── 単位の脱落 ──────────────────────────────────────────────
K.edit(1103, '原価（費用）に対する収益（料金）は８４.７６となっており',
       '原価（費用）に対する収益（料金）は８４.７６％となっており',
       'p.― 百分率の単位が抜けていた（下水道の同じ記述は「４５.０７％」）')

K.save(DST)
print(f'=== 適用 {len(log)} 件 → {DST} ===')
for kind, where, what, why in log:
    print(f'  [{kind}] {where:10s} {what}')
    print(f'            {why}')
