def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            for c in r.cells:
                out.append(c.text)
    return "\n".join(out)


def _norm(s):
    return re.sub(r"\s+", "", str(s))


def load_setsumon():
    """今回の調査票の設問を集計表の現物から読む。
    調査票の docx は一部の文字が取り出せないため、集計表による。
    """
    if not os.path.exists(SHUUKEI):
        raise SystemExit(f"集計表が見つかりません: {SHUUKEI}")
    wb = load_workbook(SHUUKEI, data_only=True)
    if "単純集計" not in wb.sheetnames:
        raise SystemExit("集計表に単純集計シートがありません")
    ws = wb["単純集計"]
    setsu = {}
    for row in ws.iter_rows(min_row=1, max_row=ws.max_row,
                            max_col=3, values_only=True):
        no, midashi = row[0], row[1]
        if (no and isinstance(no, str) and re.match(r"^問", str(no).strip())
                and midashi):
            setsu.setdefault(str(no).strip(), str(midashi).strip())
    return setsu


