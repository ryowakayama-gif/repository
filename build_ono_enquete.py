def sheet(wb, name, header, rows, widths, wrap_cols=(), group_col=None, flag_col=None):
    ws = wb.create_sheet(name)
    ws.append(header)
    for c in ws[1]:
        c.font = Font(bold=True, size=9, color="FFFFFF")
        c.fill = HDR
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        c.border = BORDER
    for r in rows:
        ws.append(list(r))
    for row in ws.iter_rows(min_row=2, max_row=ws.max_row):
        for i, c in enumerate(row):
            c.font = Font(size=9)
            c.border = BORDER
            c.alignment = Alignment(wrap_text=(i in wrap_cols), vertical="top")
        if group_col is not None and len(row) > group_col and row[group_col].value:
            row[group_col].fill = GRP
            row[group_col].font = Font(size=9, bold=True)
        if flag_col is not None and len(row) > flag_col:
            v = str(row[flag_col].value or "")
            if v.startswith("▲") or "悪化" in v or "誤" in v or "不整合" in v:
                row[flag_col].fill = BAD
            elif v.startswith("改善") or "一致" in v:
                row[flag_col].fill = GOOD
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(header))}{ws.max_row}"
    return ws


