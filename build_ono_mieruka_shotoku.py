def allocate(pop):
    """段階別構成比を人数 pop に当てる。最大剰余法で合計を一致させる。"""
    tot = sum(n for *_x, n in T.SHOTOKU_R7)
    raw = [n / tot * pop for *_x, n in T.SHOTOKU_R7]
    base = [int(x) for x in raw]
    order = sorted(range(len(raw)), key=lambda i: raw[i] - base[i], reverse=True)
    for i in order[:pop - sum(base)]:
        base[i] += 1
    return base


def nyuryoku():
    """{年度: [13段階の人数]}。"""
    return {y: allocate(p) for y, p in SYS_POP.items()}


def hosei(y):
    """年度の所得段階別加入割合補正後被保険者数と補正係数。"""
    n = allocate(SYS_POP[y])
    h = sum(hyo * k for (_nm, hyo, _fu, _x), k in zip(T.SHOTOKU_R7, n))
    return h, h / SYS_POP[y]


def kikaku():
    """保険料への影響。現行（誤り）と訂正後を並べる。"""
    import build_ono_mikomi_kakutei as M
    std, chi, sogo, pop3 = M.STD3, M.CHI3, M.SOGO3, M.POP3
    g_pre = T.shotoku_hosei()
    g_post = (sum(fu * n for _nm, _h, fu, n in T.SHOTOKU_R7)
              / sum(n for *_x, n in T.SHOTOKU_R7))

    tot = sum(n for *_x, n in T.SHOTOKU_R7)
    PRE = [(h, n) for _nm, h, _f, n in T.SHOTOKU_R7]
    POST = [(f, n) for _nm, _h, f, n in T.SHOTOKU_R7]

    def m(rates, wari, kikin=0):
        # 補正後被保険者数の出し方は build_ono_tanka.hosei_ninzu と同じ。
        h = sum(r * round(n / tot * pop3) for r, n in rates)
        need = ((std + chi) * T.FUTAN_WARIAI + (std + sogo) * T.CHOSEI_SOTO
                - std * wari - kikin)
        return need / T.SHUNORITSU * 1000 / h / 12

    return {"軽減前": g_pre, "軽減後": g_post,
            "現行": m(POST, 0.061481), "G訂正": m(PRE, 0.061481),
            "訂正後": m(PRE, T.CHOSEI_MIKOMI),
            "訂正後12": m(PRE, T.CHOSEI_MIKOMI, 12000),
            "訂正後35": m(PRE, T.CHOSEI_MIKOMI, 35000),
            "旧割合": 0.061481, "新割合": T.CHOSEI_MIKOMI}


def selfcheck(N, K):
    """入力値の自己点検。"""
    bad = []
    for y, n in N.items():
        if sum(n) != SYS_POP[y]:
            bad.append(f"{y} 合計{sum(n)}≠{SYS_POP[y]}")
    if abs(K["軽減前"] - 0.99590) > 1e-4:
        bad.append(f"軽減前の補正係数 {K['軽減前']:.5f}")
    if abs(T.DAI9_HOSEI / T.DAI9_POP3 - 0.97377) > 1e-4:
        bad.append("第9期の補正係数")
    return bad


