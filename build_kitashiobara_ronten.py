def verify(memo, honpon, b):
    ng = []
    m, h, bb = _norm(memo), _norm(honpon), _norm(b)

    # ① メモの原文がメモに実在すること
    for rec in RONTEN:
        for line in rec[2].split("\n"):
            if _norm(line) not in m:
                ng.append(f"論点メモに原文がない: {rec[0]}『{line[:34]}』")

    # ② 是正の対象の語がメモに実在すること
    # 照合に用いる語（表記のゆれを含むものは照合用の語を別に持つ）
    seigo_key = {
        "ＧＨ（正式名・福祉ホーム）": "正式名・福祉ホーム",
        "ＰＥＳＯ": "ＰＥＳＯ",
        "職セン": "職セン",
        "能力及び適正": "能力及び適正",
        "適切な毛を受けられる": "適切な毛を受けられる",
    }
    for rec in SEIGO:
        w = seigo_key.get(rec[0], rec[0].split("（")[0])
        if _norm(w) not in m:
            ng.append(f"論点メモに見つからない表記: {rec[0]}（照合語 {w}）")

    # ③ 正本で「0件」と書いた語が本当に0件であること
    zero = ["ＳＤＧｓ", "SDGs", "トライアル雇用", "公共職業安定所",
            "職場適応援助者", "ジョブコーチ", "障害者就業・生活支援センター",
            "地域権利擁護", "身寄り", "死後事務", "第２種",
            "インクルーシブ", "点字ブロック", "段差", "防災無線",
            "障害者週間", "出生"]
    for w in zero:
        if _norm(w) in h:
            ng.append(f"正本にある（0件としたもの）: {w}")

    # ④ 正本で「ある」と書いたものが実在すること
    aru = ["近年の障がい者施策の動向", "物品調達件数",
           "会津支援学校", "さくら小学校", "裏磐梯中学校",
           "重度（Ａ判定）が31.3％", "市民後見人養成事業",
           "対応時間は1,015分", "障がい者の状態だけでなく",
           "地域生活支援センターいなわしろ"]
    for w in aru:
        if _norm(w) not in h:
            ng.append(f"正本に見つからない（あるとしたもの）: {w}")

    # ⑤ 論点メモが読んだ版（b）が当方の素案であることの裏づけ
    for w in ("推計対象の３層", "利用希望量と利用可能量の区別",
              "福島県の計画との整合", "会津障がい保健福祉圏域"):
        if _norm(w) not in bb:
            ng.append(f"②に見つからない（当方の素案の特徴）: {w}")
    for w in ("重度障がい者の内数", "意思形成", "住まいの確保"):
        if _norm(w) in bb:
            ng.append(f"②にある（第2回レビューの修正が入っていないはず）: {w}")

    # ⑥ 語彙と番号
    for rec in RONTEN:
        assert rec[7] in ("最優先", "高", "中", "低"), f"重さが未定義: {rec[0]}"
        assert rec[1] in ("構成", "データ", "施策", "地域生活支援事業",
                          "成年後見"), f"区分が未定義: {rec[0]}"
    ids = [r[0] for r in RONTEN]
    assert len(ids) == len(set(ids)), "論点の番号が重複している"
    kids = [r[0] for r in KAIKAI]
    assert len(kids) == len(set(kids)), "照会の番号が重複している"

    # ⑦ 他団体の名を出さない
    for data in (RONTEN, HAN, SEIGO, KAIKAI):
        for rec in data:
            s = "".join(str(x) for x in rec)
            for bad in ("小野町", "金ヶ崎", "阿蘇", "札幌"):
                if bad in s:
                    ng.append(f"他団体名が含まれている: {bad}")

    if ng:
        print("自己点検 不合格:")
        for e in ng:
            print("   -", e)
        raise SystemExit(1)
    print(f"  自己点検: 論点{len(RONTEN)}件の原文がメモに実在／"
          f"正本で0件とした{len(zero)}語・あるとした{len(aru)}語を実測／"
          "②が当方の素案であることを7語で裏づけ")


