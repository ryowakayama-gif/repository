def body(path):
    d = Document(path)
    parts = []
    for ch in d.element.body.iterchildren():
        tag = ch.tag.split("}")[-1]
        if tag == "p":
            parts.append(Paragraph(ch, d).text)
        elif tag == "tbl":
            for row in Table(ch, d).rows:
                seen = set()
                for c in row.cells:
                    if id(c._tc) in seen:
                        continue
                    seen.add(id(c._tc))
                    parts.append(c.text)
    return "\n".join(parts), len(d.paragraphs), len(d.tables)


def note_count(path):
    d = Document(path)
    n1 = sum(1 for t in d.tables if len(t.rows) == 1 and len(t.columns) == 1)
    txt = "\n".join(c.text for t in d.tables for r in t.rows for c in r.cells)
    return n1, txt.count("【要更新"), txt.count("【要確認")


