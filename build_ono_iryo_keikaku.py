def jiko():
    ng = []
    import inspect
    import re
    src = inspect.getsource(doc_build) + "".join(
        str(x) for x in (SHOU, KENCHU, TEISEI, TSUCHI, BAMEN, SHIHYO,
                         CHUI, SHOKAI))
    # 1 他町村を指す語がない
    for w in ("北塩原", "大雪", "金ヶ崎", "川崎町", "本村", "同村"):
        if w in src:
            ng.append("他町村を指す語がある：%s" % w)
    # 2 本町の医療圏を取り違えていない
    for w in ("本町は県北", "本町は県南", "本町は会津", "本町は相双",
              "本町はいわき"):
        if w in src:
            ng.append("本町の医療圏を取り違えている：%s" % w)
    if "県中医療圏" not in src:
        ng.append("県中医療圏に触れていない")
    # 3 訂正には素案の記述と判定と経緯がそろっている
    for x in TEISEI:
        if not (x[1].strip() and x[2].strip() and x[3].strip()):
            ng.append("訂正に欠けがある：%s" % x[0])
    # 4 通知が求める3つの資源がそろっている
    if len(TSUCHI) != 3:
        ng.append("通知が求める資源が3つでない：%d" % len(TSUCHI))
    # 5 4つの場面がそろっている
    if len(BAMEN) != 4:
        ng.append("4つの場面がそろっていない：%d" % len(BAMEN))
    # 6 照会に重複がない
    nos = [x[0] for x in SHOKAI]
    if len(nos) != len(set(nos)):
        ng.append("照会番号が重複している")
    # 7 食い違いを断定していない
    if "素案が誤り" in src or "県計画が誤り" in src:
        ng.append("食い違いを断定している")
    # 8 本文に件数を手で書いていない
    for m in re.findall(r"（\d+件）", inspect.getsource(doc_build)):
        ng.append("本文に件数を手で書いている：%s" % m)
    return ng


