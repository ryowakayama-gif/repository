def chapter(doc, text):
    doc.add_page_break()
    doc.add_heading(text, level=1)


def table(doc, header, rows):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for c, h in zip(t.rows[0].cells, header):
        c.text = ""
        r = c.paragraphs[0].add_run(h)
        r.font.bold = True
        r.font.size = Pt(9)
        r.font.name = JP_GO
        r.element.rPr.rFonts.set(qn("w:eastAsia"), JP_GO)
    for row in rows:
        for c, v in zip(t.add_row().cells, row):
            c.text = ""
            r = c.paragraphs[0].add_run(str(v))
            r.font.size = Pt(9)
    return t


def bullets(doc, items):
    for it in items:
        p = doc.add_paragraph(it, style="List Bullet")
        p.paragraph_format.space_after = Pt(0)


def note(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(9)
    r.italic = True
    return p


def body(doc, *paras):
    for t in paras:
        doc.add_paragraph(t)


