def kyufu_kubun(y, mode):
    """同じ資料を、受給率の分母の粒度だけ変えて計算する。

    mode "7" 要介護度7区分（当方の算定）
         "2" 要介護・要支援の2区分（アプリの target）
         "1" 区分なし（従前の一律の伸び）
    """
    t = 0.0
    for lab in SVC:
        base, p = JISSEKI[lab], (tanka(lab) or 0)
        if mode == "7":
            u = sum(base[i] * NIN[y][i] / NIN_R7[i] for i in range(7))
        elif mode == "2":
            u = 0.0
            for sl in (SH, KG):
                br = sum(NIN_R7[sl])
                if br:
                    u += sum(base[sl]) * sum(NIN[y][sl]) / br
        else:
            u = sum(base) * sum(NIN[y]) / sum(NIN_R7)
        t += u * 12 * p
    return t


