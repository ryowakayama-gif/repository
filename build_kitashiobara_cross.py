def verify():
    """データの内部整合を検証する。"""
    assert len(GAPS) == 4, f"欠落項目が4件でない: {len(GAPS)}"
    judges = {g[5] for g in GAPS}
    assert judges <= {DAITAI_KA, BUBUN, SAIKYOGI}, f"未定義の判定: {judges}"
    # 再協議が必要なのは①のみ
    saikyogi = [g[0] for g in GAPS if g[5] == SAIKYOGI]
    assert saikyogi == ["①"], f"再協議の対象が①以外にある: {saikyogi}"

    ids = [c[0] for c in CROSS]
    assert len(ids) == len(set(ids)), "クロス集計の No が重複している"
    pris = {c[1] for c in CROSS}
    assert pris <= {"最優先", "高", "中", "低"}, f"未定義の優先度: {pris}"

    # 欠落の代替となるクロス集計が各欠落について1件以上あること
    for mark in ("欠落①", "欠落②", "欠落③", "欠落④"):
        assert any(mark in c[2] for c in CROSS), f"{mark}の代替クロスがない"

    aids = [a[0] for a in ADMIN_CHECK]
    assert len(aids) == len(set(aids)), "行政データ突合の No が重複している"
    sids = [s[0] for s in SAIKYOGI_ITEMS]
    assert len(sids) == len(set(sids)), "再協議事項の No が重複している"

    assert YUKO == 110, f"想定有効回答の計算が想定と異なる: {YUKO}"


