# ============================================================
# 女川町(税込)
# ============================================================
ONAGAWA_METER = {13: 55, 20: 77, 25: 110, 40: 220,
                  50: 880, 75: 1100, 100: 1320, 150: 3300}

def onagawa(q, c):
    """女川町の水道料金計算(税込、円)
    q: 月間使用水量(㎥)、c: メーター口径(mm)
    """
    if q <= 5:
        body = 990
    elif q <= 10:
        body = 1210
    elif q <= 100:
        body = 1210 + (q - 10) * 121
    else:
        body = 1210 + 90 * 121 + (q - 100) * 110
    return body + ONAGAWA_METER.get(c, 0)


# ============================================================
# 気仙沼市(税抜計算後に×1.10で税込)
# ============================================================
def kesennuma(q, c):
    """気仙沼市の水道料金計算(税込、円)"""
    if c in (13, 20):
        basic = {13: 1010, 20: 1990}[c]
        fee = 0
        r = q
        for w, u in [(10, 96), (10, 172), (980, 250), (float('inf'), 260)]:
            take = min(r, w)
            fee += take * u
            r -= take
            if r <= 0:
                break
    elif c in (25, 30, 40):
        basic = {25: 2790, 30: 3970, 40: 6560}[c]
        fee = 0
        r = q
        for w, u in [(1000, 287), (float('inf'), 260)]:
            take = min(r, w)
            fee += take * u
            r -= take
            if r <= 0:
                break
    elif c in (50, 75, 100):
        basic = {50: 10090, 75: 21380, 100: 30090}[c]
        fee = 0
        r = q
        for w, u in [(1000, 323), (float('inf'), 292)]:
            take = min(r, w)
            fee += take * u
            r -= take
            if r <= 0:
                break
    else:
        return -1
    return int((basic + fee) * 1.10)


# ============================================================
# 石巻広域(税抜計算後に×1.10で税込)
# ============================================================
def ishinomaki(q, c):
    """石巻広域の水道料金計算(税込、円)"""
    if c == 13:
        basic = 1480
        if q <= 10:
            return int(basic * 1.10)
        fee = 0
        r = q - 10
        for w, u in [(10, 260), (30, 280), (float('inf'), 320)]:
            take = min(r, w)
            fee += take * u
            r -= take
            if r <= 0:
                break
        return int((basic + fee) * 1.10)

    basics = {25: 2340, 50: 7130, 75: 14130, 100: 24820}
    basic = basics.get(c, 0)
    fee = 0
    r = q
    for w, u in [(50, 300), (float('inf'), 320)]:
        take = min(r, w)
        fee += take * u
        r -= take
        if r <= 0:
            break
    return int((basic + fee) * 1.10)


# ============================================================
# 塩竈市(税抜計算後に×1.10で税込)
# ============================================================
SHIOGAMA_BASIC = {13: 700, 20: 1300, 25: 2100, 40: 5000,
                   50: 10000, 75: 20000, 100: 38000, 150: 83000}

def shiogama(q, c):
    """塩竈市の水道料金計算(一般用、税込、円)"""
    basic = SHIOGAMA_BASIC.get(c, 0)
    fee = 0
    r = q
    for w, u in [(10, 83), (10, 175), (30, 235), (50, 255), (float('inf'), 295)]:
        take = min(r, w)
        fee += take * u
        r -= take
        if r <= 0:
            break
    return int((basic + fee) * 1.10)


def shiogama_production(q):
    """塩竈市 生産用水用 料金計算(税込、円)- 産業用優遇料金"""
    return int(q * 105 * 1.10)


