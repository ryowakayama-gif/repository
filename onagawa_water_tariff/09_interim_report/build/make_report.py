def setfont(run, name=JP, size=None, bold=None, color=None):
    run.font.name = name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), name)
    if size: run.font.size = Pt(size)
    if bold is not None: run.bold = bold
    if color: run.font.color.rgb = color

def P(text='', size=10.5, bold=False, color=None, align=None, space_after=6, indent=None, font=JP):
    p = doc.add_paragraph()
    if align: p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.15
    if indent: p.paragraph_format.left_indent = Cm(indent)
    if text:
        setfont(p.add_run(text), font, size, bold, color)
    return p

def H1(text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(16); p.paragraph_format.space_after = Pt(8)
    setfont(p.add_run(text), JPG, 14, True, NAVY)
    pbd = OxmlElement('w:pBdr'); b = OxmlElement('w:bottom')
    b.set(qn('w:val'),'single'); b.set(qn('w:sz'),'12'); b.set(qn('w:space'),'2'); b.set(qn('w:color'),'1F3864')
    pbd.append(b); p._p.get_or_add_pPr().append(pbd)
    return p

def H2(text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(12); p.paragraph_format.space_after = Pt(5)
    setfont(p.add_run(text), JPG, 11.5, True, BLUE); return p

def H3(text):
    p = doc.add_paragraph(); p.paragraph_format.space_before = Pt(9); p.paragraph_format.space_after = Pt(4)
    setfont(p.add_run(text), JPG, 10.5, True, RGBColor(0xC5,0x5A,0x11)); return p

def bullet(text, size=10.5):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_after = Pt(3); p.paragraph_format.line_spacing = 1.12
    setfont(p.add_run(text), JP, size); return p

def shade(cell, hexcolor):
    e = OxmlElement('w:shd'); e.set(qn('w:val'),'clear'); e.set(qn('w:fill'),hexcolor)
    cell._tc.get_or_add_tcPr().append(e)

def table(headers, rows, widths=None, size=9, note=None, align_right=None):
    t = doc.add_table(rows=1, cols=len(headers)); t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    if widths:
        t.autofit = False
        for i, w in enumerate(widths):
            for row in t.rows: row.cells[i].width = Cm(w)
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]; c.text = ''
        pr = c.paragraphs[0]; pr.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pr.paragraph_format.space_after = Pt(2)
        setfont(pr.add_run(str(h)), JPG, size, True, RGBColor(0xFF,0xFF,0xFF))
        shade(c, '2E75B6')
    for r in rows:
        cells = t.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = ''
            pr = cells[i].paragraphs[0]; pr.paragraph_format.space_after = Pt(2)
            txt = str(v)
            if align_right and i in align_right: pr.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            elif i == 0: pr.alignment = WD_ALIGN_PARAGRAPH.LEFT
            else: pr.alignment = WD_ALIGN_PARAGRAPH.CENTER
            bold = txt.startswith('★') or txt.startswith('【')
            setfont(pr.add_run(txt.lstrip('★')), JP, size, bold)
            if widths: cells[i].width = Cm(widths[i])
        if widths:
            for i, w in enumerate(widths): cells[i].width = Cm(w)
    if note:
        P(note, size=8.5, color=GREY, space_after=10)
    else:
        P('', size=4, space_after=4)
    return t

def pagebreak():
    doc.add_paragraph().add_run().add_break(WD_BREAK.PAGE)

def yen(v): return f'{round(v):,}'

