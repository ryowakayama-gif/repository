def jiko(doc):
    ng = []
    # 1 法定記載事項に3つの根拠法がそろっている
    konkyo = "".join(x[0] for x in HOTEI)
    for law in ("障害者基本法第11条第3項", "障害者総合支援法第88条第1項",
                "児童福祉法第33条の20第1項"):
        if law not in konkyo:
            ng.append("法定記載事項に %s がない" % law)
    # 2 令和8年改正の新設4号がそろっている
    for g in ("第88条第3項第3号", "第88条第3項第4号", "第88条第3項第5号",
              "第33条の20第3項第3号"):
        if g not in konkyo:
            ng.append("新設の号 %s がない" % g)
    # 3 第2部の章と施策の対応が取れている（第1章を除く）
    for ch, nm, setsu in BUNYA:
        if ch == "第1章":
            continue
        if ch not in SHISAKU:
            ng.append("%s の施策がない" % ch)
        elif len(SHISAKU[ch][1]) != len(setsu):
            ng.append("%s の節(%d)と施策のまとまり(%d)の数が合わない"
                      % (ch, len(setsu), len(SHISAKU[ch][1])))
        elif any(not b for b in SHISAKU[ch][1]):
            ng.append("%s に施策の方向が空の節がある" % ch)
    # 4 前回計画の9章すべてに、本計画での引き継ぎ先がある
    for sho, _k, _t in _zen_sho():
        key = sho.split("　")[0]
        if key not in BUNYA_TAIO:
            ng.append("前回計画の%s に引き継ぎ先がない" % key)
    if len(_zen_sho()) != 9:
        ng.append("前回計画の章が%d件（9件のはず）" % len(_zen_sho()))
    # 5 成果目標が8分野
    if len(SEIKA) != 8:
        ng.append("成果目標が8分野でない：%d" % len(SEIKA))
    # 5 見込量の区分が6つ
    if len(MIKOMI) != 6:
        ng.append("見込量の区分が6つでない：%d" % len(MIKOMI))
    # 6 方策が5つ（法定の新設を含む）
    if len(HOSAKU) != 5:
        ng.append("方策が5つでない：%d" % len(HOSAKU))
    if "都道府県と連携した取組" not in "".join(x[1] for x in HOSAKU):
        ng.append("方策に条文の文言「都道府県と連携した取組」がない")
    # 7 手帳の推移　内訳の和が、前回計画が図に載せている「計」と一致する
    for i, nen in enumerate(TECHO_NEN):
        vals = [v[i] for _nm, v in TECHO_SUII]
        kei = TECHO_KEI[i]
        if any(x is None for x in vals) or kei is None:
            if not (all(x is None for x in vals) and kei is None):
                ng.append("%s　内訳と計のどちらか片方だけがある" % nen)
            continue
        if sum(vals) != kei:
            ng.append("%s　内訳の和%d と計%d が合わない" % (nen, sum(vals), kei))
    if len(TECHO_NEN) != len(TECHO_KEI):
        ng.append("手帳の年の数と計の数が合わない")
    for _nm, v in TECHO_SUII:
        if len(v) != len(TECHO_NEN):
            ng.append("手帳の推移の長さが年の数と合わない：%s" % _nm)
    if TECHO_GOKEI != (sum(x[1] for x in TECHO), sum(x[2] for x in TECHO)):
        ng.append("手帳の合計が内訳の和と合わない")
    # 8 接点が高齢者計画の箇所まで書けている
    for x in SETTEN_SAKI:
        if not x[3].strip():
            ng.append("接点に高齢者計画の箇所がない：%s" % x[0])
    # 9 「整合性の確保」と「調和」を混ぜていない
    txt = "".join(x[3] for x in KANREN)
    if "障害者総合支援法" in txt and "整合性の確保" in txt:
        ng.append("障がい2法に「整合性の確保」を使っている（正しくは「調和」）")
    # 10 未確定の印が定義した4種だけ
    marks = set(re.findall(r"【[^】]+】", repr(
        (HOTEI, KANREN, SETTEN_SAKI, SHISAKU, SEIKA, MIKOMI, HOSAKU))))
    for m in marks:
        if m not in (TBD, TGT, DEC, CALC):
            ng.append("定義していない印を使っている：%s" % m)
    return ng


