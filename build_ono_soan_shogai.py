_TBL_SEQ = {}


def _caption(doc):
    ch = sec = ""
    for lv, text, _nm in doc.headings:
        if lv == 1:
            ch, sec = text, ""
        elif lv == 2:
            sec = text
    key = (ch + "/" + sec) or "―"
    n = _TBL_SEQ.get(key, 0) + 1
    _TBL_SEQ[key] = n
    # 部の名は長い（「第3部　第8期障がい福祉計画・第4期障がい児福祉計画」）。
    # 表題には部の番号だけを採り、章の見出しを続ける。
    bu = re.match(r"^(第\d+部)", ch)
    if not sec:
        base = ch or "―"
    elif bu:
        base = f"{bu.group(1)}{sec}"
    else:
        base = f"{ch}　{sec}"
    return base if n == 1 else f"{base}（{n}）"


def table(doc, header, rows, widths=None, right=(), caption=None):
    if caption is None:
        caption = _caption(doc)
    return doc.tbl([list(header)] + [list(r) for r in rows],
                   widths=widths, right=right,
                   caption=None if caption is False else caption)


