def _jisseki_rows():
    """第6期の見込量と実績、第7期の見込量を表の行にする。

    実績・見込量とも全年度0のサービスは載せない。
    0が並ぶ行を並べても、読み手の手がかりにならない。
    """
    Z.load()
    out = []
    for nm in sorted(Z.SERVICE):
        if not _oya(nm):
            continue
        for u in sorted(Z.SERVICE[nm]):
            d = Z.SERVICE[nm][u]
            v6, v7 = d.get("6期"), d.get("7期")
            if not v6 or not any(x for x in v6 if x):
                continue
            cells = []
            for i in range(3):
                mi, ji = v6[i * 2], v6[i * 2 + 1]
                if mi is None or ji is None:
                    cells.append("―")
                elif mi:
                    cells.append("%d→%d（%.0f％）" % (mi, ji, ji / mi * 100))
                else:
                    cells.append("%d→%d（―）" % (mi, ji))
            nana = "―" if not v7 else ("%d" % v7[0] if len(set(v7)) == 1
                                       else "／".join(str(x) for x in v7))
            out.append([nm, u] + cells + [nana])
    return out





