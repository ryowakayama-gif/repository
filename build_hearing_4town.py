BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)

def sheet(wb, name, title, note, headers, widths, tab):
    ws = wb.create_sheet(name)
    n = len(headers)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=n)
    c = ws.cell(1, 1, title)
    c.font = Font(bold=True, size=14, color=C_TITLE); c.alignment = Alignment(vertical="center")
    ws.row_dimensions[1].height = 26
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=n)
    c = ws.cell(2, 1, note)
    c.font = Font(size=8, color=C_NOTE); c.alignment = Alignment(wrap_text=True, vertical="center")
    ws.row_dimensions[2].height = 30
    for i, h in enumerate(headers, 1):
        c = ws.cell(4, i, h)
        c.font = Font(bold=True, size=10, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=C_HEAD)
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
        c.border = BORDER
    ws.row_dimensions[4].height = 32
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A5"
    ws.sheet_properties.tabColor = C_TAB[tab]
    return ws

def rows(ws, data, lvcol=1, n=None):
    n = n or ws.max_column
    r = 5
    for row in data:
        for i, v in enumerate(row, 1):
            c = ws.cell(r, i, v)
            c.font = Font(size=9, bold=(i == lvcol))
            c.alignment = Alignment(wrap_text=True, vertical="top",
                                    horizontal="center" if i == lvcol else "left")
            c.border = BORDER
            if i == lvcol and str(v).startswith("L"):
                c.fill = PatternFill("solid", fgColor=C_LVFILL)
            if isinstance(v, str) and v.startswith("【要確認】"):
                c.fill = PatternFill("solid", fgColor=C_WARN)
            elif isinstance(v, str) and v.startswith("【確認済】"):
                c.fill = PatternFill("solid", fgColor=C_OK)
        r += 1
    ws.auto_filter.ref = f"A4:{get_column_letter(len(data[0]))}{r-1}"
    return ws

