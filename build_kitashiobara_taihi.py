def verify(toc):
    assert toc, "目次が読めていません"
    ch = [h for h in toc if h["level"] == 1]
    assert len(ch) == 8, f"章の数が8でない: {len(ch)}"
    pages = [h["page"] for h in toc]
    assert pages == sorted(pages), "目次のページ番号が昇順になっていません"
    assert pages[0] == 1, f"最初の章が1ページから始まっていません: {pages[0]}"

    judges = {m[4] for m in MAPPING}
    assert judges <= set(JUDGE_FILL), f"未定義の判定: {judges - set(JUDGE_FILL)}"

    # 欠落と判定した件数と、03_不足分 の件数の整合
    gap_rows = [m for m in MAPPING if m[4] == J_GAP]
    done_rows = [m for m in MAPPING if m[4] == J_DONE]
    assert len(gap_rows) == 1, f"欠落の件数が想定と異なる: {len(gap_rows)}"
    assert len(done_rows) == 3, f"反映済の件数が想定と異なる: {len(done_rows)}"
    assert os.path.exists(GAIYOU_DOCX), f"概要版が見当たりません: {GAIYOU_DOCX}"
    # 反映した3件が計画素案の目次に現れていること
    titles = "".join(h["text"] for h in toc)
    for need in ("障がい福祉サービスの体系", "用語解説"):
        assert need in titles, f"計画素案の目次に見当たりません: {need}"
    assert len(GAPS) == 6, f"不足分の件数が想定と異なる: {len(GAPS)}"

    ids = [g[0] for g in GAPS]
    assert len(ids) == len(set(ids)), "不足分の番号が重複しています"
    assert len(SPEC_ITEMS) == 8, "仕様書の記載事項が8項目でない"


def main():
    toc = load_toc(SRC_DOCX)
    total = max(h["page"] for h in toc)
    verify(toc)
    ensure_out_dir()
    wb = Workbook()
    wb.remove(wb.active)
    sheet_overview(wb, toc, total)
    sheet_toc(wb, toc, total)
    sheet_mapping(wb)
    sheet_gaps(wb)
    sheet_new(wb)
    sheet_spec(wb)
    wb.save(OUT_FILE)

    from collections import Counter
    cnt = Counter(m[4] for m in MAPPING)
    print(f"作成: {OUT_FILE}")
    print(f"  シート数: {len(wb.sheetnames)}")
    print(f"  計画素案の目次: {len(toc)}項目・推定{total}ページ")
    print(f"  新旧対照: {len(MAPPING)}件　" + "／".join(f"{k}{v}" for k, v in cnt.items()))
    print(f"  不足分: {len(GAPS)}件／新設: {len(NEW_ITEMS)}件")


if __name__ == "__main__":
    main()
