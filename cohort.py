"""コーホート変化率法の計算.

5歳階級21区分（0〜4歳から100歳以上まで）の男女別人口を受け取り、
5年後の人口を返す。

変化率の置き方
  階級a（5〜9歳から85〜89歳まで）　＝　基準年のa ÷ 5年前の(a−5歳)
  90〜94歳　＝　基準年の90〜94歳 ÷ 5年前の85〜89歳
  95〜99歳　＝　基準年の95〜99歳 ÷ 5年前の90〜94歳
  100歳以上 ＝　基準年の100歳以上 ÷ 5年前の（95〜99歳＋100歳以上）
**最後の階級は開放区間であるため、5年前の95〜99歳と100歳以上の和を分母とする。**
分母を5年前の同じ階級に採ると、その階級に入ってくる人を数えないまま
出ていく人だけを数えることになり、率が1を超えて発散する。

0〜4歳の置き方
  子ども女性比（基準年の0〜4歳 ÷ 基準年の20〜39歳女性）を固定し、
  **予測年の20〜39歳女性**に乗じる。男女別は出生性比105対100で分ける。
  基準年の20〜39歳女性に乗じると、将来の女性人口の減少を織り込まないまま
  子どもの数を置くことになる。

本モジュールは `build_member_work_review.py` と `build_cohort_review.py` の
双方が読む（同じ計算を2か所に書かない。CLAUDE.md §4）。
"""

# 出生性比（男児105・女児100）
DANJI = 105 / 205
JOJI = 100 / 205


def rates(p0, p1):
    """変化率。p0は5年前、p1は基準年の21階級の人口。"""
    r = [0.0] * 21
    for a in range(1, 18):
        r[a] = p1[a] / p0[a - 1] if p0[a - 1] else 0.0
    r[18] = p1[18] / p0[17] if p0[17] else 0.0
    r[19] = p1[19] / p0[18] if p0[18] else 0.0
    d = p0[19] + p0[20]
    r[20] = p1[20] / d if d else 0.0
    return r


def cwr(pm, pf):
    """子ども女性比（0〜4歳 ÷ 20〜39歳女性）。"""
    w = sum(pf[4:8])
    return ((pm[0] + pf[0]) / w) if w else 0.0


def step(pm, pf, rm, rf, cwm, cwf):
    """5年後の男女別人口を返す。cwm・cwfは子ども女性比に出生性比を乗じたもの。"""
    nm, nf = [0.0] * 21, [0.0] * 21
    for a in range(1, 18):
        nm[a] = pm[a - 1] * rm[a]
        nf[a] = pf[a - 1] * rf[a]
    nm[18], nf[18] = pm[17] * rm[18], pf[17] * rf[18]
    nm[19], nf[19] = pm[18] * rm[19], pf[18] * rf[19]
    nm[20] = (pm[19] + pm[20]) * rm[20]
    nf[20] = (pf[19] + pf[20]) * rf[20]
    w = sum(nf[4:8])                       # 予測年の20〜39歳女性
    nm[0], nf[0] = w * cwm, w * cwf
    return nm, nf


def agg(pm, pf, frm, to=21):
    """階級frmから階級to−1までの男女計。"""
    return sum(pm[i] + pf[i] for i in range(frm, to))
