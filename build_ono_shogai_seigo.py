def jiko():
    ng = []
    import inspect
    import re
    src = inspect.getsource(doc_build) + "".join(
        str(x) for x in (GENJO, KAKETE, IRYO_TSUKAERU, HOUREI, SHOKAI, HANEI))
    # 1 他町村を指す語がない
    for w in ("北塩原", "大雪", "金ヶ崎", "川崎町", "本村", "同村", "村内"):
        if w in src:
            ng.append("他町村を指す語がある：%s" % w)
    # 2 本町の医療圏を取り違えていない
    for w in ("本町は県北", "本町は県南", "本町は会津", "本町は相双", "本町はいわき"):
        if w in src:
            ng.append("本町の医療圏を取り違えている：%s" % w)
    # 3 欠けている計画に根拠・理由・優先がそろっている
    for x in KAKETE:
        if not (x[1].strip() and x[2].strip() and x[3].strip()):
            ng.append("欠けている計画に欠けがある：%s" % x[0])
    # 4 県計画から拾ったものに当たり先がある
    for x in IRYO_TSUKAERU:
        if not x[2].strip():
            ng.append("県計画の記述に当たり先がない：%s" % x[0])
    # 5 照会に重複がない
    nos = [x[0] for x in SHOKAI]
    if len(nos) != len(set(nos)):
        ng.append("照会番号が重複している")
    # 6 未確認の条項番号に断りを付けている
    for x in HOUREI:
        if "調和" in x[2] and "項番号" not in x[2] and "第" in x[1]:
            ng.append("調和の規定に項番号の断りがない：%s" % x[0])
    # 7 高齢者計画と同じ観点であることを書いている
    if "高齢者計画" not in src:
        ng.append("高齢者計画との対応に触れていない")
    # 8 本文に件数を手で書いていない
    for m in re.findall(r"（\d+件）|は\d+件", inspect.getsource(doc_build)):
        if "%d" not in m:
            ng.append("本文に件数を手で書いている：%s" % m)
    return ng


