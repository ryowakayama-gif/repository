def sheet_moto(wb, gl):
    ws = add_sheet(
        wb, "07_原典", "原典（手元にあるもの）",
        "本文と事例集の現物がある。"
        "本書の第2版に関する記述は、レビューの記述ではなく"
        "この原典を出所とする。",
        [16, 54, 14, 24, 46])
    r = 5
    style_header_row(ws, r, ["区分", "資料名", "頁数", "ファイル",
                             "リポジトリ内の場所"])
    r += 1
    for i, (kubun, mei, path, fname) in enumerate((
            ("本文", "障害福祉サービス等の提供に係る意思決定支援"
                     "ガイドライン（第2版）（令和8年9月）", GL,
             "001749795.pdf"),
            ("事例集", "同ガイドライン（第2版）をより理解するための事例集",
             JIREI, "001749796.pdf"))):
        r = write_row(ws, r, [kubun, mei, gl[kubun + "_頁"], fname,
                              os.path.relpath(path, REPO_ROOT)],
                      alt=(i % 2 == 1))
    r += 1
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=5)
    style_note(ws.cell(row=r, column=1),
               "レビューは概要資料（001749797.pdf）も挙げているが、"
               "当方は受領していない。本文と事例集で足りている。"
               "事例集は計画本文に転載せず、"
               "村職員の研修、相談支援専門員との打合せ、"
               "自立支援協議会の事例の検討に用いる。"
               "とくに、言葉で意思を伝えることが難しい方についても"
               "本人が会議に参加し、本人をよく知る人の情報と"
               "日々の反応を集めるという事例は、"
               "本村のように対象となる方が少数で"
               "一人ずつ積み上げる進め方と相性がよい。")
    ws.row_dimensions[r].height = 62
    return ws


