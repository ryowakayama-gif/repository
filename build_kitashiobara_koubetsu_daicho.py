def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            for c in r.cells:
                out.append(c.text)
    return "\n".join(out)


def _norm(s):
    return re.sub(r"\s+", "", str(s))


def verify():
    ng = []
    for p in (HONPON, SHOUKAI_BUN):
        if not os.path.exists(p):
            ng.append(f"原典が無い: {os.path.basename(p)}")
    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("   -", x)
        raise SystemExit(1)

    hon = _norm(load_docx(HONPON))
    sho = _norm(load_docx(SHOUKAI_BUN))
    kizon = hon.replace("M-", "Ｍ-")

    # ① 個人を特定する欄を置いていないこと。
    #    台帳は村の手元に残るものだが、様式の側で置かないようにする。
    retsumei = [r[1] for r in RETSU] + [r[0] for r in MIJUUSOKU_RETSU]
    for warui in ("氏名", "名前", "生年月日", "住所", "受給者証番号",
                  "電話", "世帯"):
        for na in retsumei:
            if warui in na:
                ng.append(f"個人を特定する欄を置いている: {na}")

    # ②「氏名を書かない」ことを記入要領に書いていること
    you = _norm("\n".join(v for rec in YOURYOU for v in rec))
    for need in ("氏名、生年月日、住所、受給者証番号の欄は置いていない",
                 "「把握していない」と「該当なし」を区別"):
        if _norm(need) not in you:
            ng.append(f"記入要領に無い: {need}")

    # ③ 台帳の列が参照する照会番号が起票済みであること
    for grp, na, _ki, _rei, _naze, shoukai, _doko in RETSU:
        for m in re.findall(r"Ｍ-\d+", shoukai):
            if m not in sho and m not in kizon:
                ng.append(f"列「{na}」が未起票の番号を参照している: {m}")
    for shoukai, kenmei, _doko in MATOMERU:
        for m in re.findall(r"Ｍ-\d+", shoukai):
            if m not in sho and m not in kizon:
                ng.append(f"まとめる照会に未起票の番号がある: {m}（{kenmei}）")

    # ④ 集計先の表が正本の現物にあること。
    #    表番号は追記のたびにずれるため、生成のたびに確かめる。
    for hyo, _sv, _how in SHUUKEI:
        if _norm(hyo) not in hon:
            ng.append(f"集計先の表が正本に無い: {hyo}")

    # ⑤ 意思決定支援の欄が第2版の用語で、正本と揃っていること
    for need in ("本人の意思、選好及び価値観", "意思と選好に基づく最善の解釈"):
        if _norm(need) not in hon:
            ng.append(f"正本に第2版の用語が無い: {need}")
    ishi = [r[1] for r in RETSU if r[0] == "本人の意思"]
    for need in ("本人の意思", "選好", "価値観", "意思の確かめ方",
                 "体験の利用", "家族の意向"):
        if need not in ishi:
            ng.append(f"本人の意思のグループに欄が無い: {need}")

    # ⑥ グループが定義どおりであること
    grp_def = ["基本", "いま受けている支援", "本人の意思", "年齢の到達",
               "必要量", "確保と制約"]
    for grp, na, *_ in RETSU:
        if grp not in grp_def:
            ng.append(f"グループが未定義: {grp}（{na}）")
    #    グループが並び替わっていないこと（結合した見出しが崩れる）
    jun = []
    for grp, *_ in RETSU:
        if not jun or jun[-1] != grp:
            jun.append(grp)
    if jun != grp_def:
        ng.append(f"グループの並びが定義と違う: {jun}")

    # ⑦ 列の名前が重複していないこと
    na_all = [r[1] for r in RETSU]
    if len(na_all) != len(set(na_all)):
        dup = [x for x in set(na_all) if na_all.count(x) > 1]
        ng.append(f"列の名前が重複している: {sorted(dup)}")

    # ⑧ 表記の作法と他団体の名前、英字の語
    zenbun = "\n".join(str(v) for g in (RETSU, YOURYOU, SHUUKEI,
                                        MATOMERU, MIJUUSOKU_RETSU)
                       for rec in g for v in rec)
    for warui in ("小野町", "金ケ崎", "金ヶ崎", "阿蘇", "札幌"):
        if warui in zenbun:
            ng.append(f"他団体の案件の地名が入っている: {warui}")
    if "か所" in zenbun and "カ所" in zenbun:
        ng.append("「か所」と「カ所」が混在している")
    if "~" in zenbun:
        ng.append("半角チルダがある")
    eiji = re.findall(r"[A-Za-zА-Яа-яЁё]{3,}", zenbun)
    if eiji:
        ng.append(f"英字等の語が残っている: {sorted(set(eiji))[:5]}")

    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("   -", x)
        return False
    print(f"  自己点検: 列{len(RETSU)}欄に個人を特定する欄が無い／"
          f"記入要領に氏名を書かないことと"
          f"「把握していない」「該当なし」の区別を明記／"
          f"列と照会の対応に未起票の番号が無い／"
          f"集計先の表{len(SHUUKEI)}点が正本の現物に実在／"
          f"意思決定支援の欄が第2版の用語で正本と一致／"
          f"グループ{len(grp_def)}区分の並び／列名の重複なし／"
          f"表記の作法")
    return True


