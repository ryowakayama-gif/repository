def xlsx_build():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "切り分け"
    HEAD = ["№", "切り分け", "区分の意味", "事項", "分野", "出所",
            "いま分かっていること／残る部分", "町にお尋ねするか"]
    W = [6, 8, 16, 42, 10, 44, 56, 14]
    ws.append(HEAD)
    fill = PatternFill("solid", fgColor="1F3864")
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF", size=10)
        c.fill = fill
        c.alignment = Alignment(vertical="center", wrap_text=True)
    for i, w in enumerate(W, 1):
        ws.column_dimensions[chr(64 + i)].width = w
    for no, k, deta, nokori in sorted(KIRIWAKE, key=lambda x: (x[1], x[0])):
        koto, _ku, bun = _koto(no)
        ws.append([no, k, KUBUN[k][0], _p(koto), bun, _p(deta), _p(nokori),
                   "要" if k == "Ⅳ" else "不要"])
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.alignment = Alignment(vertical="top", wrap_text=True)
        ws.row_dimensions[row[0].row].height = 46
    ws.freeze_panes = "A2"
    p = OUT / ("小野町_町データ待ちの切り分け_%s.xlsx" % ASOF.strftime("%Y%m%d"))
    wb.save(p)
    return p


# ---------------------------------------------------------------- 自己点検
def jiko():
    ng = []
    # 1 №が確認事項の一覧に実在する
    nos = {x[0] for x in K.KAKUNIN}
    for no, _k, _d, _n in KIRIWAKE:
        if no not in nos:
            ng.append("確認事項に無い№を挙げている：%d" % no)
    # 2 重複がない
    mine = [x[0] for x in KIRIWAKE]
    if len(mine) != len(set(mine)):
        ng.append("同じ№を2度挙げている：%s"
                  % sorted({n for n in mine if mine.count(n) > 1}))
    # 3 区分が4つのいずれか
    for no, k, _d, _n in KIRIWAKE:
        if k not in KUBUN:
            ng.append("区分が4つのいずれかでない：№%d" % no)
    # 4 確認事項のＣ・Ｄをすべて拾っている
    need = {x[0] for x in K.KAKUNIN if x[2] in ("Ｃ", "Ｄ") and x[3] != "県"}
    nukeru = need - set(mine)
    if nukeru:
        ng.append("Ｃ・Ｄ（町宛）で切り分けていないものがある：%s"
                  % sorted(nukeru))
    # 5 余計なものを拾っていない（Ａ・Ｂ・県宛を混ぜない）
    yokei = set(mine) - need
    if yokei:
        ng.append("Ｃ・Ｄ（町宛）でないものを混ぜている：%s" % sorted(yokei))
    # 6 出所と残る部分が空でない
    for no, _k, d, n in KIRIWAKE:
        if not d.strip() or not n.strip():
            ng.append("出所または残る部分が空：№%d" % no)
    # 7 取れないものに、どの事項に要るかが書いてある
    for a, b, c in TORENAI:
        if not b.strip() or not c.strip():
            ng.append("取れない資料に事項または理由がない：%s" % a)
    # 8 Ⅳ以外は「お尋ねしない」と言い切れている
    if any(k == "Ⅳ" for _no, k, _d, _n in KIRIWAKE) is False:
        ng.append("Ⅳが1件もない（切り分けが働いていない）")
    return ng


