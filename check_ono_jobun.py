RESULT = []


def _get(nm):
    """法令XMLを取る。キャッシュがあれば使う。"""
    CACHE.mkdir(parents=True, exist_ok=True)
    p = CACHE / ("%s.xml" % re.sub(r"[^\w]", "_", nm))
    if p.exists() and p.stat().st_size > 1000:
        return ET.parse(p).getroot()
    import subprocess
    url = API + urllib.parse.quote(LAWS[nm])
    r = subprocess.run(["curl", "-sS", "--max-time", "180", url, "-o", str(p)],
                       capture_output=True)
    if r.returncode != 0 or not p.exists() or p.stat().st_size < 1000:
        return None
    try:
        return ET.parse(p).getroot()
    except Exception:
        return None


def _tx(el):
    return re.sub(r"\s+", "", "".join(el.itertext()))


def _find(root, jo, ko, go):
    """条・項・号の本文を返す。見つからなければ None。"""
    for a in root.iter("Article"):
        if a.get("Num") != jo:
            continue
        for ph in a.findall("Paragraph"):
            if ph.get("Num") != ko:
                continue
            if go is None:
                return _tx(ph)
            for it in ph.findall("Item"):
                if it.get("Num") == go:
                    return _tx(it)
            return None
    return None


def main():
    roots = {}
    for nm in LAWS:
        roots[nm] = _get(nm)

    torenai = [nm for nm, r in roots.items() if r is None]
    print("■ 条文番号の原典確認（e-Gov 法令API）")
    print("   法令 %d件／引いている条項 %d件" % (len(LAWS), len(JOBUN)))
    if torenai:
        print("   **取れなかった法令：%s**" % "・".join(torenai))
        print("   取れないものは「参考」とし、NGにしません。")
    print()

    for law, jo, ko, go, words, doko in JOBUN:
        root = roots.get(law)
        joko = "第%s条第%s項%s" % (jo.replace("_", "の"), ko,
                               "第%s号" % go if go else "")
        if root is None:
            RESULT.append(("参考", law, joko, doko, "法令が取れない"))
            continue
        body = _find(root, jo, ko, go)
        if body is None:
            RESULT.append(("**NG**", law, joko, doko, "その条項が見当たらない"))
            continue
        nai = [w for w in words if w not in body]
        if nai:
            RESULT.append(("**NG**", law, joko, doko,
                           "語がない：%s" % "・".join(nai)))
        else:
            RESULT.append(("OK", law, joko, doko, body[:46]))

    last = None
    for mark, law, joko, doko, memo in RESULT:
        if law != last:
            print("── %s" % law)
            last = law
        print("   %-6s %-20s %s" % (mark, joko, doko))
        if mark != "OK":
            print("          └ %s" % memo)

    ng = [x for x in RESULT if x[0] == "**NG**"]
    sankou = [x for x in RESULT if x[0] == "参考"]
    print()
    print("   点検 %d件　OK %d／**NG %d**／参考 %d"
          % (len(RESULT), len(RESULT) - len(ng) - len(sankou), len(ng),
             len(sankou)))
    if not ng:
        print("   **引いている条・項・号は、すべて現行条文のとおりです。**")
    return ng


if __name__ == "__main__":
    sys.exit(1 if main() else 0)
