# ── 保険料の標準乗率を政令の現物と突き合わせる ─────────────────
#    法令APIは**政令・省令も返す**（令和8年10月19日に確認）。
#    13段階の乗率は介護保険法施行令第38条第1項が漢数字で定めており、
#    当方は build_ono_tanka.SHOTOKU_R7 に小数で持っている。
#    **「十分の六・八五」を 0.685 に読み替えて突き合わせる。**
_KANSU = {"〇": 0, "一": 1, "二": 2, "三": 3, "四": 4,
          "五": 5, "六": 6, "七": 7, "八": 8, "九": 9}


def _kan(s):
    """「十分の二十三」「十分の六・八五」などを小数にする。"""
    seibu, _, shosu = s.partition("・")
    n = 0
    if "十" in seibu:
        a, _, b = seibu.partition("十")
        n = (_KANSU.get(a, 1) if a else 1) * 10 + (_KANSU.get(b, 0) if b else 0)
    else:
        n = _KANSU.get(seibu, None)
        if n is None:
            return None
    v = float(n)
    for i, c in enumerate(shosu):
        if c not in _KANSU:
            return None
        v += _KANSU[c] / (10.0 ** (i + 1))
    return v / 10.0


def joritsu():
    """保険料の標準乗率13件を、介護保険法施行令第38条第1項と突き合わせる。"""
    out = []
    root = H.get("介護保険法施行令")
    if root is None:
        return [("参考", "介護保険法施行令", "―", "第38条第1項",
                 "保険料の標準乗率", "政令が取れない")]
    a = H.arts(root).get("38")
    if a is None:
        return [("**NG**", "介護保険法施行令", "―", "第38条第1項",
                 "保険料の標準乗率", "条が見当たらない")]
    rei = {}
    for it in a.findall("Paragraph")[0].findall("Item"):
        m = re.search(r"十分の([〇一二三四五六七八九十・]+)", H.tx(it))
        if m:
            rei[it.get("Num")] = _kan(m.group(1))
    import build_ono_tanka as T
    for i, (nm, hyojun, _fuka, _n) in enumerate(T.SHOTOKU_R7, start=1):
        v = rei.get(str(i))
        joko = "第38条第1項第%d号" % i
        if v is None:
            out.append(("**NG**", "介護保険法施行令", "―", joko, nm,
                        "政令から乗率を読み取れない"))
        elif abs(v - hyojun) > 1e-9:
            out.append(("**NG**", "介護保険法施行令", "―", joko, nm,
                        "政令 %.3f ／ 当方 %.3f" % (v, hyojun)))
        else:
            out.append(("OK", "介護保険法施行令", "―", joko,
                        "%s 標準割合 %.3f" % (nm, hyojun),
                        "政令のとおり"))
    if len(rei) != len(T.SHOTOKU_R7):
        out.append(("**NG**", "介護保険法施行令", "―", "第38条第1項", "段階の数",
                    "政令%d段階／当方%d段階" % (len(rei), len(T.SHOTOKU_R7))))
    return out


def main():
    jiten = {GEN: None, TEN: H.TENKI}
    need = sorted({(law, jiten[t] or "") for law, t, *_ in JOBUN})
    need = [(law, asof or None) for law, asof in need]
    roots = {}
    for law, asof in need:
        roots[(law, asof)] = H.get(law, asof)

    torenai = sorted({law for (law, _), r in roots.items() if r is None})
    print("■ 条文番号の原典確認（e-Gov 法令API v2）")
