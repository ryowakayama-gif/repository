def load_docx(path):
    doc = docx.Document(path)
    parts = []
    for ch in doc.element.body.iterchildren():
        tag = ch.tag.split("}")[-1]
        if tag == "p":
            parts.append(Paragraph(ch, doc).text)
        elif tag == "tbl":
            for row in Table(ch, doc).rows:
                seen = set()
                for c in row.cells:
                    if id(c._tc) in seen:
                        continue
                    seen.add(id(c._tc))
                    parts.append(c.text)
    return "\n".join(parts)


def verify(honpon):
    ng = []
    norm = re.sub(r"[\s　]+", "", honpon)

    # ① レビューの原文が手元にあり、本書が引いている語が実在すること
    if not os.path.exists(REVIEW):
        ng.append(f"レビューの原文が見つからない: {REVIEW}")
    else:
        with open(REVIEW, encoding="utf-8") as f:
            rv = re.sub(r"[\s　]+", "", f.read())
        for w in ("北塩原村手話言語条例", "手話出前講座", "指文字",
                  "ヘルプマーク", "ヘルプカード", "耳マーク",
                  "電話お願い手帳", "おもいやり駐車場", "つなぐ窓口",
                  "重度心身障害者医療費の受給対象者のみで構成される世帯",
                  "北塩原村障がい者活躍推進計画", "人工透析患者通院交通費助成",
                  "パラスポーツ"):
            if re.sub(r"[\s　]+", "", w) not in rv:
                ng.append(f"レビューに実在しない語を引いている: {w}")

    # ② 入れる文章が「追記できる」とした反映と1対1で対応すること
    ima = sorted(r[0] for r in SEIHON if "追記できる" in r[4])
    kaku = sorted(r["no"] for r in HP_EDITS)
    if ima != kaku:
        ng.append(f"入れる文章と追記できる反映が対応しない: {ima} ≠ {kaku}")

    # ③ 挿入位置の引用が正本に実在すること
    for rec in HP_EDITS:
        if rec["kata"] == "注記後":
            continue
        if re.sub(r"[\s　]+", "", rec["ichi"]) not in norm:
            ng.append(f"挿入位置の引用が正本にない: {rec['no']}")

    # ④ 表記の作法
    for rec in HP_EDITS:
        txt = []
        for blk in rec["nakami"]:
            if blk[0] in ("h3", "p", "note"):
                txt.append(blk[1])
            elif blk[0] == "tbl":
                txt += [str(v) for row in blk[1] for v in row]
        joined = "\n".join(txt)
        if "〜" in joined:
            ng.append(f"波ダッシュ（〜）が混じっている: {rec['no']}")
        if "か所" in joined or "ヶ所" in joined:
            ng.append(f"「カ所」に揃っていない: {rec['no']}")
        if re.search(r"令和[0-9]年", joined):
            ng.append(f"令和の1桁が半角になっている: {rec['no']}")
        if "%" in joined:
            ng.append(f"半角の％が混じっている: {rec['no']}")

    # ⑤ 「正本に0件」と書いた語が本当に0件であること（追記の前の状態）
    #    X-1〜X-6 を入れた後は実在するため、入れた語は別に確かめる
    added = ("手話言語条例", "ヘルプマーク", "ヘルプカード", "耳マーク",
             "電話お願い手帳", "つなぐ窓口", "活躍推進計画",
             "地域公共交通計画", "指文字")
    for w in added:
        if w not in honpon:
            ng.append(f"X-1〜X-6で入れたはずの語が正本にない: {w}")
    #    まだ入れていない語
    for w in ("おもいやり駐車場", "パラスポーツ", "きになる"):
        if w in honpon:
            ng.append(f"まだ入れていない語が正本に実在する: {w}")

    # ⑥ 照会番号が既存（M-58まで）と重ならないこと
    for rec in SHOUKAI:
        if int(rec[0].split("-")[1]) <= 58:
            ng.append(f"照会番号が既存と重なる: {rec[0]}")

    # ⑦ 12重点施策が12件そろっていること
    if [r[0] for r in SETSUZOKU12] != [str(i) for i in range(1, 13)]:
        ng.append("12重点施策との接続が1〜12でない")

    # ⑧ URLはすべて村又は公式の動画のものであること
    for _name, url in URLS:
        if not (url.startswith("https://www.vill.kitashiobara.fukushima.jp")
                or url.startswith("https://www.youtube.com/@kitashiobara")):
            ng.append(f"村のもの以外のURLが混じっている: {url}")

    # ⑨ 他団体の名を出さない
    joined = "\n".join(
        "".join(str(x) for x in rec)
        for grp in (BUNYA, SHUWA, SHUWA_HYOKA, HAIRYO, IDOU_TSUIN, SHURO,
                    SETSUZOKU12, SEIHON, SHOUKAI)
        for rec in grp)
    for bad in ("小野町", "金ヶ崎", "阿蘇", "札幌"):
        if bad in joined:
            ng.append(f"他団体名が含まれている: {bad}")

    if ng:
        print("自己点検 不合格:")
        for e in ng:
            print("   -", e)
        raise SystemExit(1)
    print(f"  自己点検: レビューの原文と13語を照合／"
          f"入れる文章{len(HP_EDITS)}件の挿入位置が正本に実在／"
          f"入れた{len(added)}語・まだ入れていない3語を照合／"
          f"照会{len(SHOUKAI)}件が既存と重複なし／URL{len(URLS)}件が村のもの")


