def selfcheck():
    bad = []
    if OUR_GETSU != 6048:
        bad.append(f"当方の算定 {OUR_GETSU}≠6048")
    if SYS_GETSU != 6533:
        bad.append(f"システム {SYS_GETSU}≠6533")
    if ceil100(our_getsu()) != 6100:
        bad.append(f"A-1の切上げ {ceil100(our_getsu())}≠6100")
    if ceil100(sys_getsu()) != DAI9:
        bad.append(f"B-1の切上げ {ceil100(sys_getsu())}≠{DAI9}")
    # 第9期の年額は基準額6,600円×12＝79,200円
    if ceil100(79200 * 1.0) != 79200:
        bad.append("第5段階の年額")
    if len(KETTEI) != 11:
        bad.append(f"決定事項 {len(KETTEI)}件")
    if len(SHIRYO) != 21:
        bad.append(f"依頼資料 {len(SHIRYO)}件")
    if len(HAIFU) != 17:
        bad.append(f"配布資料 {len(HAIFU)}件")
    # 依頼資料・配布資料の番号が1から通しで並んでいること
    for nm, seq in (("依頼資料", [r[0] for r in SHIRYO]),
                    ("配布資料", [r[0] for r in HAIFU])):
        if seq != [str(i) for i in range(1, len(seq) + 1)]:
            bad.append(f"{nm}の番号の並び {seq}")
    # 配布資料一覧に挙げたファイルが実在すること
    have = {p.name for p in (ROOT / "小野町_引継ぎ_整理済").rglob("*") if p.is_file()}
    for _no, nm, _d, _m in HAIFU:
        if nm.endswith((".docx", ".xlsx")) and nm not in have:
            bad.append(f"配布資料が見当たらない {nm}")
    fun = sum(int(c.replace("**", "").replace("分", "")) for _a, _b, c, _d in SHIDAI)
    if fun != 90:
        bad.append(f"次第の時間配分 {fun}分≠90分")
    return bad


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    bad = selfcheck()
    ps = [build_shidai(), build_honbun(), build_xlsx(), build_kiroku()]
    print("出力:")
    for p in ps:
        print("  ", p)
    print(f"  保険料 A-1 {our_getsu():,.0f}円（切上げ{ceil100(our_getsu()):,}円）"
          f"／B-1 {sys_getsu():,.0f}円（切上げ{ceil100(sys_getsu()):,}円）")
    print(f"  決めていただきたいこと {len(KETTEI)}件"
          f"／いただきたい資料 {len(SHIRYO)}件"
          f"／配布資料 {len(HAIFU)}件")
    print(f"  自己点検 {'OK' if not bad else 'NG: ' + ' / '.join(bad)}")


if __name__ == "__main__":
    main()
