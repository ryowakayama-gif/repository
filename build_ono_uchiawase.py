SYS_HOSEI, SYS_SHUNO = 10234.69, 0.994
SYS_WARI = 190982.0 / (SYS_STD3 + SYS_SOGO3)


def ceil100(v):
    return -(-int(round(v)) // 100) * 100


def sys_getsu(kikin=0, futan=T.FUTAN_WARIAI):
    """システムの前提による保険料基準額（月額）。"""
    need = ((SYS_STD3 + SYS_CHI3) * futan + (SYS_STD3 + SYS_SOGO3) * T.CHOSEI_SOTO
            - (SYS_STD3 + SYS_SOGO3) * SYS_WARI - kikin)
    return need / SYS_SHUNO * 1000 / SYS_HOSEI / 12


def our_getsu(**kw):
    return T.premium(**OUR3, **kw)["月額"]


