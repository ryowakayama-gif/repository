def new_doc():
    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = JP_MIN
    st.font.size = Pt(10.5)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), JP_MIN)
    for name, size in (("Heading 1", 14), ("Heading 2", 12), ("Heading 3", 11)):
        s = doc.styles[name]
        s.font.name = JP_GO
        s.font.size = Pt(size)
        s.font.bold = True
        s.font.color.rgb = None
        s.element.rPr.rFonts.set(qn("w:eastAsia"), JP_GO)
    return doc


def title(doc, main, subs):
    for _ in range(6):
        doc.add_paragraph()
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(main)
    r.font.size = Pt(20)
    r.font.bold = True
    r.font.name = JP_GO
    r.element.rPr.rFonts.set(qn("w:eastAsia"), JP_GO)
    doc.add_paragraph()
    for s in subs:
        q = doc.add_paragraph()
        q.alignment = WD_ALIGN_PARAGRAPH.CENTER
        rr = q.add_run(s)
        rr.font.size = Pt(12)
        rr.font.name = JP_GO
        rr.element.rPr.rFonts.set(qn("w:eastAsia"), JP_GO)


def chapter(doc, text):
    doc.add_page_break()
    doc.add_heading(text, level=1)


def table(doc, header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for c, h in zip(t.rows[0].cells, header):
        c.text = ""
        r = c.paragraphs[0].add_run(h)
        r.font.bold = True
        r.font.size = Pt(9)
        r.font.name = JP_GO
        r.element.rPr.rFonts.set(qn("w:eastAsia"), JP_GO)
    for row in rows:
        for c, v in zip(t.add_row().cells, row):
            c.text = ""
            r = c.paragraphs[0].add_run(str(v))
            r.font.size = Pt(9)
    return t


def bullets(doc, items):
    for it in items:
        p = doc.add_paragraph(it, style="List Bullet")
        p.paragraph_format.space_after = Pt(0)


def note(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(9)
    r.italic = True
    return p


def lead(doc, text):
    """設問の所見（見出し直下の要約文）。"""
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(10.5)
    return p


