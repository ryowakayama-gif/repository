BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)


def sheet(wb, name, header, rows, widths, status_col=None, wrap_cols=()):
    ws = wb.create_sheet(name)
    ws.append(header)
    for c in ws[1]:
        c.font = Font(bold=True, size=9)
        c.fill = HEAD
        c.border = BORDER
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="center")
    for r in rows:
        ws.append(list(r))
    for row in ws.iter_rows(min_row=2):
        for i, c in enumerate(row):
            c.font = Font(size=9)
            c.border = BORDER
            c.alignment = Alignment(wrap_text=(i in wrap_cols), vertical="top")
        if status_col is not None and len(row) > status_col:
            v = row[status_col].value
            if v in ST:
                row[status_col].fill = PatternFill("solid", fgColor=ST[v])
                row[status_col].alignment = Alignment(horizontal="center", vertical="center")
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    return ws


