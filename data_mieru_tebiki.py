def _no_pi():
    import re
    blob = _flat([GENTEN, KINOU, SHIN, RADAR, JIGYO_KOUMOKU, JIGYO_SHIKI,
                  JIGYO_KUBUN, JIGYO_SEIYAKU, JUNRO, KENGEN, SUIKEI_NAGARE,
                  JINKO_SOURCE, NOBI_POINT, SHISAKU_KANTEN, HOKENRYO_KOMOKU,
                  TEIGI, OSHIRASE])
    return not (re.search(r"0\d{1,3}[-(]\d{2,4}[-)]\d{4}", blob)
                or re.search(r"[\w.+-]+@[\w-]+\.[\w.-]+", blob))


def _no_val():
    """当広域連合の値（人数・円）を収めていないこと。

    「1人あたり」「1月あたり」は単位の言い方であって値ではないため、
    桁区切りのある数と3桁以上の人数・金額の形で探す。
    """
    import re
    blob = _flat([SHIN, JIGYO_KOUMOKU, TEIGI, RADAR, JIGYO_SHIKI])
    return not (re.search(r"[0-9]{1,3}(,[0-9]{3})+", blob)
                or re.search(r"[0-9]{3,}\s*(人|円)", blob))


def _flat(x):
    if isinstance(x, str):
        return x + "\n"
    if isinstance(x, dict):
        return "".join(_flat(k) + _flat(v) for k, v in x.items())
    if isinstance(x, (list, tuple)):
        return "".join(_flat(v) for v in x)
    return ""


