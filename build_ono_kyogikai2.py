def selfcheck(kh, kouho_):
    ok, ng = [], []

    def chk(no, name, kitai, kekka):
        (ok if kitai == kekka else ng).append((no, name, str(kitai),
                                               str(kekka)))

    # 1 保険料の2案が算定値と整合
    chk("1a", "案1が算定値の100円未満切上げ",
        _ceil100(BASE["月額"]), int(kh[0][1].replace("**", "").replace(",", "")
                                   .replace("円", "")))
    chk("1b", "案2が第9期の基準額", T.DAI9_KIJUN,
        int(kh[1][1].replace("**", "").replace(",", "").replace("円", "")))

    # 2 標準給付費・地域支援事業費が成果品②と同じ
    chk("2a", "標準給付費 3年計", round(STD3), round(sum(A["標準給付費"])))
    chk("2b", "保険料基準額（取崩なし）", round(BASE["月額"]),
        round(T.premium(STD3, CHI3, SOGO3, POP3)["月額"]))

    # 3 開催日の候補が納期より前
    nk = datetime.date.fromisoformat(K.NOUKI_E)
    for r in kouho_:
        chk(f"3-{r['案']}", f"案{r['案']}の第2回が納期より前", True,
            r["期限"] < nk)

    # 4 候補日が土日に落ちていない
    chk("4", "候補日が土日", 0,
        sum(1 for r in kouho_ if r["期限"].weekday() >= 5))

    # 5 お諮りする決定事項が打合せ資料に実在する
    nos = {str(k[0]) for k in KETTEI}
    for n in GIDAI_KETTEI:
        chk(f"5-{n}", f"決定{n}が打合せ資料にある", True, str(n) in nos)

    # 6 骨子の章立てが素案と一致（素案を直せば本資料も変わる）
    name, mid = soan_midashi()
    sho = [k for k in mid if k.startswith("第")]
    chk("6", "素案の章数", 6, len(sho))

    # 7 認定者数の見込みが算定モジュールと一致
    chk("7", "令和11年度の認定者数", T.NINTEI_EST["令和11年度"],
        T.NINTEI_EST[NEN[-1]])

    return ok, ng, name


