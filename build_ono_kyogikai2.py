    out = []
    for mark, kaigi_n, pdays in K.CASE_E:
        g = K.gyakusan(K.NOUKI_E, K.chain_e(kaigi_n, pdays))
        d = next(x for nm, x, _y in g if "協議会 第2回" in nm)
        nakami = next(nm for nm, _x, _y in g if "協議会 第2回" in nm)
        out.append({"案": mark, "協議会": kaigi_n, "印刷日数": pdays,
                    "期限": d, "議題": nakami.split("（")[-1].rstrip("）")})
    return out


