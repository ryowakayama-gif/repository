# 図の種類ごとの、数値の並びの形
#   単一系列  vals            ＝ カテゴリごとの値
#   複数系列  series／segs    ＝ （系列名, 値の並び）の組
#   棒＋折れ線 bar_vals＋line_series
KATA = {"line": "series", "bars": "series", "stackbar": "segs",
        "stackh": "segs", "hbars": "vals", "barline": "barline"}


def by_name():
    return {d["name"]: d for d in ZU}


def cats_of(d):
    """カテゴリ（横軸又は縦軸の項目名）を返す。"""
    return list(d.get("xs") or d.get("cats") or [])


def series_of(d):
    """（系列名, 値の並び）の一覧を返す。単一系列の図は系列名を空とする。"""
    k = KATA[d["kind"]]
    if k == "vals":
        return [("", list(d["vals"]))]
    if k == "barline":
        return ([(d["bar_label"], list(d["bar_vals"]))]
                + [(n, list(v)) for n, v in d["line_series"]])
    return [(n, list(v)) for n, v in d[k]]


def put_series(d, sers):
    """series_of と同じ並びの値を書き戻す。"""
    k = KATA[d["kind"]]
    if k == "vals":
        d["vals"] = list(sers[0][1])
    elif k == "barline":
        d["bar_vals"] = list(sers[0][1])
        d["line_series"] = [(n, list(v)) for n, v in sers[1:]]
    else:
        d[k] = [(n, list(v)) for n, v in sers]
    return d


def _book_path():
    import repo_paths as RP
    return RP.ROOT + BOOK


def read_book(path=None):
    """台帳のデータシートから {図の名: [(系列名, 値の並び), ...]} を読む。

    データシートは 5 行目が見出し（A 列＝カテゴリ、B 列以降＝系列）、
    6 行目から A 列が空になるまでが数値である。
    空のセルは None として返す（0 と区別する）。
    """
    path = path or _book_path()
    if not os.path.exists(path):
        return {}
    from openpyxl import load_workbook
    wb = load_workbook(path, read_only=True, data_only=True)
    got = {}
    names = set(by_name())
    for sn in wb.sheetnames:
        nm = sn[2:] if sn.startswith("D_") else sn
        if nm not in names:
            continue
        ws = wb[sn]
        rows = [list(r) for r in ws.iter_rows(min_row=5, values_only=True)]
        if not rows:
            continue
        head = rows[0]
        ncol = sum(1 for v in head[1:] if v not in (None, "")) 
        body = []
        for r in rows[1:]:
            if r[0] in (None, ""):
                break
            body.append(r)
        if not body or ncol == 0:
            continue
        got[nm] = [(head[1 + i], [r[1 + i] for r in body]) for i in range(ncol)]
    wb.close()
    return got


def load(use_book=True, path=None):
    """作図に渡す図の定義の一覧を返す。台帳の数値があればそれを優先する。"""
    import copy
    zu = copy.deepcopy(ZU)
    if not use_book:
        return zu
    got = read_book(path)
    if not got:
        return zu
    for d in zu:
        s = got.get(d["name"])
        if not s:
            continue
        base = series_of(d)
        if len(s) != len(base) or any(len(v) != len(base[i][1]) for i, (_, v) in enumerate(s)):
            # 行数・列数が変わっているときは読み戻さない（形が合わないため）
            continue
        # 系列名は ZU の側を正とし、数値のみを差し替える
        put_series(d, [(base[i][0], v) for i, (_, v) in enumerate(s)])
    return zu
