SOAN_DIR = pathlib.Path(__file__).parent / "小野町_引継ぎ_整理済" / "03_計画素案"
SOAN_NAME = "―"


def soan_kosei():
    """生成した計画素案の docx から、章（h1）と節（h2）を拾う。

    **骨子案と素案で構成を別々に書かない。**
    片方を直したときにもう片方が古いまま残るためである。
    素案が無ければ止める（古い構成を黙って出さない）。
    """
    global SOAN_NAME
    # **版の番号ではなく末尾の日付で並べる。** 名前で並べると
    # 「第10版」が「第9版」より前に来るため（'1' < '9'）、
    # 最後の要素を取ると古い版を拾う。
    def _hiduke(p):
        m = re.search(r"_(\d{8})\.docx$", p.name)
        return (m.group(1) if m else "", p.name)

    cands = sorted(SOAN_DIR.glob("*第10期介護保険事業計画_素案_*.docx"),
                   key=_hiduke)
    if not cands:
        raise SystemExit(
            f"計画素案が見つかりません：{SOAN_DIR}\n"
            "先に python3 build_ono_soan_elderly.py を実行してください。")
    path = cands[-1]
    SOAN_NAME = path.name
    d = Document(path)
    out, cur = [], None
    for q in d.paragraphs:
        t = q.text.strip()
        if not t or t.startswith(("【", "※", "資料：")):
            continue
        sz = max((r.font.size.pt for r in q.runs if r.font.size), default=0)
        bold = any(r.bold for r in q.runs)
        if not bold:
            continue
        # 章は H1（15pt）。表紙は22pt、基本理念の掲出は16pt なので上限を切る。
        # 「第」で始まるだけでは表紙の「第10期介護保険事業計画」を拾ってしまう。
        if 15 <= sz < 16 and (re.match(r"^第\d+章　", t) or t == "資料編"
                              or t.startswith("参考")):
            cur = (t, [])
            out.append(cur)
        elif cur is not None and 12 <= sz < 15:
            cur[1].append(t)
    out = [(c, se) for c, se in out if se]

    # ---- 自己点検 ----------------------------------------------------
    # 骨子案の目次構成が素案とずれていないことを、生成の前に確かめる。
    ng = []
    sho = [c for c, _ in out if re.match(r"^第\d+章　", c)]
    if len(sho) < 6:
        ng.append(f"章が{len(sho)}しか拾えていません（素案は6章構成）")
    for i, c in enumerate(sho, start=1):
        if not c.startswith(f"第{i}章　"):
            ng.append(f"章の通し番号が飛んでいます：{i}番目が「{c}」")
    for c, se in out:
        if len(se) != len(set(se)):
            ng.append(f"「{c}」の節に重複があります")
    bad = [c for c, _ in out
           if not (re.match(r"^第\d+章　", c) or c == "資料編"
                   or c.startswith("参考"))]
    if bad:
        ng.append("章でないものが混ざっています：" + "／".join(bad))
    if ng:
        raise SystemExit("素案の構成の読み取りに問題があります：\n  - "
                         + "\n  - ".join(ng))
    return out


