def new_doc(main, subs):
    doc = S.Report(main)
    doc.cover([main], subs)
    doc.toc_here()
    doc.body_here()
    return doc


def body(doc, *texts):
    for t in texts:
        doc.p(t)


def bullets(doc, items):
    for it in items:
        doc.bul(it)


def table(doc, header, rows, widths=None, caption=None, right=()):
    return doc.tbl([list(header)] + [list(r) for r in rows],
                   widths=widths, caption=caption, right=right)


def note(doc, text):
    doc.src(text)


