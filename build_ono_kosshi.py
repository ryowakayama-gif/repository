def new_doc():
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = JP_FONT
    style.font.size = Pt(10.5)
    style.element.rPr.rFonts.set(qn("w:eastAsia"), JP_FONT)
    for name, size, bold in (("Heading 1", 14, True), ("Heading 2", 12, True), ("Heading 3", 11, True)):
        s = doc.styles[name]
        s.font.name = JP_GOTHIC
        s.font.size = Pt(size)
        s.font.bold = bold
        s.font.color.rgb = None
        s.element.rPr.rFonts.set(qn("w:eastAsia"), JP_GOTHIC)
    return doc


def title(doc, main, subs=()):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(main)
    r.font.size = Pt(18)
    r.font.bold = True
    r.font.name = JP_GOTHIC
    r.element.rPr.rFonts.set(qn("w:eastAsia"), JP_GOTHIC)
    for s in subs:
        q = doc.add_paragraph()
        q.alignment = WD_ALIGN_PARAGRAPH.CENTER
        rr = q.add_run(s)
        rr.font.size = Pt(12)
        rr.font.name = JP_GOTHIC
        rr.element.rPr.rFonts.set(qn("w:eastAsia"), JP_GOTHIC)


def body(doc, text):
    return doc.add_paragraph(text)


def bullets(doc, items):
    for it in items:
        p = doc.add_paragraph(it, style="List Bullet")
        p.paragraph_format.space_after = Pt(0)


def table(doc, header, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(header))
    t.style = "Table Grid"
    for c, h in zip(t.rows[0].cells, header):
        c.text = ""
        r = c.paragraphs[0].add_run(h)
        r.font.bold = True
        r.font.size = Pt(9.5)
        r.font.name = JP_GOTHIC
        r.element.rPr.rFonts.set(qn("w:eastAsia"), JP_GOTHIC)
    for row in rows:
        cells = t.add_row().cells
        for c, v in zip(cells, row):
            c.text = ""
            r = c.paragraphs[0].add_run(str(v))
            r.font.size = Pt(9.5)
    return t


def note(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(9)
    r.italic = True
    return p


