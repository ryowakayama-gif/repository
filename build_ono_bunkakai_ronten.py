def _n(s):
    return unicodedata.normalize("NFKC", re.sub(r"\s+", "", s))


_PG = {}


def page(key, no):
    k = (key, no)
    if k not in _PG:
        r = subprocess.run(["pdftotext", "-f", str(no), "-l", str(no), "-layout",
                            str(KOKU / GENTEN[key][0]), "-"], capture_output=True, text=True)
        _PG[k] = _n(r.stdout) if r.returncode == 0 else None
    return _PG[k]


def docx_txt(path):
    import docx
    d = docx.Document(str(path))
    t = [p.text for p in d.paragraphs]
    for tb in d.tables:
        for rw in tb.rows:
            t += [c.text for c in rw.cells]
    return _n("\n".join(t))


def sokutei():
    tx = {k: docx_txt(p) for k, p in SOAN.items()}
    res = {}
    for x in RONTEN:
        res[x[0]] = {k: {w: tx[k].count(_n(w)) for w in ws} for k, (ws, _e) in x[4].items()}
    return res


def jiko(soku):
    ng = []
    for x in KAKUNIN + RONTEN:
        refs = x[4] if len(x) == 5 else x[3]
        for key, no, ws in refs:
            t = page(key, no)
            if t is None:
                ng.append("%s：原典が読めない（%s %d頁）" % (x[0], key, no))
                continue
            for w in ws:
                if _n(w) not in t:
                    ng.append("%s：%s %d頁に「%s」がない" % (x[0], key, no, w))
    for x in RONTEN:
        for k, (ws, ex) in x[4].items():
            tot = sum(soku[x[0]][k].values())
            if ex == ">0" and any(v == 0 for v in soku[x[0]][k].values()):
                ng.append("%s：%s素案に記載ありとしたが出ない語がある %s" % (x[0], k, soku[x[0]][k]))
            if ex == "==0" and tot:
                ng.append("%s：%s素案に記載なしとしたが語が出る %s" % (x[0], k, soku[x[0]][k]))
    for c in CHO:
        if c[2] not in {x[0] for x in RONTEN}:
            ng.append("確かめること%s：論点%sがない" % (c[0], c[2]))
    return ng


