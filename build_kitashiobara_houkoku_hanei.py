def paras(path):
    return [p.text for p in Document(path).paragraphs]


def honbun(path):
    """全文（段落＋表のセル）。所在が分かる形で返す。"""
    d = Document(path)
    out = [("P%d" % i, p.text) for i, p in enumerate(d.paragraphs)]
    for ti, t in enumerate(d.tables):
        for ri, r in enumerate(t.rows):
            for ci, c in enumerate(r.cells):
                out.append(("T%d.%d.%d" % (ti, ri, ci), c.text))
    return out


def sunpou(path):
    """段落数・表数・図数・変更履歴・コメントの有無。"""
    d = Document(path)
    z = zipfile.ZipFile(path)
    x = z.read("word/document.xml").decode("utf-8")
    med = [n for n in z.namelist() if n.startswith("word/media/")]
    komento = "word/comments.xml" in z.namelist()
    z.close()
    return dict(dan=len(d.paragraphs), hyo=len(d.tables), zu=len(med),
                ins=x.count("<w:ins "), dele=x.count("<w:del "),
                komento=komento)


def sabun():
    """旧版と新版の段落の差のかたまり。差を書き写さず機械で取る。"""
    a, b = paras(KYU), paras(SHIN)
    sm = difflib.SequenceMatcher(a=a, b=b, autojunk=False)
    out = []
    for tag, i1, i2, j1, j2 in sm.get_opcodes():
        if tag == "equal":
            continue
        out.append(dict(tag=tag, kyu=[t for t in a[i1:i2] if t.strip()],
                        shin=[t for t in b[j1:j2] if t.strip()],
                        kyu_i=i1, shin_i=j1))
    return out


def genko_pages():
    """現行計画の頁ごとの文字（空白と改行を落としたもの）。"""
    with pdfplumber.open(GENKO) as pdf:
        return {i + 1: (p.extract_text() or "").replace("\n", "").replace(
            " ", "") for i, p in enumerate(pdf.pages)}


def pdf_zenbun(path):
    """ＰＤＦの全文（空白・改行を落としたもの）。

    原典は行の途中で改行するため、そのままでは語を探せない。
    """
    with pdfplumber.open(path) as pdf:
        t = "".join((p.extract_text() or "") for p in pdf.pages)
    return re.sub(r"[\s　]+", "", t)


def terasu(rows, keys):
    """正本の全文に照合語（すべて同じ段落・セル）があるか。所在を返す。"""
    if not keys:
        return []
    return [loc for loc, t in rows if all(k in t for k in keys)]


def shozai(rows, keys):
    """代表の所在を1つ返す。目次の行（タブと頁番号を含む）は避ける。

    目次にも表題が出るため、最初に当たった行が目次だと
    本文のどこにあるかが分からない。
    """
    hit = [(loc, t) for loc, t in rows if keys and all(k in t for k in keys)]
    if not hit:
        return "無"
    honbun_hit = [loc for loc, t in hit if "\t" not in t]
    daihyo = honbun_hit[0] if honbun_hit else hit[0][0]
    return f"{daihyo}（{len(hit)}）"


