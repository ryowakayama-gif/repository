def verify():
    ng = []
    for p in (KYU, SHIN, GENKO):
        if not os.path.exists(p):
            raise SystemExit(f"受領した資料が見つかりません: {p}")

    kyu_t = "\n".join(paras(KYU))
    shin_t = "\n".join(paras(SHIN))

    # ① 新版が旧版と別のものであること（差し替え忘れに気づく）
    if kyu_t == shin_t:
        ng.append("新版と旧版の本文が同一である")

    # ② 変更履歴とコメントが0件であること
    #    （履歴が付いて届くようになれば、この検査で気づいて読み方を変える）
    kb = sunpou(SHIN)
    if kb["ins"] or kb["dele"] or kb["komento"]:
        ng.append("新版に変更履歴又はコメントがある。"
                  "差分ではなく履歴から読むべきである"
                  f"（挿入{kb['ins']}・削除{kb['dele']}・"
                  f"コメント{kb['komento']}）")

    # ③ 直し残しの語が新版にあり、旧版に無いこと。
    #    もとの文は旧版にあること。
    for no, _basho, _bun, bad, good, _naosu in FUBI:
        if bad not in shin_t:
            ng.append(f"{no} 壊れている語が新版に無い: {bad}")
        if bad in kyu_t:
            ng.append(f"{no} 壊れている語が旧版にもある（今回の改訂で"
                      f"入ったものではない）: {bad}")
        if good is not None and good not in kyu_t:
            ng.append(f"{no} もとの文が旧版に無い: {good}")

    # ④ 直し残しが差のかたまりの中にあること
    #    （差分と一覧が離れていないこと）
    sa = sabun()
    sa_shin = "\n".join("\n".join(d["shin"]) for d in sa)
    for no, _b, _bu, bad, _g, _n in FUBI:
        if bad not in sa_shin:
            ng.append(f"{no} 壊れている語が差のかたまりの中に無い: {bad}")

    # ⑤ 第6章の項目の判定と、正本の照合の結果が食い違わないこと
    rows = honbun(HONPON) if os.path.exists(HONPON) else []
    sr_no = {r["no"] for r in SR_EDITS}
    if rows:
        for no, _basho, _naka, keys, hantei, sr, _memo in HR_ITEM:
            if hantei == KAIZEN:
                if keys is not None:
                    ng.append(f"{no} 改善に照合語を付けている")
                continue
            if keys is None:
                ng.append(f"{no} 照合語が無い")
                continue
            aru = bool(terasu(rows, keys))
            if hantei in (MOTO, HANEI, MODOSU) and not aru:
                ng.append(f"{no} 判定は「{hantei}」だが正本に無い: "
                          f"{'＋'.join(keys)}")
            if hantei == SHOUKAI_K and aru:
                ng.append(f"{no} 判定は「照会」だが正本にある: "
                          f"{'＋'.join(keys)}")
            if hantei == HANEI and sr not in sr_no:
                ng.append(f"{no} 判定は「反映済み」だがＳＲ番号が無い: {sr}")
            if hantei != HANEI and sr:
                ng.append(f"{no} 反映済み以外にＳＲ番号を書いている: {no}")
    else:
        print("  ※ 正本が無いため⑤⑥は省略")

    # ⑥ 前期計画の突合
    #    見出しと照合語が当該頁に実在すること（照合語を作っていないこと）。
    #    判定と照合の結果が食い違わないこと。
    pages = genko_pages()
    for pg, _bun, mido, keys, hantei, sr, memo in MAE_TORIKUMI:
        t = pages.get(pg, "")
        if mido.replace(" ", "") not in t:
            ng.append(f"前期計画の見出しが頁に無い: p{pg} {mido}")
        for k in keys:
            if k not in t:
                ng.append(f"照合語が前期計画の頁に無い: p{pg} {mido} / {k}")
        if not rows:
            continue
        aru = bool(terasu(rows, keys))
        if hantei in (HIKITSUGI, OGINAU) and not aru:
            ng.append(f"p{pg} {mido} の判定は「{hantei}」だが正本に無い")
        if hantei in (IIKAE, KEIZOKU) and aru:
            ng.append(f"p{pg} {mido} の判定は「{hantei}」だが正本にある")
        if hantei == OGINAU and sr not in sr_no:
            ng.append(f"p{pg} {mido} の判定は「本計画で補った」だが"
                      f"ＳＲ番号が無い: {sr}")
        if hantei == IIKAE:
            #   言い換えで引き継いだとするものは、
            #   正本での所在の語が実在すること。
            if not sr or not terasu(rows, [sr]):
                ng.append(f"p{pg} {mido} の言い換えの語が正本に無い: {sr}")
        if hantei in (HIKITSUGI,) and memo:
            ng.append(f"p{pg} {mido} 引継ぎ済みに備考を書いている")
        if hantei in (IIKAE, OGINAU, KEIZOKU) and not memo:
            ng.append(f"p{pg} {mido} の理由が空")

    # ⑥b 「戻」の裏づけを原典で取ること。
    #     正本の書き方が国の基本指針（告示本文）にあり、
    #     報告書の書き方が同じ告示本文に無いこと。
    #     報告書の書き方は報告書の新版に実在すること。
    #     あわせて、報告書の書き方が前期計画にあることを確かめる
    #     （報告書が前期計画に合わせたという読みの裏づけ）。
    modosu = [r for r in HR_ITEM if r[4] == MODOSU]
    if sorted(x[0] for x in modosu) != sorted(MODOSU_KAKI):
        ng.append("「戻」と報告書の書き方の一覧が1対1でない: "
                  f"{sorted(x[0] for x in modosu)} ≠ "
                  f"{sorted(MODOSU_KAKI)}")
    if os.path.exists(KOKUJI):
        k = pdf_zenbun(KOKUJI)
        g = pdf_zenbun(GENKO)
        for no, _b, _n, keys, _h, _s, _m in modosu:
            kaki = MODOSU_KAKI.get(no)
            for key in (keys or []):
                if key not in k:
                    ng.append(f"{no} 正本の書き方が基本指針の告示本文に"
                              f"無い（「戻」と言えない）: {key}")
            if not kaki:
                continue
            if kaki in k:
                ng.append(f"{no} 報告書の書き方が基本指針の告示本文に"
                          f"ある（「戻」の判定を見直すこと）: {kaki}")
            if kaki not in shin_t:
                ng.append(f"{no} 報告書の書き方が新版に無い: {kaki}")
            if kaki not in g:
                ng.append(f"{no} 報告書の書き方が前期計画にも無い"
                          f"（報告書が前期計画に合わせたという読みが"
                          f"崩れる）: {kaki}")
    else:
        print("  ※ 基本指針の告示本文が無いため⑥bは省略")

    # ⑦ 反映の挿入位置が正本にちょうど1つあること
    if rows:
        dan = [t for loc, t in rows if loc.startswith("P")]
        for rec in SR_EDITS:
            n = sum(1 for t in dan if rec["ichi"] in t)
            if n != 1:
                ng.append(f"{rec['no']} の挿入位置が{n}件（1件でない）: "
                          f"{rec['ichi'][:40]}")
            for blk in rec["nakami"]:
                if blk[0] not in ("p", "h2", "h3", "note", "tbl"):
                    ng.append(f"{rec['no']} ブロックの型が未定義: {blk[0]}")

    # ⑧ 照会の番号が重複せず、宛先と期限が入っていること
    sno = [x[0] for x in SHOUKAI]
    if len(sno) != len(set(sno)):
        ng.append(f"照会の番号に重複がある: {sno}")
    for no, ate, ken, naka, kigen in SHOUKAI:
        if ate not in ("村", "他メンバー"):
            ng.append(f"{no} 宛先が未定義: {ate}")
        if not ken.strip() or not naka.strip() or not kigen.strip():
            ng.append(f"{no} 件名・内容・期限のいずれかが空")

    # ⑨ 他団体の名が入っていないこと
    zen = "\n".join(
        str(v) for rec in (FUBI + HR_ITEM + MAE_TORIKUMI) for v in rec
        if isinstance(v, str))
    zen += "\n" + "\n".join(str(v) for rec in SHOUKAI for v in rec)
    zen += "\n" + "\n".join(
        str(rec["konkyo"]) + "".join(b[1] for b in rec["nakami"]
                                     if isinstance(b[1], str))
        for rec in SR_EDITS)
