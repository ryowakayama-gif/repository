def nintei(y, sc=2, adj75=1.0):
    v = 0.0
    for c in CL:
        p = pop(c, y) * (adj75 if c in ("75-84", "85+") else 1.0)
        v += p * rate(c, y, sc) / 100
    return v


def pop65(y, adj75=1.0):
    return sum(pop(c, y) * (adj75 if c in ("75-84", "85+") else 1.0)
               for c in CL)


