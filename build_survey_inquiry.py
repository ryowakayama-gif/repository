def sheet(name, title, subtitle, widths, freeze="A5"):
    ws = wb.create_sheet(name)
    ws.sheet_view.showGridLines = False
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w
    c = ws.cell(row=1, column=1, value=title)
    c.font = Font(name=FONT, size=14, bold=True, color=NAVY)
    ws.row_dimensions[1].height = 22
    c = ws.cell(row=2, column=1, value=subtitle)
    c.font = Font(name=FONT, size=9)
    c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=len(widths))
    ws.row_dimensions[2].height = 52
    ws.freeze_panes = freeze
    return ws


def header(ws, row, cols, height=32):
    for i, v in enumerate(cols, start=1):
        c = ws.cell(row=row, column=i, value=v)
        c.font = Font(name=FONT, size=9, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=HEAD)
        c.alignment = Alignment(horizontal="center", vertical="center",
                                wrap_text=True)
        c.border = BORDER
    ws.row_dimensions[row].height = height
    return row + 1


def body(ws, row, vals, fills=None, height=22, align=None, bold=False):
    for i, v in enumerate(vals, start=1):
        c = ws.cell(row=row, column=i, value=v)
        c.font = Font(name=FONT, size=9, bold=bold)
        c.alignment = Alignment(wrap_text=True, vertical="top",
                                horizontal=(align or {}).get(i, "left"))
        c.border = BORDER
        if fills and fills.get(i):
            c.fill = PatternFill("solid", fgColor=fills[i])
    ws.row_dimensions[row].height = height
    return row + 1


def lead(ws, row, text, span):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=FONT, size=10, bold=True, color=NAVY)
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span)
    ws.row_dimensions[row].height = 18
    return row + 1


def note(ws, row, text, span, height=None):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=FONT, size=8.5)
    c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=span)
    ws.row_dimensions[row].height = height or max(30, 13 * (len(text) // 80 + 1))
    return row + 1


# ---------------------------------------------------------------- 照会先の分類
def atesaki(f):
    """点検事項から照会先を決める。"""
    t = f[3] + f[4]
    if "華" in t or "フラワー" in t:
        return "事業者", "有料老人ホーム華／ヘルパーステーションフラワー"
    if "びえいの郷" in t:
        return "事業者", "有料老人ホームびえいの郷"
    if "ゆう" in f[3]:
        return "事業者", "サービス付き高齢者向け住宅ゆう"
    if "所在地区" in t or "地区" in f[3]:
        return "発注者・3町", "地区の定義の決定（照会の前提）"
    if "未回答" in t or "回答がない" in t or "特別養護老人ホーム" in f[3]:
        return "事業者", "未回答の施設"
    if "見える化" in t or "定員" in f[3]:
        return "発注者", "定員・稼働の突合（台帳による確認）"
    if "偏り" in f[3] or "小規模多機能" in t:
        return "発注者", "集計方法の決定（照会を要しない）"
    return "事業者", "回答事業所（個別）"


