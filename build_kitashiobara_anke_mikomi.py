    if "有効回答率{_pc('有効回答率_障がい者')}の" not in cross:
        ng.append("書換５：直した後の記述がクロス集計設計に無い")
    if "有効回答率22.1％のアンケート" in cross:
        ng.append("書換５：38件の有効回答率が文字で残っている")

