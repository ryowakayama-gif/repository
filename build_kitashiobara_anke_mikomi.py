def _jis(svc, tani):
    """正本 第5章の実績の表（台帳の反映後）の令和６・７年度の値と第７期の見込量。

    令和8年10月24日の他ＡＩの横断レビュー（RT-02）で、短期入所を
    「実績0」と書いていた（台帳の反映前の値）ことが指摘されたため、
    実績は文字で持たずに実績の表の差し替え（ＤＫ）から読む。
    """
    hits = [r for r in DK_HYOU
            if r["svc"].replace("\n", "") == svc and r["tani"] == tani]
    if len(hits) != 1:
        raise LookupError(f"実績の表の行が一意でない（{len(hits)}）: {svc} {tani}")
    out = []
    for v in hits[0]["ato"][:2]:
        m = re.match(r"^([0-9.]+)（([0-9.]+)）", v)
        out.append((m.group(1), m.group(2)))
    return out   # [(令和６年度の実績, 見込量), (令和７年度の実績, 見込量)]


