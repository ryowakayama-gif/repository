def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            for c in r.cells:
                out.append(c.text)
    return "\n".join(out)


def _norm(s):
    return re.sub(r"\s+", "", str(s))


def verify():
    ng = []
    for p in (REVIEW, HONPON, MOTO):
        if not os.path.exists(p):
            ng.append(f"原典が無い: {os.path.basename(p)}")
    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("   -", x)
        raise SystemExit(1)

    # ① レビューが引いた割合が、受領時（38件）の集計と合っていること。
    #    本書の割合は40件の集計から読む（kitashiobara_anke）。
    #    レビューが38件の値で書かれていることを確かめておけば、
    #    本書の割合とレビューの割合の違いは回収数の違いだけと言える。
    rev = _norm(open(REVIEW, encoding="utf-8").read())
