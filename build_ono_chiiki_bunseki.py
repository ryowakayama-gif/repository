def main():
    src = UKE if UKE.exists() else _find_src()
    got = read_sheet(src)

    # ---- 自己点検
    chk("1", "受領シートから指標を読めた", "30件以上", f"{len(got)}件", len(got) >= 30)
    need = ("B4-a", "B5-a", "B6-a", "B6-b", "D2", "D3", "D4",
            "D15-b", "D17-a", "D31-a")
    miss = [s for s in need if s not in got]
    chk("2", "記述に使う指標がそろっている", f"{len(need)}件すべて",
        f"{len(need) - len(miss)}件" + (f"（欠け {miss}）" if miss else ""), not miss)

    texts = make_text(got)
    chk("3", "3つのブロックの記述ができた", "3ブロック×4欄",
        f"{len(texts)}ブロック×{len(next(iter(texts.values())))}欄",
        len(texts) == 3 and all(len(v) == 4 for v in texts.values()))

    # 訪問介護が全国の半分程度であること（記述の根幹）
    rh = ratio(got, "D17-a")
    chk("4", "訪問介護の給付月額が全国を下回る", "全国の7割未満",
        pct(rh, 1), rh is not None and rh < 0.7)
    # 重度の認定率が全国より高いこと
    omo = val(got, "B6-a", "町", 1)
    omo_z = val(got, "B6-a", "全国", 1)
    chk("5", "要介護3〜5の調整済み認定率が全国より高い", "町＞全国",
        f"町{pt(omo)}％／全国{pt(omo_z)}％", omo is not None and omo > omo_z)
    # 記述に固定値の割合が混じっていないこと
    ng = [k for k, v in texts.items()
          if any("1.9％" in x or "0.4％" in x for x in v)]
    chk("6", "記述に固定値の割合が混じっていない", "なし",
        f"{len(ng)}ブロック", not ng)

    xp = write_xlsx(got, texts)
    dp = write_docx(got, texts)
    return xp, dp, got, texts


