def read_sheet(path):
    """受領シートから、指標ID→{区分→[3か年]} を読む。"""
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb.worksheets[0]
    got = {}
    for r in range(5, 113):
        nm = ws.cell(r, 1).value
        sid = ws.cell(r, 2).value
        if not nm or not sid:
            continue
        d = {}
        for lab, base in COL.items():
            d[lab] = [ws.cell(r, base + o).value for o in range(3)]
        got[str(sid).strip()] = {"名": str(nm).replace("\n", ""), "値": d}
    return got


def val(got, sid, kubun, i):
    """数値を返す。取れないときは None。"""
    try:
        v = got[sid]["値"][kubun][i]
    except (KeyError, IndexError):
        return None
    return v if isinstance(v, (int, float)) else None


def ratio(got, sid, i=2, base="全国"):
    """全国（または県）に対する町の割合。取れないときは None。"""
    a, b = val(got, sid, "町", i), val(got, sid, base, i)
    if a is None or b in (None, 0):
        return None
    return a / b


def pt(v, nd=2):
    return "―" if v is None else f"{v:,.{nd}f}"


def pct(v, nd=1):
    return "―" if v is None else f"{v * 100:,.{nd}f}％"


