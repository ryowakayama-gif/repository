def write_xlsx(got, texts):
    OUT.mkdir(parents=True, exist_ok=True)
    src = UKE if UKE.exists() else _find_src()
    dst = OUT / f"小野町_地域分析・検討シート_記入案_{ASOF}.xlsx"
    shutil.copy(src, dst)
    wb = openpyxl.load_workbook(dst)
    ws = wb.worksheets[0]
    # 4つの欄の先頭列（結合セルの左上）
    cols = {"比較": 1, "考察": 4, "検証": 6, "対応": 86}
    for name, r, _hr in BLOCKS:
        t = texts[name]
        for i, key in enumerate(("比較", "考察", "検証", "対応")):
            c = ws.cell(r, cols[key])
            c.value = t[i].replace("**", "")
            c.alignment = Alignment(wrap_text=True, vertical="top")
            c.font = Font(name="游ゴシック", size=9)
        ws.row_dimensions[r].height = 210
    wb.save(dst)
    return dst


def _find_src():
    """受領シートを探す。原本フォルダに無ければ scratchpad の展開先を使う。"""
    cands = list(OUT.glob("**/*地域分析・検討シート*.xlsx"))
    if cands:
        return cands[0]
    raise SystemExit("受領シートが見つかりません")


