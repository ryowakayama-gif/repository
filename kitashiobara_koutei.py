def verify():
    ng = []

    # ① 期限が遡る順に並んでいること
    hi = [r[1] for r in GYAKUSAN]
    if hi != sorted(hi, reverse=True):
        ng.append(f"期限が順に遡っていない: {hi}")

    # ② 所要日数が日付から数えた値と一致すること。
    #    手で書いた日数と突き合わせるのではなく、
    #    数え直して同じになることを見る。
    mae = None
    for _no, h, kou, nissu, _dare, _moto in GYAKUSAN:
        heiretsu = [x for x in _KOUTEI if x[0] == h and x[1] == kou][0][4]
        if heiretsu:
            if nissu != "―（並行）":
                ng.append(f"並行の工程に日数が入っている: {kou}")
            continue
        if mae is None:
            if nissu != "―":
                ng.append(f"納期に日数が入っている: {kou}")
        else:
            matomo = f"{eigyoubi(h, mae)}営業日"
            if nissu != matomo:
                ng.append(f"所要日数が日付と合わない: {kou} "
                          f"{nissu} ≠ {matomo}")
        mae = h

    # ③ 納期が仕様書の履行期限であること
    if GYAKUSAN[0][1] != "2027-03-31":
        ng.append(f"納期が令和9年3月31日でない: {GYAKUSAN[0][1]}")

    # ④ 入稿の日が置かれていること（令和8年10月12日のレビューの指摘）
    nyu = [r for r in GYAKUSAN if "入稿" in r[2]]
    if len(nyu) != 1:
        ng.append(f"入稿の工程が{len(nyu)}件")

    # ⑤ パブリックコメントが15日間であること
    if PABU_NISSU != 15:
        ng.append(f"パブリックコメントが15日間でない: {PABU_NISSU}日")

    # ⑥ 工程の前後関係
    #    計画の決定（庁議）が初校より前、議会全員協議会が決定より後、
    #    パブリックコメントの終了が決定より前であること。
    def ichi(kotoba):
        a = [r[1] for r in GYAKUSAN if kotoba in r[2]]
        if len(a) != 1:
            ng.append(f"工程が1件でない: {kotoba}（{len(a)}件）")
            return None
        return a[0]

    chougi = ichi("庁議")
    shokou = ichi("初校")
    gikai = ichi("議会全員協議会")
    pabu = ichi("パブリックコメントの終了")
    kyougi = ichi("北塩原村障がい者自立支援協議会")
    if chougi and shokou and not (chougi < shokou):
        ng.append(f"庁議が初校より後: {chougi} / {shokou}")
    if chougi and gikai and not (chougi < gikai):
        ng.append(f"議会全員協議会が計画の決定より前: {gikai} / {chougi}")
    if pabu and chougi and not (pabu < chougi):
        ng.append(f"パブリックコメントの終了が庁議より後: {pabu}")
    if kyougi and not (kyougi < PABU_KAISHI):
        ng.append(f"自立支援協議会がパブリックコメントより後: {kyougi}")

    # ⑦ 4町村広域の協議会と議会全員協議会が工程に入っていること。
    #    策定委員会資料のスケジュール表はこの2件を注記に落としていた。
    for iru in ("４町村広域", "議会全員協議会"):
        if not any(iru in r[2] for r in GYAKUSAN):
            ng.append(f"工程に{iru}がない")
        if not any(iru in r[2] or iru in r[5] for r in KIKAN):
            ng.append(f"工程表に{iru}がない")

    # ⑧ 概要版の表と逆算の日付が食い違っていないこと
    g = "".join(x[0] + x[1] for x in GAIYOU_HYO)
    for iru in ("１月26日", "２月９日", "２月19日", "２月下旬"):
        if iru not in g:
            ng.append(f"概要版の表に{iru}がない")
    if "２月８日" in g or "２月22日" in g:
        ng.append("概要版の表に従前のパブリックコメントの日付が残っている")

    # ⑨ 和暦の変換
    for iso, machi in (("2027-03-31", "令和９年３月31日"),
                       ("2027-01-26", "令和９年１月26日"),
                       ("2027-02-09", "令和９年２月９日"),
                       ("2026-11-18", "令和８年11月18日")):
        if _wareki(iso) != machi:
            ng.append(f"和暦の変換が合わない: {iso} → {_wareki(iso)}")

    if ng:
        for x in ng:
            print(f"  × {x}")
        raise SystemExit("工程の自己点検で止めました")

    return (f"工程{len(GYAKUSAN)}件（うち並行2件）・"
            f"工程表{len(KIKAN)}期間・"
            f"パブリックコメント{PABU_NISSU}日間・"
            f"入稿 {_wareki(nyu[0][1])}・納品 {_wareki(GYAKUSAN[0][1])}")


