def _suji(n):
    """正本の作法。1桁は全角、2桁以上は半角のままとする。"""
    return _ZEN[n] if n < 10 else str(n)


def _wareki(iso):
    """2027-03-31 → 令和９年３月31日。数字は正本の作法に合わせる。"""
    d = dt.date.fromisoformat(iso)
    nen = d.year - 2018                       # 令和元年＝2019年
    return f"令和{_suji(nen)}年{_suji(d.month)}月{_suji(d.day)}日"


def wareki(iso):
    return _wareki(iso)


