# 令和9年1月2日・3日は土曜・日曜であるため、別に挙げる必要がない。
# 1月4日（月）は開庁日である。


def eigyoubi(kara, made):
    """kara の翌日から made までの営業日数を数える。"""
    a = dt.date.fromisoformat(kara)
    b = dt.date.fromisoformat(made)
    if b < a:
        raise ValueError(f"日付が逆: {kara} → {made}")
    n = 0
    c = a
    while c < b:
        c += dt.timedelta(days=1)
        if c.weekday() < 5 and c.isoformat() not in SHUKUJITSU:
            n += 1
    return n


