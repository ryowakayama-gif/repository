# ------------------------------------------------------------------ 原本の照合
def _norm(s):
    return unicodedata.normalize("NFKC", re.sub(r"\s+", "", s))


_PAGE = {}


def _page(insatsu):
    """前回計画の印字頁の本文（空白除去・半角化）を返す。"""
    if insatsu not in _PAGE:
        n = insatsu + ZURE
        r = subprocess.run(["pdftotext", "-f", str(n), "-l", str(n), "-layout",
                            str(ZENKAI), "-"], capture_output=True, text=True)
        _PAGE[insatsu] = _norm(r.stdout)
    return _PAGE[insatsu]


def genpon_ng():
    ng = []
    if not ZENKAI.exists():
        return ["前回計画の原本がない：%s" % ZENKAI]
    for gyo, _k, _v, pages, words in ZENKAI_MOKUHYO:
        body = "".join(_page(p) for p in pages)
        for w in words:
            if _norm(w) not in body:
                ng.append("%s：原本 p.%s に「%s」がない" % (
                    gyo, "・".join(map(str, pages)), w))
        if pages and "【目標値】" not in body:
            ng.append("%s：原本 p.%s に【目標値】の表がない" % (
                gyo, "・".join(map(str, pages))))
    # 精神（にも包括）の成果目標が第5章（印字68〜78頁）に本当にないか
    sho5 = "".join(_page(p) for p in range(68, 79))
    if "精神障がいにも対応" in sho5 or "精神障害にも対応" in sho5:
        ng.append("前回計画の第5章に精神障がいにも対応した地域包括ケアの目標がある")
    return ng


