def jiko(doc_path=None):
    ng = []
    sankou = []
    # 1・2 前回計画の目標値が原本の該当頁にある／精神の目標が本当にない
    ng += genpon_ng()
    # 3 扱いが4区分のいずれか、№が1から欠番・重複なし
    for x in TAIOU:
        if x[5] not in ATSUKAI:
            ng.append("扱いが4区分でない：№%d" % x[0])
        if x[8] not in ("高", "中", "低", "―"):
            ng.append("優先が不正：№%d" % x[0])
    if [x[0] for x in TAIOU] != list(range(1, len(TAIOU) + 1)):
        ng.append("№に欠番または重複がある")
    # 4 他素案の見出しが実在する（手元にあるときだけ）
    if TASO.exists():
        import docx
        d = docx.Document(str(TASO))
        txt = _norm("\n".join(p.text for p in d.paragraphs)
                    + "\n".join(c.text for t in d.tables for rw in t.rows
                                for c in rw.cells))
        for x in TAIOU:
            if _norm(x[2]) not in txt:
                ng.append("他素案に「%s」が見当たらない：№%d" % (x[2], x[0]))
    else:
        sankou.append("他素案が手元にないため、見出しの実在は確かめていない")
    # 5 他の団体の名称が成果品に出ない
    if doc_path is not None:
        import docx
        d = docx.Document(str(doc_path))
        txt = "\n".join(p.text for p in d.paragraphs) + "\n".join(
            c.text for t in d.tables for rw in t.rows for c in rw.cells)
        for w in ("北塩原", "福島町", "北海道", "大雪", "東川"):
            if w in txt:
                ng.append("他の団体の名称が出ている：%s" % w)
    # 6 優先「高」が手順の5件と一致
    taka = [x[0] for x in TAIOU if x[8] == "高"]
    if taka != TAKA:
        ng.append("優先「高」%s が手順に書いた5件と合わない" % taka)
    # 7 前回計画の目標の行が他素案の表の7行と同じ数
    if len(ZENKAI_MOKUHYO) != 7:
        ng.append("前回計画の目標が7行でない")
    return ng, sankou


