def moji(p):
    """1頁の分量（文字数の目安）。図の面積を文字数に換算して足す。"""
    _no, _mi, _na, zu, tsu, m, _ne = p
    return m + (len(zu) + len(tsu)) * MOJI_ZU


# ---------------------------------------------------------------- 自己点検

def selfcheck():
    ok, ng = [], []

    def chk(no, name, kitai, kekka):
        (ok if kitai == kekka else ng).append((no, name, str(kitai),
                                               str(kekka)))

    # 1 仕様書の定める頁数
    chk("1", "頁数", 8, len(PAGES))
    chk("1b", "頁番号が1からの連番", list(range(1, 9)),
        [p[0] for p in PAGES])

    # 2 割り付けた図が図表データ管理台帳に実在する
    for p in PAGES:
        for z in p[3]:
            chk(f"2-{z}", f"{z} が台帳にある", True, z in SASHIKOMI)

    # 3 割り付けた図のPNGが実在する
    for p in PAGES:
        for z in p[3]:
            chk(f"3-{z}", f"{z}.png が実在する", True,
                (FIGDIR / f"{z}.png").exists())

    # 4 図の点数が上限（8点）以内
    n_zu = sum(len(p[3]) + len(p[4]) for p in PAGES)
    chk("4", "図の点数（上限8点）", True, n_zu <= 8)

    # 5 これから作る図が TSUKURU に登録されている
    tsukuru_na = {t[0] for t in TSUKURU}
    for p in PAGES:
        for t in p[4]:
            chk(f"5-{t}", f"「{t}」の作成時期を決めてある", True,
                t in tsukuru_na)

    # 6 1頁の分量が目安を超えていない
    for p in PAGES:
        m = moji(p)
        chk(f"6-p{p[0]}", f"p{p[0]} の分量（目安 {MOJI_1P}字以内）", True,
            m <= MOJI_1P)

    # 7 同じ図を2頁に置いていない
    zs = [z for p in PAGES for z in p[3]]
    chk("7", "同じ図の重複", len(zs), len(set(zs)))

    # 8 保険料・見込量・評価の頁がある（住民の関心が高い順）
    for key in ("介護保険料", "サービス見込量", "第9期計画の評価"):
        chk(f"8-{key}", f"「{key}」の頁がある", True,
            any(key in p[1] or key in p[2] for p in PAGES))

    return ok, ng


