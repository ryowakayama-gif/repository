# ---------------------------------------------------------------- 自己点検
def jiko():
    ng = []
    # 1 受領の一覧に新規と既受領の両方がある
    if not any("新規" in x[2] for x in JURYO):
        ng.append("新規の資料が一覧にない")
    if not any("既受領" in x[2] for x in JURYO):
        ng.append("既受領の資料が一覧にない")
    # 2 基金の取崩しがすべて0であることを表が示している
    kuri = [x[2].replace("**", "") for x in KIKIN]
    if set(kuri) != {"0"}:
        ng.append("基金の取崩しに0でない年度がある：%s" % kuri)
    # 3 突き合わせには必ず2つの資料がある
    for x in SHOGO:
        if not x[1].strip() or not x[3].strip():
            ng.append("突き合わせの資料が片方しかない：%s" % x[0])
    # 4 所得段階の人数の合計が計と合う
    tot = sum(int(x[2].replace(",", "")) for x in SHOTOKU)
    if tot != 3436:
        ng.append("所得段階の合計が合わない：%d（3,436でない）" % tot)
    # 5 段階の数と行数が合う
    if len(SHOTOKU) != 13:
        ng.append("所得段階が13でない：%d" % len(SHOTOKU))
    # 6 想定と違ったことには必ず「何に効くか」がある
    for x in CHIGAI:
        if not x[3].strip():
            ng.append("想定と違ったことに効き先がない：%s" % x[0])
    # 7 反映の時期が空でない
    for x in HANEI:
        if not x[3].strip():
            ng.append("反映の時期が空：%s" % x[0])
    # 8 地域支援事業の合計が内訳と整合する（令和7年度）
    #    1 + 2 + 4 = 合計
    def v(label, col):
        for x in CHIIKI:
            if x[0].replace("**", "").strip().startswith(label):
                return int(x[col].replace(",", "").replace("**", ""))
        return None
    a = v("1　介護予防", 3)
    b = v("2　包括的支援事業・任意事業", 3)
    c = v("4　包括的支援事業（社会保障充実分）", 3)
    g = v("合計", 3)
    if None not in (a, b, c, g) and a + b + c != g:
        ng.append("令和7年度の地域支援事業費の内訳と合計が合わない："
                  "%d+%d+%d=%d（合計%d）" % (a, b, c, a + b + c, g))
    # 9 原本が置かれている
    if not SRC.exists():
        ng.append("原本のフォルダがない：%s" % SRC)
    # 10 本文に件数を手で書いていない
    #    前は「5点を受領しました。うち3点が新規」と手で書いており、
    #    一覧を1行足したときに食い違った。
    import inspect
    src = inspect.getsource(doc_build)
    import re
    for m in re.findall(r"\*\*\d+[点種類件]", src):
        ng.append("本文に件数を手で書いている：%s" % m)
    return ng


