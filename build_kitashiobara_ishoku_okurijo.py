def build(member):
    doc = new_doc("他メンバー版の計画素案への移植　申し送り",
                  "令和８年10月９日　北塩原村 第８期障がい福祉計画・"
                  "第４期障がい児福祉計画")

    h2(doc, "この申し送りについて")
    para(doc,
         "他メンバー版の計画素案を正本とする方針が決まったことを受け、"
         "当方の素案に入れた９か所を他メンバー版へ移すための手順を"
         "まとめたものです。移植先は他メンバー版の章節で示し、"
         "挿入位置は他メンバー版に実在する段落の末尾を引用して示しています。"
         "入れる文章はそのまま貼れる形にし、章節の参照は"
         "他メンバー版の構成に書き換えてあります。")
    para(doc,
         "いずれも令和８年10月９日の第２回外部レビュー（27論点）への対応です。"
         "レビューが最優先に挙げた「ワークシートの仮置き値を実績に"
         "差し替えること」は村の回答（M-19）が前提であり、本書には含みません。")
    note(doc,
         "本書は文章の追加だけを扱います。先に受領した素案の網羅性点検"
         "（漏れている論点18件）のうち、本書で扱っていないものは"
         "末尾の「本書が扱っていないもの」にまとめました。"
         "基盤整備量（別表第二 三㈠⑤）は定めなければならない事項であり、"
         "本書の９件とは別に対応が必要です。")

    h2(doc, "移植の一覧")
    rows = [["番号", "移植先", "形式", "分量", "根拠"]]
    for rec in ISHOKU:
        rows.append([rec["no"], rec["saki"], rec["keishiki"], rec["ryo"],
                     rec["konkyo"]])
    table(doc, rows, [1000, 4400, 2600, 1400, 5800])

    h2(doc, "表記の作法（他メンバー版に揃えてあります）")
    table(doc, [["項目", "揃えた形", "使わない形", "例"]] +
          [list(r) for r in HYOKI], [3000, 3400, 3600, 5200])

    for rec in ISHOKU:
        doc.add_page_break()
        h2(doc, f"移植 {rec['no']}　{rec['saki']}")

        h3(doc, "挿入位置")
        para(doc, "次の段落の直後に入れてください。", indent=False)
        note(doc, rec["ichi"])

        h3(doc, "根拠")
        para(doc, rec["konkyo"])

        h3(doc, "既存の記載との関係")
        para(doc, rec["kankei"])

        h3(doc, f"入れるもの（{rec['keishiki']}／{rec['ryo']}）")
        for blk in rec["nakami"]:
            if blk[0] == "h3":
                p = doc.add_paragraph()
                _font(p.add_run(blk[1]), size=10.5, bold=True)
                p.paragraph_format.space_before = Pt(6)
                p.paragraph_format.space_after = Pt(2)
            elif blk[0] == "p":
                para(doc, blk[1])
            elif blk[0] == "bul":
                bullet(doc, blk[1])
            elif blk[0] == "tbl":
                table(doc, blk[1], blk[2])
            elif blk[0] == "note":
                note(doc, blk[1])

    doc.add_page_break()
    h2(doc, "本書が扱っていないもの（素案の網羅性点検の残り）")
    para(doc,
         "先に受領した素案の網羅性点検で挙げた論点のうち、"
         "本書の９件に含まれていないものです。"
         "移植先の目安を添えました。基盤整備量（Ｄ）は"
         "定めなければならない事項であり、最も急ぎます。")
    rows = [["区分", "論点", "根拠", "移植先の目安", "なぜ必要か", "重さ"]]
    for rec in NOKORI:
        rows.append(list(rec))
    table(doc, rows, [900, 4200, 2800, 2200, 4200, 900], size=9)

    h2(doc, "移植後に確認したいこと")
    for t in [
        "移植した箇所の章節の参照（第４章２（１）等）が、"
        "他メンバー版の構成と合っているか。",
        "第５章２に（７）～（13）を足した結果、"
        "項が13になります。読みにくければ"
        "「１ サービスの確保」「２ 体制の確保」の2つに分ける案もあります。",
        "注記（【村へ確認】【県へ確認】）は、"
        "計画の確定時に削る前提で入れてあります。"
        "庁議・協議会に出す版では残し、公表版では削ってください。",
        "本書の９件を入れると、他メンバー版は約45頁から約51頁になります"
        "（注記を削ると約49頁）。分量配分計画の60頁には収まります。",
    ]:
        bullet(doc, t)

    return doc


def main():
    os.makedirs(f"{REPO_ROOT}/output", exist_ok=True)
    member = load_member()
    verify(member)
    doc = build(member)
    doc.save(OUT_FILE)

    n_blk = sum(len(r["nakami"]) for r in ISHOKU)
    n_tbl = sum(1 for r in ISHOKU for b in r["nakami"] if b[0] == "tbl")
    n_note = sum(1 for r in ISHOKU for b in r["nakami"] if b[0] == "note")
    chars = sum(len(paste_text(r)) for r in ISHOKU)
    print(f"作成: {OUT_FILE}")
    print(f"  移植{len(ISHOKU)}件　ブロック{n_blk}"
          f"（表{n_tbl}・注記{n_note}）／貼る文字数 約{chars:,}字")
    print(f"  本書が扱っていないもの {len(NOKORI)}件")
    d = docx.Document(OUT_FILE)
    print(f"  申し送り: 段落{len(d.paragraphs)}・表{len(d.tables)}")


if __name__ == "__main__":
    main()
