HYOKI = [
    ("範囲を示す記号", "～（全角チルダ）", "〜（波ダッシュ）は使わない",
     "令和９～11年度"),
    ("箇所の単位", "カ所", "「か所」「ヶ所」は使わない", "１カ所"),
    ("本文の1桁の数", "全角", "小数と2桁以上は半角", "４人、１回、2.7％、11人"),
    ("表の中の数", "半角", "―", "1人／月、0人日"),
    ("割合の記号", "％（全角）", "―", "34.2％"),
    ("章節の参照", "全角の数字", "―", "第４章２（１）、第５章１（２）"),
    ("年度の表記", "令和＋全角1桁／半角2桁", "―", "令和９年度、令和11年度"),
]


