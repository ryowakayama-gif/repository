def load_member():
    doc = docx.Document(MEMBER)
    parts = []
    for ch in doc.element.body.iterchildren():
        tag = ch.tag.split("}")[-1]
        if tag == "p":
            parts.append(Paragraph(ch, doc).text)
        elif tag == "tbl":
            for row in Table(ch, doc).rows:
                seen = set()
                for c in row.cells:
                    if id(c._tc) in seen:
                        continue
                    seen.add(id(c._tc))
                    parts.append(c.text)
    return "\n".join(parts)


def _norm(s):
    return re.sub(r"[\s　]+", "", s)


def paste_text(rec):
    """貼る文章だけを連結する（表記の点検用）。"""
    out = []
    for blk in rec["nakami"]:
        if blk[0] in ("h3", "p", "note", "bul"):
            out.append(blk[1])
        elif blk[0] == "tbl":
            for row in blk[1]:
                out.extend(str(x) for x in row)
    return "\n".join(out)


def verify(member):
    ng = []
    mem = _norm(member)

    # ① 挿入位置の引用が他メンバー版に実在すること
    for rec in ISHOKU:
        for part in re.split(r"／【第５章２（６）】|／", rec["ichi"]):
            part = re.sub(r"^【[^】]*】", "", part).strip()
            if not part or part.startswith("上記") or part.startswith("（６）"):
                continue
            if _norm(part) not in mem:
                ng.append(f"挿入位置の引用が他メンバー版にない: {rec['no']}"
                          f"『{part[:40]}』")

    # ② 参照している章節が他メンバー版に実在すること
    sections = {
        "第１章": "第１章", "第２章": "第２章", "第３章": "第３章",
        "第４章": "第４章", "第５章": "第５章", "第６章": "第６章",
        "第７章": "第７章", "第８章": "第８章",
    }
    for key in sections:
        if key not in member:
            ng.append(f"他メンバー版に章が見つからない: {key}")
    for ref in ("第４章２（７）", "第５章１（２）", "第５章１（３）",
                "第５章１（４）", "第５章２", "第３章３"):
        head = ref[:3]
        if head not in member:
            ng.append(f"参照先の章が他メンバー版にない: {ref}")

    # ③ 貼る文章が他メンバー版の表記の作法に揃っていること
    for rec in ISHOKU:
        txt = paste_text(rec)
        if "〜" in txt:
            ng.append(f"波ダッシュ（〜）が混じっている: {rec['no']}")
        if "か所" in txt or "ヶ所" in txt:
            ng.append(f"「カ所」に揃っていない: {rec['no']}")
        if re.search(r"令和[0-9]年", txt):
            ng.append(f"令和の1桁が半角になっている: {rec['no']}")
        if re.search(r"[0-9]%", txt) or "%" in txt:
            ng.append(f"半角の％が混じっている: {rec['no']}")

    # ④ 原典未確認の法律番号を書いていないこと
    for rec in ISHOKU:
        txt = paste_text(rec)
        for bad in ("令和8年法律第51号", "令和８年法律第51号",
                    "令和8年法律第45号", "令和８年法律第45号"):
            if bad in txt:
                ng.append(f"原典未確認の法律番号が入っている: {rec['no']}")

    # ⑤ 移植先・番号の重複と語彙
    nos = [r["no"] for r in ISHOKU]
    assert len(nos) == len(set(nos)) == 9, "移植は9件で一意であること"
    for rec in NOKORI:
        assert rec[5] in ("最優先", "高", "中", "低"), f"重さが未定義: {rec[0]}"

    # ⑥ 他団体の名を出さない
    for rec in ISHOKU:
        s = paste_text(rec) + rec["saki"] + rec["konkyo"] + rec["kankei"]
        for bad in ("小野町", "金ヶ崎", "阿蘇"):
            if bad in s:
                ng.append(f"他団体名が含まれている: {bad}")

    if ng:
        print("自己点検 不合格:")
        for e in ng:
            print("   -", e)
        raise SystemExit(1)
    print(f"  自己点検: 挿入位置の引用{len(ISHOKU)}件が他メンバー版に実在／"
          "参照先の章6件が実在／表記の作法4点・法律番号の不記載すべて合")


