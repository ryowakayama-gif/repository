def bd(v, b):
    return {"65-74": sum(v[1:3]), "75-84": sum(v[3:5]),
            "85+": sum(v[5:9]), "tot": v[0]}[b]


def juki_g(b, town=None):
    """住民基本台帳の年平均変化率（平成31年→令和7年・6年）。"""
    if town:
        a, c = bd(JUKI[town][2019], b), bd(JUKI[town][2025], b)
    else:
        a = sum(bd(JUKI[t][2019], b) for t in TOWNS)
        c = sum(bd(JUKI[t][2025], b) for t in TOWNS)
    return (c / a) ** (1.0 / 6) - 1


