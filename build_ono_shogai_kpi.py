def selfcheck(ztxt, zpages, ctxt, cpages, rows, q, hq):
    ok, ng = [], []

    def chk(no, name, kitai, kekka):
        (ok if kitai == kekka else ng).append((no, name, str(kitai),
                                               str(kekka)))

    chk("1", "前回計画のPDFが読めた", True, zpages == 128)
    chk("2", "前回調査報告書のPDFが読めた", True, cpages == 110)
    # 前回計画のKPIの数値が原文に実在するか
    z = re.sub(r"\s+", " ", ztxt)
    miss = [s for s in ZEN_SHOGO if s not in z]
    chk("3", "本書に書いた前回計画の数値が原文にある", [], miss)
    # 地域生活移行の目標値が算術的に成立しないこと
    chk("4", "前回の地域生活移行の目標が基準を超える", True, 31 > 26)
    chk("5", "前回の削減目標どおりなら施設入所者は4人", 4, 26 - 22)
    chk("6", "国の率を26人に当てた場合の移行者数", 2, math.ceil(26 * 0.06))
    # 第8期の受領シートの値が国の率と合う
    chk("7", "第8期の移行者数（19人の6％・切上げ）", 2, math.ceil(19 * 0.06))
    chk("8", "第8期の削減数（19人の5％・切上げ）", 1, math.ceil(19 * 0.05))
    # 前回調査の回収率
    # **PDFは行の途中に改行が入る**（「層化無\n作為抽出法」）。
    # 空白をすべて落としてから照合する。
    c = re.sub(r"\s+", "", ctxt)
    for v in ("520", "280", "53.8", "36", "22", "61.1", "層化無作為抽出"):
        if v not in c:
            ng.append(("9", f"前回調査の「{v}」が原文にある", "True", "False"))
    if not any(x[0] == "9" for x in ng):
        ok.append(("9", "前回調査の配布・回収・抽出方法が原文にある",
                   "すべてある", "すべてある"))
    # 指針の番号
    nos = shishin_nos(rows)
    chk("10", "受領シートの成果目標の行数", True, len(rows) >= 15)
    chk("11", "対応表の番号のうちシートに行があるもの", nos,
        {t[0] for t in TAIO} & nos)
    chk("12", "第二・二が受領シートに行がない", True, "二" not in nos)
    # 設問番号の実在
    miss2 = []
    for *_x, qs, _alt in TAIO:
        for s in qs:
            if s not in q["者"] and s not in q["児"] and s not in hq:
                miss2.append(s)
    for _n, s, _b, _a in DOKUJI:
        for one in re.split(r"×", s):
            if one not in q["者"] and one not in hq:
                miss2.append(one)
    chk("13", "挙げた設問番号が集計表・報告書に実在する", [], miss2)
    # 前回KPIでアンケートが基準値になるものは0、手段になるものは1
    chk("14", "前回KPIでアンケートが基準値になる項目", 0,
        sum(1 for k in ZEN_KPI if "基準値" in k[5]))
    chk("15", "前回KPIでアンケートが手段になりうる項目", 1,
        sum(1 for k in ZEN_KPI if "手段" in k[5]))
    # 層の内訳
    ichi = sum(1 for k in ZEN_KPI if k[4] == "①" and k[3] != "―")
    nii = sum(1 for k in ZEN_KPI if k[4] == "②" and k[3] != "―")
    chk("16", "前回KPIの層の内訳が集計できる", True, ichi > 0 and nii > 0)
    # 強度行動障がいを今回の調査票が聞いていないこと
    chk("17", "今回の調査票に強度行動障がいの設問がない", 0,
        sum(1 for v in q["者"].values() if "強度行動" in v))
    return ok, ng


