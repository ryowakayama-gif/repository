def selfcheck(head, rows, q, hq):
    ok, ng = [], []

    def chk(no, name, kitai, kekka):
        (ok if kitai == kekka else ng).append((no, name, str(kitai),
                                               str(kekka)))

    nos = {shishin_no(r) for r in rows} - {None}
    chk("1", "受領シートの成果目標が読めた", True, len(rows) >= 15)
    chk("2", "指針の番号が拾えた", True, len(nos) >= 5)
    # 対応表の指針番号が受領シートに実在するか（二は無いことを確かめる）
    taio_nos = {t[0] for t in TAIO}
    chk("3", "対応表に挙げた指針番号のうちシートに行があるもの",
        nos, taio_nos & nos)
    chk("4", "第二・二が受領シートに無い", True, "二" not in nos)
    chk("5", "第二・七が受領シートに無い", True, "七" not in nos)
    # 設問番号が集計表または報告書に実在するか
    miss = []
    for *_x, qs, _alt in TAIO:
        for s in qs:
            if s not in q["者"] and s not in q["児"] and s not in hq:
                miss.append(s)
    for _n, s, _b, _a in DOKUJI:
        for one in re.split(r"×", s):
            if one not in q["者"] and one not in hq:
                miss.append(one)
    chk("6", "挙げた設問番号が集計表・報告書に実在する", [], miss)
    # 層の分類が3つを網羅し、重複しないか
    chk("7", "層の分類", {"①", "②", "③"},
        set("".join(SO.keys())) & {"①", "②", "③"})
    # 成果目標でアンケートが基準値になるものは0であること
    chk("8", "アンケートで基準値を作れる成果目標", 0,
        sum(1 for t in TAIO if t[3] == "○"))
    return ok, ng


