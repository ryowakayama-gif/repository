def seika():
    """受領した目標値設定シートの成果目標の行を読む。"""
    wb = openpyxl.load_workbook(MOKUHYO, data_only=True)
    ws = wb["成果目標算定"]
    rows, head = [], None
    for r in ws.iter_rows(values_only=True):
        v = [x for x in r if x is not None]
        if not v:
            continue
        if v[0] == "区分":
            head = v
            continue
        if head and len(v) >= 4:
            rows.append(v)
    return head, rows


def shishin_no(row):
    """出典欄から「第二・一」等を拾う。"""
    for c in row:
        m = re.search(r"第二・([一二三四五六七八])", str(c))
        if m:
            return m.group(1)
    return None


def setsumon():
    """集計表から設問番号と設問文を引く。設問名を手で書き写さない。"""
    wb = openpyxl.load_workbook(CHOSA, data_only=True)
    out = {}
    for sheet, tag in (("集計_障がい者", "者"), ("集計_障がい児", "児")):
        seen = OrderedDict()
        for r in wb[sheet].iter_rows(min_row=5, values_only=True):
            if r[0] and r[0] not in seen:
                seen[r[0]] = str(r[1] or "")
        out[tag] = seen
    return out


def honbun_setsumon():
    """報告書の見出しから (設問番号 -> 見出し) を引く。自由記述の設問も拾える。"""
    d = Document(HOKOKU)
    out = {}
    for p in d.paragraphs:
        m = re.match(r"^（\d+）(.+?)（問([\d\-]+)）$", p.text.strip())
        if m:
            out.setdefault("問" + m.group(2), m.group(1))
    return out


