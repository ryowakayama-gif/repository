# ---------------------------------------------------------------- 読み込み

def zenkei_text():
    r = pypdf.PdfReader(ZENKEI)
    return "\n".join((p.extract_text() or "") for p in r.pages), len(r.pages)


def zenchosa_text():
    r = pypdf.PdfReader(ZENCHOSA)
    return "\n".join((p.extract_text() or "") for p in r.pages[:14]), len(r.pages)


def seika_rows():
    wb = openpyxl.load_workbook(MOKUHYO, data_only=True)
    ws = wb["成果目標算定"]
    rows, head = [], False
    for r in ws.iter_rows(values_only=True):
        v = [x for x in r if x is not None]
        if not v:
            continue
        if v[0] == "区分":
            head = True
            continue
        if head and len(v) >= 4:
            rows.append(v)
    return rows


def shishin_nos(rows):
    out = set()
    for r in rows:
        for c in r:
            m = re.search(r"第二・([一二三四五六七八])", str(c))
            if m:
                out.add(m.group(1))
    return out


def setsumon():
    wb = openpyxl.load_workbook(CHOSA, data_only=True)
    out = {}
    for sheet, tag in (("集計_障がい者", "者"), ("集計_障がい児", "児")):
        seen = OrderedDict()
        for r in wb[sheet].iter_rows(min_row=5, values_only=True):
            if r[0] and r[0] not in seen:
                seen[r[0]] = str(r[1] or "")
        out[tag] = seen
    return out


def honbun_setsumon():
    d = Document(HOKOKU)
    out = {}
    for p in d.paragraphs:
        m = re.match(r"^（\d+）(.+?)（問([\d\-]+)）$", p.text.strip())
        if m:
            out.setdefault("問" + m.group(2), m.group(1))
    return out


