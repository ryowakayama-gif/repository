def mikomi_do(lab, y):
    """要介護度別の見込量（人／月）。令和7年度の月平均×要介護度別の伸び。"""
    b = nenpo_do(lab)
    f = NOBI_DO[y]
    return [b[i] / 12 * f[i] for i in range(7)]


def jisseki_do(lab):
    """令和7年度の要介護度別の月平均利用者数（人／月）。"""
    return [v / 12 for v in nenpo_do(lab)]


