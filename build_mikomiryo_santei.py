def kaisu_tanka(lab):
    """（要支援の1人1月あたり回数, 要介護の同）を返す。分母0のときはNone。"""
    c = nenpo_kaisu_do(lab)
    if c is None:
        return None
    n = nenpo_do(lab)
    out = []
    for sl in (SH_I, KG_I):
        nn, cc = sum(n[sl]), sum(c[sl])
        out.append(cc / nn if nn else None)
    return tuple(out)


def kaisu_mikomi(lab, y):
    """利用回（日）数の見込み（回・日／月）。回数のない種別はNone。"""
    t = kaisu_tanka(lab)
    if t is None:
        return None
    v = MIKOMI[y][lab]
    s = 0.0
    for sl, u in ((SH_I, t[0]), (KG_I, t[1])):
        if u:
            s += sum(v[sl]) * u
    return s


