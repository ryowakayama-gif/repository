def nenpo_do(lab):
    """総括表の行に対応する年報の要介護度別の年間の延べ人数（7区分）。"""
    out = [0] * 7
    for src, key in NENPO_MAP[lab]:
        v = src[key]
        for i in range(7):
            out[i] += v[i]
    return out


def nenpo_kaisu_do(lab):
    """同じく年間の延べ利用回（日）数。回（日）数のない種別はNone。"""
    if lab not in KAISU_MAP:
        return None
    src, key, _u = KAISU_MAP[lab]
    return list(src[key])


