def load_kenko():
    wbx = openpyxl.load_workbook(CROSS, read_only=True)
    ws = wbx["01_地区別の主要指標"]
    rows = list(ws.iter_rows(values_only=True))
    head = None
    for r in rows:
        if r and r[0] == "町":
            head = [("" if v is None else str(v).replace("\n", ""))
                    for v in r]
            break
    data, cur = {}, None
    started = False
    for r in rows:
        if r and r[0] == "町":
            started = True
            continue
        if not started or not r:
            continue
        if r[0] and str(r[0]).startswith("注"):
            break
        town = r[0] if r[0] else cur
        if r[0]:
            cur = r[0]
        if town is None or r[1] is None:
            continue
        data.setdefault(town, []).append(
            [str(r[1])] + [r[i] for i in range(2, len(head))])
    wbx.close()
    return head, data


