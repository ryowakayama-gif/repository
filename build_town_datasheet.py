def town_sheet(no, town):
    ws = sheet("%02d_%s" % (no, town), "%s　データシート" % town,
               "第10期介護保険事業計画の現状分析から%sの数値を"
               "抜き出したものです。基準日：%s。"
               "サービス見込量・給付費・保険料は保険者単位で算定するため"
               "本シートには掲げていません（05シート）。" % (town, KIJUNBI),
               [26, 12, 12, 12, 12, 12, 12, 12, 30], freeze="A5")
    r = 4

    # ---------------- 1 人口と高齢化
    r = lead(ws, r, "【1　人口と高齢化（住民基本台帳の実績）】", 9)
    r = header(ws, r, ["区分"] + ["%d年" % y for y in JUKI_Y] +
               ["平成31→令和7年の\n年平均変化率"])
    for label, band in [("総人口", "tot"), ("65〜74歳", "65-74"),
                        ("75〜84歳", "75-84"), ("85歳以上", "85+"),
                        ("65歳以上", "65+"), ("75歳以上", "75+")]:
        vals = [juki(town, y, band) for y in JUKI_Y]
        g = (vals[-1] / vals[0]) ** (1.0 / (len(JUKI_Y) - 1)) - 1
        r = body(ws, r, [label] + vals + ["%+.3f％" % (g * 100)],
                 align={9: "center"})
    tot25 = juki(town, 2025, "tot")
    r = body(ws, r, ["高齢化率（65歳以上）"] +
             ["%.1f％" % (juki(town, y, "65+") / juki(town, y, "tot") * 100)
              for y in JUKI_Y] + [""],
             align={i: "right" for i in range(2, 9)})
