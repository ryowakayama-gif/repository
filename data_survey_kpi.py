"""在宅生活改善調査（利用者票）による代表KPIの基準値。

分母は設問ごとの有効回答である。設問をまたいで有効回答を流用しない。

- H06（在宅生活継続困難割合）…「在宅生活の維持の見通し」の
  有効回答98票を分母とする。回収票99票のうち1票が当該設問の無回答である。
  72票÷98票＝73.5％。
- H12（区域内で提供できないサービスが必要と判断された利用者の割合）…
  「より適切と思われるサービス」の有効回答99票を分母とする。
  20票÷99票＝20.2％。
  要介護度の有効回答も98票であるが、要介護度はH12の分母の条件ではない。
  令和8年9月25日まで98票を分母として20.4％としていたものを改めた。

設問番号は資料により食い違うため、本モジュール及び成果品では
設問名で示し、番号を書かない。当方の結果報告書は
問1 利用者の状況／問2 在宅生活の維持の見通し／問3 困難にしている要因／
問4 必要な生活支援／問5 より適切と思われるサービスの順で構成しているが、
従前はH12のデータ源を「問3」と記載していた（誤り）。
原票による番号を確認するまで番号は用いない（確認事項No.158）。

H12の分子20票は、区域内に事業所が存在しない4サービス
（夜間対応型訪問介護、定期巡回・随時対応型訪問介護看護、
看護小規模多機能型居宅介護、介護医療院）を
「より適切と思われるサービス」として1つ以上選んだ実人数である
（調査クロス集計・分析による集計値。個票は収録しない）。
"""

import data_survey2025 as _S

RIYO_N = _S.RIYO["件数"]                                   # 利用者票の回収票数

_IJI = _S.RIYO["生活の維持"]
H06_YUKO = sum(v for k, v in _IJI.items() if k != "-")     # 問2の有効回答
H06_MUKAITO = _IJI.get("-", 0)
H06_BUNSHI = _IJI["1"]
H06 = H06_BUNSHI / H06_YUKO * 100
H06_NAME = "在宅生活継続困難割合"

DO_YUKO = sum(v for k, v in _S.RIYO["要介護度"].items() if k != "-")

H12_BUNSHI = 20
H12_BUNBO = RIYO_N
H12 = H12_BUNSHI / H12_BUNBO * 100
H12_NAME = "区域内で提供できないサービスが必要と判断された利用者の割合"
H12_KYU_NAME = "必要サービス未充足率"


def h06_str():
    """「73.5％（有効回答98票中72票）」を返す。"""
    return "%.1f％（有効回答%d票中%d票）" % (H06, H06_YUKO, H06_BUNSHI)


def h12_str():
    """「20.2％（99票中20票）」を返す。"""
    return "%.1f％（%d票中%d票）" % (H12, H12_BUNBO, H12_BUNSHI)


def h12_pct():
    return "%.1f％" % H12
