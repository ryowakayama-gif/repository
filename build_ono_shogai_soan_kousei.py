def docx_text(path):
    """成果品の全文（本文と表）を取り出す。"""
    import docx
    d = docx.Document(str(path))
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for row in t.rows:
            out += [c.text for c in row.cells]
    return "\n".join(out)


# 「◯◯市／町／村／県」の形で現れてよい語の、語末での照合用。
# 自治体名は小野町と福島県のみを許す。
MUNI_OK = {
    "小野町", "福島県",
    # 自治体名でない一般語
    "町村", "道府県", "本町", "当町", "同町", "全町", "都市", "市街", "市販",
}


def run_checks(pages, npage, juten, outpath):
    ng = []
    body = norm("".join(pages))

    # 1 前回計画の章題が本文に実在すること（書き写しの取り違えを防ぐ）
    miss = []
    for _bu, sho, _setsu in ZENKAI_KOUSEI:
        t = sho.split(" ", 1)[-1]
        if norm(t) not in body:
            miss.append(sho)
    if miss:
        ng.append(f"前回計画の本文に見つからない章題がある: {miss}")

    # 2 3章の指摘が前回計画の本文に実在すること
    for need in ("入所者数の削減目標を22人", "移行する人数の目標を31人",
                 "119.2", "84.6", "6％以上", "5％以上削減"):
        if norm(need) not in body:
            ng.append(f"3章の根拠が前回計画の本文に見つからない: {need}")

    # 3 第10章の節名の誤りが実在すること
    #   「文化芸術活動・スポーツ活動等の振興」の直後に「総合的な就労支援」が来る
    i = body.find(norm("文化芸術活動スポーツ活動等の振興"))
    if i < 0:
        ng.append("前回計画 第2部第10章の章題が見つからない")
    else:
        if norm("総合的な就労支援") not in body[i:i + 200]:
            ng.append("第2部第10章の節名の誤り（総合的な就労支援）が確認できない。"
                      "3章の指摘を取り下げる")

    # 4 4章が挙げた節が、骨子案の重点化事項に本当に現れないこと
    #   骨子案の表は「章」の列が番号のみ（第5章）、「分野」の列が章題である。
    for sho, setsu, _jokyo, _atsukai in OCHI:
        num = sho.split(" ", 1)[0]
        if num not in juten:
            ng.append(f"骨子案に章が見つからない: {num}（{sho}）")
            continue
        bunya, juten_txt = juten[num]
        if norm(bunya) != norm(sho.split(" ", 1)[-1]):
            ng.append(f"骨子案の章題と4章の書き写しが合わない: "
                      f"{num} 骨子案「{bunya}」／本書「{sho}」")
        key = norm(setsu.split(" ", 1)[-1])[:6]
        if key and key in norm(juten_txt):
            ng.append(f"4章が挙げた節は骨子案の重点化事項に現れている: "
                      f"{sho} / {setsu}")

    # 5 素案の構成案が前回の第2部10章と1対1で対応すること
    z2 = [s for b, s, _x in ZENKAI_KOUSEI if b.startswith("第2部")]
    s2 = [s for b, s, _x, _y, _z in SOAN if b.startswith("第2部")]
    if len(z2) != len(s2):
        ng.append(f"第2部の章数が前回{len(z2)}と素案{len(s2)}で一致しない")

    # 5b 第1部の章が前回より減っていないこと（5章の記述の裏付け）
    z1 = [s for b, s, _x in ZENKAI_KOUSEI if b.startswith("第1部")]
    s1 = [s for b, s, _x, _y, _z in SOAN if b.startswith("第1部")]
    if len(s1) < len(z1):
        ng.append(f"第1部の章が前回{len(z1)}から素案{len(s1)}に減っている。"
                  "「第1部と第2部はいずれも章が増えるか同じ」の記述と合わない")

    # 6 素案の第3部が3章であること（骨子案の立て方を踏まえる）
    s3 = [s for b, s, _x, _y, _z in SOAN if b.startswith("第3部")]
    if len(s3) != 3:
        ng.append(f"素案の第3部が3章でない: {len(s3)}")

    # 7 成果目標が8区分あること
    seika = next(x for x in SOAN if x[1] == "第1章 成果目標")
    if len(seika[2].split("／")) != 8:
        ng.append(f"成果目標が8区分でない: {len(seika[2].split('／'))}")

    # 8 他団体名が成果品に現れないこと（本ブランチの規律）
    #   禁止語を並べるのではなく、成果品から「◯◯市・◯◯町・◯◯村・◯◯県」の形の
    #   語を残らず拾い、小野町・福島県と一般語以外が出たら不合格とする。
    #   思いつかなかった団体名も捕まる。
    #   漢字・カタカナの続きだけを名前の一部とみなす（ひらがなで切る）。
    out_text = docx_text(outpath)
    found = set(re.findall(r"[一-龥ァ-ヶー]{1,5}[市町村県]", out_text))
    ng += [f"他団体名が成果品に現れている: {t}" for t in sorted(found)
           if not any(t.endswith(ok) for ok in MUNI_OK)]

    # 9 章番号の引用がずれていないこと
    #   見出しが CH のとおり1から順に並び、本文から引く「◯章」が実在すること。
    heads = re.findall(r"^(\d+)　(.+)$", out_text, re.M)
    want = [(str(n), t) for n, t in CH.values()]
    if [(a, b) for a, b in heads] != want:
        ng.append(f"見出しがCHと一致しない: 成果品{heads}／CH{want}")
    #   本文からの引用が成果品に残っていること（章を引く文が落ちていないか）
    for need in (f"{ch('県')}に掲げています", f"{ch('県')}に、確認できたこと",
                 f"{ch('素案')}の構成案に対応"):
        if need not in out_text:
            ng.append(f"章を引く文が成果品に見つからない: {need}")

    # 10 県計画が「手元になし」又は「未公表」「未確認」であること
    if not any("手元になし" in x[2] or "未公表" in x[2] or "未確認" in x[2]
               for x in KEN):
        ng.append("6章が県計画の入手状況を示していない")

    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("  -", x)
        return False
    print(f"自己点検: 合格　"
          f"前回計画の章題 {len(ZENKAI_KOUSEI)}件すべて本文と照合／"
          f"3章の根拠6件を本文で確認／"
          f"4章の{len(OCHI)}件が骨子案の重点化事項に現れないことを確認／"
          f"第2部の章数 前回{len(z2)}＝素案{len(s2)}／"
          f"成果目標8区分／"
          f"成果品に現れる自治体名は小野町・福島県のみ（{len(found)}語を照合）")
    return True


if __name__ == "__main__":
    import sys
