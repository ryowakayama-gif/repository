def read_zenkai_text():
    """前回計画のPDFからテキストを取り出す（章節の照合に用いる）。"""
    if not ZENKAI.exists():
        raise SystemExit(
            "\n".join([
                f"前回計画が見つかりません: {ZENKAI}",
                "令和8年10月7日に受領し 13_関連計画 に収めたものです。",
                "ブランチの取得が古い場合は git fetch してください。",
            ]))
    r = pypdf.PdfReader(str(ZENKAI))
    pages = [(pg.extract_text() or "") for pg in r.pages]
    return pages, len(pages)


def norm(s):
    """照合用に、全角数字・空白・記号のゆれを落とす。"""
    z = "０１２３４５６７８９"
    for i, c in enumerate(z):
        s = s.replace(c, str(i))
    return re.sub(r"[\s　・、。（）()]", "", s)


def read_kosshi_juten():
    """骨子案 第2版の第2部の重点化事項を読む（4章の突き合わせに用いる）。"""
    import docx
    d = docx.Document(KOSSHI)
    out = {}
    for t in d.tables:
        h = [c.text.strip() for c in t.rows[0].cells]
        if h[:2] == ["章", "分野"]:
            for row in t.rows[1:]:
                c = [x.text.strip().replace("\n", " ") for x in row.cells]
                out[c[0]] = (c[1], c[2])
    if not out:
        raise LookupError("骨子案に第2部の章立ての表が見つかりません")
    return out


