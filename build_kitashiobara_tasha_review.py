def _norm(t):
    return re.sub(r"[\s　]+", "", str(t))


def _docx_text(path):
    from docx import Document
    d = Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            out.append("｜".join(c.text for c in r.cells))
    return out


def _pdf_text(path):
    import pdfplumber
    with pdfplumber.open(path) as p:
        return "\n".join(pg.extract_text() or "" for pg in p.pages)


def kensa(review, member, honpon):
    ng = []
    rv = [_norm(x) for x in review]
    hon = _norm("\n".join(honpon)) if honpon is not None else None
    # ① レビューの語がレビューの当該指摘の行に実在すること
    for no, _j, go, *_r in SHITEKI:
        if not any(no in x and _norm(go) in x for x in rv):
            ng.append(f"① レビューに無い指摘: {no}")
    # ①b レビューの指摘を取りこぼしていないこと（R番号の数）
    nos = set(re.findall(r"R\d\d", "\n".join(review)))
    nuke = sorted(nos - {x[0] for x in SHITEKI})
    if nuke:
        ng.append(f"①b 検証していない指摘: {nuke}")
    # ② 正本の照合語が正本に実在すること
    if hon is not None:
        for no, _j, _g, _h, go, _t in SHITEKI:
            if _norm(go) not in hon:
                ng.append(f"② 正本に無い照合語: {no} {go[:20]}")
    # ③ 直す前の文が他メンバー版にちょうど1つ、直した後が正本にあること
    mem = [_norm(x) for x in member]
    for rec in TR_KAKIKAE:
        if mem.count(_norm(rec["mae"])) != 1:
            ng.append(f"③ 直す前の文が他メンバー版に一意でない: {rec['no']}")
        if hon is not None:
            if _norm(rec["ato"]) not in hon:
                ng.append(f"③ 正本の文が直っていない: {rec['no']}")
            if _norm(rec["mae"]) in hon:
                ng.append(f"③ 正本に直す前の文が残っている: {rec['no']}")
    return ng


def verify():
    ng = []
    review = _docx_text(REVIEW)
    member = _docx_text(MEMBER)
    honpon = _docx_text(HONPON) if os.path.exists(HONPON) else None
    ng += kensa(review, member, honpon)

    # ④ R13 の根拠：村の計画策定方針に「中間見直しを行い」が実在すること
    if "中間見直しを行い" not in _norm(_pdf_text(SAKUTEI)):
        ng.append("④ 計画策定方針に中間見直しの語が無い")

    # ⑤ R15 の検算：計は円単位の和を千円に丸めた値であること
    for y, kei in ((3, 49246), (7, 55513)):
        en = KAIGO_TOTAL[y][1] + JIDO_TOTAL[y][1]
        if round(en / 1000) != kei:
            ng.append(f"⑤ 給付費の計が円単位の和と合わない: 令和{y}年度")
        uchi = round(KAIGO_TOTAL[y][1] / 1000) + round(JIDO_TOTAL[y][1] / 1000)
        if y == 3 and uchi == kei:
            ng.append("⑤ 令和３年度の端数の差が無くなった（断りを外す）")

    # ⑥ 国の原本を当方が持っていること（レビューの二次資料に頼らない）
    if not os.path.exists(SHISHIN):
        ng.append("⑥ 基本指針の告示本文が無い")
    if "公式文書そのものではありません" not in _pdf_text(NIJI):
        ng.append("⑥ レビューのPDFが二次資料である旨の記載が見当たらない")

    # 否定試験65〜66
    if not kensa(review + ["R16 新しい指摘"], member, honpon):
        ng.append("否定試験65: 指摘を足しても①bが落ちない")
    if not kensa(review, member + [TR_KAKIKAE[0]["mae"]], honpon):
        ng.append("否定試験66: 直す前の文が二つあっても③が落ちない")

    if ng:
        print("自己点検 不合格:")
        for e in ng:
            print("   -", e)
        raise SystemExit(1)
    return (f"指摘{len(SHITEKI)}件をレビューと正本の現物で照合／"
            f"書き換え{len(TR_KAKIKAE)}件／"
            + ("正本に反映済み／" if honpon is not None else "正本は未生成／")
            + "端数の検算／否定試験2件")


