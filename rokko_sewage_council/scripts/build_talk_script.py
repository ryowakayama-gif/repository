def build_notes():
    """各ページのノート欄に読み上げ文と進行メモを書き込む."""
    marks, t = [], START
    for item in SCRIPT:
        marks.append(t)
        t += item[2]
    by_src = {"本編": {}, "別紙": {}}
    for item, mark in zip(SCRIPT, marks):
        src, page, dur, head, talk, memo = item
        if src in by_src:
            body = [f"【{hhmm(mark)}〜{hhmm(mark + dur)}／{mmss(dur)}】{head}", "", talk]
            if memo:
                body += ["", "― 進行メモ ―"] + [f"・{m}" for m in memo]
            by_src[src][page] = "\n".join(body)

    for path, src in ((DECK, "本編"), (APPX, "別紙")):
        prs = Presentation(path)
        for i, slide in enumerate(prs.slides, start=1):
            text = by_src[src].get(i)
            if text:
                slide.notes_slide.notes_text_frame.text = text
        prs.save(path)
        print(f"notes written: {path.name}（{len(by_src[src])}ページ）")


