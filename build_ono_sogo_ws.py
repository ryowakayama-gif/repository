def _taihi(y, a, b, c):
    """歳出シートの値を、当方が年報から読んだ値と突き合わせる。"""
    j = T.CHIIKI_JISSEKI.get(y)
    if j is None:
        return "**当方は年報を令和3年度から読んでいるため対比なし**"
    return "**1円まで一致**" if (a, b, c) == (
        j["介護予防・生活支援サービス事業"], j["一般介護予防事業"],
        j["包括的支援事業・任意事業"]) else "**差がある**"


def nintei(p):
    """年齢階層別認定率（令和7年度実績）×将来推計人口。"""
    r = T.NINTEI_RATE_R7
    return round(r["65-74"] * p[3] + r["75-84"] * p[4] + r["85+"] * p[5])


def jinzai():
    """需要（認定者数の推計）と、生産年齢人口で縮めた供給可能量。"""
    base_n, base_w = nintei(JINKO[0]), JINKO[0][2]
    rows = []
    for p in JINKO:
        n = nintei(p)
        sup = round(base_n * p[2] / base_w)
        rows.append((p[0], p[1], p[2], n, sup, sup - n))
    return rows


