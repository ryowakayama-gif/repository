def selfcheck(figs):
    bad = []
    # 社人研の65歳以上人口が見える化の第1号被保険者数と一致すること
    SYS = {"2030年": 3406, "2035年": 3206, "2040年": 2993, "2045年": 2818,
           "2050年": 2565}
    for y, tot, _w, a, b, c in JINKO:
        if y in SYS and a + b + c != SYS[y]:
            bad.append(f"{y} 65歳以上 {a + b + c}≠見える化{SYS[y]}")
    # 歳出シートの値が年報と一致すること
    for y, (a, b, c) in SAISHUTSU.items():
        j = T.CHIIKI_JISSEKI.get(y)
        if j is None:
            continue                      # 年報は令和3年度以降のみ読んでいる
        if (a, b, c) != (j["介護予防・生活支援サービス事業"], j["一般介護予防事業"],
                         j["包括的支援事業・任意事業"]):
            bad.append(f"{y} 歳出が年報と不一致")
    if len(JINZAI) != len(JINKO):
        bad.append("人材の視点の行数")
    if JINZAI[0][5] != 0:
        bad.append(f"基準年の過不足 {JINZAI[0][5]}≠0")
    for k in ("人材", "軽度", "調査"):
        if not pathlib.Path(figs[k]).exists():
            bad.append(f"図が作られていない {k}")
    return bad


