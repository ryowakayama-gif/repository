def verify():
    cats = {rec[0] for rec in SPEC_ITEMS}
    assert cats == set(CATEGORIES), f"区分が定義と一致しません: {cats ^ set(CATEGORIES)}"
    states = {rec[4] for rec in SPEC_ITEMS} | {s[4] for s in SCHEDULE}
    unknown = states - set(PROGRESS_FILL)
    assert not unknown, f"未定義の状態: {unknown}"
    nos = [rec[1] for rec in SPEC_ITEMS]
    assert len(nos) == len(set(nos)), "項番が重複しています"
    for rec in SPEC_ITEMS:
        assert 0.0 <= rec[5] <= 1.0, f"進捗率が範囲外: {rec[1]} {rec[5]}"
    overall = sum(rec[5] for rec in SPEC_ITEMS) / len(SPEC_ITEMS)
    print(f"  自己検証: 仕様書項目{len(SPEC_ITEMS)}件・区分{len(CATEGORIES)}・"
          f"村資料{len(VILLAGE_DOCS)}件・リスク{len(RISKS)}件／全体平均進捗 {overall:.0%}")


