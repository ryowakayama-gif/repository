NAVY, PALE, HEAD = "1F4E78", "EAF3F8", "5B9BD5"
IN_Y, OK_G, NG_O, GRAY = "FFF2CC", "E2EFDA", "FCE4D6", "F2F2F2"
thin = Side(style="thin", color="BFBFBF")
BORDER = Border(left=thin, right=thin, top=thin, bottom=thin)
wb = Workbook()


def sheet(name, title, subtitle, widths):
    ws = wb.create_sheet(name)
    ws["A1"] = title
    ws["A1"].font = Font(name=FONT, size=15, bold=True, color="FFFFFF")
    ws["A1"].fill = PatternFill("solid", fgColor=NAVY)
    ws["A2"] = subtitle
    ws["A2"].font = Font(name=FONT, size=10)
    ws["A2"].fill = PatternFill("solid", fgColor=PALE)
    n = len(widths)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=n)
    ws.merge_cells(start_row=2, start_column=1, end_row=2, end_column=n)
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.row_dimensions[1].height = 26
    ws.row_dimensions[2].height = 18
    return ws


def table(ws, row, head, rows, fills=None):
    for i, h in enumerate(head, 1):
        c = ws.cell(row=row, column=i, value=h)
        c.font = Font(name=FONT, size=10, bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor=HEAD)
        c.alignment = Alignment(wrap_text=True, horizontal="center", vertical="center")
        c.border = BORDER
    ws.row_dimensions[row].height = 30
    r = row + 1
    for data in rows:
        for i, v in enumerate(data, 1):
            c = ws.cell(row=r, column=i, value=v)
            c.font = Font(name=FONT, size=9)
            c.alignment = Alignment(wrap_text=True, vertical="top")
            c.border = BORDER
            if fills and fills.get(i):
                c.fill = PatternFill("solid", fgColor=fills[i])
        r += 1
    return r - 1


def note(ws, row, text, n=8):
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(name=FONT, size=8, italic=True)
    c.alignment = Alignment(wrap_text=True, vertical="top")
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=n)
    ws.row_dimensions[row].height = 40


