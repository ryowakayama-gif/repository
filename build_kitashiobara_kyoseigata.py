def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            for c in r.cells:
                out.append(c.text)
    return "\n".join(out)


def _norm(s):
    return re.sub(r"\s+", "", str(s))


def load_koku():
    """国の資料7件と村の手引きを読む。"""
    import pypdf
    out = {}
    for f in sorted(os.listdir(KOKU_DIR)):
        if not f.endswith(".pdf"):
            continue
        r = pypdf.PdfReader(f"{KOKU_DIR}/{f}")
        out[f[:-4]] = _norm("\n".join((p.extract_text() or "")
                                      for p in r.pages))
    if not os.path.exists(TEBIKI):
        raise SystemExit(f"高齢者サービスの手引きが見つかりません: {TEBIKI}")
    r = pypdf.PdfReader(TEBIKI)
    out["手引き"] = _norm("\n".join((p.extract_text() or "")
                                  for p in r.pages))
    return out


