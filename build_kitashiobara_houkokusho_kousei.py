def run_checks(needs, jido):
    ng = []

    # 1 ニーズの実数が集計と一致すること（施設入所支援は現在5・今後9）
    d = {n[0]: n for n in needs}
    if d["施設入所支援"][1] != 5 or d["施設入所支援"][3] != 9:
        ng.append(f"施設入所支援が現在5・今後9でない: "
                  f"{d['施設入所支援'][1]}・{d['施設入所支援'][3]}")
    if d["就労継続支援A型"][1] != 1:
        ng.append(f"就労継続支援A型の現在利用が1でない: {d['就労継続支援A型'][1]}")
    if d["移動支援"][1] != 1 or d["移動支援"][3] != 2:
        ng.append(f"移動支援が現在1・今後2でない: {d['移動支援'][1]}・{d['移動支援'][3]}")

    # 2 差が 今後－現在 であること
    for n in needs:
        if n[4] != n[3] - n[1]:
            ng.append(f"差が今後－現在になっていない: {n[0]}")

    # 3 障がい児の移動支援が3件（全員）であること
    j = dict(jido)
    if j.get("移動支援") != VALID_CHILD:
        ng.append(f"児問29の移動支援が{VALID_CHILD}件でない: {j.get('移動支援')}")

    # 4 構成案が8章で、新設が第6章・第7章だけであること
    chaps = []
    for x in KOUSEI:
        if x[0] not in chaps:
            chaps.append(x[0])
    if len(chaps) != 8:
        ng.append(f"構成案が8章でない: {len(chaps)}章 {chaps}")
    shinsetsu = {x[0] for x in KOUSEI if x[6] == "新設"}
    if shinsetsu != {"第6章 調査結果の背景", "第7章 ニーズの整理"}:
        ng.append(f"新設が第6章・第7章だけでない: {sorted(shinsetsu)}")

    # 5 ご提案の6区分すべてに見解を述べていること
    teian = {x[0] for x in KENKAI}
    want = {"単純集計", "クロス集計", "課題整理", "要因分析", "ニーズ",
            "計画策定時の注意点"}
    if teian != want:
        ng.append(f"ご提案の6区分と見解が対応していない: {sorted(teian ^ want)}")

    # 6 背景の6節それぞれに村の状況と背景が書かれていること
    for h in HAIKEI:
        if not h[2].strip() or not h[3].strip():
            ng.append(f"04シートに空欄がある: {h[0]}")
    if len(HAIKEI) != 6:
        ng.append(f"背景が6節でない: {len(HAIKEI)}")

