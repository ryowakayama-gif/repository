def _rows(ws, r, recs, aligns, h=40, mark_col=None, fills=None):
    for i, rec in enumerate(recs):
        write_row(ws, r, list(rec), alt=(i % 2 == 1), aligns=aligns)
        if mark_col:
            c = ws.cell(row=r, column=mark_col)
            fill = (fills or {}).get(str(c.value))
            if fill:
                c.fill = PatternFill("solid", fgColor=fill)
                c.font = Font(name=FONT, size=10, bold=True, color="FFFFFF")
        ws.row_dimensions[r].height = h
        r += 1
    return r


def _bullets(ws, r, ncol, items, h=52):
    for i, t in enumerate(items):
        ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=ncol)
        c = ws.cell(row=r, column=1, value=t)
        c.font = Font(name=FONT, size=10)
        c.alignment = Alignment(vertical="top", horizontal="left",
                                wrap_text=True, indent=1)
        if i % 2 == 1:
            c.fill = PatternFill("solid", fgColor=COLORS["alt"])
        ws.row_dimensions[r].height = h
        r += 1
    return r


