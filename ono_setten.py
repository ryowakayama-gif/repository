def check():
    """両計画に**同じ文言で**入っていることを確かめる。

    片方の生成器だけを直すと食い違う。現物を読んで照合する。
    """
    import pathlib
    import re
    import warnings
    import zipfile
    import ono_shogai_hyoki as HY
    warnings.filterwarnings("ignore")

    root = pathlib.Path(__file__).parent / "小野町_引継ぎ_整理済"
    text = {}
    for nm, rel in TAISHO:
        p = root / rel
        if not p.exists():
            print("** 見つからない %s" % rel)
            return 1
        with zipfile.ZipFile(p) as z:
            raw = z.read("word/document.xml").decode("utf-8", "ignore")
        # 「障害」「障がい」の書き分けは各計画の規則による（障がい計画は前回計画の書き方）。
        # 書き分けの違いを除いて同じ文言であることを確かめる。
        text[nm] = HY.kyotsu(re.sub(r"\s+", "", re.sub(r"<[^>]+>", "", raw)))

    def plain(s):
        return HY.kyotsu(re.sub(r"\s+", "", s.replace("**", "")))

    ng = []
    # 1 9つの場面が両方にあること（制度の内容・本町での扱いとも）
    for no, ken, seido, atsukai in SETTEN:
        for nm in text:
            for lbl, s in (("場面", ken), ("制度の内容", seido),
                           ("本町での扱い", atsukai)):
                if plain(s) not in text[nm]:
                    ng.append("%s に %s の%sがない" % (nm, no, lbl))
    # 2 前書き・人口の前提・断りが両方にあること
    for lbl, s in ([("前書き%d" % (i + 1), x) for i, x in enumerate(LEAD)]
                   + [("人口の前提", JINKO), ("条文番号の断り", JOBUN)]):
        for nm in text:
            if plain(s) not in text[nm]:
                ng.append("%s に%sがない" % (nm, lbl))
    # 3 確かめることが両方にあること
    for i, s in enumerate(KAKUNIN):
        for nm in text:
            if plain(s) not in text[nm]:
                ng.append("%s に確認事項%dがない" % (nm, i + 1))
    # 4 接点の語が両計画に現れること
    GO = ("適用除外", "受給者証", "介護保険優先", "共生型", "基準該当",
          "特定疾病", "第2号被保険者", "計画相談支援", "居宅介護支援",
          "地域包括支援センター", "40歳", "65歳", "障害支援区分",
          "支援会議", "支援協議会", "第115条の48", "第89条の3")
    for g in GO:
        miss = [nm for nm in text if HY.kyotsu(g) not in text[nm]]
        if miss:
            ng.append("語「%s」が %s にない" % (g, "・".join(miss)))

    print("■ 両計画の接点　同じ文言で入っているかの点検")
    for nm, rel in TAISHO:
        print("   %s　%s" % (nm, rel.split("/")[-1]))
    print("   場面%d　確認事項%d　接点の語%d" % (len(SETTEN), len(KAKUNIN), len(GO)))
    if ng:
        for x in ng[:20]:
            print("   NG  %s" % x)
        if len(ng) > 20:
            print("   ほか%d件" % (len(ng) - 20))
        return 1
    print("   すべて両計画に同じ文言で入っています")
    return 0


if __name__ == "__main__":
    raise SystemExit(check())
