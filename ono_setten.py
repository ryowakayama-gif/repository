def render(doc, tbl, body, note, tbd, h3=None):
    """両計画に同じ節を置く。

    doc  … ono_style.Report
    tbl  … 表を置く関数 tbl(doc, header, rows, widths=None)
    body … 段落をまとめて置く関数 body(doc, *paras)
    note … 注記を置く関数 note(doc, text)
    tbd  … 未確定の表示（素案と骨子案で記号が違う）
    """
    body(doc, *LEAD)
    tbl(doc, ["#", "場面", "制度の内容", "本町での扱い"],
        [(n, k, s, t) for n, k, s, t in SETTEN],
        widths=[0.8, 3.4, 6.6, 6.4])
    doc.p(JINKO)
    note(doc, JOBUN)
    doc.spacer()
    doc.p("**上の判定を行うために、次のことを町に確かめます。**")
    # **zip を使わない。** 以前は zip(KAKUNIN, 効くもの) としていたため、
    #   KAKUNIN に1件足したとき**短い方で止まって黙って落ちた**
    #   （接点の点検が「確認事項7がない」で捕まえた）。
    #   数が合わなければ、その場で止める。
    KIKU = ["5（保険料の分母）", "2・4・7・9（両計画の見込量）",
            "1（両計画の見込量）", "6（事業所の数え方）", "8（引継ぎ）",
            "10（判定を行う場）", "10（判定を行う場）"]
    if len(KIKU) != len(KAKUNIN):
        raise ValueError("確かめること%d件に対し、効くもの%d件（数を合わせる）"
                         % (len(KAKUNIN), len(KIKU)))
    tbl(doc, ["#", "確かめること", "効くもの"],
        [(str(i + 1), x, y) for i, (x, y) in enumerate(zip(KAKUNIN, KIKU))],
        widths=[0.8, 12.0, 4.4])
    doc.p(f"いずれも{tbd}です。"
          "**2の一覧が得られれば、2・4・7・9がまとめて片付きます。**")


