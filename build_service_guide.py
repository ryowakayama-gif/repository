def shozai(town, name):
    """公表資料による所在地。引けないものは記入枠とする。"""
    key = (town, _n(ALIAS.get((town, name), name)))
    return ADDR.get(key, "［　　］")


ADDR_NG = []                    # 所在地を引けなかった事業所

JIGYOSHO = {}
for town, rows in S.SHIGEN.items():
    for row in rows:
        JIGYOSHO.setdefault(svc(row[3]), []).append((town, row[1], row[2]))


def jigyosho_table(names, midashi):
    """掲載区分ごとの事業所表。所在地は公表資料、電話番号は記入枠とする。"""
    rows = []
    for nm in names:
        for town, jname, hojin in sorted(JIGYOSHO.get(nm, []),
                                         key=lambda x: (x[0], x[1])):
            ad = shozai(town, jname)
            if ad == "［　　］" and (town, jname) not in ADDR_NG:
                ADDR_NG.append((town, jname))
            rows.append([nm, town, jname, hojin, ad, "［　　］"])
    if not rows:
        return
    H2(midashi)
    TBL(["サービスの種類", "町", "事業所の名称", "法人等", "所在地", "電話番号"],
        rows, [3.0, 1.4, 4.6, 3.6, 4.4, 1.6], size=8.5, center={1, 5})


def n_of(names):
    return sum(len(JIGYOSHO.get(nm, [])) for nm in names)


