def _n(s_):
    s_ = unicodedata.normalize("NFKC", s_)
    s_ = re.sub(r"[\s「」（）()・\-ー,、.。]", "", s_)
    for w in _STRIP:
        s_ = s_.replace(w, "")
    return s_


