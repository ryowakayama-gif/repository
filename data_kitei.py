def _literal(fn, name):
    src = io.open(os.path.join(RP.ROOT, fn), encoding="utf-8").read()
    for node in ast.parse(src).body:
        if isinstance(node, ast.Assign) and any(
                getattr(t, "id", None) == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise RuntimeError("%s に %s が見つからない" % (fn, name))


def _from_ledger():
    """台帳（業務工程管理表）の回答欄に書かれている既定値。

    回答欄に「決着しない場合は…」と書いてあるものは、それが既定値である。
    読む側がそれぞれ回答欄を切り出していると、同じ切り出しが幾つもできる。
    本モジュールで1度だけ切り出す。

    台帳の書き方は2通りある。「決着しない場合は…」と
    「決着しない場合の当方の扱い＝…」であり、後者の接続の語を
    落とさないと「の当方の扱い＝」が既定値の先頭に残る。
    """
    out = {}
    for c in _literal("build_process_control.py", "CHECK"):
        kotae = str(c[9])
        if "決着しない場合" not in kotae:
            continue
        v = kotae.split("決着しない場合", 1)[-1]
        for tsunagi in ("の当方の扱い＝", "の当方の扱い=", "の扱い＝", "の扱い="):
            if v.startswith(tsunagi):
                v = v[len(tsunagi):]
                break
        v = v.lstrip("は、 　").strip()
        if v:
            out[c[0]] = v.rstrip("。")
    return out


def all_kitei():
    """既定値の全件（台帳の回答欄・従前の2か所・本モジュールを束ねたもの）。

    **読む側はこれを使う。** 4か所を個別に読まない。
    後に書いたものが優先する（台帳の回答欄が最も弱い）。
    """
    out = _from_ledger()
    out.update(_literal("build_soan_kadai.py", "KITEI"))
    out.update(_literal("build_chiiki_kadai_10.py", "KITEI_ADD"))
    out.update(KITEI)
    return out


