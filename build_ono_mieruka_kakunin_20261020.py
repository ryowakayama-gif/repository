    ng = jiko(v, soan_txt())
    p, miss = build(v)
    print("■ 見える化出力資料の確認結果")
    print("   ", p.relative_to(HERE))
    print("   受領 %d指標／未着 %s" % (len({fid(x) for x in files()}), "、".join(miss)))
    print("\n■ 自己点検")
    for x in ng:
        print("   NG", x)
    print("   すべて適合" if not ng else "   **%d件**" % len(ng))
    return 1 if ng else 0


