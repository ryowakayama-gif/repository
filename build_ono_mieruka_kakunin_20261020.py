def jiko(v, soan):
    ng = []
    for k, d in v.items():
        if not d and k not in ("F27",):
            ng.append("%s の値が読めない" % k)
    # 期待：次の語が素案にある（埋める先）
    for w in ["第13版までは自立度Ⅲa・Ⅲbの値がなく", "認定者に対する受給者の比率", "町内介護サービス事業所数",
              "認知症サポーター数（65歳以上人口10万対）", "入院時情報連携加算の算定者数割合は全保険者の上位1割",
              "死亡場所別の死亡数"]:
        if _n(w) not in soan:
            ng.append("素案に「%s」がない" % w)
    # 自立度の人数の合計が合計欄と一致するか（読み違いの検査）
    t = list(v["自立度計"])[-1]
    s = sum(v["自立度" + k][t] for k in ["自立", "Ⅰ", "Ⅱａ", "Ⅱｂ", "Ⅲa", "Ⅲb", "Ⅳ", "Ｍ"])
    if abs(s - v["自立度計"][t]) > 0.5:
        ng.append("B7 の人数の合計（%d）が合計欄（%d）と合わない" % (s, v["自立度計"][t]))
    return ng


