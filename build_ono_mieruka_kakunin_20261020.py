def _n(s):
    return unicodedata.normalize("NFKC", re.sub(r"\s+", "", str(s)))


def files():
    return sorted(p for p in SRC.glob("*.xlsx"))


def fid(p):
    return p.name.split("_")[0]


def read(p, sheet_prefix, label):
    """指定シートで label を含む行を探し、{見出し: 値} を返す（列番号で対応）。"""
    wb = openpyxl.load_workbook(p, read_only=True, data_only=True)
    ws = [w for w in wb.worksheets if w.title.startswith(sheet_prefix)][0]
    rows = [list(r) for r in ws.iter_rows(values_only=True)]
    hdr = None
    for r in rows:
        cells = [c for c in r if c is not None]
        if not cells or str(cells[0]).startswith("出力日"):
            continue
        if any(re.search(r"(年度|年|月|末|全国|福島県|小野町|20\d\d)", str(c)) for c in cells) and \
                not any(isinstance(c, (int, float)) for c in r):
            hdr = r
            break
    if hdr is None:
        return {}
    for r in rows:
        txt = " ".join(str(c) for c in r if isinstance(c, str))
        if _n(label) in _n(txt) and any(isinstance(c, (int, float)) for c in r):
            out = {}
            for j, h in enumerate(hdr):
                if h is not None and j < len(r) and isinstance(r[j], (int, float)) \
                        and not str(h).startswith("列"):
                    out[str(h).replace("\n", "")] = r[j]
            return out
    return {}


def last(d, n=1):
    ks = list(d)
    return [(k, d[k]) for k in ks[-n:]]


def P(i):
    m = [p for p in files() if fid(p) == i]
    return m[0] if m else None


def soan_txt():
    import docx
    doc = docx.Document(str(SOAN))
    t = [p.text for p in doc.paragraphs]
    for tb in doc.tables:
        for rw in tb.rows:
            t += [c.text for c in rw.cells]
    return _n("\n".join(t))


