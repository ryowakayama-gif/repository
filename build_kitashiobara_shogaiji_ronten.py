        if omosa not in (OMOI, CHU, KEI):
            ng.append(f"重さが未定義: {no} {omosa}")
        if moto not in gen:
            ng.append(f"原典の指定が不正: {no} {moto}")
            continue
        if _norm(konkyo) not in gen[moto]:
            ng.append(f"原典に無い語を根拠にしている: {no}"
                      f"（{konkyo[:30]}…／{moto}）")

