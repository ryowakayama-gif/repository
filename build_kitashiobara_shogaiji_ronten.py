def load_pdf(path):
    r = PdfReader(path)
    return "\n".join((pg.extract_text() or "") for pg in r.pages)


def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for row in t.rows:
            for c in row.cells:
                out.append(c.text)
    return "\n".join(out)


def _norm(s):
    return re.sub(r"[\s　]+", "", str(s))


def verify():
    ng = []

    # ① 原典が手元にあること
    gen = {}
    for key, path in GENTEN.items():
        if not os.path.exists(path):
            ng.append(f"原典が無い: {os.path.basename(path)}")
        else:
            gen[key] = _norm(load_pdf(path))

    # ② 漏れとして挙げた根拠が、挙げた原典の現物にあること。
    #    記憶で書いていないことの裏づけはここである。
