def verify():
    ng = []
    for p in (GENKO, MEMBER):
        if not os.path.exists(p):
            raise SystemExit(f"資料が見つかりません: {p}")
    pages = genko_pages()
    live = daichou()

    # ① 仮説Ａ ― 語が当該頁に実在し、照会番号が台帳に実在すること
    for no, pg, go, kotae, shiboru in KASETSU_A:
        if go.replace(" ", "") not in pages.get(pg, ""):
            ng.append(f"{no} 前期計画の語が p{pg} に無い: {go}")
        if no not in live:
            ng.append(f"{no} が照会の台帳に無い")
        if not kotae.strip() or not shiboru.strip():
            ng.append(f"{no} 答えている部分又は絞り方が空")

    # ② 仮説Ｂ ― 語が当該頁に実在し、正本と照会に無いこと
    hon = flat(HONPON) if os.path.exists(HONPON) else ""
    sho = re.sub(r"[\s　]+", "",
                 "".join(str(v["kenmei"]) + str(v["naiyo"])
                         for v in live.values()))
    sz_no = {r["no"] for r in SZ_EDITS} | {"ＳＺ-1", "ＳＺ-2"}
    for no, go, pg, omo, jotai, saki, dou in KASETSU_B:
        if go not in pages.get(pg, ""):
            ng.append(f"{no} 前期計画の語が p{pg} に無い: {go}")
        if omo not in (MAJI, CHU, KARUI):
            ng.append(f"{no} 重みが未定義: {omo}")
        if jotai not in (HANEI, TOU, HORYU):
            ng.append(f"{no} 状態が未定義: {jotai}")
        if not dou.strip():
            ng.append(f"{no} どうするかが空")
        if jotai == HANEI:
            if hon and go not in hon:
                ng.append(f"{no} 「正本に反映した」が正本に無い: {go}")
            if saki not in sz_no:
                ng.append(f"{no} 反映したのにＳＺ番号が無い: {saki}")
        else:
            if hon and go in hon:
                ng.append(f"{no} 「{jotai}」だが正本にある: {go}")
            if jotai == TOU:
                if saki not in live:
                    ng.append(f"{no} 照会番号が台帳に無い: {saki}")
            elif saki:
                ng.append(f"{no} 保留に行き先を書いている: {saki}")
        #   照会で尋ねているかは、反映したものには求めない
        if jotai == TOU and go not in sho and saki not in live:
            ng.append(f"{no} 照会にも正本にも無い: {go}")

    # ③ 仮説Ｃ ― 正本の文が実在し、前期計画の根拠の語が当該頁にあること
    for no, pg, go, mae, ato, saki, naze in KASETSU_C:
        if go not in pages.get(pg, ""):
            ng.append(f"{no} 前期計画の根拠の語が p{pg} に無い: {go}")
        if hon:
            if mae.replace(" ", "") in hon:
                ng.append(f"{no} 直す前の文が正本に残っている: {mae[:30]}")
            if ato.replace(" ", "") not in hon:
                ng.append(f"{no} 直した後の文が正本に無い: {ato[:30]}")
        if saki not in sz_no:
            ng.append(f"{no} ＳＺ番号が無い: {saki}")
        if not naze.strip():
            ng.append(f"{no} 何が違うかが空")

    # ④ 仮説Ｄ ― 正本が引く番号のうち台帳に無いものが、
    #    統合の一覧と旧番号の一覧の和にちょうど一致すること。
    #    これが永続の検査である。以後、正本に新しい番号を書いて
    #    台帳に載せ忘れると止まる。
    if os.path.exists(HONPON):
        nai, _tougou, kyu = todoite_inai()
        #   これが永続の検査である。正本の注記が引く番号は
        #   すべて照会の台帳にあること。以後、正本に新しい番号を
        #   書いて台帳に載せ忘れると止まる。
        if nai:
            ng.append(f"正本が引くのに台帳に無い番号がある"
                      f"（村に届かない）: {sorted(nai)}")
        hiku = set(honpon_ban())
        #   台帳へ戻した旧番号は、台帳にあり、正本が引いていること
        for no, _a, _k, _n, _g in KYUBAN:
            if no not in live:
                ng.append(f"台帳へ戻したはずの旧番号が台帳に無い: {no}")
            if no not in hiku:
                ng.append(f"旧番号を正本が引いていない"
                          f"（戻す必要がない）: {no}")
        #   統合したものは、正本の注記から統合先に書き換えてあること
        for old_no, new_no, riyu in TOUGOU:
            if old_no in hiku:
                ng.append(f"統合したのに正本が旧番号を引いている: "
                          f"{old_no} → {new_no}")
            if old_no in live:
                ng.append(f"統合したのに台帳にも残っている: {old_no}")
            if new_no not in live:
                ng.append(f"統合先が台帳に無い: {old_no} → {new_no}")
            if new_no not in hiku:
                ng.append(f"統合先を正本が引いていない: "
                          f"{old_no} → {new_no}")
            if new_no in kyu:
                ng.append(f"統合先が旧番号である（統合の連鎖）: "
                          f"{old_no} → {new_no}")
            if not riyu.strip():
                ng.append(f"統合の理由が空: {old_no}")
    else:
        print("  ※ 正本が無いため④は省略")

    # ⑤ 仮説Ｅ・Ｆ ― 語が当該頁に実在すること
    for no, kas, go, pg, naka in KASETSU_EF:
        if kas not in ("Ｅ", "Ｆ"):
            ng.append(f"{no} 仮説の別が未定義: {kas}")
        if go.replace(" ", "") not in pages.get(pg, ""):
            ng.append(f"{no} 前期計画の語が p{pg} に無い: {go}")
        if not naka.strip():
            ng.append(f"{no} 内容が空")
    #    ＲＴ-7 ― 正本が保健福祉課を用いており、前期計画は住民課である
    if hon:
        if "北塩原村保健福祉課" not in hon:
            ng.append("正本に「北塩原村保健福祉課」が無い"
                      "（ＲＴ-7の前提が崩れる）")
        if "住民課" in hon:
            ng.append("正本に「住民課」がある（ＲＴ-7の判定を見直すこと）")
    #    ＲＴ-8 ― 任期の書き換えが他メンバー版の段階で起きていること
    mem = flat(MEMBER)
    if "任期：令和６年４月１日～令和９年３月31日".replace(" ", "") not in mem:
        ng.append("他メンバー版に書き換え後の任期が無い"
                  "（ＲＴ-8の読みが崩れる）")

    # ⑥ 仮説の一覧が6つで、いずれにも当たりがあること
    if len(KASETSU) != 6:
        ng.append(f"仮説が6つでない: {len(KASETSU)}")
    k = _kazu()
    for no, na, _h, key in KASETSU:
        if key not in k:
            ng.append(f"仮説{no}の数え先が未定義: {key}")
        elif k[key] == 0:
            ng.append(f"仮説{no}に当たりが0件（仮説を取り下げるか見直す）")

    # ⑦ 照会の番号が重複せず、台帳の現行採番（Ｍ-40〜）と衝突しないこと
    sno = [x[0] for x in SHOUKAI]
    if len(sno) != len(set(sno)):
        ng.append(f"照会の番号に重複がある: {sno}")
    for no, ate, ken, naka, kigen in SHOUKAI:
        if ate not in ("村", "他メンバー"):
            ng.append(f"{no} 宛先が未定義: {ate}")
        if not ken.strip() or not naka.strip() or not kigen.strip():
            ng.append(f"{no} 件名・内容・期限のいずれかが空")
    for no, _a, _k, _n, _g in SHINKI:
        if int(no.split("-")[1]) <= 132:
            ng.append(f"新しい照会の番号が既存の採番と衝突する: {no}")
    for no, _a, _k, _n, _g in KYUBAN:
        if int(no.split("-")[1]) >= 40:
            ng.append(f"旧番号に40以上を入れている: {no}")

    # ⑧ 反映の挿入位置が正本にちょうど1つあること
    if os.path.exists(HONPON):
        dan = [t for loc, t in honbun(HONPON) if loc.startswith("P")]
        for rec in SZ_EDITS:
            n = sum(1 for t in dan if rec["ichi"] in t)
            if n != 1:
                ng.append(f"{rec['no']} の挿入位置が{n}件（1件でない）: "
                          f"{rec['ichi'][:30]}")

    # ⑨ 他団体の名が入っていないこと
    zen = "\n".join(str(v) for rec in (KASETSU + KASETSU_B + KASETSU_C +
                                       KASETSU_EF + TOUGOU)
                    for v in rec if isinstance(v, str))
    zen += "\n" + "\n".join(str(v) for rec in SHOUKAI for v in rec)
    zen += "\n" + "\n".join(
        str(rec["konkyo"]) + "".join(b[1] for b in rec["nakami"])
        for rec in SZ_EDITS)
    for hoka in ("小野町", "金ヶ崎", "金ケ崎", "阿蘇", "札幌", "川崎町"):
        if hoka in zen:
            ng.append(f"他団体の名が入っている: {hoka}")

    if ng:
        for x in ng:
            print(f"  × {x}")
        raise SystemExit("前期計画のレッドチーム分析の自己点検で止めました")

    nai, _t, _k = todoite_inai() if os.path.exists(HONPON) else ([], 0, 0)
    return (f"仮説6件すべてに当たり（合計{sum(k.values())}件）／"
            f"前期計画 {len(pages)}頁／"
            f"絞り込める照会 {len(KASETSU_A)}件／"
            f"落ちているもの {len(KASETSU_B)}件／"
            f"読み違い {len(KASETSU_C)}件／"
            f"届いていなかった番号 {len(TOUGOU) + len(KYUBAN)}種"
            f"（統合{len(TOUGOU)}・台帳へ{len(KYUBAN)}。"
            f"いま台帳に無いもの {len(nai)}種）／"
            f"新しい照会 {len(SHINKI)}件／反映 {len(SZ_EDITS)}件")


