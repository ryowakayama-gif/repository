def genko_pages():
    """前期計画の頁ごとの文字（空白と改行を落としたもの）。"""
    with pdfplumber.open(GENKO) as pdf:
        return {i + 1: re.sub(r"[\s　]+", "", p.extract_text() or "")
                for i, p in enumerate(pdf.pages)}


def honbun(path):
    """全文（段落＋表のセル）。所在が分かる形で返す。"""
    d = Document(path)
    out = [("P%d" % i, p.text) for i, p in enumerate(d.paragraphs)]
    for ti, t in enumerate(d.tables):
        for ri, r in enumerate(t.rows):
            for ci, c in enumerate(r.cells):
                out.append(("T%d.%d.%d" % (ti, ri, ci), c.text))
    return out


def flat(path):
    return re.sub(r"[\s　]+", "", "".join(t for _l, t in honbun(path)))


def daichou():
    """照会の台帳（生きている番号）。"""
    import importlib
    m = importlib.import_module("build_kitashiobara_kakunin_kubun")
    return m.zenbu()


def honpon_ban():
    """正本の注記が引く照会番号。"""
    txt = "\n".join(t for _l, t in honbun(HONPON))
    return sorted(set(re.findall(r"[ＭＳ]-\d+", txt)),
                  key=lambda s: (s[0], int(s.split("-")[1])))


def todoite_inai():
    """正本が引くのに台帳に無い番号。統合できるものと、どこにも無いもの。"""
    live = set(daichou())
    hiku = set(honpon_ban())
    nai = hiku - live
    tougou = {x[0] for x in TOUGOU}
    kyu = {x[0] for x in KYUBAN}
    return sorted(nai, key=lambda s: (s[0], int(s.split("-")[1]))), tougou, kyu


