def selfcheck(figs):
    bad = []
    # 目標別の合計が総合と合うこと
    moku = sum(v["小野町"] for nm, v in GOKEI.items() if v["満点"] == 100)
    if abs(moku - ZEN["小野町"]) > 0.5:
        bad.append(f"目標別の合計 {moku}≠{ZEN['小野町']}")
    # 2つの交付金の和が総合と合うこと
    two = (GOKEI["保険者機能強化推進交付金 計"]["小野町"]
           + GOKEI["介護保険保険者努力支援交付金 計"]["小野町"])
    if abs(two - ZEN["小野町"]) > 0.5:
        bad.append(f"交付金別の合計 {two}≠{ZEN['小野町']}")
    # 指標群の和＋成果指標群が総合と合うこと
    if abs(TAI_O + KATS_O + SEIKA_O * 2 - ZEN["小野町"]) > 0.5:
        bad.append("指標群別の合計")
    # 指標ごとの配点の和が指標群の配点と合うこと
    for nm, v in GUN.items():
        kf = "保険者機能強化推進交付金" if nm.startswith("推進") else "介護保険保険者努力支援交付金"
        mk = "目標" + nm.split("　")[0][-1]
        g = "体制" if "体制" in nm else "活動"
        h = sum(s["配点"] for s in SHIHYO
                if s["交付金"] == kf and s["目標"].startswith(mk)
                and (("体制" in s["指標群"]) == (g == "体制")))
        if h != v["配点"]:
            bad.append(f"{nm} 配点の和 {h}≠{v['配点']}")
    if len(TEKISEIKA) != 4:
        bad.append(f"適正化の指標 {len(TEKISEIKA)}件")
    if len(RENKEI) != 5:
        bad.append(f"連携の指標 {len(RENKEI)}件")
    if len(SANJIGYO) != 3 or len(ICHIZUKE) != 3:
        bad.append("主要3事業／位置づけの案の件数")
    if abs(sum(s["全国平均"] - s["小野町"] for s in NOBI) - NOBI_KEI) > 0.01:
        bad.append("伸びしろの合計")
    for k, v in figs.items():
        if not pathlib.Path(v).exists():
            bad.append(f"図が作られていない {k}")
    return bad


