def selfcheck(figs):
    bad = []
    s = SOGO["推進・支援合計"]
    if abs(SOGO["推進合計"][0] + SOGO["支援合計"][0] - s[0]) > 0.5:
        bad.append(f"総合の内訳 {SOGO['推進合計'][0]}+{SOGO['支援合計'][0]}≠{s[0]}")
    if len(TEKISEIKA) != 4:
        bad.append(f"適正化の項目 {len(TEKISEIKA)}件")
    if len(SANJIGYO) != 3:
        bad.append(f"主要3事業 {len(SANJIGYO)}件")
    if len(ICHIZUKE) != 3:
        bad.append(f"位置づけの案 {len(ICHIZUKE)}件")
    # 伸びしろの合計が明細と合うこと
    if abs(sum(m[3] - m[2] for m in NOBI) - NOBI_KEI) > 0.01:
        bad.append("伸びしろの合計")
    for k, v in figs.items():
        if not pathlib.Path(v).exists():
            bad.append(f"図が作られていない {k}")
    return bad


