def _hayasa(nm):
    if "医療情報との突合" in nm:
        return "**早い（国保連への委託）**"
    if "方策を策定" in nm or "評価得点" in nm:
        return "**早い（計画に書く）**"
    if "ケアプラン点検" in nm:
        return "中（実施要領の策定が要る）"
    if "要介護度の変化" in nm or "健康寿命" in nm:
        return "**遅い（成果指標。3年程度）**"
    return "中"


