# ── 取り出し ──────────────────────────────────────────────
def rows(gun=None, svc=None, machi=None):
    """群・サービス種類コード・町で絞って ((群, 事業所番号, コード), 値) を返す。"""
    out = []
    for k, v in JIGYO.items():
        if gun and k[0] != gun:
            continue
        if svc and k[2] != svc:
            continue
        if machi and v["町"] != machi:
            continue
        out.append((k, v))
    return out


def svc_name(code):
    return SVC.get(code, "―")


def teiin(code, year=-1, machi=None):
    """当該サービスの区域内の定員の合計（既定は令和7年）。"""
    s = 0
    for k, v in JIGYO.items():
        if k[2] != code or "定員" not in v:
            continue
        if machi and v["町"] != machi:
            continue
        t = v["定員"][year]
        if t is not None:
            s += t
    return s


def juten(v, year=-1):
    """定員充足率＝1月あたり延べ利用者数÷定員（原本の数式のとおり）。"""
    if "定員" not in v:
        return None
    t, n = v["定員"][year], v["延べ利用者数"][year]
    if not t or n is None:
        return None
    return n / t


kaiten = juten  # 回転率も同じ式である


def gensho(v, kagi="利用者数"):
    """令和3年から令和7年までの変化の割合。いずれかが欠けるときは None。"""
    a, b = v[kagi][0], v[kagi][-1]
    if a in (None, 0) or b is None:
        return None
    return (b - a) / a


def renzoku_gensho(v, kagi="利用者数"):
    """令和4年から令和7年まで4年続けて前年を下回るとき True。"""
    x = v[kagi]
    if any(i is None for i in x):
        return False
    return all(x[i] < x[i - 1] for i in range(1, 5))


