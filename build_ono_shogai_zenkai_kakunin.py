"""障がい計画：前回計画の記載で町に確かめること（町との協議資料）。

素案 第5版で計画書から外した協議用の記述を、町との協議資料としてまとめる。
計画書には載せず、事務局（健康福祉課）と確かめたうえで第8期の設定に用いる。

  1　前回計画の成果目標①（施設入所者の地域生活移行）の値
  2　短期入所（福祉型・医療型）の第7期の見込量
  3　障がい児の第7期の見込量の単位（人と人日）
  4　前回計画の第10章の見出し

値は、前回計画のPDFから読み取ったもの（ono_shogai_zenkai。書き写さない）と、
素案の生成器（build_ono_soan_shogai）と同じ関数で作る。

出力
  16_町データ依頼/小野町_障がい計画_前回計画の記載で町に確かめること_YYYYMMDD.docx
"""

import pathlib
import sys

import docx

import build_ono_soan_shogai as SO
import ono_style as S

HERE = pathlib.Path(__file__).parent
OUT = HERE / "小野町_引継ぎ_整理済" / "16_町データ依頼"
ASOF = "20261023"
ASOF_JP = "令和8年10月23日"
ZENKAI = "おのまち障がい者基本計画・第7期障がい福祉計画・第3期障がい児福祉計画（令和6年3月）"

# 前回計画 第3部第5章 の成果目標①（原本の値。素案 第4版で照合済み）
NYUSHO = 26
IKO, SAKUGEN = 31, 22


def main():
    ng = []
    r = S.Report("障がい計画　前回計画の記載で町に確かめること")
    r.cover(["おのまち障がい者計画・第4期障がい児福祉計画・第8期障がい福祉計画"],
            ["前回計画の記載で町に確かめること（町との協議資料）", ASOF_JP, "ビズアップ公共コンサルティング株式会社"])
    r.toc_here()
    r.body_here()

    r.h1("1　この資料について")
    r.p("前回計画の数値・記載のうち、第8期の設定に引き継ぐ前に町に確かめたい事項を4つまとめました。"
        "**計画書（素案）には載せず、事務局と確かめたうえで、成果目標と見込量の設定に用います。**")
    r.tbl([["№", "事項", "前回計画の箇所", "第8期で使う場面"],
           ["1", "成果目標①（施設入所者の地域生活移行）の値", "第3部第5章1", "成果目標①の基準と目標値"],
           ["2", "短期入所（福祉型・医療型）の第7期の見込量", "第3部第6章2", "短期入所の見込量"],
           ["3", "障がい児の第7期の見込量の単位（人と人日）", "第3部第7章1", "障がい児支援の見込量"],
           ["4", "第10章の見出し", "第2部第10章", "第2部第10章の節立て"]],
          widths=[0.8, 7.0, 3.6, 5.8], caption="町に確かめる事項")

    r.h1("2　成果目標①（施設入所者の地域生活移行）の値")
    r.p("前回計画は、施設入所者の地域生活移行の目標を次のように定めています。")
    r.tbl([["項目", "前回計画の値", f"{NYUSHO}人に対する割合", "見方"],
           ["令和4年度末の施設入所者数", f"{NYUSHO}人", "―", "基準となる人数"],
           ["令和8年度末の地域生活移行者数（目標値）", f"{IKO}人", "%.1f％" % (IKO / NYUSHO * 100),
            f"入所者{NYUSHO}人より多い人数は移行できない"],
           ["令和8年度末の削減見込者数（目標値）", f"{SAKUGEN}人", "%.1f％" % (SAKUGEN / NYUSHO * 100),
            f"削減後は{NYUSHO - SAKUGEN}人。同じ計画の施設入所支援の見込量は15人"]],
          widths=[6.0, 2.6, 2.8, 5.8], caption="前回計画の成果目標①")
    r.src(f"資料：{ZENKAI}第3部第5章。国の基本指針は「令和4年度末時点の施設入所者の6％以上が令和8年度末までに"
          "地域生活へ移行」「令和8年度末時点の施設入所者を令和4年度末時点から5％以上削減」としている。"
          f"{NYUSHO}人に当てはめると、移行は%.2f人（2人）、削減は%.2f人（2人）" % (NYUSHO * 0.06, NYUSHO * 0.05))
    r.p("**町に確かめること：**目標値（移行31人・削減22人）の由来。"
        "第8期は、令和7年度末の確定値を基準に国の考え方に当てはめて設定し、成果目標と見込量が矛盾しないことを確かめます。")

    r.h1("3　短期入所（福祉型・医療型）の第7期の見込量")
    r.tbl([["区分", "第6期の実績（令和3〜5年度）", "第7期の見込量"],
           ["短期入所（福祉型）", "2〜3人／14〜21人日（実績あり）", "0人／0人日"],
           ["短期入所（医療型）", "0人／0人日（全年度0）", "2人／24人日"]],
          widths=[4.4, 7.0, 5.8], caption="短期入所の第6期の実績と第7期の見込量")
    r.src(f"資料：{ZENKAI}第3部第6章")
    r.p("実績のある福祉型を0とし、実績のない医療型に見込みを立てています。"
        "前回計画の本文は「短期入所（医療型）については、今後も利用が見込まれることから、"
        "第7期は各年度3人、24人日（一人あたり12人日）として算出しています」としていますが、表は2人です"
        "（24人日÷12人日＝2人）。")
    r.p("**町に確かめること：**福祉型と医療型の見込みが入れ替わっていないか。"
        "第8期は、実績のある福祉型に見込みを置く考えです。")

    r.h1("4　障がい児の第7期の見込量の単位")
    rows = SO._ayashii_rows()
    if not rows:
        ng.append("前回計画の障がい児の見込量が読み取れない")
    r.tbl([["サービス", "第6期の実績（令和5年度）", "第7期の見込量（前回計画）", "見方"]] + [list(x) for x in rows],
          widths=[3.6, 4.0, 4.0, 5.6], caption="障がい児の第6期の実績と第7期の見込量")
    r.src(f"資料：{ZENKAI}第3部第7章（PDFから読み取った値）")
    r.p(f"人と人日が入れ替わっているとみられます。本町の手帳所持者は{SO.TECHO_KEI[-1]}人（令和8年）であり、"
        "放課後等デイサービスを月391人が利用することは考えにくい値です。"
        "なお、障がい児の表だけ見出しが「◆第7期の目標」となっており、ほかの「◆第7期の見込量」と違います。")
    r.p("**町に確かめること：**第7期の見込量の人と人日。確かめたうえで、第7期の実績との対比に用います。")

    r.h1("5　前回計画の第10章の見出し")
    g = SO._goki_rows()
    r.tbl([["箇所", "前回計画の記載", "本来の記載"]] + [list(x) for x in g],
          widths=[4.0, 5.6, 7.6], caption="前回計画の第10章の見出し")
    r.src(f"資料：{ZENKAI}第2部第10章")
    r.p("節の名に第9章第1節の名がそのまま入っており、章の中身（文化芸術活動・スポーツ活動）と合っていません。"
        "本計画の第10章は、3つの節（文化芸術活動の振興／スポーツ・レクリエーションの振興／地域交流・社会参加の促進）を立てます。")

    p = OUT / f"小野町_障がい計画_前回計画の記載で町に確かめること_{ASOF}.docx"
    r.build_toc()
    r.save(p)
    t = "\n".join(x.text for x in docx.Document(str(p)).paragraphs)
    for w in ("訂正", "お詫び", "おわび", "北塩原", "大雪", "福島町"):
        if w in t:
            ng.append("「%s」が出ている" % w)
    if len(g) != 2:
        ng.append("第10章の見出しの行が%d件（2件のはず）" % len(g))
    print("■ 前回計画の記載で町に確かめること")
    print("   ", p.relative_to(HERE))
    print("\n■ 自己点検")
    for x in ng:
        print("   NG", x)
    print("   すべて適合" if not ng else "   **%d件**" % len(ng))
    return 1 if ng else 0


if __name__ == "__main__":
    sys.exit(main())
