def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            for c in r.cells:
                out.append(c.text)
    return "\n".join(out)


def _norm(s):
    return re.sub(r"\s+", "", str(s))


def load_kokuji():
    import pypdf
    if not os.path.exists(KOKUJI):
        raise SystemExit(f"告示本文が見つかりません: {KOKUJI}")
    r = pypdf.PdfReader(KOKUJI)
    return _norm("\n".join((p.extract_text() or "") for p in r.pages)), \
        len(r.pages)


def load_pdf_text(path):
    """原典のPDFから本文テキストを取り出す。記憶で書かないための裏づけ。"""
    from pypdf import PdfReader
    r = PdfReader(path)
    return "\n".join((pg.extract_text() or "") for pg in r.pages)


def verify(ko):
    ng = []
    for p in (HONPON, MOTO):
        if not os.path.exists(p):
            ng.append(f"原典が無い: {os.path.basename(p)}")
    if ng:
        print("自己点検 不合格:")
        for x in ng:
            print("   -", x)
        raise SystemExit(1)

    hon = _norm(load_docx(HONPON))
    moto = _norm(load_docx(MOTO))

    # ① 条項の内容が告示の現物にあること。
    #    条文を記憶で書かない。告示が引いている文言で確かめる。
    for jou, kubun, _naiyo, terasu in JOUKOU:
        if _norm(terasu) not in ko:
            ng.append(f"告示に見つからない（{jou}）: {terasu[:30]}")
        if kubun not in ("計画の根拠", "義務", "努力義務"):
            ng.append(f"区分が未定義: {jou} {kubun}")

    # ①b 義務と努力義務を取り違えていないこと。
    #     協議会は第9項で努力義務、合議制の機関は第10項で義務である。
    #     ここを逆に書くと、計画の手続が変わる。
    gimu = {j for j, k, *_ in JOUKOU if k == "義務"}
    doryoku = {j for j, k, *_ in JOUKOU if k == "努力義務"}
    if "障害者総合支援法第88条第10項" not in gimu:
        ng.append("法第88条第10項（合議制の機関）を義務にしていない")
    if "障害者総合支援法第88条第9項" not in doryoku:
        ng.append("法第88条第9項（協議会）を努力義務にしていない")
    if gimu & doryoku:
        ng.append(f"同じ条項が義務と努力義務の両方にある: {gimu & doryoku}")

    # ② 告示の項目の照合語が告示の現物にあること
    for basho, koumoku, terasu, _doko, _hon_t, _hantei in KISAI:
        if _norm(terasu) not in ko:
            ng.append(f"告示に見つからない（{basho} {koumoku}）: "
                      f"{terasu[:30]}")

    # ③ 「合」とした項目は、正本の現物にその語があること。
    #    言葉で合と書くだけでは確かめたことにならない。
    for basho, koumoku, _t, _doko, hon_t, hantei in KISAI:
        if _norm(hon_t) not in hon:
            ng.append(f"{basho}（{koumoku}）の照合語が正本に無い: "
                      f"{hon_t[:28]}")
        if hantei not in ("合", "合（ＫＴ-1で追記）",
                          "不足だった（ＫＴ-1で追記）"):
            ng.append(f"判定が未定義: {basho} {hantei}")

    # ④ 不足としたものが、他メンバー版には無かったこと。
    #    当方が足したものであることの裏づけ。
    for basho, koumoku, _t, _doko, hon_t, hantei in KISAI:
        if hantei.startswith("不足") and _norm(hon_t) in moto:
            ng.append(f"不足としたが他メンバー版にある: {basho} {hon_t[:24]}")

    # ⑤ 追記の挿入位置が正本にちょうど1つあること
    for rec in KT_EDITS:
        n = hon.count(_norm(rec["ichi"]))
        if n != 1:
            ng.append(f"{rec['no']}の挿入位置が正本に{n}件: "
                      f"{rec['ichi'][:30]}")
        if rec["kata"] not in ("本文", "注記後", "表の後"):
            ng.append(f"{rec['no']}の挿入位置の型が未定義: {rec['kata']}")

    # ⑥ 追記した文が他メンバー版に無く、正本にちょうど1つ入ったこと
    for rec in KT_EDITS:
        for blk in rec["nakami"]:
            if blk[0] not in ("p", "note"):
                continue
            if _norm(blk[1]) in moto:
                ng.append(f"{rec['no']}の文が既に他メンバー版にある")
            if hon.count(_norm(blk[1])) != 1:
                ng.append(f"{rec['no']}の文が正本に"
                          f"{hon.count(_norm(blk[1]))}件: {blk[1][:26]}")

    # ⑦ 条文の原典が無いものを、あるように書いていないこと
    if not JOUBUN_NASHI:
        ng.append("条文の原典が無いものの記録が空")
    for jou, _k, _n, daitai in JOUBUN_NASHI:
        if "告示" not in daitai:
            ng.append(f"代替の出所に告示を挙げていない: {jou}")

    # ⑧ 照会の番号と、本文の注記に未定義の番号が無いこと
    nos = [s[0] for s in SHOUKAI]
    if nos != ["Ｍ-110"]:
        ng.append(f"照会の番号が想定と違う: {nos}")
    for rec in KT_EDITS:
        for blk in rec["nakami"]:
            if blk[0] != "note":
                continue
            for m in re.findall(r"Ｍ-\d+", blk[1]):
                if m not in nos:
                    ng.append(f"{rec['no']}の注記が未起票の番号を"
                              f"参照している: {m}")

    # ⑨ 第1章5（4）の時制を書き換えていないこと（他メンバー版の体裁）。
    #   日程は工程の引き直し（案Ａ）によりＴＫ-4で書き換えたが、
    #   時制は他メンバーの編集上の判断であるため触れない（Ｓ-27）。
