def scan_draft(path):
    """計画素案から［要協議］等の所在を章節別に抽出する。"""
    doc = Document(path)
    h1re = re.compile(r"^第[0-9１-９]+章|^資料編")
    h2re = re.compile(r"^第[0-9１-９]+節|^基本目標[0-9]|^資料[0-9]")
    cur1 = cur2 = ""
    got = []

    def pick(txt):
        for w in ("要協議", "要確認", "要内訳", "未対応", "暫定"):
            for _ in range(txt.count(w)):
                got.append((cur1, cur2, w))

    for ch in doc.element.body.iterchildren():
        if ch.tag.endswith("}p"):
            t = Paragraph(ch, doc).text.strip()
            if h1re.match(t) and len(t) < 30:
                cur1, cur2 = t, ""
            elif h2re.match(t) and len(t) < 40:
                cur2 = t
            pick(t)
        elif ch.tag.endswith("}tbl"):
            for row in Table(ch, doc).rows:
                for c in row.cells:
                    pick(c.text)
    return got


