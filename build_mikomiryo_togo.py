def count_checks(wbk):
    """自己点検シートの適合・不適合を実物から数える。

    件数を固定値で書くと実物とずれるため、
    「判定」の列を見出しから見つけ、番号のある行だけを数える。
    """
    for ws in wbk.worksheets:
        if "自己点検" not in ws.title:
            continue
        hrow = hcol = None
        for row in ws.iter_rows():
            for c in row:
                if c.value == "判定":
                    hrow, hcol = c.row, c.column
                    break
            if hrow:
                break
        if hrow is None:
            continue
        ok = ng = 0
        for row in ws.iter_rows(min_row=hrow + 1):
            a = row[0].value
            if a is None or not str(a).strip().isdigit():
                continue
            v = ws.cell(row=row[0].row, column=hcol).value
            if v == "適合":
                ok += 1
            elif v == "不適合":
                ng += 1
        return ok, ng
    return 0, 0


def count_kakunin(wbk):
    """確認事項シートのNo.を実物から数える。"""
    nos = set()
    for ws in wbk.worksheets:
        if "確認事項" not in ws.title:
            continue
        for row in ws.iter_rows(values_only=True):
            for v in row:
                s = str(v) if v is not None else ""
                if s.startswith("No.") and s[3:].split()[0].rstrip("・、").isdigit():
                    nos.add(int(s[3:].split()[0].rstrip("・、")))
    return sorted(nos)


