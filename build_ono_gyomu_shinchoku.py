def sheet_wbs(wb, rows):
    ws = wb.create_sheet("01_WBS")
    ws.append(HDR_WBS)
    for r in rows:
        ws.append(list(r))
    head_row(ws)
    last = ws.max_row
    for r in range(2, last + 1):
        st = ws[f"I{r}"].value
        if st in ST_FILL:
            ws[f"I{r}"].fill = ST_FILL[st]
            ws[f"I{r}"].alignment = Alignment(horizontal="center", vertical="center")
        ws[f"J{r}"].fill = IN_FILL
        ws[f"J{r}"].number_format = '0"%"'
        ws[f"K{r}"].fill = IN_FILL
        ws[f"K{r}"].alignment = Alignment(horizontal="center", vertical="center")
    body_style(ws, wrap_cols=(0, 2, 3, 4, 11, 12), max_row=last)
    # 状態の入力規則
    dv = DataValidation(type="list", formula1='"' + ",".join(STATES) + '"', allow_blank=True)
    ws.add_data_validation(dv)
    dv.add(f"I2:I{last}")
    dv2 = DataValidation(type="whole", operator="between", formula1=0, formula2=100,
                         allow_blank=True)
    ws.add_data_validation(dv2)
    dv2.add(f"J2:J{last}")
    # 進捗率の色分け
    ws.conditional_formatting.add(
        f"J2:J{last}",
        CellIsRule(operator="equal", formula=["100"],
                   fill=PatternFill("solid", bgColor="C6EFCE")))
    ws.conditional_formatting.add(
        f"J2:J{last}",
        CellIsRule(operator="equal", formula=["0"],
                   fill=PatternFill("solid", bgColor="EEEEEE")))
    widths(ws, W_WBS)
    ws.freeze_panes = "C2"
    ws.auto_filter.ref = f"A1:M{last}"
    return ws, last


def sheet_phase(wb, rows, last, bottleneck):
    """段階サマリ。01_WBS を数式で参照するので、Excel上の編集が反映される。"""
    ws = wb.create_sheet("02_段階サマリ")
    ws.append(["段階", "作業数", "完了", "進行中", "要対応", "データ待ち", "未着手",
               "加重進捗率", "予定開始", "予定完了", "律速要因"])
    phases = []
    for r in rows:
        if r[0] not in phases:
            phases.append(r[0])
    W = f"'01_WBS'"
    for i, ph in enumerate(phases):
        rr = 2 + i
        sub = [r for r in rows if r[0] == ph]
        ws.append([
            ph,
            f'=COUNTIF({W}!$A$2:$A${last},$A{rr})',
            f'=COUNTIFS({W}!$A$2:$A${last},$A{rr},{W}!$I$2:$I${last},"完了")',
            f'=COUNTIFS({W}!$A$2:$A${last},$A{rr},{W}!$I$2:$I${last},"進行中")',
            f'=COUNTIFS({W}!$A$2:$A${last},$A{rr},{W}!$I$2:$I${last},"要対応")',
            f'=COUNTIFS({W}!$A$2:$A${last},$A{rr},{W}!$I$2:$I${last},"データ待ち")',
            f'=COUNTIFS({W}!$A$2:$A${last},$A{rr},{W}!$I$2:$I${last},"未着手")',
            f'=IF(SUMPRODUCT(({W}!$A$2:$A${last}=$A{rr})*{W}!$K$2:$K${last})=0,0,'
            f'SUMPRODUCT(({W}!$A$2:$A${last}=$A{rr})*{W}!$J$2:$J${last}*{W}!$K$2:$K${last})'
            f'/SUMPRODUCT(({W}!$A$2:$A${last}=$A{rr})*{W}!$K$2:$K${last})/100)',
            min(r[6] for r in sub),
            max(r[7] for r in sub),
            bottleneck.get(ph, "―"),
        ])
    n = len(phases)
    tot = 2 + n
    ws.append([
        "合計", f"=SUM(B2:B{tot - 1})", f"=SUM(C2:C{tot - 1})", f"=SUM(D2:D{tot - 1})",
        f"=SUM(E2:E{tot - 1})", f"=SUM(F2:F{tot - 1})", f"=SUM(G2:G{tot - 1})",
        f'=IF(SUM({W}!$K$2:$K${last})=0,0,'
        f'SUMPRODUCT({W}!$J$2:$J${last},{W}!$K$2:$K${last})/SUM({W}!$K$2:$K${last})/100)',
        min(r[6] for r in rows), max(r[7] for r in rows), "",
    ])
    head_row(ws)
    for r in range(2, tot + 1):
        ws[f"H{r}"].number_format = "0.0%"
        ws[f"H{r}"].fill = CALC_FILL
        for col in "BCDEFG":
            ws[f"{col}{r}"].alignment = Alignment(horizontal="center", vertical="center")
    for col in "ABCDEFGH":
        ws[f"{col}{tot}"].font = Font(bold=True, size=10)
    body_style(ws, wrap_cols=(0, 10), max_row=tot)
    widths(ws, (18, 9, 8, 9, 9, 11, 9, 12, 11, 11, 56))
    ws.freeze_panes = "B2"
    ws.append([])
    ws.append(["※ 加重進捗率＝Σ（進捗率×重み）÷Σ重み。重みは工数の目安（1〜5）。"])
    ws.append(["※ 01_WBS の「状態」「進捗率」を書き換えると、本表とダッシュボードが再計算されます。"])
    return ws, tot, phases


