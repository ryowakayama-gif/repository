def sheet_simple(wb, name, header, rows, ws_widths, wrap_cols=(), st_col=None, notes=()):
    ws = wb.create_sheet(name)
    ws.append(header)
    for r in rows:
        ws.append(list(r))
    head_row(ws)
    last = ws.max_row
    if st_col is not None:
        for r in range(2, last + 1):
            v = ws.cell(r, st_col + 1).value
            if v in ST_FILL:
                ws.cell(r, st_col + 1).fill = ST_FILL[v]
                ws.cell(r, st_col + 1).alignment = Alignment(horizontal="center",
                                                             vertical="center")
    body_style(ws, wrap_cols=wrap_cols, max_row=last)
    widths(ws, ws_widths)
    ws.freeze_panes = "A2"
    for t in notes:
        ws.append([t])
    return ws


