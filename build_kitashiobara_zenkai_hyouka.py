def load_docx(path):
    d = docx.Document(path)
    out = [p.text for p in d.paragraphs]
    for t in d.tables:
        for r in t.rows:
            for c in r.cells:
                out.append(c.text)
    return "\n".join(out)


def hyo(path, atama):
    """正本から表頭で表を1つ取る。"""
    d = docx.Document(path)
    for t in d.tables:
        h = [c.text.strip() for c in t.rows[0].cells]
        if h[:len(atama)] == atama:
            return [[c.text.strip() for c in r.cells] for r in t.rows[1:]]
    return None


def _norm(s):
    return re.sub(r"\s+", "", str(s))


