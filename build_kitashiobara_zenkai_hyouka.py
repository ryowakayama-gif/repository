def _cell(v):
    """「2.6（4）人分」→ (2.6, 4.0, '人分')。実績が「―」なら None。"""
    m = re.match(r"^([0-9.]+|―)（([0-9.]+)）(.*)$", v)
    if not m:
        raise ValueError(f"実績の表のセルの形が違う: {v}")
    a = None if m.group(1) == "―" else float(m.group(1))
    return a, float(m.group(2)), m.group(3)


def _fmt(x):
    return f"{x:g}"


def _bunrui(jisseki):
    """[(実績, 計画)] ×3年度 → (区分, 暫定で決めたか)。0/0 は None。"""
    kaku = [(a, p) for a, p in jisseki[:2] if a is not None]
    if all(a == 0 and p == 0 for a, p in jisseki if a is not None):
        return None, False
    if any(p == 0 and a > 0 for a, p in jisseki if a is not None):
        return "見込み超過", False
    hi = [a / p for a, p in kaku if p > 0]
    if not hi:
        #   確定した年度の計画値が０（実績も０）で、令和８年度にだけ
        #   計画値があるもの。令和８年度（暫定）で決める
        a8, p8 = jisseki[2]
        if a8 is None or p8 == 0:
            return None, False
        return ("概ね妥当" if 0.9 <= a8 / p8 <= 1.1 else
                "見込み超過" if a8 > p8 else "見込み未達"), True
    if all(0.9 <= r <= 1.1 for r in hi):
        return "概ね妥当", False
    ue = any(r > 1 for r in hi)
    shita = any(r < 1 for r in hi)
    if not (ue and shita):
        return ("見込み超過" if ue else "見込み未達"), False
    a8, p8 = jisseki[2]
    if a8 is None or p8 == 0 or 0.9 <= a8 / p8 <= 1.1:
        r7 = kaku[-1][0] / kaku[-1][1]
        return ("概ね妥当" if 0.9 <= r7 <= 1.1 else
                "見込み超過" if r7 > 1 else "見込み未達"), True
    return ("見込み超過" if a8 > p8 else "見込み未達"), True


def _gyou_text(rec):
    vs = [_cell(v) for v in rec["ato"]]
    tani = vs[0][2]
    parts = []
    for nen, (a, p, _t) in zip(NENDO[:2], vs[:2]):
        parts.append(f"{nen} {_fmt(a)}{tani}（見込量{_fmt(p)}{tani}）"
                     if a is not None else
                     f"{nen} 実績なし（見込量{_fmt(p)}{tani}）")
    a8, p8, _t = vs[2]
    #   令和８年度の値は、サービスにより数え方が違う（正本 第５章の注記）。
    #   令和8年10月24日、計画相談支援（実人数）まで「平均」と書いていたため、
    #   実績の表の差し替え（ＤＫ）が持つ数え方から書く。
    kazoe = rec.get("r8kazoe") or ""
    if kazoe.startswith("実人数"):
        mae8 = "令和８年度は年度途中までの実人数で"
    elif kazoe.startswith("申請件数"):
        mae8 = "令和８年度は年度途中までの申請件数で"
    elif kazoe.startswith("給付の決定の月数"):
        mae8 = "令和８年度は年度を通した給付の決定の月数で"
    elif kazoe.startswith("利用者数（令和８年４月から９月まで）"):
        mae8 = "令和８年度は４月から９月までの利用者数で"
    else:
        mae8 = "令和８年度は年度途中までの平均で"
    r8 = (f"{mae8}{_fmt(a8)}{tani}"
          f"（見込量{_fmt(p8)}{tani}。暫定）"
          if a8 is not None else
          f"令和８年度は確認中（見込量{_fmt(p8)}{tani}。Ｍ-137）")
    tan = f"［{rec['tani']}］" if rec.get("tani") else ""
    if kazoe.startswith("実人数"):
        tan += "（いずれも年度の中で利用した方の実人数。数え方はＭ-136で確認中）"
    return f"{tan}{'、'.join(parts)}。{r8}", vs


