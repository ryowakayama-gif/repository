def _dk(svc, tani):
    hits = [r for r in DK_HYOU if r.get("svc") == svc and r.get("tani") == tani]
    if len(hits) != 1:
        raise LookupError(f"実績の表の行が一意でない（{len(hits)}）: {svc} {tani}")
    return hits[0]


def _mikomi():
    out = []
    for namae, hito, ryo, setsuzoku in MIKOMI_TEIGI:
        rec = _dk(*hito)
        txt, vs = _gyou_text(rec)
        kubun, zantei = _bunrui([(a, p) for a, p, _t in vs])
        if ryo:
            txt2, _vs2 = _gyou_text(_dk(*ryo))
            txt = f"{txt}　量は{txt2}"
        if kubun is None:
            kubun = "把握不足"
            txt = "計画・実績とも０。" + txt
        if zantei:
            txt += ("。令和６・７年度では区分が決まらないため、"
                    "令和８年度（暫定）の向きで区分した")
        out.append((namae, kubun, txt, setsuzoku, rec["no"]))
    for rec in MIKOMI_ZERO:
        out.append(rec + ("",))
    return out


