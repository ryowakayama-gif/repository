# 自己点検
# ===========================================================================
def verify():
    ng = []

    # ① 引用した語が原典の当該頁に実在すること
    tsuika = 0
    for f, pg, go in list(TERASHIAWASE) + _shihyou_terashi():
        path = f"{KEN_DIR}/{f}"
        if not os.path.exists(path):
            ng.append(f"原典が無い: {f}")
            continue
        t = _pdf_text(path, [pg])
        if t is None:
            print("  ※ pdfplumber が無いため①は省略")
            break
        if _norm(go) not in _norm(t):
            ng.append(f"原典に無い語: {f} p{pg} 「{go}」")
        else:
            tsuika += 1

    # ② 国の基本指針で確かめる語
    kokuji_ok = 0
    if os.path.exists(KOKUJI):
        for pg, go in KOKUJI_TERASHI:
            t = _pdf_text(KOKUJI, [pg])
            if t is None:
                break
            if _norm(go) not in _norm(t):
                ng.append(f"基本指針に無い語: p{pg} 「{go}」")
            else:
                kokuji_ok += 1
    else:
        ng.append("基本指針の告示本文が無い")

    # ③ 指標の表の形が揃っていること
    for rec in SEISHIN_MOKUHYO + SHOGAIJI_MOKUHYO:
        if len(rec) != 8:
            ng.append(f"指標の列数が8でない: {rec[0]}")
        for i, v in enumerate(rec):
            if not str(v).strip():
                ng.append(f"指標の{i}列が空: {rec[0]}")

    # ④ 令和11年の目標値を持つ指標があること（本計画の終期と同じ年）
    r11 = [r for r in SEISHIN_MOKUHYO + SHOGAIJI_MOKUHYO
           if "11" in r[6].replace("１", "1")]
    if len(r11) < 7:
        ng.append(f"令和11年の目標値を持つ指標が{len(r11)}件しかない")

    # ⑤ 圏域の構成市町村の数が本文の記述と合っていること
    iryo = [x for x in KEN_KUIKI if x[0].startswith("医療圏")][0]
    shogai = [x for x in KEN_KUIKI if x[0] == "障がい保健福祉圏域"][0]
    n_iryo = iryo[2].count("、") + 1
    n_shogai = shogai[2].count("、") + 1
    if n_iryo != 17:
        ng.append(f"医療圏の構成市町村が17でない: {n_iryo}")
    if n_shogai != 13:
        ng.append(f"障がい保健福祉圏域の構成市町村が13でない: {n_shogai}")
    if "（17市町村）" not in iryo[2]:
        ng.append("医療圏の構成に17市町村と書いていない")
    #    障がい保健福祉圏域の13市町村は、医療圏の17市町村に含まれること
    for shi in shogai[2].split("（")[0].split("、"):
        shi = shi.strip()
        if shi and shi not in iryo[2]:
            ng.append(f"障がい保健福祉圏域の市町村が医療圏に無い: {shi}")

    # ⑥ 村内のへき地診療所が2カ所で、いずれも北塩原村であること
    if len(HEKICHI_MURA) != 2:
        ng.append(f"村内のへき地診療所が2カ所でない: {len(HEKICHI_MURA)}")
    for rec in HEKICHI_MURA:
        if "北塩原村" not in rec[3]:
            ng.append(f"所在が北塩原村でない: {rec[2]}")

    # ⑦ 正本の側の状態（反映前であること／反映先が実在すること）
    if os.path.exists(HONPON):
        try:
            import docx
        except ImportError:
            print("  ※ python-docx が無いため⑦は省略")
        else:
            d = docx.Document(HONPON)
            hon = "\n".join(p.text for p in d.paragraphs)
            for tb in d.tables:
                for row in tb.rows:
                    hon += "\n" + " | ".join(c.text for c in row.cells)
            n_hon = _norm(hon)
            #    反映先の章節が実在すること
            for iru in ("（２）精神障害にも対応した地域包括ケアシステムの構築",
                        "（４）障がい児支援の提供体制の整備等",
                        "第７章　他計画との連携",
                        "（１）福島県の計画との整合",
                        "（２）県が定める区域と本計画でいう圏域"):
                if _norm(iru) not in n_hon:
                    ng.append(f"正本に反映先が見当たらない: {iru}")
            #    反映した語が正本に入っていること。
            #    令和8年10月15日に反映を済ませたため、
            #    「まだ入っていないこと」の検査から入れ替えた。
            #    原典の数値がそのまま正本に載っていることも見る。
            for haitta in ("第８次福島県医療計画",
                           "会津・南会津医療圏",
                           "南東北裏磐梯診療所",
                           "南東北桧原診療所",
                           "５　第８次福島県医療計画との連携",
                           "表７-５",
                           "医療的ケア児等コーディネーター配置市町村数",
                           "精神障がい者アウトリーチ事業",
                           "災害拠点精神科病院",
                           "福島県南会津保健所"):
                if _norm(haitta) not in n_hon:
                    ng.append(f"正本に反映した語が無い: {haitta}")
            #    県の数値が正本に載っていること（原典で照合済みのもの）
            for suji in ("334日以上", "836人以下", "1,564人以下",
                         "59市町村", "80施設", "27カ所"):
                if _norm(suji) not in n_hon:
                    ng.append(f"正本に県の数値が無い: {suji}")
            #    17市町村の医療圏の構成が正本にそろっていること
            for shi in ("下郷町", "檜枝岐村", "只見町", "南会津町"):
                if _norm(shi) not in n_hon:
                    ng.append(f"正本に医療圏の市町村が無い: {shi}")
            #    当方が引いている会津障がい保健福祉圏域の13市町村
            if _norm("会津障がい保健福祉圏域") not in n_hon:
                ng.append("正本に会津障がい保健福祉圏域の記述がない")
            #    挿入位置（ichi）が正本に1カ所だけあること
            #    find_para と同じ決め方（完全一致、無ければ部分一致）で
            #    1カ所に決まることを見る。
            atama_ps = [_norm(p.text) for p in d.paragraphs]
            for rec in KI_EDITS:
                key = _norm(rec["ichi"])
                n = sum(1 for t in atama_ps if t == key)
                if n == 0:
                    n = sum(1 for t in atama_ps if key and key in t)
                if n != 1:
                    ng.append(f"挿入位置が正本に{n}カ所: "
                              f"{rec['no']}「{rec['ichi'][:30]}」")
            #    行を足す表の見出しが正本に1つだけあること
            for rec in KI_GYOU:
                n = 0
                for tb in d.tables:
                    if len(tb.rows) < 1:
                        continue
                    h = tuple(c.text.strip() for c in tb.rows[0].cells)
                    if h == tuple(rec["atama"]):
                        n += 1
                if n != 1:
                    ng.append(f"行を足す表が正本に{n}つ: {rec['no']}")
    else:
        print("  ※ 正本が未生成のため⑦は省略")

    # ⑧ 反映の一覧と現物の番号が一致すること。
    #    一覧だけ直して現物を直し忘れる（又はその逆）ことを止める。
    kata_ok = {"本文", "注記後", "書き換え", "表に行を足す", "章の末尾に足す"}
    for rec in KI_PLAN:
        if rec[4] not in kata_ok:
            ng.append(f"反映の型が未定義: {rec[0]} {rec[4]}")
    plan_no = {r[0] for r in KI_PLAN}
    genbutsu_no = {r["no"] for r in KI_EDITS} | {r["no"] for r in KI_GYOU}
    if plan_no != genbutsu_no:
        ng.append(f"反映の一覧と現物の番号が合わない: "
                  f"一覧のみ{sorted(plan_no - genbutsu_no)}／"
                  f"現物のみ{sorted(genbutsu_no - plan_no)}")
    #    現物の形が揃っていること
    blk_ok = {"h2", "h3", "p", "tbl", "note"}
    for rec in KI_EDITS:
        if rec["kata"] not in ("本文", "注記後", "表の後"):
            ng.append(f"挿入の型が未定義: {rec['no']} {rec['kata']}")
        for key in ("saki", "ichi", "konkyo"):
            if not rec[key].strip():
                ng.append(f"{rec['no']}の{key}が空")
        for blk in rec["nakami"]:
            if blk[0] not in blk_ok:
                ng.append(f"ブロックの型が未定義: {rec['no']} {blk[0]}")
            if blk[0] == "tbl" and len(blk) != 3:
                ng.append(f"表のブロックの形が違う: {rec['no']}")
    for rec in KI_GYOU:
        if len(rec["atama"]) != len(rec["gyou"][0]):
            ng.append(f"足す行の列数が見出しと合わない: {rec['no']}")

    # ⑨ 照会番号が重複しておらず、既にある番号とぶつからないこと
    nos = [x[0] for x in SHOUKAI]
    if len(nos) != len(set(nos)):
        ng.append(f"照会番号が重複している: {nos}")

    # ⑩ 他団体の案件の資料を混ぜていないこと
    zen = "\n".join(
        str(v) for recs in (SHIRYO, NAI, KIHON, SEISHIN_MOKUHYO,
                            KUIKICHIGAI, SEISHIN_SESAKU, SHOGAIJI_MOKUHYO,
                            SHOGAIJI, HEKICHI_MURA, HEKICHI, KEN_KUIKI,
                            AIZU_DATA, AIZU_TORIKUMI, KI_PLAN, SHOUKAI)
        for rec in recs for v in rec)
    for hoka in ("小野町", "金ヶ崎", "阿蘇", "札幌", "kawasaki"):
        if hoka in zen:
            ng.append(f"他団体の案件の語が入っている: {hoka}")

    # ⑪ 受領資料の頁数の合計が、各PDFの実際の頁数と合うこと
    try:
        import pdfplumber
    except ImportError:
        print("  ※ pdfplumber が無いため⑪は省略")
    else:
        for shou, f, n, _toshi, _omo, _k in SHIRYO:
            path = f"{KEN_DIR}/{f}"
            if not os.path.exists(path):
                ng.append(f"原典が無い: {f}")
                continue
            with pdfplumber.open(path) as pdf:
                if len(pdf.pages) != n:
                    ng.append(f"頁数が合わない: {f} "
                              f"{n} ≠ {len(pdf.pages)}")

    if ng:
        for x in ng:
            print(f"  × {x}")
        raise SystemExit("県医療計画の自己点検で止めました")

    return (f"受領{len(SHIRYO)}点（{sum(x[2] for x in SHIRYO)}頁）・"
            f"手元に無い章{len(NAI)}件／"
            f"原典で照合した語{tsuika}件・基本指針{kokuji_ok}件／"
            f"精神疾患の全体目標{len(SEISHIN_MOKUHYO)}件・"
            f"小児医療の指標{len(SHOGAIJI_MOKUHYO)}件／"
            f"正本への反映{len(KI_PLAN)}件・照会{len(SHOUKAI)}件")


