def _pdf_text(path, pages):
    """原典の指定頁の文字を返す。pdfplumber が無い環境では None。"""
    try:
        import pdfplumber
    except ImportError:
        return None
    out = []
    with pdfplumber.open(path) as pdf:
        for i in pages:
            if 1 <= i <= len(pdf.pages):
                out.append(pdf.pages[i - 1].extract_text() or "")
    return "\n".join(out)


def _norm(s):
    return "".join(s.split())


def _shihyou_terashi():
    """指標の表そのものから、原典で確かめる語を組み立てる。

    番号・現況値・調査年・目標値・目標年を、記録した頁の文字に当てる。
    指標の名称は、原典の表の中で他の列と行をまたいで入り交じるため
    連続した文字列にならない。名称は 02・03 シートの見出しの語で
    別に確かめる。
    """
    out = []
    for pdf, page, recs in ((SEISHIN_PDF, SEISHIN_PAGE, SEISHIN_MOKUHYO),
                            (SHOGAIJI_PDF, SHOGAIJI_PAGE,
                             SHOGAIJI_MOKUHYO)):
        for no, _na, genkyo, chosa, _hou, mokuhyo, moku_nen, _shu in recs:
            for go in (no, genkyo, chosa, mokuhyo, moku_nen):
                out.append((pdf, page, go))
    return out


