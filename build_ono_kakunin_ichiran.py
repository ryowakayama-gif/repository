# ---------------------------------------------------------------- 自己点検
def jiko():
    ng = []
    nos = [x[0] for x in KAKUNIN]
    # 1 1から最後まで欠番・重複なし（他町村の案件が行っていた検算）
    if sorted(nos) != list(range(1, len(KAKUNIN) + 1)):
        miss = set(range(1, len(KAKUNIN) + 1)) - set(nos)
        dup = [n for n in set(nos) if nos.count(n) > 1]
        ng.append("通し番号に欠番または重複がある（欠番%s／重複%s）"
                  % (sorted(miss), sorted(dup)))
    # 2 区分が4つのいずれか
    for x in KAKUNIN:
        if x[2] not in KUBUN:
            ng.append("区分が4つのいずれかでない：№%d" % x[0])
    # 3 Ａは宛先が「―」（照会から外すため）
    for x in _by("Ａ"):
        if x[3] != "―":
            ng.append("Ａなのに宛先がある：№%d" % x[0])
    # 4 Ｂは宛先が「―」（当方で確かめるため）
    for x in _by("Ｂ"):
        if x[3] != "―":
            ng.append("Ｂなのに宛先がある：№%d" % x[0])
    # 5 Ｃ・Ｄは宛先がある
    for x in _by("Ｃ") + _by("Ｄ"):
        if x[3] == "―" or not x[3].strip():
            ng.append("Ｃ・Ｄなのに宛先がない：№%d" % x[0])
    # 6 Ａ以外は期限がある
    for x in KAKUNIN:
        if x[2] != "Ａ" and not x[7].strip():
            ng.append("期限が空：№%d" % x[0])
    # 7 「何に効くか」が空でない
    for x in KAKUNIN:
        if not x[6].strip():
            ng.append("何に効くかが空：№%d" % x[0])
    # 8 従前の記号が空でない（新規は「―」と書く）
    for x in KAKUNIN:
        if not x[5].strip():
            ng.append("従前の記号が空：№%d" % x[0])
    # 9 区分の基準に原則を書いている
    if "委ねない" not in GENSOKU:
        ng.append("区分の基準に原則を書いていない")
    # 10 xlsxの見出しと列幅の数が合う
    if len(HEAD) != len(W):
        ng.append("xlsxの見出しと列幅の数が合わない")
    return ng


