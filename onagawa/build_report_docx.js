// rows: [[cell, ...], ...]  cell = string | {t, b(old), a(lign), f(ill)}
function TBL(headers, rows, widths, opt = {}) {
  const size = opt.size || 17;
  const cellsFor = (arr, isHead, rowFill) => arr.map((c, i) => {
    const o = typeof c === "object" && c !== null ? c : { t: c };
    const align = o.a || (opt.aligns ? opt.aligns[i] : "left");
    const fill = isHead ? BLUE : (o.f || rowFill);
    return new TableCell({
      width: { size: widths[i], type: WidthType.DXA },
      shading: fill ? { type: ShadingType.CLEAR, fill, color: "auto" } : undefined,
      verticalAlign: VerticalAlign.CENTER,
      margins: { top: 60, bottom: 60, left: 90, right: 90 },
      children: String(o.t ?? "").split("\n").map((ln) => new Paragraph({
        alignment: align === "center" ? AlignmentType.CENTER
          : align === "right" ? AlignmentType.RIGHT : AlignmentType.LEFT,
        spacing: { before: 0, after: 0, line: 240 },
        children: [new TextRun({
          text: ln, font: GOTHIC, size: isHead ? size : size,
          bold: isHead || o.b || false,
          color: isHead ? "FFFFFF" : (o.c || "000000"),
        })],
      })),
    });
  });

  const bd = { style: BorderStyle.SINGLE, size: 4, color: "AFC4DB" };
  return new Table({
    width: { size: W, type: WidthType.DXA },
    columnWidths: widths,
    borders: { top: bd, bottom: bd, left: bd, right: bd, insideHorizontal: bd, insideVertical: bd },
    rows: [
      new TableRow({ tableHeader: true, children: cellsFor(headers, true) }),
      ...rows.map((r, j) => new TableRow({
        children: cellsFor(r, false, j % 2 ? ALT : "FFFFFF"),
      })),
    ],
  });
}

