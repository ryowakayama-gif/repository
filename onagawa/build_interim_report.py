def genkou(kei, w):
    """現行料金（税込・メーター使用料込み）"""
    kihon = 990 if w <= 5 else 1210
    juryo = max(0, min(w, 100) - 10) * 121 + max(0, w - 100) * 110
    if w <= 5:
        juryo = 0
    elif w <= 10:
        juryo = (w - 5) * 44
    else:
        juryo = 5 * 44 + max(0, min(w, 100) - 10) * 121 + max(0, w - 100) * 110
        kihon = 990
    return kihon + juryo + METER[kei]


