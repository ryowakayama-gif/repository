def load():
    jis = {}
    for r in openpyxl.load_workbook(MOKUHYO, data_only=True)["サマリー"] \
            .iter_rows(values_only=True):
        v = [x for x in r if x is not None]
        if len(v) >= 7 and isinstance(v[2], (int, float)) \
                and isinstance(v[3], (int, float)):
            jis[str(v[1])] = v[2]
    wc = openpyxl.load_workbook(CHOSA, data_only=True)["集計_障がい者"]
    cur, iko, q28, q29 = {}, {}, {}, {}
    for r in wc.iter_rows(min_row=5, values_only=True):
        if r[0] == "問31-1" and str(r[2]) == "利用している":
            cur[str(r[1])] = r[3]
        if r[0] == "問31-2" and str(r[2]) == "利用したい":
            iko[str(r[1])] = r[3]
        if r[0] == "問28":
            q28[str(r[2])] = r[3]
        if r[0] == "問29":
            q29[str(r[2])] = r[3]
    return jis, cur, iko, q28, q29


def rows(jis, cur, iko):
    out = []
    for q, pl in PLAN:
        j = sum(jis[x] for x in pl)
        c, i = cur[q], iko[q]
        d = c - j
        nm, ari = KAIGO[q]
        if d <= 0:
            ku = "捕捉漏れ" if d < 0 else "一致"
        elif ari in ("あり", "名称が近い"):
            ku = "取り違えで説明しうる"
        else:
            ku = "説明できない"
        out.append({"設問": q, "計画": "＋".join(pl), "実績": j, "現在": c,
                    "差": d, "意向": i, "類似": nm, "有無": ari, "区分": ku})
    return out


def selfcheck(jis, cur, iko, q28, q29, rs):
    ok, ng = [], []

    def chk(no, name, kitai, kekka):
        (ok if kitai == kekka else ng).append((no, name, str(kitai),
                                               str(kekka)))

    chk("1", "問31の15サービスすべてを計画の区分に対応づけた", 15, len(rs))
    chk("2", "対応づけた計画の区分に重複がない", True,
        len([x for r in rs for x in r["計画"].split("＋")])
        == len({x for r in rs for x in r["計画"].split("＋")}))
    # 取り違えで説明しうる上振れの合計が、介護保険の利用者数を超えないこと
    ue_ari = sum(r["差"] for r in rs if r["区分"] == "取り違えで説明しうる")
    ue_nashi = sum(r["差"] for r in rs if r["区分"] == "説明できない")
    chk("3", "取り違えで説明しうる上振れが介護保険の利用者数以内", True,
        ue_ari <= q29["利用している"])
    chk("4", "上振れの合計が介護保険の利用者数以内", True,
        ue_ari + ue_nashi <= q29["利用している"])
    # 問28の無回答と問29の利用者が一致すること（傍証）
    chk("5", "問28の無回答と問29の介護保険利用者の人数",
        q29["利用している"], q28["無回答"])
    # 説明できない分が「介護保険に類似なし」だけであること
    chk("6", "説明できない分はすべて介護保険に類似のないサービス", True,
        all(r["有無"] == "なし" for r in rs if r["区分"] == "説明できない"))
    # 個票がないこと（本書の前提）
    sheets = openpyxl.load_workbook(CHOSA, data_only=True).sheetnames
    chk("7", "集計表に個票のシートがない", True,
        not any("個票" in s or "ローデータ" in s or "raw" in s.lower()
                for s in sheets))
    return ok, ng, ue_ari, ue_nashi


