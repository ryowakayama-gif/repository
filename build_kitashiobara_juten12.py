def load_docx(path):
    doc = docx.Document(path)
    parts = []
    for ch in doc.element.body.iterchildren():
        tag = ch.tag.split("}")[-1]
        if tag == "p":
            parts.append(Paragraph(ch, doc).text)
        elif tag == "tbl":
            for row in Table(ch, doc).rows:
                seen = set()
                for c in row.cells:
                    if id(c._tc) in seen:
                        continue
                    seen.add(id(c._tc))
                    parts.append(c.text)
    return "\n".join(parts)


def load_pdf_text(path):
    """PDFの本文を1本につなぐ（画像だけの頁は空になる）。"""
    import logging
    import pdfplumber
    logging.getLogger("pdfminer").setLevel(logging.ERROR)
    out = []
    with pdfplumber.open(path) as pdf:
        for pg in pdf.pages:
            out.append(pg.extract_text() or "")
    return "\n".join(out)


