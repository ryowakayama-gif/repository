BAND = {
    "tot": slice(0, 1),
    "65-74": slice(1, 3),
    "75-84": slice(3, 5),
    "85+": slice(5, 9),
    "75+": slice(3, 9),
    "65+": slice(1, 9),
}


def pop(town, year, band):
    """町別・年別・区分別の人口。"""
    return sum(JUKI[town][year][BAND[band]])


def pop3(year, band):
    """3町計。"""
    return sum(pop(t, year, band) for t in TOWNS)


def g(band, town=None, y0=2019, y1=2025):
    """年平均変化率。town を省くと3町計。"""
    if town:
        a, b = pop(town, y0, band), pop(town, y1, band)
    else:
        a, b = pop3(y0, band), pop3(y1, band)
    return (b / a) ** (1.0 / (y1 - y0)) - 1


