def load_kikan():
    """国の一覧から、会津障がい保健福祉圏域の設置状況を数える。

    一覧は「主設置市町村」と「共同設置市町村」の2つの欄を持ち、
    共同設置は主設置と同じ行に置かれている。
    文字の並びだけで読むと、どの行の共同設置かが分からなくなるため、
    文字の横位置（x座標）で欄を切り分ける。
      x≈ 39  連番
      x≈ 51  主設置市町村
      x≈104  共同設置市町村
      x≈347  名称
      x≈494  住所
    """
    import pdfplumber
    if not os.path.exists(KIKAN_PDF):
        raise SystemExit(
            f"国の一覧が見つかりません: {KIKAN_PDF}\n"
            "厚生労働省の基幹相談支援センター一覧を格納してください。")
    SAKAI = [(0, 48, "no"), (48, 100, "shu"), (100, 340, "kyodo"),
             (340, 480, "meisho"), (480, 10000, "jusho")]
    gyou = []
    with pdfplumber.open(KIKAN_PDF) as pdf:
        for pg in pdf.pages:
            tate = {}
            for w in pg.extract_words():
                tate.setdefault(round(w["top"] / 4), []).append(w)
            for y in sorted(tate):
                ran = {k: [] for _a, _b, k in SAKAI}
                for w in sorted(tate[y], key=lambda w: w["x0"]):
                    for x0, x1, k in SAKAI:
                        if x0 <= w["x0"] < x1:
                            ran[k].append(w["text"])
                            break
                rec = {k: " ".join(v).strip() for k, v in ran.items()}
                if re.fullmatch(r"\d+", rec["no"]) and rec["shu"]:
                    gyou.append(rec)

    aizu_shu = []
    for g in gyou:
        if g["shu"] not in AIZU_13:
            continue
        tomo = [x for x in re.split(r"[、，,・]", g["kyodo"]) if x]
        aizu_shu.append(dict(shichoson=g["shu"], meisho=g["meisho"],
                             jusho=g["jusho"], tomo=tomo))
    kyodo_all = sorted({t for x in aizu_shu for t in x["tomo"]} & set(AIZU_13),
                       key=AIZU_13.index)
    motteru = sorted({x["shichoson"] for x in aizu_shu} | set(kyodo_all),
                     key=AIZU_13.index)
    nai = [x for x in AIZU_13 if x not in motteru]
    return dict(zenkoku=len(gyou), aizu_shu=aizu_shu, aizu_kyodo=kyodo_all,
                motteru=motteru, nai=nai)


