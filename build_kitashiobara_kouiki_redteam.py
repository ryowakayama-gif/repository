def sheet_url(wb, evid):
    ws = add_sheet(
        wb, "09_参照元", "参照元（受領したエビデンスパックによる）",
        "令和8年10月10日に受領した「北塩原村_広域連携_参照エビデンス」"
        "（source/レビュー_20261010/広域連携_参照エビデンス）を読んだもの。"
        "いずれも当方の環境からは原典を取得できない"
        "（組織のネットワーク方針により接続が403で遮断される。"
        "再試行はしない）。"
        "本書の記述のうち相手方の計画・県資料に関する部分は、"
        "出所がこのパックの記述である。",
        [7, 30, 18, 38, 30, 10, 34])
    r = 5
    style_header_row(ws, r, ["番号", "資料", "公表主体", "確認した根拠事項",
                             "留意事項", "確認日", "URL（当方は未取得）"])
    r += 1
    from openpyxl.styles import PatternFill
    for i, e in enumerate(evid):
        url = e["url"]
        if e["kanren"]:
            url += "\n（関連）" + e["kanren"]
        if e["bikou"]:
            url += "\n※" + e["bikou"]
        row0 = r
        r = write_row(ws, r, [e["no"], e["shiryo"], e["nushi"], e["konkyo"],
                              e["ryui"], e["hi"], url], alt=(i % 2 == 1))
        if e["bikou"]:
            ws.cell(row=row0, column=7).fill = PatternFill(
                "solid", fgColor=MI)
    r += 1
    ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=7)
    from kitashiobara_common import style_note
    style_note(ws.cell(row=r, column=1),
               "パックに収められているのは、公式URL・資料名・公表主体・"
               "確認日・確認した根拠事項を整理したメモであり、"
               "原本のPDF・HTMLそのものではありません。"
               "村へ正式に提出する際は、各公式URLから原本を取得し、"
               "同じ番号で添えると追跡しやすくなります。"
               "猪苗代町（E09）は現行計画の本文まで確認できておらず、"
               "個別の目標値は推測せず要原典確認としています。"
               "なお、レビュー本体が挙げていた会津若松市の"
               "児童発達支援センター等のページはパックに含まれていません。"
               "児童発達支援センターの機能の確認（Ｍ-102）では、"
               "県の事業所一覧（E12）を根拠として用いています。")
    ws.row_dimensions[r].height = 62
    return ws


