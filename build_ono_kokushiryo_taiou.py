# ------------------------------------------------------------------ 読み取り
def _n(s):
    return unicodedata.normalize("NFKC", re.sub(r"\s+", "", s))


_PG = {}


def page(key, no):
    k = (key, no)
    if k not in _PG:
        kind, name, _t = GENTEN[key]
        if kind == "json":
            d = json.load(open(K26 / (name + ".json"), encoding="utf-8"))
            _PG[k] = _n(d["pages"][no - 1]) if no <= len(d["pages"]) else None
        else:
            r = subprocess.run(["pdftotext", "-f", str(no), "-l", str(no), "-layout",
                                str(K25 / name), "-"], capture_output=True, text=True)
            _PG[k] = _n(r.stdout) if r.returncode == 0 else None
    return _PG[k]


def soan_txt():
    import docx
    d = docx.Document(str(SOAN))
    t = [p.text for p in d.paragraphs]
    for tb in d.tables:
        for rw in tb.rows:
            t += [c.text for c in rw.cells]
    return _n("\n".join(t))


def sokutei():
    tx = soan_txt()
    return {x[0]: {w: tx.count(_n(w)) for w in x[4]} for x in RONTEN}


def jiko(soku):
    ng = []
    for x in RONTEN:
        for key, no, qs in x[2]:
            t = page(key, no)
            if t is None:
                ng.append("№%s：%s %d頁が読めない" % (x[0], key, no))
                continue
            for q in qs:
                if _n(q) not in t:
                    ng.append("№%s：%s %d頁に「%s」がない" % (x[0], key, no, q))
        for w, ex in x[4].items():
            v = soku[x[0]][w]
            if ex == ">0" and v == 0:
                ng.append("№%s：素案に「%s」があるとしたが出ない" % (x[0], w))
            if ex == "==0" and v:
                ng.append("№%s：素案に「%s」がないとしたが%d件出る" % (x[0], w, v))
        if x[7] not in KUBUN:
            ng.append("№%s：区分が不正" % x[0])
    return ng


